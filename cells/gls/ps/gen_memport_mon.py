#!/usr/bin/env python3
"""gen_memport_mon.py -- the one-hot check of every bdc_memport, on the gate-level netlist of one bench route.

    python3 cells/gls/ps/gen_memport_mon.py ROUTED_JSON NETS_MAP OUT.v
    (or PS_MON_GEN=cells/gls/ps/gen_memport_mon.py cells/gls/ps/build_ps.sh ... / bench_gate.sh ...)

bdc/mem.py's plain bdc_memport is a one-hot AND-OR mux: at most one slot may request at a time.  Its own check is
behavioural (`ifndef SYNTHESIS) and does not exist in a netlist, so a gate-level run could break the obligation and
say nothing.  With bdc/emit.py --host-mem the bench's host sequencer is one more slot on each memory
(research/data/suite/bench/README.md), and the obligation is the bench's: it must never request while the kernel's
own slots do.  This monitor watches every slot request of every memory -- nets taken at their DRIVER pins in the
netlist the bench gate simulates (gen_bench_mon.py's resolution), the same wires the port's mux reads -- and prints
  MEMPORTMON batch=B mem=M host_reqs=H kernel_reqs=K overlaps=O
at the end of every batch (bench_busy falling), counting since the previous line, and
  MEMPORT ONEHOT FAIL t=.. mem=M s_req=b..
for the first 20 instants two of one memory's slot requests are high together.  A slot request that cannot be found
is an error, not a silent omission.  The slots come from the kernel's own Verilog (`<k>_kernel_bench.v` beside the
routed JSON): each `bdc_memport_* ... <mc>_uport (` instance's `.s_req({...})`, the last entry the host slot.
"""
import glob, json, os, re, sys


def main():
    rj, nmap, out = sys.argv[1:4]
    kv = glob.glob(os.path.join(os.path.dirname(rj), "*_kernel_bench.v"))
    if len(kv) != 1:
        sys.exit("gen_memport_mon: want exactly one *_kernel_bench.v beside %s, found %s" % (rj, kv))
    ktext = open(kv[0]).read()
    # memories in signature order = the kernel's <m>_host_req ports in declaration order (bdc/emit.py HOST_MEM)
    hosts = re.findall(r"input\s+wire\s+(\w+)_host_req", ktext)
    ports = re.findall(r"(bdc_memport_\d+_\d+_\d+)\s*#\(.*?\)\s*(\w+)_uport\s*\(.*?\.s_req\(\{?([^)}]*)\}?\)", ktext, re.S)
    if not hosts or not ports:
        sys.exit("gen_memport_mon: %s has no host port / no bdc_memport (built without --host-mem?)" % kv[0])
    m = list(json.load(open(rj))["modules"].values())[0]
    nets, cells = m["netnames"], m["cells"]
    drv = {}
    for c in cells.values():
        bel = c["attributes"].get("NEXTPNR_BEL")
        for p, d in c.get("port_directions", {}).items():
            if d == "output" and bel:
                for b in c["connections"][p]:
                    drv[b] = (bel, p)
    by_pin = {}
    for line in open(nmap):
        if line.startswith("#"):
            continue
        w, _, n = line.strip().partition(" ")
        by_pin.setdefault(n, w)

    def wire(name):
        if name not in nets:
            sys.exit("gen_memport_mon: no net %r in %s" % (name, rj))
        b = nets[name]["bits"][0]
        if b not in drv:
            sys.exit("gen_memport_mon: net %r has no placed driver" % name)
        pin = "%s/%s" % drv[b]
        if pin not in by_pin:
            sys.exit("gen_memport_mon: %r -> %s not in %s" % (name, pin, nmap))
        return "tb_ps.dut." + by_pin[pin], pin

    L = ["// GENERATED by cells/gls/ps/gen_memport_mon.py for one route -- do not check in.",
         "`timescale 1ps/1ps", "module memport_mon;"]
    busy, bp = wire("bridge_i.bench_busy")
    L.append("    wire bench_busy = %s;   // %s" % (busy, bp))
    L.append("    integer batch = 0;")
    blocks = []
    for k, (mod, mc, sreq) in enumerate(ports):
        names = [s.strip() for s in sreq.split(",")]
        host = names[0]      # the concatenation is {last slot, ..., slot 0}: the host slot is written first
        if not host.endswith("_host_req") or host[:-len("_host_req")] not in hosts:
            sys.exit("gen_memport_mon: %s's s_req %s does not end with a host slot" % (mc, sreq))
        mi = hosts.index(host[:-len("_host_req")])
        hnet = "bridge_i.mem_hreq" if len(hosts) == 1 else "bridge_i.mem_hreq[%d]" % mi
        if hnet not in nets and len(hosts) > 1:
            hnet = "bridge_i.mem_hreq"   # a multi-bit net keeps its bits under the base name
        kn = names[1:]
        slots = [wire("bridge_i.udut." + n) for n in reversed(kn)]
        if hnet == "bridge_i.mem_hreq" and len(hosts) > 1:
            b = nets[hnet]["bits"][mi]
            pin = "%s/%s" % drv[b]
            hw = ("tb_ps.dut." + by_pin[pin], pin)
        else:
            hw = wire(hnet)
        L.append("    // memory %d (%s, %s): host %s; kernel slots %s" % (
            mi, mc, mod, hw[1], ", ".join("%s %s" % (n, p) for n, (_, p) in zip(kn, slots[::-1]))))
        L.append("    wire [%d:0] sreq%d = {%s};" % (len(kn), k, ", ".join([hw[0]] + [w for w, _ in reversed(slots)])))
        L.append("    integer nh%d = 0, nk%d = 0, no%d = 0;" % (k, k, k))
        L.append("    always @(sreq%d) if (^sreq%d !== 1'bx && (sreq%d & (sreq%d - 1'b1)) != 0) begin" % (k, k, k, k))
        L.append("        no%d = no%d + 1;" % (k, k))
        L.append('        if (no%d <= 20) $display("MEMPORT ONEHOT FAIL t=%%0t mem=%d s_req=%%b", $time, sreq%d);' % (k, mi, k))
        L.append("    end")
        L.append("    always @(posedge sreq%d[%d]) nh%d = nh%d + 1;" % (k, len(kn), k, k))
        for s in range(len(kn)):
            L.append("    always @(posedge sreq%d[%d]) nk%d = nk%d + 1;" % (k, s, k, k))
        blocks.append((k, mi))
    L.append("    always @(negedge bench_busy) begin")
    for k, mi in blocks:
        L.append('        $display("MEMPORTMON batch=%%0d mem=%d host_reqs=%%0d kernel_reqs=%%0d overlaps=%%0d", batch, nh%d, nk%d, no%d);'
                 % (mi, k, k, k))
        L.append("        nh%d = 0; nk%d = 0; no%d = 0;" % (k, k, k))
    L.append("        batch = batch + 1;")
    L.append("    end")
    L.append("endmodule")
    open(out, "w").write("\n".join(L) + "\n")
    print("memport monitor: %d memor%s -> %s" % (len(blocks), "y" if len(blocks) == 1 else "ies", out))


if __name__ == "__main__":
    main()
