#!/usr/bin/env python3
"""gen_bench_mon.py -- a monitor on gcd_bench_gen's batch FSM and kernel handshake, for one route.

    python3 cells/gls/ps/gen_bench_mon.py ROUTED_JSON NETS_MAP OUT.v
    (or PS_MON_GEN=cells/gls/ps/gen_bench_mon.py cells/gls/ps/build_ps.sh ...)

Two questions the board could not answer (cells/hw/README.md, research/JOURNAL.md 2026-10-30 17:08):
  * where the bench's "RTZ tail" (cycles/run - latmin, rtz_cost.sh) goes: kernel return-to-zero, or
    the FSM's own synchronizer cycles;
  * at what phase of aclk the kernel's asynchronous i_ack/o_req land, i.e. how close each run comes to
    the race that hung the August harness (a 3-bit state register sampling an async latch).

Printed (all times ps; nets taken at their DRIVER pins in the netlist decoded from the bits, so
routing to the consumers is not included):
  BRUN n=.. t_issue= iack= oreq= oack_to_oreq_fall= oreq_fall_to_s= iack_ph= oreq_ph= cyc_res= cyc_tail=
      one line per transaction: req_core rise -> i_ack_pl rise (iack) and -> o_req_pl rise (oreq);
      bench_o_ack rise -> o_req_pl fall (the kernel's output RTZ); o_req_pl fall -> o_req_s fall (the
      synchronizer); iack_ph/oreq_ph = time since the last aclk rise at i_ack_pl / o_req_pl rise;
      cyc_res = aclk cycles from entering S_ISSUE to entering S_ACK, cyc_tail = cycles from entering
      S_ACK to leaving S_NEXT (S_ACK + S_RTZ + S_NEXT: the part of a run lat_ctr does not count).
      Printed when the NEXT run is issued, so the last run of each batch has no line.
  BILL t= st=from->to   an FSM transition gen_bench.py's st_legal does not allow (sampled 3 ns after
      each aclk rise, so clock skew between the three state flops is not a transition)
  BST t= st=s           every state change for the first +BTRACE=<n> runs (default 2)
A net that cannot be found is an error, not a silent omission.
"""
import json, sys


def main():
    rj, nmap, out = sys.argv[1:4]
    m = list(json.load(open(rj))["modules"].values())[0]
    nets, cells = m["netnames"], m["cells"]
    drv = {}
    for c in cells.values():
        bel = c["attributes"].get("NEXTPNR_BEL")
        for p, d in c.get("port_directions", {}).items():
            if d == "output" and bel:
                for b in c["connections"][p]:
                    drv[b] = (bel, p)
    by_pin = {}
    for line in open(nmap):
        if line.startswith("#"):
            continue
        w, _, n = line.strip().partition(" ")
        by_pin.setdefault(n, w)

    def wire(rtl, bit=0):
        if rtl not in nets:
            sys.exit("gen_bench_mon: no net %r in %s" % (rtl, rj))
        b = nets[rtl]["bits"][bit]
        if b not in drv:
            sys.exit("gen_bench_mon: net %r[%d] has no placed driver" % (rtl, bit))
        bel, port = drv[b]
        pin = bel + "/" + port
        if pin not in by_pin:
            sys.exit("gen_bench_mon: %r -> %s not in %s" % (rtl, pin, nmap))
        return "tb_ps.dut." + by_pin[pin], pin

    sig = {k: wire("bridge_i." + k) for k in
           ("aclk", "req_core", "i_ack_pl", "o_req_pl", "bench_o_ack", "o_req_s")}
    st = [wire("bridge_i.st", i) for i in range(3)]
    L = ["// GENERATED by cells/gls/ps/gen_bench_mon.py for one route -- do not check in."]
    L += ["// %s = %s" % (k, p) for k, (_, p) in sig.items()]
    L += ["// st[%d] = %s" % (i, p) for i, (_, p) in enumerate(st)]
    L += ["`timescale 1ps/1ps", "module bench_mon;"]
    L += ["    wire %s = %s;" % (k, w) for k, (w, _) in sig.items()]
    L += ["    wire [2:0] st = {%s};" % ", ".join(w for w, _ in reversed(st))]
    L += ["""    integer n = 0, ntrace, nill = 0, cyc = 0, c_issue = 0, c_ack = 0, c_next = 0, c_res = 0;
    reg [2:0] s_prev = 0, s_now;
    time t_clk = 0, t_issue = 0, t_iack = 0, t_oreq = 0, t_oack = 0, t_ofall = 0, ph_i = 0, ph_o = 0;
    reg have = 0;
    time t_sfall = 0;
    initial begin ntrace = 2; if ($value$plusargs("BTRACE=%d", ntrace)) ; end
    function legal(input [2:0] a, input [2:0] b);
        legal = (a == b) ? (a == 0 || a == 1 || a == 3 || a == 4 || a == 6)
              : ((a == 0 && b == 1) || (a == 1 && b == 2) || (a == 2 && b == 3) || (a == 3 && b == 4) ||
                 (a == 4 && b == 5) || (a == 5 && b == 6) || (a == 6 && b == 7) || (a == 7 && b == 1) ||
                 (a == 7 && b == 0));
    endfunction
    always @(posedge aclk) begin
        t_clk = $time; cyc = cyc + 1;
        #3000;
        s_now = st;
        if (s_now !== s_prev) begin
            if (n < ntrace) $display("BST t=%0t st=%0d", $time, s_now);
            if (s_now == 3'd2) c_issue = cyc;
            if (s_now == 3'd5) c_ack = cyc;
            if (s_prev == 3'd7) c_next = cyc;
        end
        if (^s_now === 1'bx || !legal(s_prev, s_now)) begin
            nill = nill + 1;
            if (nill <= 20) $display("BILL t=%0t st=%0d->%0b run=%0d", $time, s_prev, s_now, n);
        end
        s_prev = s_now;
    end
    always @(posedge req_core) begin
        if (have) $display("BRUN n=%0d t_issue=%0t iack=%0d oreq=%0d oack_to_oreq_fall=%0d oreq_fall_to_s=%0d iack_ph=%0d oreq_ph=%0d cyc_res=%0d cyc_tail=%0d",
                           n, t_issue, t_iack - t_issue, t_oreq - t_issue, t_ofall - t_oack, t_sfall - t_ofall,
                           ph_i, ph_o, c_ack - c_res, c_next - c_ack);
        if (have) n = n + 1;
        have = 1; t_issue = $time; c_res = c_issue;
    end
    always @(posedge i_ack_pl) begin t_iack = $time; ph_i = $time - t_clk; end
    always @(posedge o_req_pl) begin t_oreq = $time; ph_o = $time - t_clk; end
    always @(posedge bench_o_ack) t_oack = $time;
    always @(negedge o_req_pl) t_ofall = $time;
    always @(negedge o_req_s) t_sfall = $time;
endmodule"""]
    open(out, "w").write("\n".join(L) + "\n")
    print("bench monitor: %s -> %s" % (", ".join("%s %s" % (k, p) for k, (_, p) in sig.items()), out))


if __name__ == "__main__":
    main()
