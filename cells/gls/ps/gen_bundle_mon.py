#!/usr/bin/env python3
"""gen_bundle_mon.py -- a bundling monitor on gcd_ps's kernel boundary (out0), for one route.

    python3 cells/gls/ps/gen_bundle_mon.py ROUTED_JSON NETS_MAP OUT.v

WHY.  gcd_ps's host reads O_DATA at least two FCLK0 periods after out0_req
rises (the 2-flop synchronizer, then an AXI read), so a result that settles
AFTER its request is still read correctly: the PS harness cannot see an
out0 bundling violation at all.  (Measured: umux21, which drives out0, cut
to 1 link still gives 24/24.)  This monitor looks at the kernel boundary
itself, where the bundled-data contract (and formal's theorem) lives:

  BUNDLE_REQ  n=.. margin=<ps>   at each out0_req rise: time since out0_data
                                 last changed (negative is impossible; small
                                 is the warning)
  BUNDLE_LATE ... <ps> after     out0_data changed while out0_req was high and
                                 the host had not yet acknowledged (ctrl_o_ack
                                 low): a bundling violation
  (each BUNDLE_REQ line also carries the running count of BUNDLE_LATE events)

The nets are taken at their DRIVER pins in the netlist decoded from the
bitstream (fasm2net names nets <site>/<bel>/<pin>); routing from there to the
consumer is not included, for the request or the data.

The driver of each RTL net is looked up in nextpnr's routed JSON
(NEXTPNR_BEL + port), then found in nets.map; a net that cannot be found is
an error, not a silent omission.
"""
import json, sys

def main():
    rj, nmap, out = sys.argv[1:4]
    m = list(json.load(open(rj))["modules"].values())[0]
    nets, cells = m["netnames"], m["cells"]
    drv = {}
    for c in cells.values():
        bel = c["attributes"].get("NEXTPNR_BEL")
        for p, d in c.get("port_directions", {}).items():
            if d == "output" and bel:
                for b in c["connections"][p]:
                    drv[b] = (bel, p)
    by_pin = {}
    for line in open(nmap):
        if line.startswith("#"):
            continue
        w, _, n = line.strip().partition(" ")
        by_pin.setdefault(n, w)

    def wire(rtl):
        if rtl not in nets:
            sys.exit("gen_bundle_mon: no net %r in %s" % (rtl, rj))
        b = nets[rtl]["bits"][0]
        if b not in drv:
            sys.exit("gen_bundle_mon: net %r has no placed driver" % rtl)
        bel, port = drv[b]
        pin = bel + "/" + {"O6": "O6", "O5": "O5", "Q": "Q"}.get(port, port)
        if pin not in by_pin:
            sys.exit("gen_bundle_mon: %r -> %s not in %s" % (rtl, pin, nmap))
        return "tb_ps.dut." + by_pin[pin], pin

    req, rpin = wire("core_o_req")
    ack, apin = wire("bridge_i.ctrl_o_ack")
    data = [wire("bridge_i.o_data_pl[%d]" % i) for i in range(32)]
    L = ["// GENERATED by cells/gls/ps/gen_bundle_mon.py for one route -- do not check in.",
         "// out0_req = core_o_req @ %s; host ack = bridge_i.ctrl_o_ack @ %s" % (rpin, apin),
         "`timescale 1ps/1ps",
         "module bundle_mon;",
         "    wire req = %s;" % req,
         "    wire ack = %s;" % ack,
         "    wire [31:0] data = {%s};" % ", ".join(w for w, _ in reversed(data)),
         "    time t_data = 0, t_req = 0;",
         "    integer nreq = 0, nlate = 0, minm = 2147483647;",
         "    always @(data) begin",
         "        if (req === 1'b1 && ack !== 1'b1) begin",
         "            nlate = nlate + 1;",
         "            if (nlate <= 20) $display(\"BUNDLE_LATE out0_data changed %0d ps after out0_req rose (t=%0t data=%08h)\",",
         "                                      $time - t_req, $time, data);",
         "        end",
         "        t_data = $time;",
         "    end",
         "    always @(posedge req) begin",
         "        nreq = nreq + 1; t_req = $time;",
         "        if ($time - t_data < minm) minm = $time - t_data;",
         "        $display(\"BUNDLE_REQ n=%0d margin=%0d ps data=%08h t=%0t late_so_far=%0d\", nreq, $time - t_data, data, $time, nlate);",
         "    end",
         "endmodule"]
    open(out, "w").write("\n".join(L) + "\n")
    print("bundle monitor: req %s, ack %s, 32 data bits -> %s" % (rpin, apin, out))

if __name__ == "__main__":
    main()
