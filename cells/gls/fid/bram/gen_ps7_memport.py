#!/usr/bin/env python3
"""gen_ps7_memport.py -- writes ps7_memport.v (next to this file): a behavioural
PS7_PS7 for the GLS of cells/hw/mem_port_ps.v, the RAMB18E1 self-test of
cells/gls/fid/bram/README.md.  The AXI master is gen_ps7.py's own task text and
the port list is ps7_pins.py's, so it plugs into cells/gls/ps/build_ps.sh as
PS_HOST=../fid/bram/ps7_memport.v exactly like ps7_bench.v.

The program: release mem_port_ps's ctrl_rst (CTRL 0x00 = 0), which starts its
BIST (bd_mem through its real handshake: 33 write+read passes over all 1024
words -- walking 1, walking 0, address = data -- then SPD_N timed reads), poll
STATUS (0x04) until port_done or +TMEM=<ns>, then print one MEMPORT line:
done, run_pass / edge_pass (the synchronized and the raw-ack-edge checkers),
both mismatch counts, the first failure of each, and the progress word.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "ps"))
import gen_ps7, ps7_pins  # noqa: E402

PROG = r'''
    localparam integer TCO = 100;
    localparam [11:0] ID = 12'h3E7;
    reg fclk = 1'b0;
    integer fclk_ps, tmem_ns, idmis;
    reg        aresetn = 1'b0;
    reg [31:0] araddr = 0, awaddr = 0, wdata = 0;
    reg [11:0] arid = 0, awid = 0;
    reg [3:0]  wstrb = 0;
    reg        arvalid = 0, awvalid = 0, bready = 0, rready = 0, wvalid = 0;
    reg [31:0] st, mis, emis, faddr, fgot, fexp, fpk, prog, spd, eaddr, egot, eexp;
    reg        timed_out;
    time       t0, tlast;
    initial begin
        fclk_ps = 12000; tmem_ns = 20000000;
        if ($value$plusargs("FCLK_PS=%d", fclk_ps)) ;
        if ($value$plusargs("TMEM=%d", tmem_ns)) ;
    end
    always #(fclk_ps / 2) fclk = ~fclk;

''' + gen_ps7.BODY[gen_ps7.BODY.index("    task automatic edge_;"):gen_ps7.BODY.index("    // poll STATUS")] + r'''
    // mem_port_ps.v's map (5-bit word address): 0x00 CTRL [0]=ctrl_rst, 0x04 STATUS {edge_pass&done,
    // run_pass&done, done, busy, ack_s}, 0x08 mismatch_count, 0x0C fail_addr, 0x10 fail_got,
    // 0x14 fail_expect, 0x18 {fail_k, fail_pat}, 0x1C {addr, k, pat} progress, 0x20 spd_cycles,
    // 0x28 edge_mismatch_count, 0x2C edge_fail_addr, 0x30 edge_fail_got, 0x34 edge_fail_expect.
    initial begin
        idmis = 0; timed_out = 0;
        #1;
        repeat (16) @(posedge MAXIGP0ACLK);
        #(TCO) aresetn = 1'b1;
        repeat (4) @(posedge MAXIGP0ACLK);
        axi_write(32'h00, 32'h1);               // hold the BIST in reset
        repeat (8) @(posedge MAXIGP0ACLK);
        axi_write(32'h00, 32'h0);               // release it: the BIST starts
        t0 = $time; tlast = t0;
        axi_read(32'h04, st);
        while (!st[2] && ($time - t0 < tmem_ns * 1000)) begin
            repeat (400) @(posedge MAXIGP0ACLK);
            axi_read(32'h04, st);
            if ($time - tlast > 1000000000) begin
                axi_read(32'h1C, prog); axi_read(32'h08, mis); axi_read(32'h28, emis);
                $display("MEMPROG t=%0t pat=%0d k=%0d addr=%0d mismatch=%0d edge_mismatch=%0d",
                         $time, prog[1:0], prog[5:2], prog[25:16], mis, emis);
                tlast = $time;
            end
        end
        axi_read(32'h08, mis);  axi_read(32'h0C, faddr); axi_read(32'h10, fgot); axi_read(32'h14, fexp);
        axi_read(32'h18, fpk);  axi_read(32'h1C, prog);  axi_read(32'h20, spd);
        axi_read(32'h28, emis); axi_read(32'h2C, eaddr); axi_read(32'h30, egot); axi_read(32'h34, eexp);
        $display("MEMPORT done=%0d run_pass=%0d edge_pass=%0d mismatch=%0d edge_mismatch=%0d first_fail addr=%0d got=%04h exp=%04h pat=%0d k=%0d edge_first_fail addr=%0d got=%04h exp=%04h spd_cycles=%0d progress=%08h id_mismatch=%0d t=%0t %0s",
                 st[2], st[3], st[4], mis, emis, faddr, fgot[15:0], fexp[15:0], fpk[1:0], fpk[5:2],
                 eaddr, egot[15:0], eexp[15:0], spd, prog, idmis, $time, st[2] ? "DONE" : "TIMEOUT");
        $finish;
    end
'''


def main():
    out = os.path.join(HERE, "ps7_memport.v")
    ports = ["    output %s" % p for p in ps7_pins.OUTPUTS] + ["    input  %s" % p for p in ps7_pins.INPUTS]
    lines = ["// GENERATED by cells/gls/fid/bram/gen_ps7_memport.py -- do not edit.",
             "// A behavioural PS7_PS7 for the GLS of cells/hw/mem_port_ps.v (the RAMB18E1 self-test).",
             "`timescale 1ps/1ps", "module PS7_PS7 (", ",\n".join(ports), ");"]

    def bus_in(name, w, reg):
        lines.append("    wire [%d:0] %s = {%s};" % (w - 1, reg, ", ".join("%s%d" % (name, i) for i in reversed(range(w)))))
    bus_in("MAXIGP0BID", 12, "bid_i"); bus_in("MAXIGP0RDATA", 32, "rdata_i"); bus_in("MAXIGP0RID", 12, "rid_i")
    lines.append("    wire bvalid_i = MAXIGP0BVALID, rvalid_i = MAXIGP0RVALID;")
    lines.append(PROG)
    outs = {"MAXIGP0ARADDR": "araddr", "MAXIGP0ARID": "arid", "MAXIGP0AWADDR": "awaddr", "MAXIGP0AWID": "awid",
            "MAXIGP0WDATA": "wdata", "MAXIGP0WSTRB": "wstrb"}
    for name, reg in outs.items():
        for i in range(gen_ps7.BUSES[name]):
            lines.append("    assign %s%d = %s[%d];" % (name, i, reg, i))
    for p, r in [("FCLKCLK0", "fclk"), ("FCLKCLK1", "1'b0"), ("FCLKCLK2", "1'b0"), ("FCLKCLK3", "1'b0"),
                 ("MAXIGP0ARESETN", "aresetn"), ("MAXIGP0ARVALID", "arvalid"), ("MAXIGP0AWVALID", "awvalid"),
                 ("MAXIGP0BREADY", "bready"), ("MAXIGP0RREADY", "rready"), ("MAXIGP0WVALID", "wvalid")]:
        lines.append("    assign %s = %s;" % (p, r))
    lines.append("endmodule")
    open(out, "w").write("\n".join(lines) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
