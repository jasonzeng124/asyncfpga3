#!/usr/bin/env python3
"""Shard B: generate Formal/Cells/CElemWinViewPS/Bxx.lean and Formal/Cells/CElemWinViewPS.lean: celemtab.py's C-element rows
with every pin's copy chain and source, checked by CElemWinView.crowOK, and the instance of
CElemWinView.target_celemw_forced. usage: gen_celemwin_ps.py CELEMTAB.json OUTDIR [maxchunks] [maxrows]"""
import json, sys, os
R = json.load(open(sys.argv[1])); R = R["rows"] if isinstance(R, dict) else R; OUT = sys.argv[2]
MAXC = int(sys.argv[3]) if len(sys.argv) > 3 else 12; MAXR = int(sys.argv[4]) if len(sys.argv) > 4 else 20
C = 2500; RST = 186905
bl = lambda l: "[" + ", ".join("true" if b else "false" for b in l) + "]"
nl = lambda l: "[" + ", ".join(str(x) for x in l) + "]"
rows = []
for r in sorted(R, key=lambda r: r["q"]):
    k = r["k"]; ci = [i in r["ci"] for i in range(k)]; pol = [False] * k
    for i, p in zip(r["ci"], r["pol"]): pol[i] = bool(p)
    ov = [False] * k
    for i, v in r["ov"].items(): ov[int(i)] = bool(v)
    pins = ", ".join("(%s, %d)" % (nl(r["chains"][i]), r["srcs"][i]) for i in range(k))
    gates = {r["q"]} | {c for ch in r["chains"] for c in ch} | {s for i, s in enumerate(r["srcs"]) if not ci[i] and i != r["fb"] and i != r["sp"] and s != RST}
    rows.append(("⟨%d, %d, %d, %s, %s, %s, [%s]⟩" % (r["q"], r["fb"], r["sp"], bl(ci), bl(pol), bl(ov), pins), {x // C for x in gates}))
files = []; cur = []; cs = set()
for i, (txt, ch) in enumerate(rows):
    if cur and (len(cs | ch) > MAXC or len(cur) >= MAXR): files.append((cur, cs)); cur = []; cs = set()
    cur.append(i); cs |= ch
if cur: files.append((cur, cs))
D = os.path.join(OUT, "CElemWinViewPS"); os.makedirs(D, exist_ok=True)
for fi, (idx, cs) in enumerate(files):
    body = ["import Formal.Cells.CElemWinView", "",
            "/-! GENERATED by tools-B/ps/gen_celemwin_ps.py: rows %d-%d (%d netlist chunks). -/" % (idx[0], idx[-1], len(cs)), "",
            "namespace Formal.Cells.CElemWinViewPS", "open Formal.Cells.CElemWinView", "",
            "set_option maxRecDepth 100000 in", "def rows%02d : List CRow := [" % fi]
    body.append(",\n".join("  " + rows[i][0] for i in idx) + "]")
    body += ["", "set_option maxHeartbeats 0 in", "set_option maxRecDepth 100000 in",
             "theorem rows%02d_ok : rows%02d.all crowOK = true := by decide +kernel" % (fi, fi), "", "end Formal.Cells.CElemWinViewPS", ""]
    open(os.path.join(D, "B%02d.lean" % fi), "w").write("\n".join(body))
nf = len(files)
top = ["import Formal.Cells.CElemWinViewPS.B%02d" % i for i in range(nf)]
top += ["", "/-!", "# Formal.Cells.CElemWinViewPS — THE target's mux joins switch only when forced while their select is held",
        "(GENERATED by tools-B/ps/gen_celemwin_ps.py)", "",
        "`allRows` (%d mux joins of `DecodedPS.net`, from the untrusted muxjtab.py, each with every pin's copy chain and" % len(rows),
        "source) passes `CElemWinView.crowOK` (kernel `decide`). `target_ps_muxj_forced` is `CElemWinView.target_celemw_forced`",
        "for them: in every behaviour of THE circuit (any `0 ≤ κ ≤ 1`, `g > 0`), at its corner, every listed C-element, given",
        "its environment hypothesis `hA`, the timing premises (with the summed integer window ends of its own routed",
        "pins), the reset held low and a quiet start, switches only when forced, with separated toggles.",
        "Not covered: `hA` and the timing premises themselves; C-elements the classifier missed.", "-/", "",
        "namespace Formal.Cells.CElemWinViewPS", "open Formal.Cells.CElemWinView", "",
        "set_option maxRecDepth 100000 in", "def allRows : List CRow := " + " ++ ".join("rows%02d" % i for i in range(nf)), "",
        "set_option maxRecDepth 100000 in", "theorem allRows_ok : allRows.all crowOK = true := by",
        "  simp only [allRows, List.all_append, " + ", ".join("rows%02d_ok" % i for i in range(nf)) + ", Bool.and_self]", "",
        "set_option maxRecDepth 100000 in", "theorem allRows_length : allRows.length = %d := by decide" % len(rows), "",
        "/-- **THE target's mux joins switch only when forced while the select is held** (see `CElemWinView.target_celemw_forced`). -/",
        "theorem target_ps_muxj_forced : type_of% (@target_celemw_forced allRows allRows_ok) :=", "  @target_celemw_forced allRows allRows_ok", "",
        "end Formal.Cells.CElemWinViewPS", ""]
open(os.path.join(OUT, "CElemWinViewPS.lean"), "w").write("\n".join(top))
print("rows", len(rows), "files", nf)
