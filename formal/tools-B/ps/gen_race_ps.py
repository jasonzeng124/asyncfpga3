#!/usr/bin/env python3
"""Shard B: generate, for THE target gcd_ps, (1) Formal/Cells/RaceStaticPS.lean: the arcs of the tightest storage node's
episode path and feedback loop (from tools-B/ps/kadv.py's .arcs.json) and its static race margin at Spec's Adm window
ends, decided exactly; (2) Formal/Cells/TargetLinkPS.lean: those arcs, and ArbCleanPS.targetQPS, tied to
Formal.Target.DecodedPS.net by equalities decided on the netlist. Untrusted generator; the Lean checks the data.
usage: gen_race_ps.py NET.json ARBS.json BND.json ARCS.json KHOLD KFAIL OUTDIR   (κ as e.g. 435/1000 440/1000)"""
import sys, os, json, math
from fractions import Fraction as F
HERE = os.path.dirname(os.path.abspath(__file__)); TB = os.path.join(HERE, "..", "target")
NETF, ARBF, BNDF, ARCF, KH, KF, OUT = sys.argv[1:8]
N = json.load(open(NETF)); g = N["gates"]; A = json.load(open(ARCF))
gi = A["node"]; path = [tuple(x) for x in A["path"]]; loop = [tuple(x) for x in A["loop"]]; route = A["route"]; fbj = A["fbpin"]
pin = path[-1][1]; assert path[-1][0] == gi and loop[-1] == (gi, fbj)
name = g[gi]["name"]
sys.argv = [sys.argv[0], NETF, ARBF, BNDF, "0,1"]
src = open(os.path.join(TB, "adv.py")).read(); src = src[:src.index('base, res0 = run({}, "base")')]
ns = {"__file__": os.path.join(TB, "adv.py")}; exec(compile(src, "adv.py", "exec"), ns)
qidx = [ns["roles"](a)["q"] for a in ns["A"]]
kh = F(KH); kf = F(KF); c = F(1, 2)
def lerp(a, b): return (1 - c) * a + c * b
def lo(e, k): return math.ceil((1 - k) * lerp(e["fmin"], e["smin"]))
def hi(e, k): return math.floor((1 + k) * lerp(e["fmax"], e["smax"]))
ar = lambda m, p: g[m]["arcs"][p]
nums = (sum(lo(ar(*x), kh) for x in path), sum(hi(ar(*x), kh) for x in loop), sum(lo(ar(*x), kf) for x in path), sum(hi(ar(*x), kf) for x in loop))
assert nums[1] <= nums[0] and nums[2] < nums[3], nums
fmt = lambda l: "[" + ", ".join("⟨%d, %d, %d, %d⟩" % tuple(ar(m, p)[k] for k in ("fmin", "fmax", "smin", "smax")) for m, p in l) + "]"
qs = lambda k: "(%d/%d)" % (k.numerator, k.denominator)
open(os.path.join(OUT, "RaceStaticPS.lean"), "w").write("""import Formal.Cells.Ua1Static

/-!
# Formal.Cells.RaceStaticPS — the tightest C-element race of THE target gcd_ps, at Spec's own window ends

Shard B, THE goal, S3. GENERATED by tools-B/ps/gen_race_ps.py.

## Problem, plainly
Storage node `%s` (gate %d of `Formal.Target.DecodedPS.net`; the routed cell
`ulink_n_falseResult_85.many.stage[0].u.ctl.u.u`, a link controller C-element) is the node with the
smallest static race margin found by B's scan (16 rig + 16 full-width vectors, corner 0.5): its tightest
flipping episode is ended by a causal path that starts at its own output and comes back to its pin %d
(%d arcs), while its own new value comes round its feedback loop to pin %d (%d arcs). If, with every delay
inside Spec's `Adm` window (g = 1, corner 1/2, scatter κ), the path can be faster than the loop, the node
can latch a runt (`SpecFb.fb_runt_oscillates`; seen in simulation).

## Results (decided on the generated arc data, integer ps)
* `race_holds`: at κ = %s the path's smallest admissible total (%d ps) is at least the loop's largest
  (%d ps): fb_switch's timing premise holds for this episode under every admissible delay.
* `race_fails`: at κ = %s the path's smallest total (%d ps) is below the loop's largest (%d ps).
Simulation with the same per-pin choice (tools-B/ps/kadv.py map): clean at κ = 0.435, runt at 0.44.

## Not covered
That the episode is ended by this path in every behaviour (causality: a network fact); that no other node
or episode binds at a smaller κ (the scan is simulation over 32 vectors, one corner); the dynamics. The
link of these arcs to `DecodedPS.net` is in `TargetLinkPS`.
-/

namespace Formal.Cells.RaceStaticPS
open Formal.Target Formal.Cells.Ua1Static

def racePath : List Arc := %s
def raceLoop : List Arc := %s

def pathLo (g κ c : ℚ) : Int := (racePath.map (lo g κ c)).sum
def loopHi (g κ c : ℚ) : Int := (raceLoop.map (hi g κ c)).sum

theorem race_holds : loopHi 1 %s (1/2) ≤ pathLo 1 %s (1/2) := by decide +kernel
theorem race_fails : pathLo 1 %s (1/2) < loopHi 1 %s (1/2) := by decide +kernel
theorem race_numbers : pathLo 1 %s (1/2) = %d ∧ loopHi 1 %s (1/2) = %d ∧
    pathLo 1 %s (1/2) = %d ∧ loopHi 1 %s (1/2) = %d := by decide +kernel

end Formal.Cells.RaceStaticPS
""" % (name, gi, pin, len(path), fbj, len(loop), float(kh), nums[0], nums[1], float(kf), nums[2], nums[3], fmt(path), fmt(loop),
       qs(kh), qs(kh), qs(kf), qs(kf), qs(kh), nums[0], qs(kh), nums[1], qs(kf), nums[2], qs(kf), nums[3]))
# ---- TargetLinkPS
C = 2500; NCH = (len(g) + C - 1) // C
out = ["""import Formal.Target.NetPS.All
import Formal.Cells.ArbCleanPS
import Formal.Cells.RaceStaticPS
import Formal.Cells.SpecFbChain

/-!
# Formal.Cells.TargetLinkPS — B's gcd_ps data, tied to shard A's Lean netlist (GENERATED by tools-B/ps/gen_race_ps.py)

`ArbCleanPS.targetQPS` (the nine ustates' names, tables, pin counts) and `RaceStaticPS.racePath`/`raceLoop` were
generated from a JSON rebuild of `Formal/Target/NetPS`. Here each is proved equal to the corresponding gate or arc
of `Formal.Target.DecodedPS.net`, and the path and loop are shown wired as claimed, so `targetQPS_facts` and
`race_holds`/`race_fails` are statements about the netlist THE theorem is about. Not re-derived: the roles of the
ustate pins (generator's table analysis; `targetQPS_facts` checks the facts they are used for).
-/

namespace Formal.Cells.TargetLinkPS

open Formal.Target Formal.Target.DecodedPS

/-- Gate `i` of the decoded gcd_ps netlist. -/
def gate (i : Nat) : Gate := net.gates.getD i default

theorem getD_skip {α : Type} (l1 l2 : List α) (h : l1.length = 2500) (i : Nat) (d : α) :
    (l1 ++ l2).getD (i + 2500) d = l2.getD i d := by
  simp only [List.getD_eq_getElem?_getD]
  rw [List.getElem?_append_right (by omega)]
  congr 2; omega

theorem getD_left {α : Type} (l1 l2 : List α) (i : Nat) (hi : i < l1.length) (d : α) :
    (l1 ++ l2).getD i d = l1.getD i d := by
  simp only [List.getD_eq_getElem?_getD]
  rw [List.getElem?_append_left hi]
"""]
used = sorted(set(qidx + [m for m, _ in path + loop]))
for i in used:
    k, j = divmod(i, C)
    skips = ", ".join("getD_skip _ _ g%03d_len" % cc for cc in range(k))
    idx = "%d" % j + " + 2500" * k
    tail = "" if k == NCH - 1 else "\n  rw [getD_left _ _ _ (by rw [g%03d_len]; omega)]" % k
    out.append("theorem gate_%d : gate %d = (g%03d).getD %d default := by\n  show gates.getD (%s) default = _\n  simp only [gates]%s%s\n" % (
        i, i, k, j, idx, ("\n  rw [" + skips + "]") if k else "", tail))
out.append("/-- The nine ustate O6 gates of `ArbCleanPS.targetQPS` are gates of the decoded netlist, with the same name,\npin count and table. -/")
for r, i in enumerate(qidx):
    G = g[i]
    out.append('theorem q%d : (gate %d).name = "%s" ∧ (gate %d).k = %d ∧ (gate %d).init = %d := by\n  rw [gate_%d]; decide +kernel\n' % (r, i, G["name"], i, G["k"], i, G["init"], i))
def arcl(l): return "[" + ", ".join("(gate %d).arcs.getD %d default" % (m, p) for m, p in l) + "]"
out.append("/-- The arcs of `RaceStaticPS.racePath` and `raceLoop` are the decoded netlist's arcs of these gate pins. -/")
out.append("theorem racePath_eq : Formal.Cells.RaceStaticPS.racePath = %s := by\n  simp only [%s]\n  decide +kernel\n" % (arcl(path), ", ".join("gate_%d" % m for m in sorted(set(m for m, _ in path)))))
out.append("theorem raceLoop_eq : Formal.Cells.RaceStaticPS.raceLoop = %s := by\n  simp only [%s]\n  decide +kernel\n" % (arcl(loop), ", ".join("gate_%d" % m for m in sorted(set(m for m, _ in loop)))))
L = "Formal.Cells.Ua1Static"
out.append("/-- **The race verdicts as statements about the decoded netlist's own arcs.** -/")
out.append("theorem race_holds_decoded :\n    ((%s).map (%s.hi 1 %s (1/2))).sum <=\n      ((%s).map (%s.lo 1 %s (1/2))).sum := by\n  rw [← racePath_eq, ← raceLoop_eq]; exact Formal.Cells.RaceStaticPS.race_holds\n" % (arcl(loop), L, qs(kh), arcl(path), L, qs(kh)))
out.append("theorem race_fails_decoded :\n    ((%s).map (%s.lo 1 %s (1/2))).sum <\n      ((%s).map (%s.hi 1 %s (1/2))).sum := by\n  rw [← racePath_eq, ← raceLoop_eq]; exact Formal.Cells.RaceStaticPS.race_fails\n" % (arcl(path), L, qs(kf), arcl(loop), L, qs(kf)))
arcs = path[:-1]
def wires(l, close):
    return [(m, p, l[k + 1][0] if k + 1 < len(l) else close) for k, (m, p) in enumerate(l)]
pw = [(gi, pin, arcs[0][0])] + wires(arcs, gi)
lw = [(gi, fbj, route[0])] + wires([(m, 0) for m in route], gi)
def wthm(nm, pairs, doc):
    body = " ∧\n    ".join("(gate %d).ins.getD %d 0 = %d" % w for w in pairs)
    lem = ", ".join("gate_%d" % m for m in sorted(set(w[0] for w in pairs)))
    return "/-- %s -/\ntheorem %s :\n    %s := by\n  simp only [%s]\n  decide +kernel\n" % (doc, nm, body, lem)
out.append(wthm("racePath_wired", pw, "The episode path is wired: pin %d of gate %d reads the first listed gate, each listed pin reads the next listed gate's output, and the last reads gate %d's own output." % (pin, gi, gi)))
out.append("/-- The feedback route consists of copy gates (one pin, table 0b10). -/\ntheorem raceLoop_copies :\n    " + " ∧\n    ".join("(gate %d).k = 1 ∧ (gate %d).init = 2" % (m, m) for m in route) + " := by\n  simp only [%s]\n  decide +kernel\n" % ", ".join("gate_%d" % m for m in route))
out.append(wthm("raceLoop_wired", lw, "The feedback loop is wired: pin %d reads a chain of copy gates that starts at gate %d's own output." % (fbj, gi)))
# the race node's pin chains (feedback pin: its route; other pins: empty chains) and the loop bound
G = g[gi]
pcs = ", ".join(("⟨%d, [%s]⟩" % (gi, ", ".join("gate %d" % r for r in route))) if i == fbj else ("⟨%d, []⟩" % G["ins"][i]) for i in range(G["k"]))
hl = sum(hi(ar(*x), kh) for x in loop)
lem = ", ".join("gate_%d" % m for m in sorted(set([gi] + route)))
out.append("""/-- Pin chains of gate %d: the feedback pin %d reads the gate's own output through its route of copy gates;
the other pins read their pin nodes directly. -/
def racePcs : List Formal.Timing.SpecChain.PinChain := [%s]

/-- The chains are wired as listed (shard C's per-gate check `pinsOK`, decided on the netlist). -/
theorem race_pinsOK : Formal.Timing.SpecChain.pinsOK (gate %d) racePcs = true := by
  simp only [racePcs, %s]
  decide +kernel

/-- The composite feedback arcs (pin arc, then the route) have window-end sum %d ps at κ = %s, corner 1/2. -/
theorem race_loop_hi :
    ((Formal.Timing.SpecChain.pinArcs (gate %d) racePcs %d).map (%s.hi 1 %s (1/2))).sum = %d := by
  simp only [racePcs, Formal.Timing.SpecChain.pinArcs, %s]
  decide +kernel

/-- **In every behaviour at g = 1, κ = %s, corner 1/2, node %d's routed feedback delay is at most %d ps**:
every composite delay its feedback pin can have (one admissible delay per arc, `SumAdm`) is bounded. With C's
`SpecChain.collapse` and `SpecFbChain.cfb_switch`, a set condition lasting %d ps switches the node cleanly. -/
theorem race_loop_delay_le {D : Nat}
    (h : Formal.Timing.SpecChain.SumAdm ⟨1, %s⟩ (1/2) (Formal.Timing.SpecChain.pinArcs (gate %d) racePcs %d) D) :
    D ≤ %d := by
  have := (Formal.Cells.SpecFbChain.sumAdm_bounds _ D h).2
  have e := race_loop_hi
  simp only at this
  omega
""" % (gi, fbj, pcs, gi, lem, hl, qs(kh), gi, fbj, L, qs(kh), hl, lem, float(kh), gi, hl, hl, qs(kh), gi, fbj, hl))
out.append("end Formal.Cells.TargetLinkPS")
open(os.path.join(OUT, "TargetLinkPS.lean"), "w").write("\n".join(out) + "\n")
print("node", name, gi, "numbers", nums, "used gates", len(used))
