#!/usr/bin/env python3
"""Shard B: generate Formal/Cells/RaceLinkPS.lean: every arc of every row of RaceTablePS.raceTable is the arc of the
listed (gate, pin) of Formal.Target.DecodedPS.net (via a generic chunk-lookup lemma), and the listed pins are wired
(each path pin reads the next listed gate; the path ends at the row's node; the loop is the node's own copy-gate
route). usage: gen_racelink_ps.py PINS.json NCHUNKS OUT.lean"""
import sys, json
R = json.load(open(sys.argv[1])); n = int(sys.argv[2]); OUT = sys.argv[3]
pl = lambda l: "[" + ", ".join("(%d, %d)" % (m, p) for m, p in l) + "]"
out = ["""import Formal.Target.NetPS.All
import Formal.Cells.RaceTablePS

/-!
# Formal.Cells.RaceLinkPS — RaceTablePS's rows are arcs of THE target's Lean netlist (GENERATED by tools-B/ps/gen_racelink_ps.py)

## Problem, plainly
`RaceTablePS.raceTable` (185 acknowledgement races of gcd_ps) carries arc data copied by an untrusted generator.
Are those arcs exactly the arcs of the claimed gate pins of `Formal.Target.DecodedPS.net`, and are the claimed
paths and loops actually wired that way in the netlist?

## Results
* `cat_get` (generic): indexing a right-nested concatenation of equal-length chunks (the shape of the generated
  `gates`) is indexing chunk `i / C` at `i % C`.
* `arcAt_eq`: so `arcAt i p` (chunk lookup) is the arc of pin `p` of gate `i` of `DecodedPS.net`.
* `rows_arcs`: every row's path and loop arcs are `arcAt` of the listed pins (kernel `decide`).
* `rows_wired`: in every row, the node's end pin reads the first listed path gate, each listed path pin reads the
  next listed gate's output and the last reads the node's own output (a closed causal path); the loop is the node's
  feedback pin reading a chain of copy gates (k = 1, table 0b10) that starts at the node's output.
-/

namespace Formal.Cells.RaceLinkPS
open Formal.Target Formal.Target.DecodedPS

def cat {α : Type} : List (List α) → List α
  | [] => []
  | [c] => c
  | c :: c' :: cs => c ++ cat (c' :: cs)

theorem cat_get {α : Type} (C : Nat) (hC : 0 < C) :
    ∀ (cs : List (List α)), (∀ c ∈ cs.dropLast, c.length = C) → (∀ c ∈ cs.getLast?, c.length ≤ C) →
      ∀ i, (cat cs)[i]? = (cs.getD (i / C) [])[i % C]?
  | [], _, _, i => by simp [cat]
  | [c], _, hl, i => by
    have hc : c.length ≤ C := hl c (by simp)
    simp only [cat]
    by_cases h : i < C
    · rw [Nat.div_eq_of_lt h, Nat.mod_eq_of_lt h]; simp
    · have h1 : 1 ≤ i / C := (Nat.le_div_iff_mul_le hC).2 (by omega)
      obtain ⟨j, hj⟩ : ∃ j, i / C = j + 1 := ⟨i / C - 1, by omega⟩
      rw [hj, List.getElem?_eq_none (by omega)]
      simp
  | c :: c' :: cs, hf, hl, i => by
    have hc : c.length = C := hf c (by simp)
    have ih := cat_get C hC (c' :: cs) (fun x hx => hf x (by simp [List.dropLast] at hx ⊢; exact Or.inr hx))
      (fun x hx => hl x (by simpa using hx))
    simp only [cat]
    by_cases h : i < C
    · rw [List.getElem?_append_left (by omega), Nat.div_eq_of_lt h, Nat.mod_eq_of_lt h]; simp
    · obtain ⟨j, rfl⟩ := Nat.exists_eq_add_of_le (Nat.le_of_not_lt h)
      rw [List.getElem?_append_right (by omega), hc, Nat.add_sub_cancel_left, ih j,
        Nat.add_div_left _ hC, Nat.add_mod_left]
      simp
"""]
out.append("def chunks : List (List Gate) := [%s]\n" % ", ".join("g%03d" % c for c in range(n)))
out.append("""set_option maxRecDepth 100000 in
theorem gates_cat : gates = cat chunks := by simp only [gates, chunks, cat]

theorem chunks_full : ∀ c ∈ chunks.dropLast, c.length = 2500 := by decide +kernel
theorem chunks_last : ∀ c ∈ chunks.getLast?, c.length ≤ 2500 := by decide +kernel

/-- Gate `i` of the netlist, looked up chunk-wise. -/
def gateAt (i : Nat) : Gate := (chunks.getD (i / 2500) []).getD (i % 2500) default
def arcAt (i p : Nat) : Arc := (gateAt i).arcs.getD p default

theorem gateAt_eq (i : Nat) : gateAt i = net.gates.getD i default := by
  show _ = gates.getD i default
  simp only [gateAt, List.getD_eq_getElem?_getD, gates_cat, cat_get 2500 (by decide) chunks chunks_full chunks_last i]

theorem arcAt_eq (i p : Nat) : arcAt i p = (net.gates.getD i default).arcs.getD p default := by
  simp only [arcAt, gateAt_eq]
""")
out.append("set_option maxHeartbeats 0 in\nset_option maxRecDepth 100000 in\n/-- (node gate, path pins, loop pins) of each row, in `raceTable`'s order. -/\ndef rowPins : List (Nat × List (Nat × Nat) × List (Nat × Nat)) := [\n  " +
           ",\n  ".join("(%d, %s, %s)" % (r["gate"], pl(r["path"]), pl(r["loop"])) for r in R) + "]\n")
out.append("""set_option maxHeartbeats 0 in
set_option maxRecDepth 100000 in
theorem rows_arcs : Formal.Cells.RaceTablePS.raceTable.map (fun r => (r.gate, r.path, r.loop)) =
    rowPins.map (fun q => (q.1, q.2.1.map (fun x => arcAt x.1 x.2), q.2.2.map (fun x => arcAt x.1 x.2))) := by
  decide +kernel

/-- Each listed pin reads the next listed gate's output; the last listed pin reads `node`. -/
def chainTo (node : Nat) : List (Nat × Nat) → Bool
  | [] => true
  | [x] => (gateAt x.1).ins.getD x.2 0 == node
  | x :: y :: rest => (gateAt x.1).ins.getD x.2 0 == y.1 && chainTo node (y :: rest)

/-- A list `[..., (node, j)]` (listed end-first, as the generator writes paths and loops): `node`'s pin `j` reads
the first listed gate, and the chain closes at `node`'s own output. -/
def endWired (node : Nat) (l : List (Nat × Nat)) : Bool :=
  match l.getLast? with
  | some (g, j) => g == node &&
      (match l.dropLast with
       | [] => (gateAt g).ins.getD j 0 == node
       | x :: _ => (gateAt g).ins.getD j 0 == x.1 && chainTo node l.dropLast)
  | none => false

def rowWired (q : Nat × List (Nat × Nat) × List (Nat × Nat)) : Bool :=
  endWired q.1 q.2.1 && endWired q.1 q.2.2 &&
    q.2.2.dropLast.all (fun x => x.2 == 0 && (gateAt x.1).k == 1 && (gateAt x.1).init == 2)

set_option maxHeartbeats 0 in
set_option maxRecDepth 100000 in
theorem rows_wired : rowPins.all rowWired = true := by decide +kernel

end Formal.Cells.RaceLinkPS""")
open(OUT, "w").write("\n".join(out) + "\n")
print("rows", len(R))
