#!/usr/bin/env python3
"""Shard B: generate Formal/Cells/PrimsPS.lean: every gate of Formal.Target.DecodedPS.net is a constant, a copy gate,
a LUT6/LUT5 table, a 2:1 mux (0xCA) or a CARRY4 output with shard A's carry table, checked chunk by chunk on the
netlist; with PrimTables, the mux and carry tables are Core's models. usage: gen_prims_ps.py NCHUNKS OUT.lean"""
import sys
n = int(sys.argv[1]); out = []
out.append("""import Formal.Target.NetPS.All
import Formal.Cells.PrimTables

/-!
# Formal.Cells.PrimsPS — H_PRIM coverage: every gate of THE target's decoded netlist is a modelled primitive

Shard B, THE goal (target gcd_ps_e6bb4aec). GENERATED by tools-B/ps/gen_prims_ps.py.

## Problem, plainly
H_PRIM says each primitive behaves as its Core model. Which primitives does THE target's decoded Lean netlist
actually contain, and are the tables the decoder gave the non-LUT ones exactly Core's models?

## Results (decided on `Formal.Target.DecodedPS.net`, chunk by chunk)
* `kinds`: every one of its 186,873 gates is one of: a constant (`k = 0`, table 0 or 1); a copy gate (`k = 1`,
  table `0b10`: a pip, wire or site hop); a 2:1 mux (`k = 3`, table `0xCA`: MUXF7/MUXF8); a CARRY4 output with
  the table of shard A's decoder layout for one of the 8 outputs (`carryTab`, proved equal to
  `PrimTables.aCarryInit`); a 5-pin table below `2^32` (LUT6_2 O5) or a 6-pin table below `2^64` (LUT6 / O6).
* `prim_cover`: hence, for every gate of the netlist, its Spec table read is Core's model: copy = identity,
  mux = Core `bmux` (`PrimTables.muxf_gate`), carry outputs = Core `Carry.bout` on the mapped pins
  (`PrimTables.aCarry_gate`), and LUTs are LUT tables (any INIT; `PrimTables.lut6_gate`/`lut5_gate` give Core's
  `Lut.eval` for the LUT6_2 that holds them). No other kind of gate (FF, latch, DSP, RAM) is in the netlist.

## Not covered
Whether a 5/6-pin gate is physically a LUT rather than a CARRY4 output is not distinguished here (both are
table gates; the carry tables happen to have 5 or 6 pins for O1/CO1, and are then counted under either
disjunct); the decoder's choice of pins and tables (H_DECODE, shard A's round trip); timing.
-/

namespace Formal.Cells.PrimsPS
open Formal.Target Formal.Target.DecodedPS Formal.Cells.PrimTables

/-- (k, table) of the 8 CARRY4 outputs in shard A's decoder layout: O0..O3, then CO0..CO3. -/
def carryTab : List (Nat × Nat) := [""")
tabs = []
def aK(co, i): return 2 + (i + 1) + ((i + 1) if co else i)
def F(co, i, a):
    v = lambda q: (a >> q) & 1; s = lambda j: v(2 + j); di = lambda j: v(3 + i + j)
    cc = v(0) | v(1)
    for j in range(i): cc = cc if s(j) else di(j)
    return (cc if s(i) else di(i)) if co else (s(i) ^ cc)
for co in (False, True):
    for i in range(4):
        k = aK(co, i); tabs.append("(%d, 0x%x)" % (k, sum(1 << a for a in range(2 ** k) if F(co, i, a))))
out[-1] += ",\n  ".join(tabs) + "]\n"
out.append("""/-- The listed tables are `aCarryInit` (A's loop, transcribed in PrimTables). -/
theorem carryTab_eq : carryTab = [(aK false 0, aCarryInit false 0), (aK false 1, aCarryInit false 1),
    (aK false 2, aCarryInit false 2), (aK false 3, aCarryInit false 3), (aK true 0, aCarryInit true 0),
    (aK true 1, aCarryInit true 1), (aK true 2, aCarryInit true 2), (aK true 3, aCarryInit true 3)] := by
  decide +kernel

/-- The kinds of gate the netlist may contain. -/
def kindOK (g : Gate) : Bool :=
  (g.k == 0 && g.init < 2) || (g.k == 1 && g.init == 2) || (g.k == 3 && g.init == 0xCA) ||
    carryTab.contains (g.k, g.init) || (g.k == 5 && g.init < 2 ^ 32) || (g.k == 6 && g.init < 2 ^ 64)
""")
for c in range(n):
    out.append("theorem k%03d : ∀ g ∈ g%03d, kindOK g = true := by decide +kernel" % (c, c))
expr = "k%03d" % (n - 1)
for c in range(n - 2, -1, -1):
    expr = "List.forall_mem_append.2 ⟨k%03d, %s⟩" % (c, expr)
out.append("""
/-- **Every gate of the decoded gcd_ps netlist is of a modelled kind.** -/
theorem kinds : ∀ g ∈ net.gates, kindOK g = true :=
  %s
""" % expr)
out.append("""/-- Negative controls: a 3-pin gate with any table other than 0xCA, and a 7-pin gate with a non-carry table, are
rejected. -/
theorem kindOK_rejects : kindOK ⟨"x", 3, 0xCB, [0, 1, 2], [], 3⟩ = false ∧
    kindOK ⟨"x", 7, 0x1000efff1f00e0ff10ffef001fffe001, [0, 1, 2, 3, 4, 5, 6], [], 7⟩ = false := by
  decide +kernel

theorem carry_mem {k init : Nat} (h : carryTab.contains (k, init) = true) :
    ∃ co : Bool, ∃ i : Fin 4, k = aK co i.val ∧ init = aCarryInit co i.val := by
  rw [carryTab_eq] at h
  simp only [List.contains_cons, List.contains_nil, Bool.or_false, Bool.or_eq_true, beq_iff_eq,
    Prod.mk.injEq] at h
  rcases h with h | h | h | h | h | h | h | h
  · exact ⟨false, 0, h.1, h.2⟩
  · exact ⟨false, 1, h.1, h.2⟩
  · exact ⟨false, 2, h.1, h.2⟩
  · exact ⟨false, 3, h.1, h.2⟩
  · exact ⟨true, 0, h.1, h.2⟩
  · exact ⟨true, 1, h.1, h.2⟩
  · exact ⟨true, 2, h.1, h.2⟩
  · exact ⟨true, 3, h.1, h.2⟩

/-- **H_PRIM coverage on THE target's netlist**: every gate's Spec table read is a constant, the identity (copy),
Core's MUXF (`bmux`), Core's CARRY4 output (`bout`, on A's pin layout), or a LUT5/LUT6 table. -/
theorem prim_cover : ∀ g ∈ net.gates,
    (g.k = 0 ∧ g.init < 2) ∨
    (g.k = 1 ∧ ∀ v : Nat → Bool, g.init.testBit (addr 1 v) = v 0) ∨
    (g.k = 3 ∧ ∀ v : Nat → Bool, g.init.testBit (addr 3 v) = Formal.Core.Prims.bmux (v 2) (v 0) (v 1)) ∨
    (∃ co : Bool, ∃ i : Fin 4, g.k = aK co i.val ∧
      ∀ v : Nat → Bool, g.init.testBit (addr g.k v) = Formal.Core.Prims.bout (aToCore co i.val v) (coutOf co i)) ∨
    (g.k = 5 ∧ g.init < 2 ^ 32) ∨ (g.k = 6 ∧ g.init < 2 ^ 64) := by
  intro g hg
  have h := kinds g hg
  simp only [kindOK, Bool.or_eq_true, Bool.and_eq_true, beq_iff_eq, decide_eq_true_eq] at h
  rcases h with ((((h | h) | h) | h) | h) | h
  · exact Or.inl h
  · refine Or.inr (Or.inl ⟨h.1, fun v => ?_⟩)
    rw [h.2]; cases hv : v 0 <;> simp [addr, hv] <;> decide
  · refine Or.inr (Or.inr (Or.inl ⟨h.1, fun v => ?_⟩))
    rw [h.2]; exact muxf_gate v
  · obtain ⟨co, i, hk, hi⟩ := carry_mem h
    refine Or.inr (Or.inr (Or.inr (Or.inl ⟨co, i, hk, fun v => ?_⟩)))
    rw [hi, hk]; exact aCarry_gate co i v
  · exact Or.inr (Or.inr (Or.inr (Or.inr (Or.inl h))))
  · exact Or.inr (Or.inr (Or.inr (Or.inr (Or.inr h))))

end Formal.Cells.PrimsPS""")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
