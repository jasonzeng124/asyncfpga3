#!/usr/bin/env python3
"""Shard B: generate Formal/Cells/LatchPS/{Defs,Bxxx}.lean and Formal/Cells/LatchPS.lean from latchtab.py's rows:
for every listed latch of Formal.Target.DecodedPS.net, its INIT facts (SpecLatchFact.lfact) and its wiring (feedback
pin reads a copy chain from the gate's own output; every held pin reads a copy chain from a constant gate of the
stated value or from the reset node). usage: gen_latch_ps.py LATCHTAB.json OUTDIR [maxchunks] [maxrows]"""
import json, sys, os
R = json.load(open(sys.argv[1])); OUT = sys.argv[2]
MAXC = int(sys.argv[3]) if len(sys.argv) > 3 else 12; MAXR = int(sys.argv[4]) if len(sys.argv) > 4 else 20
C = 2500; RST = 186905
bl = lambda l: "[" + ", ".join("true" if b else "false" for b in l) + "]"
nl = lambda l: "[" + ", ".join(str(x) for x in l) + "]"
rows = []
for r in sorted(R, key=lambda r: r["q"]):
    k = r["k"]; held = [False] * k; ov = [False] * k
    for i, v in r["ov"].items(): held[int(i)] = True; ov[int(i)] = bool(v)
    hs = ["(%d, %s, %d)" % (i, nl(r["chains"][i]), r["srcs"][i]) for i in range(k) if held[i]]
    gates = {r["q"]} | set(r["chains"][r["fb"]]) | {c for i in range(k) if held[i] for c in r["chains"][i]} | \
            {r["srcs"][i] for i in range(k) if held[i] and r["srcs"][i] != RST}
    rows.append(("(%d, %d, %d, %d, %d, %s, %s, %s, %s, %s, [%s])" % (r["q"], k, r["e"], r["d"], r["fb"],
                 "true" if r["pe"] else "false", "true" if r["pd"] else "false", bl(held), bl(ov),
                 nl(r["chains"][r["fb"]]), ", ".join(hs)), {x // C for x in gates}))
files = []; cur = []; cs = set()
for i, (txt, ch) in enumerate(rows):
    if cur and (len(cs | ch) > MAXC or len(cur) >= MAXR): files.append((cur, cs)); cur = []; cs = set()
    cur.append(i); cs |= ch
if cur: files.append((cur, cs))
D = os.path.join(OUT, "LatchPS"); os.makedirs(D, exist_ok=True)
open(os.path.join(D, "Defs.lean"), "w").write('''import Formal.Cells.CElemPS.Defs
import Formal.Cells.SpecLatchFact

/-! GENERATED by tools-B/ps/gen_latch_ps.py: the latch rows of THE target (latchtab.py) and their row check. -/

namespace Formal.Cells.LatchPS
open Formal.Target Formal.Target.DecodedPS Formal.Cells.RaceLinkPS Formal.Cells.SpecCElemFact
  Formal.Cells.SpecLatchFact Formal.Cells.CElemPS

/-- A row: (gate q, k, enable e, data d, feedback j, pe, pd, held, ov, feedback chain, held pins (pin, chain, source)). -/
abbrev Row := Nat × Nat × Nat × Nat × Nat × Bool × Bool × List Bool × List Bool × List Nat × List (Nat × List Nat × Nat)

/-- The row check: gate `q` has `k` pins, `e`, `d`, `j` distinct pins, its INIT is a latch (`lfact`); pin `j` reads its
own output through the listed copy chain; every held pin reads, through its listed chain, a constant gate of value
`ov i` or the reset node (then `ov i = false`), and every held pin is listed. -/
def rowOK (r : Row) : Bool :=
  let (q, k, e, d, j, pe, pd, held, ov, fbc, hp) := r
  let G := gateAt q
  G.k == k && G.out == q && e < k && d < k && j < k && e != d && e != j && d != j &&
  !(fl held e) && !(fl held j) &&
  lfact k G.init e d j pe pd (fl held) (fl ov) &&
  chainAt (G.ins.getD j 0) fbc q &&
  (List.range k).all (fun i => !(fl held i) || hp.any fun h => h.1 == i) &&
  hp.all fun (i, ch, s) => i < k && fl held i && chainAt (G.ins.getD i 0) ch s &&
    ((s == rstNode && !(fl ov i)) || ((gateAt s).k == 0 && (gateAt s).out == s && (gateAt s).init.testBit 0 == fl ov i))

end Formal.Cells.LatchPS
''')
for fi, (idx, cs) in enumerate(files):
    body = ["import Formal.Cells.LatchPS.Defs", "",
            "/-! GENERATED by tools-B/ps/gen_latch_ps.py: rows %d-%d (%d netlist chunks). -/" % (idx[0], idx[-1], len(cs)), "",
            "namespace Formal.Cells.LatchPS", "open Formal.Target Formal.Target.DecodedPS Formal.Cells.RaceLinkPS", "",
            "set_option maxRecDepth 100000 in", "def rows%03d : List Row := [" % fi]
    body.append(",\n".join("  " + rows[i][0] for i in idx) + "]")
    body += ["", "set_option maxHeartbeats 0 in", "set_option maxRecDepth 100000 in",
             "theorem rows%03d_ok : rows%03d.all rowOK = true := by decide +kernel" % (fi, fi), "", "end Formal.Cells.LatchPS", ""]
    open(os.path.join(D, "B%03d.lean" % fi), "w").write("\n".join(body))
nf = len(files)
top = ["import Formal.Cells.LatchPS.B%03d" % i for i in range(nf)]
top += ["", "/-!", "# Formal.Cells.LatchPS — THE target's latches, checked on `DecodedPS.net` (GENERATED by tools-B/ps/gen_latch_ps.py)", "",
        "## Problem, plainly",
        "Which storage gates of THE target's Lean netlist satisfy the INIT and wiring premises of `SpecLatch.latch_close`?",
        "`allRows` (%d gates, from the untrusted latchtab.py) all pass `rowOK`: INIT facts (`lfact`), feedback through a copy" % len(rows),
        "chain from the gate's own output, every held pin tied through a copy chain to a constant of the stated value or to",
        "the reset node. `row_hopen` / `row_hclosed` turn a passing row into `latch_close`'s `hopen` / `hclosed` for the",
        "netlist's gate `net.gates.getD q default`.", "",
        "## Not covered", "That this list is every latch; the enable/data windows (the bundling obligations); CGateOK for these",
        "gates (C's `collapsed` view).", "-/", "",
        "namespace Formal.Cells.LatchPS",
        "open Formal.Target Formal.Target.DecodedPS Formal.Cells.RaceLinkPS Formal.Cells.SpecCElemFact Formal.Cells.SpecLatchFact", ""]
# allRows as a concatenation, proved in groups to keep terms small
G = 20
groups = [list(range(a, min(a + G, nf))) for a in range(0, nf, G)]
for gi, grp in enumerate(groups):
    top += ["set_option maxRecDepth 100000 in", "def grp%02d : List Row := " % gi + " ++ ".join("rows%03d" % i for i in grp),
            "set_option maxRecDepth 100000 in",
            "theorem grp%02d_ok : grp%02d.all rowOK = true := by" % (gi, gi),
            "  simp only [grp%02d, List.all_append, " % gi + ", ".join("rows%03d_ok" % i for i in grp) + ", Bool.and_self]", ""]
top += ["set_option maxRecDepth 100000 in", "def allRows : List Row := " + " ++ ".join("grp%02d" % i for i in range(len(groups))),
        "set_option maxRecDepth 100000 in", "theorem allRows_ok : allRows.all rowOK = true := by",
        "  simp only [allRows, List.all_append, " + ", ".join("grp%02d_ok" % i for i in range(len(groups))) + ", Bool.and_self]", "",
        '''theorem row_ok {r : Row} (hr : r ∈ allRows) : rowOK r = true := by
  have := allRows_ok; simp only [List.all_eq_true] at this; exact this r hr

theorem lfact_of_row {q k e d j : Nat} {pe pd : Bool} {held ov : List Bool} {fbc : List Nat}
    {hp : List (Nat × List Nat × Nat)} (h : rowOK (q, k, e, d, j, pe, pd, held, ov, fbc, hp) = true) :
    (net.gates.getD q default).k = k ∧ e < k ∧ d < k ∧ j < k ∧
      lfact k (net.gates.getD q default).init e d j pe pd (fl held) (fl ov) = true := by
  simp only [rowOK, Bool.and_eq_true] at h
  obtain ⟨⟨⟨⟨⟨⟨⟨⟨⟨⟨⟨⟨⟨h1, -⟩, h3⟩, h4⟩, h5⟩, -⟩, -⟩, -⟩, -⟩, -⟩, h11⟩, -⟩, -⟩, -⟩ := h
  have h1' : (gateAt q).k = k := beq_iff_eq.mp h1
  rw [← gateAt_eq]
  exact ⟨h1', of_decide_eq_true h3, of_decide_eq_true h4, of_decide_eq_true h5, h11⟩

/-- **`hopen` for every listed latch of the netlist.** -/
theorem row_hopen {q k e d j : Nat} {pe pd : Bool} {held ov : List Bool} {fbc : List Nat}
    {hp : List (Nat × List Nat × Nat)} (hr : (q, k, e, d, j, pe, pd, held, ov, fbc, hp) ∈ allRows) :
    ∀ v : Nat → Bool, (v e ^^ pe) = true → (∀ i, i < k → fl held i = true → v i = fl ov i) →
      (net.gates.getD q default).init.testBit (addr k v) = (v d ^^ pd) :=
  have h := lfact_of_row (row_ok hr)
  hopen_of_lfact h.2.2.2.2 h.2.1 h.2.2.1

/-- **`hclosed` for every listed latch of the netlist.** -/
theorem row_hclosed {q k e d j : Nat} {pe pd : Bool} {held ov : List Bool} {fbc : List Nat}
    {hp : List (Nat × List Nat × Nat)} (hr : (q, k, e, d, j, pe, pd, held, ov, fbc, hp) ∈ allRows) :
    ∀ v : Nat → Bool, (v e ^^ pe) = false → (∀ i, i < k → fl held i = true → v i = fl ov i) →
      (net.gates.getD q default).init.testBit (addr k v) = v j :=
  have h := lfact_of_row (row_ok hr)
  hclosed_of_lfact h.2.2.2.2 h.2.1 h.2.2.2.1
''',
        "set_option maxRecDepth 100000 in", "theorem allRows_length : allRows.length = %d := by decide" % len(rows), "",
        "end Formal.Cells.LatchPS", ""]
open(os.path.join(OUT, "LatchPS.lean"), "w").write("\n".join(top))
print("rows", len(rows), "files", nf)
