#!/usr/bin/env python3
"""Shard B (UNTRUSTED generator; every row is checked in Lean by CertPS.certOK and LatchHoldCert.latchHoldOK):
latch-hold rows for THE target. Input: a scan (JSON list, from a ctlcert.py run per latch close: name, es = the
latch's enable source = the cause, ds = its data source, path = ctlcert --chainjson path from ds back to es).
Builds RaceTablePS-format rows (cause = es, path = chain + the latch reading its data pin, want_cv = the enable's
open value), calls gen_certs_ps.py (CERTONLY) for the certificate family NAME, then writes NAME's row file
Formal/Cells/<OUTNAME>.lean pairing each certificate with the latch's LRow (copied verbatim from LatchViewPS).
usage: gen_latchhold_ps.py NET.json LATCH.json SCAN.json DUMP.json LEANCELLS   (env NAME, OUTNAME, MAXC, MAXROWS)"""
import json, sys, os, re, subprocess, glob
NETF, LATF, SCANF, DUMPF, CELLS = sys.argv[1:6]
NAME = os.environ.get("NAME", "CertLatchPS"); OUTNAME = os.environ.get("OUTNAME", "LatchHoldPS")
MAXROWS = int(os.environ.get("MAXROWS", "10000"))
HERE = os.path.dirname(os.path.abspath(__file__))
N = json.load(open(NETF)); gates = N["gates"]; drv = {g["out"]: i for i, g in enumerate(gates)}
lat = {r["name"]: r for r in json.load(open(LATF))["rows"]}
scan = [s for s in json.load(open(SCANF)) if s.get("path")][:MAXROWS]
rows = []
for s in scan:
    L = lat[s["name"]]
    assert drv.get(s["es"]) == s["es"] and L["srcs"][L["e"]] == s["es"] and L["srcs"][L["d"]] == s["ds"]
    rows.append(dict(node=s["name"], gate=s["es"], path=[list(x) for x in s["path"]] + [[L["q"], L["d"]]],
                     want_cv=(L["pe"] == 0), latch_q=L["q"]))
tmp = os.path.join(os.path.dirname(os.path.abspath(SCANF)), "_latch_rows.json")
json.dump(dict(rows=rows), open(tmp, "w"))
outjson = os.path.join(os.path.dirname(os.path.abspath(SCANF)), "_latch_certs.json")
env = dict(os.environ, CERTONLY="1", NAME=NAME, OUTJSON=outjson)
r = subprocess.run([sys.executable, "-I", os.path.join(HERE, "gen_certs_ps.py"), NETF, tmp, DUMPF, CELLS], env=env,
                   capture_output=True, text=True)
print(r.stdout.strip().splitlines()[-1] if r.stdout.strip() else r.stderr[-2000:])
made = json.load(open(outjson))["rows"]           # in certificate order c000, c001, ...
qof = {x["node"]: x["latch_q"] for x in rows}
# LRow literals, verbatim from LatchViewPS
lit = {}
for f in glob.glob(os.path.join(CELLS, "LatchViewPS", "B*.lean")):
    for m in re.finditer(r"^  (⟨(\d+), .*⟩)(?:,|\])?$", open(f).read(), re.M):
        lit[int(m.group(2))] = m.group(1)
# which certificate file holds which index
fam = open(os.path.join(CELLS, NAME + ".lean")).read()
nfiles = len(re.findall(r"certs\d\d_ok", fam))
# per-row margin ratio (kA, kB) from the Lean-evaluated arc sums (env SUMS: JSON list [Fmax_e, Fmin_path, Smax_e,
# Smin_path] per certificate, from `#eval`); without it 1/1 (a first pass, to evaluate the sums)
from fractions import Fraction
SUMS = json.load(open(os.environ["SUMS"])) if os.environ.get("SUMS") else None
out = []; kap = []
for i, x in enumerate(made):
    q = qof[x["node"]]
    if SUMS:
        fx, fn, sx, sn = SUMS[i]
        r_ = min(Fraction(fn, fx + 1), Fraction(sn, sx + 1)); kA, kB = r_.numerator, r_.denominator
        if kA <= kB: print("no margin at κ = 0:", x["node"]); continue
        kap.append((float((kA - kB) / Fraction(kA + kB)), x["node"]))
    else: kA, kB = 1, 1
    out.append("⟨c%03d, %s, %d, %d⟩" % (i, lit[q], kA, kB))
if kap: print("row κ bounds: min %.3f (%s), median %.3f" % (min(kap)[0], min(kap)[1], sorted(kap)[len(kap) // 2][0]))
names = ", ".join("certs%02d" % k for k in range(nfiles))
T = ["import Formal.Cells.LatchHoldCert", "import Formal.Cells." + NAME, "",
     "/-!", "# Formal.Cells.%s — latch hold windows of THE target from certificates (GENERATED)" % OUTNAME, "",
     "GENERATED by tools-B/ps/gen_latchhold_ps.py from ctlcert.py chains on a simb.py dump. %d latches: each row pairs"
     % len(out),
     "a chain hold certificate (cause = the latch's enable source closing; last row = its data source) with the latch's",
     "LatchViewPS row; `rows_full` checks them (certOK, latchHoldOK: lrowOK, wiring, open value, the two arc-sum facts",
     "with one step to spare). `target_latch_holds` is `LatchHoldCert.target_latch_holds_of` for them: in every",
     "behaviour of THE circuit (g = 1, one corner), each listed latch, for κ in its own range (1+κ)·kB ≤ kA·(1-κ), holds its data value through the close",
     "with its hold window and open window discharged, given the certificate's local premises and the setup half.",
     "-/", "",
     "namespace Formal.Cells." + OUTNAME,
     "open Formal.Target Formal.Cells.CertPS Formal.Cells.LatchView Formal.Cells.LatchHoldCert Formal.Cells." + NAME, "",
     "set_option maxRecDepth 100000 in", "def rows : List LatchHoldRow := [\n  %s]" % ",\n  ".join(out), "",
     "set_option maxHeartbeats 0 in", "set_option maxRecDepth 100000 in",
     "theorem rows_ok : rows.all latchHoldOK = true := by decide +kernel", "",
     "set_option maxRecDepth 100000 in",
     "theorem rows_pc : rows.map LatchHoldRow.pc = certs := rfl", "",
     "theorem rows_full : ∀ r ∈ rows, certOK r.pc.1 r.pc.2 = true ∧ latchHoldOK r = true := by",
     "  intro r hr",
     "  have h1 := List.mem_map_of_mem (f := LatchHoldRow.pc) hr",
     "  rw [rows_pc] at h1",
     "  exact ⟨(List.all_eq_true.1 certs_ok) _ h1, (List.all_eq_true.1 rows_ok) r hr⟩", "",
     "/-- **THE target's listed latches hold through the close, hold window from a certificate** (module docstring). -/",
     "theorem target_latch_holds : type_of% (@target_latch_holds_of rows rows_full) := @target_latch_holds_of rows rows_full",
     "", "end Formal.Cells." + OUTNAME, ""]
if not SUMS:   # first pass: an #eval file printing the sums (run with `lake env lean`), no row file
    E = ["import Formal.Cells.LatchHoldCert", "import Formal.Cells." + NAME,
         "open Formal.Target Formal.Cells.CertPS Formal.Cells.LatchView Formal.Cells.LatchHoldCert Formal.Cells.CertRaceAll",
         "  Formal.Cells.RaceCornersPS Formal.Cells." + NAME,
         "set_option maxRecDepth 100000 in", "def rows : List LatchHoldRow := [\n  %s]" % ",\n  ".join(out),
         "#eval IO.println (toString (rows.map fun r => [sFmax (r.l.arcs r.l.e), sFmin (pathArcs r.pc.2), "
         "sSmax (r.l.arcs r.l.e), sSmin (pathArcs r.pc.2)]))"]
    open(os.environ.get("EVALOUT", "/tmp/_lh_sums.lean"), "w").write("\n".join(E) + "\n")
    print("first pass: wrote", os.environ.get("EVALOUT", "/tmp/_lh_sums.lean")); sys.exit(0)
open(os.path.join(CELLS, OUTNAME + ".lean"), "w").write("\n".join(T))
print("rows", len(out))
