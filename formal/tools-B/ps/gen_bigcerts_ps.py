#!/usr/bin/env python3
"""Shard B (UNTRUSTED generator; every piece is checked in Lean): split checks for certificates too large for one
kernel decide. Reads the CertRowsPS/RaceAllPS files left out of the batch (C_Bxx.lean / R_Bxx.lean, gen_certs_ps.py
output) and writes Formal/Cells/BigCertPS/: per certificate a data file, row-range check files (krowOK and the path
arc sums per range, each range touching at most MAXC netlist chunks), and a combining file; plus BigCertPS.lean with
`target_switches` over all of them.  usage: gen_bigcerts_ps.py EXCLDIR OUTDIR(Formal/Cells) [MAXC]"""
import sys, os, re, glob, json
EX = sys.argv[1]; OUT = sys.argv[2]; MAXC = int(sys.argv[3]) if len(sys.argv) > 3 else 12
C = 2500
NET = json.load(open(os.environ.get("NETJSON", "/tmp/claude-0/sp/net.json")))
G = NET["gates"]
def parse_row(l):
    q = int(re.match(r"⟨⟨(\d+),", l).group(1))
    pins = [(list(map(int, a.split(", "))) if a.strip() else [], int(b)) for a, b in re.findall(r"\(\[([\d, ]*)\], (\d+)\)", l)]
    lists = re.findall(r"\], (\[[\d, ]*\]), \[(?:true|false)", l)
    P = json.loads(lists[0]) if lists else []
    labs = [(int(a), int(b)) for a, b in re.findall(r"⟨(\d+), (\d+)⟩", l.split("⟩, [")[-1])]
    return q, pins, P, labs
def path_sums(l):
    q, pins, P, labs = parse_row(l)
    jj = [j for j in P if labs[j][0] != 1][0]
    arcs = [G[q]["arcs"][jj]] + [G[c]["arcs"][0] for c in pins[jj][0]]
    return sum(a["fmin"] for a in arcs), sum(a["smin"] for a in arcs)
D = os.path.join(OUT, "BigCertPS"); os.makedirs(D, exist_ok=True)
def chunks(txt): return {int(x) // C for x in re.findall(r"\d+", txt) if int(x) < 186873}
mods = []; swnames = []
for cf in sorted(glob.glob(os.path.join(EX, "C_B*.lean"))):
    rf = cf.replace("C_B", "R_B")
    ctext = open(cf).read(); rtext = open(rf).read()
    for m in re.finditer(r"set_option maxRecDepth 100000 in\n/-- (.*?) -/\ndef (c\d+) : Prem × List CRow := \((.*?)\]\)\n", ctext, re.S):
        doc, name, body = m.group(1), m.group(2), m.group(3)
        prem, rows = body.split(", [\n", 1)
        rowlines = [l.strip().rstrip(",") for l in rows.split("\n") if l.strip()]
        swm = re.search(r"⟨⟨%s, (.*?)⟩, (⟨\d+, \[.*?\], \[.*?\], \[.*?\], (?:true|false), \d+, (?:true|false), \[.*?\], \[.*?\]⟩), (⟨\d+, \[.*?\], \[.*?\], \[.*?\], (?:true|false), \d+, (?:true|false), \[.*?\], \[.*?\]⟩)⟩" % name, rtext, re.S)
        rrm = re.search(r"⟨%s, (⟨\d+, \[.*?\], \[\], \[\], false, 0, false, \[\], \[\]⟩), (\d+), (\d+)⟩" % name, rtext, re.S)
        node, ja, jf = rrm.group(1), rrm.group(2), rrm.group(3)
        F, Cr = swm.group(2), swm.group(3)
        n = len(rowlines)
        base = "Formal.Cells.BigCertPS." + name.upper()
        dat = ["import Formal.Cells.CertSplit", "", "/-! GENERATED by tools-B/ps/gen_bigcerts_ps.py: %s -/" % doc, "",
               "namespace Formal.Cells.BigCertPS", "open Formal.Cells.CertPS Formal.Cells.RaceCertPS Formal.Cells.CertRaceAll Formal.Cells.CertSwitchAll", "",
               "set_option maxRecDepth 100000 in", "def %s : Prem × List CRow := (%s, [\n  %s])" % (name, prem, ",\n  ".join(rowlines)), "",
               "set_option maxRecDepth 100000 in", "def %s_sw : SwRow := ⟨⟨%s, %s, %s, %s⟩, %s, %s⟩" % (name, name, node, ja, jf, F, Cr), "",
               "set_option maxRecDepth 100000 in", "theorem %s_len : %s.2.length = %d := rfl" % (name, name, n), "", "end Formal.Cells.BigCertPS", ""]
        open(os.path.join(D, name.upper() + ".lean"), "w").write("\n".join(dat))
        # ranges
        ranges = []; cur = []; cs = set()
        for i, l in enumerate(rowlines):
            ch = chunks(l)
            if cur and len(cs | ch) > MAXC: ranges.append(cur); cur = []; cs = set()
            cur.append(i); cs |= ch
        if cur: ranges.append(cur)
        rmods = []; rsums = []
        for k, rg in enumerate(ranges):
            a, m_ = rg[0], len(rg)
            f = lambda i: "(%s.2.getD i default)" % name
            L = ["import " + base, "", "namespace Formal.Cells.BigCertPS",
                 "open Formal.Cells.CertPS Formal.Cells.RaceCertPS Formal.Cells.CertMarginPS Formal.Cells.CertRaceAll Formal.Cells.RaceCornersPS", "",
                 "set_option maxHeartbeats 0 in", "set_option maxRecDepth 100000 in",
                 "theorem %s_k%d : (List.range' %d %d).all (fun i => krowOK (%s.2.getD i default).r) = true := by decide +kernel" % (name, k, a, m_, name), "",
                 "set_option maxHeartbeats 0 in", "set_option maxRecDepth 100000 in",
                 "theorem %s_f%d : ((List.range' %d %d).map fun i => sFmin ((%s.2.getD i default).r.arcs (pathPin (%s.2.getD i default)))).sum = %s.2.length * 0 + ((List.range' %d %d).map fun i => sFmin ((%s.2.getD i default).r.arcs (pathPin (%s.2.getD i default)))).sum := by simp" % (name, k, a, m_, name, name, name, a, m_, name, name),
                 "", "end Formal.Cells.BigCertPS", ""]
            # (the sums are evaluated in the combining file's decide over the per-range values below)
            sf = sum(path_sums(rowlines[i])[0] for i in rg); ss = sum(path_sums(rowlines[i])[1] for i in rg)
            L = L[:8] + ["", "set_option maxHeartbeats 0 in", "set_option maxRecDepth 100000 in",
                 "theorem %s_sf%d : ((List.range' %d %d).map fun i => sFmin ((%s.2.getD i default).r.arcs (pathPin (%s.2.getD i default)))).sum = %d := by decide +kernel" % (name, k, a, m_, name, name, sf),
                 "", "set_option maxHeartbeats 0 in", "set_option maxRecDepth 100000 in",
                 "theorem %s_ss%d : ((List.range' %d %d).map fun i => sSmin ((%s.2.getD i default).r.arcs (pathPin (%s.2.getD i default)))).sum = %d := by decide +kernel" % (name, k, a, m_, name, name, ss),
                 "", "end Formal.Cells.BigCertPS", ""]
            rsums.append((sf, ss))
            mn = "%s_R%d" % (name.upper(), k)
            open(os.path.join(D, mn + ".lean"), "w").write("\n".join(L)); rmods.append((mn, a, m_))
        # combine: krowOK over the whole range, and the rest by decide (sums touch every row's arcs: also split)
        comb = ["import Formal.Cells.BigCertPS.%s" % mn for mn, a, m_ in rmods]
        comb += ["", "namespace Formal.Cells.BigCertPS",
                 "open Formal.Cells.CertPS Formal.Cells.RaceCertPS Formal.Cells.CertRaceAll Formal.Cells.CertSwitchAll Formal.Cells.CertSplit Formal.Cells.CertMarginPS Formal.Cells.RaceCornersPS", ""]
        acc = "%s_k0" % name; tot = rmods[0][2]
        for k in range(1, len(rmods)):
            acc = "(all_range'_append _ 0 %d %d %s %s_k%d)" % (tot, rmods[k][2], acc, name, k); tot += rmods[k][2]
        comb += ["theorem %s_krow : (List.range' 0 %s.2.length).all (fun i => krowOK (%s.2.getD i default).r) = true := %s" % (name, name, name, acc), "",
                 "set_option maxHeartbeats 0 in", "set_option maxRecDepth 100000 in",
                 "theorem %s_labs : (List.range %s.2.length).all (fun i => labOK %s.1 %s.2 i (%s.2.getD i default)) = true := by decide +kernel" % (name, name, name, name, name), "",
                 "theorem %s_cert : certOK %s.1 %s.2 = true := certOK_of_split _ _ %s_krow %s_labs" % (name, name, name, name, name), ""]
        for tag, idxs in (("sf", 0), ("ss", 1)):
            acc = "%s_%s0" % (name, tag); tot = rmods[0][2]; val = rsums[0][idxs]
            for k in range(1, len(rmods)):
                acc = "(sum_block _ 0 %d %d _ _ %s %s_%s%d)" % (tot, rmods[k][2], acc, name, tag, k)
                tot += rmods[k][2]; val += rsums[k][idxs]
            fn = "sFmin" if tag == "sf" else "sSmin"
            comb += ["theorem %s_%s : ((List.range' 0 %s.2.length).map fun i => %s ((%s.2.getD i default).r.arcs (pathPin (%s.2.getD i default)))).sum = %d := %s" % (name, tag, name, fn, name, name, val, acc), ""]
        comb += ["set_option maxHeartbeats 0 in", "set_option maxRecDepth 100000 in",
                 "theorem %s_race : raceOK %s_sw.rr = true := raceOK_of_split %s_sw.rr _ _ %s_sf %s_ss (by decide +kernel)" % (name, name, name, name, name), "",
                 "set_option maxHeartbeats 0 in", "set_option maxRecDepth 100000 in",
                 "theorem %s_swok : swOK %s_sw = true := by decide +kernel" % (name, name), "",
                 "theorem %s_full : certOK %s_sw.rr.pc.1 %s_sw.rr.pc.2 = true ∧ raceOK %s_sw.rr = true ∧ swOK %s_sw = true :=" % (name, name, name, name, name),
                 "  ⟨%s_cert, %s_race, %s_swok⟩" % (name, name, name), "",
                 "end Formal.Cells.BigCertPS", ""]
        open(os.path.join(D, name.upper() + "_C.lean"), "w").write("\n".join(comb))
        mods.append((name, [mn for mn, a, m_ in rmods], len(ranges), doc))
T = ["import Formal.Cells.BigCertPS.%s_C" % nm.upper() for nm, _, _, _ in mods]
T += ["", "/-! GENERATED by tools-B/ps/gen_bigcerts_ps.py: the %d race rows whose certificates are checked in pieces. -/" % len(mods), "",
      "namespace Formal.Cells.BigCertPS", "open Formal.Cells.CertPS Formal.Cells.CertRaceAll Formal.Cells.CertSwitchAll", "",
      "def sws : List SwRow := [%s]" % ", ".join("%s_sw" % nm for nm, _, _, _ in mods), "",
      "theorem sws_full : ∀ s ∈ sws, certOK s.rr.pc.1 s.rr.pc.2 = true ∧ raceOK s.rr = true ∧ swOK s = true := by",
      "  intro s hs",
      "  simp only [sws, List.mem_cons, List.not_mem_nil, or_false] at hs",
      "  rcases hs with " + " | ".join("rfl" for _ in mods)] + ["  · exact %s_full" % nm for nm, _, _, _ in mods] + ["",
      "/-- **The storage nodes of these rows switch cleanly, in every behaviour of THE circuit** (`CertSwitchAll.target_switches_of`). -/",
      "theorem target_switches : type_of% (@target_switches_of sws sws_full) := @target_switches_of sws sws_full", "",
      "end Formal.Cells.BigCertPS", ""]
open(os.path.join(OUT, "BigCertPS.lean"), "w").write("\n".join(T))
print("certificates", len(mods), "range files", sum(r for _, _, r, _ in mods))
