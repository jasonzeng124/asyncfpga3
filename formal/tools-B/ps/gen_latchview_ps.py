#!/usr/bin/env python3
"""Shard B: generate Formal/Cells/LatchViewPS/Bxx.lean and Formal/Cells/LatchViewPS.lean: latchtab.py's latch rows
with every pin's copy chain and source, checked by LatchView.lrowOK, and the instance of
LatchView.target_latch_close. usage: gen_latchview_ps.py CELEMTAB.json OUTDIR [maxchunks] [maxrows]"""
import json, sys, os
R = json.load(open(sys.argv[1])); OUT = sys.argv[2]
MAXC = int(sys.argv[3]) if len(sys.argv) > 3 else 12; MAXR = int(sys.argv[4]) if len(sys.argv) > 4 else 20
C = 2500; RST = 186905
bl = lambda l: "[" + ", ".join("true" if b else "false" for b in l) + "]"
nl = lambda l: "[" + ", ".join(str(x) for x in l) + "]"
rows = []
for r in sorted(R, key=lambda r: r["q"]):
    k = r["k"]; held = [False] * k; ov = [False] * k
    for i, v in r["ov"].items(): held[int(i)] = True; ov[int(i)] = bool(v)
    pins = ", ".join("(%s, %d)" % (nl(r["chains"][i]), r["srcs"][i]) for i in range(k))
    gates = {r["q"]} | {c for ch in r["chains"] for c in ch} | {r["srcs"][i] for i in range(k) if held[i] and r["srcs"][i] != RST}
    rows.append(("⟨%d, %d, %d, %d, %s, %s, %s, %s, [%s]⟩" % (r["q"], r["e"], r["d"], r["fb"], "true" if r["pe"] else "false",
                 "true" if r["pd"] else "false", bl(held), bl(ov), pins), {x // C for x in gates}))
files = []; cur = []; cs = set()
for i, (txt, ch) in enumerate(rows):
    if cur and (len(cs | ch) > MAXC or len(cur) >= MAXR): files.append((cur, cs)); cur = []; cs = set()
    cur.append(i); cs |= ch
if cur: files.append((cur, cs))
D = os.path.join(OUT, "LatchViewPS"); os.makedirs(D, exist_ok=True)
for fi, (idx, cs) in enumerate(files):
    body = ["import Formal.Cells.LatchView", "",
            "/-! GENERATED by tools-B/ps/gen_latchview_ps.py: rows %d-%d (%d netlist chunks). -/" % (idx[0], idx[-1], len(cs)), "",
            "namespace Formal.Cells.LatchViewPS", "open Formal.Cells.LatchView", "",
            "set_option maxRecDepth 100000 in", "def rows%02d : List LRow := [" % fi]
    body.append(",\n".join("  " + rows[i][0] for i in idx) + "]")
    body += ["", "set_option maxHeartbeats 0 in", "set_option maxRecDepth 100000 in",
             "theorem rows%02d_ok : rows%02d.all lrowOK = true := by decide +kernel" % (fi, fi), "", "end Formal.Cells.LatchViewPS", ""]
    open(os.path.join(D, "B%02d.lean" % fi), "w").write("\n".join(body))
nf = len(files)
top = ["import Formal.Cells.LatchViewPS.B%02d" % i for i in range(nf)]
top += ["", "/-!", "# Formal.Cells.LatchViewPS — THE target's latches close cleanly, in every behaviour",
        "(GENERATED by tools-B/ps/gen_latchview_ps.py)", "",
        "`allRows` (%d latches of `DecodedPS.net`, from the untrusted latchtab.py, each with every pin's copy chain and" % len(rows),
        "source) passes `LatchView.lrowOK` (kernel `decide`). `target_ps_latch_close` is `LatchView.target_latch_close` for",
        "them: in every behaviour of THE circuit, at its corner, every listed latch whose enable and data windows meet the",
        "derived setup / hold / width conditions (its own summed window ends) holds its data value through the close.",
        "Not covered: that the network supplies those windows; latches the classifier missed.", "-/", "",
        "namespace Formal.Cells.LatchViewPS", "open Formal.Cells.LatchView", "",
        "set_option maxRecDepth 100000 in", "def allRows : List LRow := " + " ++ ".join("rows%02d" % i for i in range(nf)), "",
        "set_option maxRecDepth 100000 in", "theorem allRows_ok : allRows.all lrowOK = true := by",
        "  simp only [allRows, List.all_append, " + ", ".join("rows%02d_ok" % i for i in range(nf)) + ", Bool.and_self]", "",
        "set_option maxRecDepth 100000 in", "theorem allRows_length : allRows.length = %d := by decide" % len(rows), "",
        "/-- **THE target's latches close cleanly** (see `LatchView.target_latch_close` for the full statement). -/",
        "theorem target_ps_latch_close : type_of% (@target_latch_close allRows allRows_ok) :=", "  @target_latch_close allRows allRows_ok", "",
        "end Formal.Cells.LatchViewPS", ""]
open(os.path.join(OUT, "LatchViewPS.lean"), "w").write("\n".join(top))
print("rows", len(rows), "files", nf)
