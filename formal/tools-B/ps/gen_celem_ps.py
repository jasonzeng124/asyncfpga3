#!/usr/bin/env python3
"""Shard B: generate Formal/Cells/CElemPS/{Defs,Bxx}.lean and Formal/Cells/CElemPS.lean from celemtab.py's rows:
for every listed C-element of Formal.Target.DecodedPS.net, its INIT facts (SpecCElemFact.cfact) and its wiring
(feedback pin j reads a copy chain from the gate's own output; every held pin reads a copy chain from a constant gate
of the stated value or from the reset node). usage: gen_celem_ps.py CELEMTAB.json RESETNODE OUTDIR [maxchunks] [maxrows]"""
import json, sys, os
R = json.load(open(sys.argv[1])); RST = int(sys.argv[2]); OUT = sys.argv[3]; MAXC = int(sys.argv[4]) if len(sys.argv) > 4 else 30; MAXR = int(sys.argv[5]) if len(sys.argv) > 5 else 1000
C = 2500
bl = lambda l: "[" + ", ".join("true" if b else "false" for b in l) + "]"
nl = lambda l: "[" + ", ".join(str(x) for x in l) + "]"
rows = []
for r in sorted(R, key=lambda r: r["q"]):
    k = r["k"]; ci = [i in r["ci"] for i in range(k)]
    pol = [False] * k
    for i, p in zip(r["ci"], r["pol"]): pol[i] = bool(p)
    ov = [False] * k
    for i, v in r["ov"].items(): ov[int(i)] = bool(v)
    held = [i for i in range(k) if i != r["fb"] and not ci[i]]
    hs = ["(%d, %s, %d)" % (i, nl(r["chains"][i]), r["srcs"][i]) for i in held]
    gates = {r["q"]} | {c for ch in r["chains"] for c in ch} | {r["srcs"][i] for i in held if r["srcs"][i] != RST}
    rows.append(("(%d, %d, %d, %s, %s, %s, %s, [%s])" % (r["q"], k, r["fb"], bl(ci), bl(pol), bl(ov), nl(r["chains"][r["fb"]]), ", ".join(hs)),
                 {g // C for g in gates}))
# group rows into files with at most MAXC chunks
files = []; cur = []; cs = set()
for i, (txt, ch) in enumerate(rows):
    if cur and (len(cs | ch) > MAXC or len(cur) >= MAXR): files.append((cur, cs)); cur = []; cs = set()
    cur.append(i); cs |= ch
if cur: files.append((cur, cs))
D = os.path.join(OUT, "CElemPS"); os.makedirs(D, exist_ok=True)
open(os.path.join(D, "Defs.lean"), "w").write('''import Formal.Cells.RaceLinkPS.Defs
import Formal.Cells.SpecCElemFact

/-! GENERATED by tools-B/ps/gen_celem_ps.py: the C-element rows of THE target (celemtab.py) and their row check. -/

namespace Formal.Cells.CElemPS
open Formal.Target Formal.Target.DecodedPS Formal.Cells.RaceLinkPS Formal.Cells.SpecCElemFact

/-- The reset node of THE target (`SLICE_X2Y29.DQ`, a flop output driven by the environment in `circuit`). -/
def rstNode : Nat := %d

/-- `v` reads a chain of copy gates (k = 1, table 0b10, listed by index, nearest first) back to node `u`. -/
def chainAt : Nat → List Nat → Nat → Bool
  | v, [], u => v == u
  | v, c :: cs, u => (gateAt c).k == 1 && (gateAt c).init == 2 && (gateAt c).out == v &&
      chainAt ((gateAt c).ins.getD 0 0) cs u

/-- A row: (gate q, k, feedback pin j, ci, pol, ov, feedback chain, held pins (pin, chain, source)). -/
abbrev Row := Nat × Nat × Nat × List Bool × List Bool × List Bool × List Nat × List (Nat × List Nat × Nat)

/-- The row check: gate `q` has `k` pins and its INIT is a C-element over `ci`/`pol` with the other pins at `ov`
(`cfact`); pin `j` reads its own output through the listed copy chain; every held pin reads, through its listed
chain, either a constant gate (k = 0) of value `ov i` or the reset node (then `ov i = false`). -/
def rowOK (r : Row) : Bool :=
  let (q, k, j, ci, pol, ov, fbc, held) := r
  let G := gateAt q
  G.k == k && G.out == q && j < k && cfact k G.init j (fl ci) (fl pol) (fl ov) &&
  chainAt (G.ins.getD j 0) fbc q &&
  held.all fun (i, ch, s) => i < k && i != j && !(fl ci i) && chainAt (G.ins.getD i 0) ch s &&
    ((s == rstNode && !(fl ov i)) || ((gateAt s).k == 0 && (gateAt s).out == s && (gateAt s).init.testBit 0 == fl ov i))

end Formal.Cells.CElemPS
''' % RST)
for fi, (idx, cs) in enumerate(files):
    body = ["import Formal.Cells.CElemPS.Defs", "",
            "/-! GENERATED by tools-B/ps/gen_celem_ps.py: rows %d-%d (%d netlist chunks). -/" % (idx[0], idx[-1], len(cs)), "",
            "namespace Formal.Cells.CElemPS", "open Formal.Target Formal.Target.DecodedPS Formal.Cells.RaceLinkPS Formal.Cells.SpecCElemFact", "",
            "set_option maxRecDepth 100000 in", "def rows%02d : List Row := [" % fi]
    body.append(",\n".join("  " + rows[i][0] for i in idx) + "]")
    body += ["", "set_option maxHeartbeats 0 in", "set_option maxRecDepth 100000 in",
             "theorem rows%02d_ok : rows%02d.all rowOK = true := by decide +kernel" % (fi, fi), "", "end Formal.Cells.CElemPS", ""]
    open(os.path.join(D, "B%02d.lean" % fi), "w").write("\n".join(body))
top = ["import Formal.Cells.CElemPS.B%02d" % i for i in range(len(files))]
top += ["", "/-!", "# Formal.Cells.CElemPS — THE target's C-elements, checked on `DecodedPS.net` (GENERATED by tools-B/ps/gen_celem_ps.py)", "",
        "## Problem, plainly",
        "Which storage gates of THE target's Lean netlist satisfy the INIT and wiring premises of `SpecCElem.celem_forced`?",
        "`allRows` (%d gates, from the untrusted celemtab.py) all pass `rowOK`: INIT facts (`cfact`), feedback through a" % len(rows),
        "copy chain from the gate's own output, every other non-C pin tied through a copy chain to a constant of the stated",
        "value or to the reset node. `row_hall`/`row_hhold` turn a passing row into `celem_forced`'s `hall`/`hhold` for",
        "the netlist's gate `net.gates.getD q default`.", "",
        "## Not covered", "That this list is every C-element (the classifier is untrusted; a missed one is simply not covered);",
        "the environment hypothesis `hA` and the timing conditions; the routed chain delays (CGateOK via C's `collapse`).", "-/", "",
        "namespace Formal.Cells.CElemPS", "open Formal.Target Formal.Target.DecodedPS Formal.Cells.RaceLinkPS Formal.Cells.SpecCElemFact", "",
        "set_option maxRecDepth 100000 in", "def allRows : List Row := " + " ++ ".join("rows%02d" % i for i in range(len(files))), "",
        "set_option maxRecDepth 100000 in", "theorem allRows_ok : allRows.all rowOK = true := by",
        "  simp only [allRows, List.all_append, " + ", ".join("rows%02d_ok" % i for i in range(len(files))) + ", Bool.and_self]", "",
        '''theorem cfact_of_row {q k j : Nat} {ci pol ov : List Bool} {fbc : List Nat} {held : List (Nat × List Nat × Nat)}
    (h : rowOK (q, k, j, ci, pol, ov, fbc, held) = true) :
    (net.gates.getD q default).k = k ∧ j < k ∧
      cfact k (net.gates.getD q default).init j (fl ci) (fl pol) (fl ov) = true := by
  simp only [rowOK, Bool.and_eq_true] at h
  obtain ⟨⟨⟨⟨⟨h1, -⟩, h3⟩, h4⟩, -⟩, -⟩ := h
  have h1' : (gateAt q).k = k := beq_iff_eq.mp h1
  rw [← gateAt_eq]
  exact ⟨h1', of_decide_eq_true h3, h4⟩

theorem row_ok {r : Row} (hr : r ∈ allRows) : rowOK r = true := by
  have := allRows_ok; simp only [List.all_eq_true] at this; exact this r hr

/-- **`hall` for every listed C-element of the netlist.** -/
theorem row_hall {q k j : Nat} {ci pol ov : List Bool} {fbc : List Nat} {held : List (Nat × List Nat × Nat)}
    (hr : (q, k, j, ci, pol, ov, fbc, held) ∈ allRows) :
    ∀ (w : Bool) (v : Nat → Bool), (∀ i, i < k → i ≠ j → fl ci i = true → (v i ^^ fl pol i) = w) →
      (∀ i, i < k → i ≠ j → fl ci i = false → v i = fl ov i) →
      (net.gates.getD q default).init.testBit (addr k v) = w :=
  hall_of_cfact (cfact_of_row (row_ok hr)).2.2

/-- **`hhold` for every listed C-element of the netlist.** -/
theorem row_hhold {q k j : Nat} {ci pol ov : List Bool} {fbc : List Nat} {held : List (Nat × List Nat × Nat)}
    (hr : (q, k, j, ci, pol, ov, fbc, held) ∈ allRows) :
    ∀ (w : Bool) (v : Nat → Bool), v j = !w →
      (∀ i, i < k → i ≠ j → fl ci i = false → v i = fl ov i) →
      (net.gates.getD q default).init.testBit (addr k v) = w →
      ∀ i, i < k → i ≠ j → fl ci i = true → (v i ^^ fl pol i) = w :=
  hhold_of_cfact (cfact_of_row (row_ok hr)).2.2 (cfact_of_row (row_ok hr)).2.1

set_option maxRecDepth 100000 in\ntheorem allRows_length : allRows.length = %d := by decide

end Formal.Cells.CElemPS
''' % len(rows)]
open(os.path.join(OUT, "CElemPS.lean"), "w").write("\n".join(top))
print("rows", len(rows), "files", len(files), [len(c) for _, c in files])
