#!/usr/bin/env python3
"""Shard B (UNTRUSTED generator; rows checked in Lean by ArbOneAck.oneAckOK): one-acknowledge rows for the arbiters
with a server-path certificate (CertArbPS / ArbServerPS.rowsA). For each certificate (cause value cv = q's old value),
the losing side is the grant needing q = cv; its acknowledge rows kA (held by A0 low + reset), kG (held by its grant
low + reset) and the grant row kGr (held low by q = !cv), from ArbAckPS.arows.  usage: gen_oneack_ps.py LEANDIR OUT.lean"""
import sys, re, ast, os
D = sys.argv[1]
def lean2py(t):
    t = t.replace("⟨", "(").replace("⟩", ")").replace("true", "True").replace("false", "False")
    return ast.literal_eval(t)
ack = open(os.path.join(D, "ArbAckPS.lean")).read()
body = ack[ack.index("def arows : List ARow := [") + len("def arows : List ARow := "):]
body = body[:body.index("\n\nset_option")]
arows = lean2py(body)
srv = open(os.path.join(D, "ArbServerPS.lean")).read()
pairs = [(int(i), c) for i, c in re.findall(r"⟨arbs\.getD (\d+) ⟨0, \[\]⟩, (c\d+)⟩", srv)]
FAM = os.environ.get("CERTFAM", "CertArbPS"); NAME = os.environ.get("OUTNAME", "ArbOneAckAllPS")
if os.environ.get("PAIRS"): pairs = [(int(x.split(":")[0]), x.split(":")[1]) for x in os.environ["PAIRS"].split(",")]
certs = {}
for f in sorted(os.listdir(os.path.join(D, FAM))):
    t = open(os.path.join(D, FAM, f)).read()
    for m in re.finditer(r"def (c\d+) : Prem × List CRow := \((.*?)\]\)\n", t, re.S):
        prem, rows = m.group(2).split(", [\n", 1)
        rowl = [l.strip().rstrip(",") for l in rows.split("\n") if l.strip()]
        cn, cv = re.match(r"⟨(\d+), (true|false),", prem).groups()
        certs[m.group(1)] = (int(cn), cv == "true", [int(re.match(r"⟨⟨(\d+),", r).group(1)) for r in rowl])
RST = 186905
def pins_txt(pins): return "[" + ", ".join("(%s, %d)" % ("[" + ", ".join(map(str, ch)) + "]", s) for ch, s in pins) + "]"
def bl(l): return "[" + ", ".join("true" if b else "false" for b in l) + "]"
out = []
for ai, cname in pairs:
    cn, cv, rowqs = certs[cname]
    a0src = rowqs[-2]
    side = [r for r in arows if r[0] == ai and r[1] == cv][0]
    gq, gpins, gj, gheld, gov = side[2]
    aq, apins, gp, fb, aheld, aov = side[3]
    k = len(apins)
    ja0 = [i for i, (ch, s) in enumerate(apins) if s == a0src]
    jrst = [i for i, (ch, s) in enumerate(apins) if s == RST]
    if not ja0 or not jrst: print("skip", cname, "no A0/rst pin"); continue
    ja0, jrst = ja0[0], jrst[0]
    def krow(q, pins, P, w, fbi, mem, held, ov, vals):
        kk = len(pins); bv = [vals.get(i, False) for i in range(kk)]
        return "⟨%d, %s, [%s], %s, %s, %d, %s, %s, %s⟩" % (q, pins_txt(pins), ", ".join(map(str, P)), bl(bv),
            "true" if w else "false", fbi, "true" if mem else "false", bl(list(held) + [False] * (kk - len(held))),
            bl(list(ov) + [False] * (kk - len(ov))))
    kA = krow(aq, apins, [ja0, jrst], False, fb, True, aheld, aov, {})
    kG = krow(aq, apins, [gp, jrst], False, fb, True, aheld, aov, {})
    kGr = krow(gq, gpins, [gj], False, len(gpins), False, gheld, gov, {gj: not cv})
    out.append("⟨arbs.getD %d ⟨0, []⟩, %s, %s, %s, %s, %d, %d, %d, %d⟩" % (ai, cname, kA, kG, kGr, ja0, jrst, gp, gj))
L = ["import Formal.Cells.ArbOneAck", "import Formal.Cells.ArbServerPS", "import Formal.Cells." + FAM, "",
     "/-!", "# Formal.Cells." + NAME + " — the losing client is not acknowledged, %d arbiters of THE target (GENERATED)" % len(out), "",
     "GENERATED by tools-B/ps/gen_oneack_ps.py. For each arbiter with a server-path certificate (`" + FAM + "`), in the",
     "certificate's transaction (q leaves its old value `cv`), the losing side's acknowledge (the side whose grant needs",
     "q = cv) stays low: `ArbOneAck.one_ack_of`, in every behaviour of THE circuit with H_ARB(T), one corner.", "-/", "",
     "namespace Formal.Cells." + NAME, "open Formal.Target Formal.Target.DecodedPS Formal.Cells.CertPS Formal.Cells.ArbServer",
     "  Formal.Cells.ArbOneAck Formal.Cells." + FAM, "",
     "set_option maxRecDepth 100000 in", "def rows : List OneAckRow := [\n  %s]" % ",\n  ".join(out), "",
     "set_option maxHeartbeats 0 in", "set_option maxRecDepth 100000 in",
     "theorem rows_ok : rows.all (fun r => oneAckOK r && arbCertOK r.A r.pc) = true := by decide +kernel", "",
     "set_option maxHeartbeats 0 in", "set_option maxRecDepth 100000 in",
     "theorem rows_full : ∀ r ∈ rows, oneAckOK r = true ∧ certOK r.pc.1 r.pc.2 = true ∧ arbCertOK r.A r.pc = true ∧ r.A ∈ arbs := by",
     "  have hc : ∀ pc ∈ certs, certOK pc.1 pc.2 = true := List.all_eq_true.1 certs_ok",
     "  have ho := List.all_eq_true.1 rows_ok",
     "  intro r hr",
     "  have h := ho r hr",
     "  simp only [Bool.and_eq_true] at h",
     "  refine ⟨h.1, ?_, h.2, ?_⟩",
     "  · simp only [rows, List.mem_cons, List.not_mem_nil, or_false] at hr",
     "    rcases hr with " + " | ".join("rfl" for _ in out) + " <;> exact hc _ (by simp [certs, " + ", ".join(sorted(set(re.findall(r"\b(certs\d\d)\b", open(os.path.join(D, FAM + ".lean")).read())))) + "])",
     "  · simp only [rows, List.mem_cons, List.not_mem_nil, or_false] at hr",
     "    rcases hr with " + " | ".join("rfl" for _ in out)] + \
    ["    · exact Formal.Cells.ArbServerPS.getD_mem (i := %d) (by decide)" % ai for ai, _ in pairs] + ["",
     "/-- **The losing client is not acknowledged**, for each listed arbiter transaction (see `ArbOneAck.one_ack_of`). -/",
     "theorem target_one_ack : type_of% (@one_ack_of rows rows_full) := @one_ack_of rows rows_full", "",
     "end Formal.Cells." + NAME, ""]
open(sys.argv[2], "w").write("\n".join(L))
print("rows", len(out))
