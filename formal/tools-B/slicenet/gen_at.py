#!/usr/bin/env python3
"""Shard B (UNTRUSTED generator; the Lean kernel re-checks everything it emits).
Writes formal/lean/Formal/Cells/ArcTreePS/{A000..A074,AT}.lean: per-chunk trees of the packed arc0 of every gate.
usage: gen_at.py net.json"""
import json, sys, os
net = json.load(open(sys.argv[1])); G = net["gates"]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../lean/Formal/Cells/ArcTreePS")
C, D, NCH = 2500, 12, 75
hdr = "/-! GENERATED by formal/tools-B/slicenet/gen_at.py. Do not edit. -/\n\n"
def enc(g):
    if not g["arcs"]: return 0
    a = g["arcs"][0]
    for k in ("fmin", "fmax", "smin", "smax"): assert a[k] < 4096
    return a["fmin"] + 4096 * (a["fmax"] + 4096 * (a["smin"] + 4096 * a["smax"]))
def tree(leaves, d):
    if d == 0: return ".lf none" if leaves[0] is None else ".lf (some %d)" % leaves[0]
    h = len(leaves) // 2
    return ".nd (%s) (%s)" % (tree(leaves[:h], d - 1), tree(leaves[h:], d - 1))
for c in range(NCH):
    ch = G[c * C:(c + 1) * C]
    leaves = [enc(g) for g in ch] + [None] * (2 ** D - len(ch))
    with open(os.path.join(OUT, "A%03d.lean" % c), "w") as f:
        f.write("import Formal.Cells.ArcTree\nimport Formal.Target.NetPS.G%03d\n\n" % c + hdr)
        f.write("namespace Formal.Cells.ArcTreePS\nopen Formal.Target.DecodedPS Formal.Timing.SpecChain Formal.Timing.ChunkCM Formal.Cells.ArcTree\n\n")
        f.write("set_option maxRecDepth 100000 in\ndef a%03d : BT :=\n  %s\n\n" % (c, tree(leaves, D)))
        f.write("set_option maxRecDepth 100000 in\ntheorem a%03d_fact : a%03d.perf 12 = true ∧\n" % (c, c))
        f.write("    a%03d.toList = g%03d.map (fun g => some (encA (arc0 g))) ++ List.replicate (2 ^ 12 - g%03d.length) none ∧\n" % (c, c, c))
        f.write("    g%03d.all (fun g => decA (encA (arc0 g)) == arc0 g) = true :=\n" % c)
        f.write("  ⟨by decide +kernel, by decide +kernel, by decide +kernel⟩\n\nend Formal.Cells.ArcTreePS\n")
with open(os.path.join(OUT, "AT.lean"), "w") as f:
    f.write("".join("import Formal.Cells.ArcTreePS.A%03d\n" % c for c in range(NCH)))
    f.write("import Formal.Net.CViewPS.CM\n\n" + hdr)
    f.write("namespace Formal.Cells.ArcTreePS\nopen Formal.Target Formal.Target.DecodedPS Formal.Timing.SpecChain Formal.Timing.ChunkCM Formal.Cells.ArcTree Formal.Net.CViewPS\n\n")
    f.write("def atPS : List BT := [%s]\n\n" % ", ".join("a%03d" % c for c in range(NCH)))
    f.write("theorem at_len : atPS.length = cs.length := rfl\n\n")
    f.write("theorem afacts : ∀ c, c < cs.length → AChunkFact atPS cs 12 c := by\n  intro c hc\n  rw [cs_len] at hc\n  match c, hc with\n")
    for c in range(NCH):
        f.write("  | %d, _ => simp only [AChunkFact, atPS, cs, List.getD_cons_succ, List.getD_cons_zero]; exact a%03d_fact\n" % (c, c))
    f.write("  | n + %d, h => exact absurd h (by omega)\n\n" % NCH)
    f.write("/-- The arc0 of the gate driving node `u`, from the trees. -/\ndef aPS (u : Nat) : Arc := aOf atPS 2500 12 u\n\n")
    f.write("theorem aPS_eq (u : Nat) : aPS u = arc0 (gaOf cs 2500 u) :=\n")
    f.write("  aOf_eq (C := 2500) (d := 12) (by decide) (by decide) at_len afacts u\n\nend Formal.Cells.ArcTreePS\n")
print("written")
