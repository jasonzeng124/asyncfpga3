#!/usr/bin/env python3
"""Shard B (UNTRUSTED generator; everything it emits is re-checked by the Lean kernel).
Writes formal/lean/Formal/Cells/SliceNetPS/{Data,S000..S074}.lean for THE target's slice net:
  cl      : the constant (k = 0) logic nodes and their values, per chunk (kNNN_ok checks each chunk)
  sNNN_ok : chunkSelOK gNNN vNNN = true  (per chunk: every logic gate's kept pin sources are distinct)
usage: gen.py net.json bnd.json   (from formal/tools/cview/lean2json.py on Formal/Target/NetPS)"""
import json, sys, os, re
net = json.load(open(sys.argv[1])); G = net["gates"]; bnd = json.load(open(sys.argv[2]))
idx = {n: i for i, n in enumerate(net["nodes"])}
env = set(idx[x] for x in bnd["env"])
OUT = os.path.join(os.path.dirname(__file__), "../../lean/Formal/Cells/SliceNetPS")
os.makedirs(OUT, exist_ok=True)
consts = sorted((v, g["init"] & 1) for v, g in enumerate(G) if g["k"] == 0 and v not in env)
NCH = 75
per = [[] for _ in range(NCH)]
for v, b in consts: per[v // 2500].append((v % 2500, b))
hdr = "/-! GENERATED by formal/tools-B/slicenet/gen.py. Do not edit. -/\n\n"
with open(os.path.join(OUT, "Data.lean"), "w") as f:
    f.write("import Formal.Cells.SliceNetPS.Defs\n\n" + hdr + "namespace Formal.Cells.SliceNetPS\n\n")
    for c in range(NCH):
        f.write("def cl%03d : List (Nat × Bool) := [%s]\n" % (c, ", ".join("(%d, %s)" % (o, "true" if b else "false") for o, b in per[c])))
    f.write("\n/-- The %d constant logic nodes of THE target, per chunk. -/\ndef cl : List (List (Nat × Bool)) := [%s]\n\n" % (len(consts), ", ".join("cl%03d" % c for c in range(NCH))))
    f.write("def constF (s : Nat) : Option Bool := constOf cl s\n\nend Formal.Cells.SliceNetPS\n")
for c in range(NCH):
    with open(os.path.join(OUT, "S%03d.lean" % c), "w") as f:
        f.write("import Formal.Cells.SliceNetPS.Data\nimport Formal.Net.CViewPS.V%03d\n\n" % c + hdr)
        f.write("namespace Formal.Cells.SliceNetPS\nopen Formal.Target.DecodedPS Formal.Net.CViewPS\n\n")
        f.write("set_option maxRecDepth 100000 in\ntheorem s%03d_ok : chunkSelOK constF g%03d v%03d = true := by decide +kernel\n\n" % (c, c, c))
        f.write("set_option maxRecDepth 100000 in\ntheorem k%03d_ok : constChunkOK g%03d cl%03d = true := by decide +kernel\n\n" % (c, c, c))
        f.write("end Formal.Cells.SliceNetPS\n")
with open(os.path.join(OUT, "Chunks.lean"), "w") as f:
    f.write("import Formal.Net.CViewPS.All\n" + "".join("import Formal.Cells.SliceNetPS.S%03d\n" % c for c in range(NCH)) + "\n" + hdr)
    f.write("namespace Formal.Cells.SliceNetPS\nopen Formal.Target.DecodedPS Formal.Net.CViewPS\n\n")
    f.write("set_option maxRecDepth 100000 in\ntheorem sel_ok : ∀ q ∈ cs.zip vss, chunkSelOK constF q.1 q.2 = true := by\n")
    f.write("  have h : (cs.zip vss).all (fun q => chunkSelOK constF q.1 q.2) = true := by\n")
    f.write("    simp only [cs, vss, List.zip_cons_cons, List.zip_nil_left, List.all_cons, List.all_nil, Bool.and_true, %s]\n" %
            ", ".join("s%03d_ok" % c for c in range(NCH)))
    f.write("  simpa [List.all_eq_true] using h\n\n")
    f.write("theorem const_ok : ∀ c, c < cs.length → constChunkOK (cs.getD c []) (cl.getD c []) = true := by\n  intro c hc\n  rw [cs_len] at hc\n  match c, hc with\n")
    for c in range(NCH):
        f.write("  | %d, _ => simp only [cs, cl, List.getD_cons_succ, List.getD_cons_zero]; exact k%03d_ok\n" % (c, c))
    f.write("  | n + %d, h => exact absurd h (by omega)\n" % NCH)
    f.write("\nend Formal.Cells.SliceNetPS\n")
print("consts", len(consts), "chunks", NCH)
