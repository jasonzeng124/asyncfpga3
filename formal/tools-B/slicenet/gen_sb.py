#!/usr/bin/env python3
"""Shard B (UNTRUSTED generator; the Lean kernel re-checks everything it emits).
Writes formal/lean/Formal/Cells/StartBoundPS/{F000..F074,FT,C000..C074,Chunks}.lean: per-chunk value trees
(stN(gate) + smax(arc0) per node, depth 12) and per-chunk checks that every logic gate's collapsed start at
g = 1, kappa = 0 is <= HB.  usage: gen_sb.py net.json HB"""
import json, sys, os
net = json.load(open(sys.argv[1])); G = net["gates"]; HB = int(sys.argv[2])
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../lean/Formal/Cells/StartBoundPS")
C, D, NCH = 2500, 12, 75
assert (len(G) + C - 1) // C == NCH
hdr = "/-! GENERATED by formal/tools-B/slicenet/gen_sb.py. Do not edit. -/\n\n"
def stn(g): return max([a["smax"] for a in g["arcs"]] + [0])
def val(g): return stn(g) + (g["arcs"][0]["smax"] if g["arcs"] else 0)
def tree(leaves, d):
    if d == 0: return ".lf none" if leaves[0] is None else ".lf (some %d)" % leaves[0]
    h = len(leaves) // 2
    return ".nd (%s) (%s)" % (tree(leaves[:h], d - 1), tree(leaves[h:], d - 1))
for c in range(NCH):
    ch = G[c * C:(c + 1) * C]
    leaves = [val(g) for g in ch] + [None] * (2 ** D - len(ch))
    with open(os.path.join(OUT, "F%03d.lean" % c), "w") as f:
        f.write("import Formal.Cells.StartBound\nimport Formal.Target.NetPS.G%03d\n\n" % c + hdr)
        f.write("namespace Formal.Cells.StartBoundPS\nopen Formal.Target.DecodedPS Formal.Timing.ChunkCM Formal.Cells.StartBound\n\n")
        f.write("set_option maxRecDepth 100000 in\ndef f%03d : BT :=\n  %s\n\n" % (c, tree(leaves, D)))
        f.write("set_option maxRecDepth 100000 in\ntheorem f%03d_fact : f%03d.perf 12 = true ∧\n" % (c, c))
        f.write("    f%03d.toList = g%03d.map fS ++ List.replicate (2 ^ 12 - g%03d.length) none :=\n" % (c, c, c))
        f.write("  ⟨by decide +kernel, by decide +kernel⟩\n\nend Formal.Cells.StartBoundPS\n")
with open(os.path.join(OUT, "FT.lean"), "w") as f:
    f.write("".join("import Formal.Cells.StartBoundPS.F%03d\n" % c for c in range(NCH)))
    f.write("import Formal.Net.CViewPS.CM\n\n" + hdr)
    f.write("namespace Formal.Cells.StartBoundPS\nopen Formal.Target.DecodedPS Formal.Timing.ChunkCM Formal.Cells.StartBound Formal.Net.CViewPS\n\n")
    f.write("def tfPS : List BT := [%s]\n\n" % ", ".join("f%03d" % c for c in range(NCH)))
    f.write("theorem tf_len : tfPS.length = cs.length := rfl\n\n")
    f.write("theorem ffacts : ∀ c, c < cs.length → FChunkFact tfPS cs 12 c := by\n  intro c hc\n  rw [cs_len] at hc\n  match c, hc with\n")
    for c in range(NCH):
        f.write("  | %d, _ => simp only [FChunkFact, tfPS, cs, List.getD_cons_succ, List.getD_cons_zero]; exact f%03d_fact\n" % (c, c))
    f.write("\n/-- Per-node values from the trees. -/\ndef fPS (u : Nat) : Nat := fOf tfPS 2500 12 u\n\n")
    f.write("theorem fPS_eq (u : Nat) : fPS u = stN (gaOf cs 2500 u) + (arc0 (gaOf cs 2500 u)).smax :=\n")
    f.write("  fOf_eq (by decide) (by decide) tf_len ffacts u\n\nend Formal.Cells.StartBoundPS\n")
for c in range(NCH):
    with open(os.path.join(OUT, "C%03d.lean" % c), "w") as f:
        f.write("import Formal.Cells.StartBoundPS.FT\nimport Formal.Cells.StartBoundPS.Defs\nimport Formal.Net.CViewPS.V%03d\n\n" % c + hdr)
        f.write("namespace Formal.Cells.StartBoundPS\nopen Formal.Target.DecodedPS Formal.Net.CViewPS\n\n")
        f.write("set_option maxRecDepth 100000 in\ntheorem c%03d_ok : chunkStartOK cmPS fPS %d g%03d v%03d = true := by decide +kernel\n\n" % (c, HB, c, c))
        f.write("end Formal.Cells.StartBoundPS\n")
with open(os.path.join(OUT, "Chunks.lean"), "w") as f:
    f.write("import Formal.Net.CViewPS.All\n" + "".join("import Formal.Cells.StartBoundPS.C%03d\n" % c for c in range(NCH)) + "\n" + hdr)
    f.write("namespace Formal.Cells.StartBoundPS\nopen Formal.Target.DecodedPS Formal.Net.CViewPS\n\n")
    f.write("/-- The bound checked on every chunk (ps, at g = 1, κ = 0). -/\ndef HB : Nat := %d\n\n" % HB)
    f.write("set_option maxRecDepth 100000 in\ntheorem start_ok : ∀ q ∈ cs.zip vss, chunkStartOK cmPS fPS HB q.1 q.2 = true := by\n")
    f.write("  have h : (cs.zip vss).all (fun q => chunkStartOK cmPS fPS HB q.1 q.2) = true := by\n")
    f.write("    simp only [HB, cs, vss, List.zip_cons_cons, List.zip_nil_left, List.all_cons, List.all_nil, Bool.and_true, %s]\n" %
            ", ".join("c%03d_ok" % c for c in range(NCH)))
    f.write("  simpa [List.all_eq_true] using h\n\nend Formal.Cells.StartBoundPS\n")
print("written; HB =", HB)
