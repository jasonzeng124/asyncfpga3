#!/usr/bin/env python3
"""tools-B/select/muxn_rows.py NET.json ROUTED.json OUT.lean NAMESPACE (shard B, UNTRUSTED emitter; Lean checks the output):
the decode LUTs of every bdc_muxnN in a decoded route (a LUT read by a join `<mux>.uj<k>.u`), as Lean facts for
Formal.Cells.MuxNDecode.decode_no_pulse:
  * `req_k`: the request pin at 0 forces the LUT's INIT to 0;
  * `idx_k`: of the 2^m assignments of the index pins, exactly one does NOT force 0 (the one selecting k).
Pins are the DECODED gate's pins (after nextpnr's permutation), sources traced back through pips / hops. The request pin
is the one whose source is shared by all N decode LUTs of the mux and that is a positive literal in each (research's
muxn_decode_sites reads it the same way, from the LUT functions); the other pins in the INIT's support are the index
pins. Each fact is decided by the Lean kernel (`decide`), not by this script."""
import json, re, sys, collections
net, rout, outp, ns = sys.argv[1:5]
G = json.load(open(net))["gates"]
cells = json.load(open(rout))["modules"]["top"]["cells"]
bel = {v["attributes"].get("NEXTPNR_BEL"): k for k, v in cells.items()}
drvg = {g["out"]: g for g in G}
def src(u):
    for _ in range(400):
        g = drvg.get(u)
        if g is None or g["kind"] not in ("pip", "hop"): return u
        u = g["ins"][0]
    return u
def cellof(g):
    m = re.match(r"^(SLICE_X\d+Y\d+)\.([A-D])LUT\.O([56])$", g["name"])
    return bel.get("%s/%s%sLUT" % m.groups(), "") if m else ""
# readers by gate output node -> which LUT cells read it (through pips)
reads = collections.defaultdict(set)
for g in G:
    if g["kind"] in ("lut5", "lut6"):
        for u in g["ins"]: reads[src(u)].add(cellof(g))
dec = collections.defaultdict(dict)   # mux -> k -> gate
for g in G:
    if g["kind"] not in ("lut5", "lut6"): continue
    for r in reads.get(g["out"], ()):
        m = re.match(r"^(.*)\.uj(\d+)\.u(\$LUT[56])?$", r)
        if m and cellof(g).startswith(m.group(1) + ".") and ".uj" not in cellof(g):
            dec[m.group(1)][int(m.group(2))] = g
def f(g, a): return (int(g["init"]) >> a) & 1
def support(g):
    k = len(g["ins"]); return [i for i in range(k) if any(f(g, a) != f(g, a ^ (1 << i)) for a in range(1 << k))]
def positive(g, i):   # output 1 only where pin i is 1
    k = len(g["ins"]); return all(not f(g, a) or (a >> i) & 1 for a in range(1 << k))
L = ["import Formal.Cells.MuxNDecode", "", "/-! GENERATED by formal/tools-B/select/muxn_rows.py from %s. Decode LUTs of the" % net,
     "route's N-way muxes: the request pin forces 0, and exactly one index assignment does not (each by `decide`). -/", "",
     "namespace %s" % ns, "open Formal.Timing.Island", ""]
n = 0
for mux in sorted(dec):
    gs = dec[mux]; N = len(gs)
    common = None
    for k, g in gs.items():
        s = {src(g["ins"][i]) for i in support(g) if positive(g, i)}
        common = s if common is None else common & s
    for k, g in sorted(gs.items()):
        kk = len(g["ins"]); sup = support(g)
        r = [i for i in sup if src(g["ins"][i]) in (common or set()) and positive(g, i)]
        if len(r) != 1: print("SKIP %s k=%d: request pin not unique %s" % (mux, k, r)); continue
        r = r[0]; P = [i for i in sup if i != r]; m = len(P)
        nm = re.sub(r"[^A-Za-z0-9]", "_", mux.replace("bridge_i.udut.", "")) + "_k%d" % k
        asg = "fun v => P.map fun j => (j, (v >>> P.idxOf j) % 2 == 1)".replace("P", "[%s]" % ", ".join(map(str, P)))
        L += ["/-- %s, decode of input %d: LUT %s, k = %d, INIT = %d, request pin %d, index pins %s. -/" % (mux, k, g["name"], kk, int(g["init"]), r, P),
              "theorem req_%s : ForcesP %d %d [(%d, false)] false = true := by decide" % (nm, kk, int(g["init"]), r),
              "theorem idx_%s : ((List.range %d).filter fun v => ForcesP %d %d ((%s) v) false).length = %d := by decide" % (nm, 2 ** m, kk, int(g["init"]), asg, 2 ** m - 1), ""]
        n += 1
L += ["end %s" % ns, ""]
open(outp, "w").write("\n".join(L))
print("%d muxes, %d decode LUTs emitted" % (len(dec), n))
