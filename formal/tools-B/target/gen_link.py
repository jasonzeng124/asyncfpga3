#!/usr/bin/env python3
"""Shard B: generate Formal/Cells/TargetLink.lean, which ties B's generated target data (ArbClean.targetQ,
Ua1Static.ua1Path/ua1Loop) to shard A's Lean netlist Formal.Target.Decoded.net by equalities decided on the
netlist itself. usage: gen_link.py NET.json ARBS.json BND.json DUMP.json > TargetLink.lean"""
import sys, os, json
HERE = os.path.dirname(os.path.abspath(__file__))
NETF, ARBF, BNDF, DUMPF = sys.argv[1:5]
N = json.load(open(NETF)); g = N["gates"]
# targetQ gates (same order as ArbClean.targetQ)
sys.argv = [sys.argv[0], NETF, ARBF, BNDF, "0,1"]
src = open(os.path.join(HERE, "adv.py")).read(); src = src[:src.index('base, res0 = run({}, "base")')]
ns = {"__file__": os.path.join(HERE, "adv.py")}; exec(compile(src, "adv.py", "exec"), ns)
qidx = [ns["roles"](a)["q"] for a in ns["A"]]
# ua1 path/loop (same as ua1arcs.py)
sys.argv = [sys.argv[0], NETF, DUMPF, "0.5", "1.0"]
src2 = open(os.path.join(HERE, "kstar.py")).read(); src2 = src2[:src2.index("res = []")]
ns2 = {}; exec(compile(src2, "kstar.py", "exec"), ns2)
crit = ns2["crit"]
gi = next(i for i, G in enumerate(g) if G["name"] == "SLICE_X2Y18.DLUT.O6"); G = g[gi]
n = G["ins"][0]; route = []
while g[n]["k"] == 1 and n != gi: route.append(n); n = g[n]["ins"][0]
loop = [(m, 0) for m in route] + [(gi, 0)]
arcs, ok = crit(G["ins"][4], 601880, 600888 - 5000, gi); assert ok
path = arcs + [(gi, 4)]
C = 2500
def at(i): return "(gate %d)" % i
out = []
out.append("""import Formal.Target.Net.All
import Formal.Cells.ArbClean
import Formal.Cells.Ua1Static

/-!
# Formal.Cells.TargetLink — B's target data, tied to shard A's Lean netlist (GENERATED by tools-B/target/gen_link.py)

`ArbClean.targetQ` (the nine ustates' names, tables, pin counts) and `Ua1Static.ua1Path`/`ua1Loop` (the arcs of
ua1's episode path and feedback loop) were generated from a JSON rebuild of `Formal/Target/Net`. Here each is
proved equal to the corresponding gate or arc of `Formal.Target.Decoded.net` itself, so `targetQ_facts` and
`ua1_holds_at_015`/`ua1_fails_at_016` are statements about the netlist the Spec theorem is about. The roles of
the ustate pins and the identity of the path (which gate pin reads which node) are not re-derived here.
-/

namespace Formal.Cells.TargetLink

open Formal.Target Formal.Target.Decoded

/-- Gate `i` of the decoded netlist. -/
def gate (i : Nat) : Gate := net.gates.getD i default

theorem getD_skip {α : Type} (l1 l2 : List α) (h : l1.length = 2500) (i : Nat) (d : α) :
    (l1 ++ l2).getD (i + 2500) d = l2.getD i d := by
  simp only [List.getD_eq_getElem?_getD]
  rw [List.getElem?_append_right (by omega)]
  congr 2; omega

theorem getD_left {α : Type} (l1 l2 : List α) (i : Nat) (hi : i < l1.length) (d : α) :
    (l1 ++ l2).getD i d = l1.getD i d := by
  simp only [List.getD_eq_getElem?_getD]
  rw [List.getElem?_append_left hi]
""")
chunks = sorted(set(i // C for i in qidx + [m for m, _ in path + loop]))
def chunk_lemma(i):
    k, j = divmod(i, C)
    return k, j
# a lemma per used index: gate i = (g<k>).getD j default
lines = []
for i in sorted(set(qidx + [m for m, _ in path + loop])):
    k, j = divmod(i, C)
    rw = " ".join([])
    proof = "  show (" + " ++ (".join("g%03d" % c for c in range(0, 80)) + ")" * 1 + ").getD %d default = _\n" % i if False else ""
    lines.append((i, k, j))
for i, k, j in lines:
    skips = ", ".join("getD_skip _ _ g%03d_len" % c for c in range(k))
    idx = "%d" % j + " + 2500" * k
    tail = "" if k == 79 else "\n  rw [getD_left _ _ _ (by rw [g%03d_len]; omega)]" % k
    out.append("theorem gate_%d : gate %d = (g%03d).getD %d default := by\n  show gates.getD (%s) default = _\n  simp only [gates]%s%s\n" % (
        i, i, k, j, idx, ("\n  rw [" + skips + "]") if k else "", tail))
# targetQ link
out.append("/-- The nine ustate O6 gates of `ArbClean.targetQ` are gates of the decoded netlist, with the same name,\npin count and table. -/")
for r, i in enumerate(qidx):
    G = g[i]
    out.append('theorem q%d : (gate %d).name = "%s" ∧ (gate %d).k = %d ∧ (gate %d).init = %d := by\n  rw [gate_%d]; decide +kernel\n' % (r, i, G["name"], i, G["k"], i, G["init"], i))
# ua1 arcs
def arcl(l): return "[" + ", ".join("(gate %d).arcs.getD %d default" % (m, p) for m, p in l) + "]"
out.append("/-- The arcs of `Ua1Static.ua1Path` and `ua1Loop` are the decoded netlist's arcs of these gate pins. -/")
out.append("theorem ua1Path_eq : Formal.Cells.Ua1Static.ua1Path = %s := by\n  simp only [%s]\n  decide +kernel\n" % (arcl(path), ", ".join("gate_%d" % m for m in sorted(set(m for m, _ in path)))))
out.append("theorem ua1Loop_eq : Formal.Cells.Ua1Static.ua1Loop = %s := by\n  simp only [%s]\n  decide +kernel\n" % (arcl(loop), ", ".join("gate_%d" % m for m in sorted(set(m for m, _ in loop)))))
out.append("""/-- **Ua1Static's verdicts as statements about the decoded netlist's own arcs.** -/""")
out.append("theorem ua1_holds_decoded :\n    ((%s).map (Formal.Cells.Ua1Static.hi 1 (15/100) (1/2))).sum <=\n      ((%s).map (Formal.Cells.Ua1Static.lo 1 (15/100) (1/2))).sum := by\n  rw [← ua1Path_eq, ← ua1Loop_eq]; exact Formal.Cells.Ua1Static.ua1_holds_at_015\n" % (arcl(loop), arcl(path)))
out.append("theorem ua1_fails_decoded :\n    ((%s).map (Formal.Cells.Ua1Static.lo 1 (16/100) (1/2))).sum <\n      ((%s).map (Formal.Cells.Ua1Static.hi 1 (16/100) (1/2))).sum := by\n  rw [← ua1Path_eq, ← ua1Loop_eq]; exact Formal.Cells.Ua1Static.ua1_fails_at_016\n" % (arcl(path), arcl(loop)))
# wiring: each listed gate pin reads the next listed gate's output node; both chains close at ua1
def wires(l, close):
    pairs = []
    for k, (m, pin) in enumerate(l):
        nxt = l[k + 1][0] if k + 1 < len(l) else close
        pairs.append((m, pin, nxt))
    return pairs
pw = wires(arcs, gi) + [(gi, 4, arcs[0][0])]
lw = wires([(m, 0) for m in route], gi) + [(gi, 0, route[0])]
def wthm(nm, pairs, doc):
    body = " ∧\n    ".join("(gate %d).ins.getD %d 0 = %d" % w for w in pairs)
    lem = ", ".join("gate_%d" % m for m in sorted(set(w[0] for w in pairs)))
    return "/-- %s -/\ntheorem %s :\n    %s := by\n  simp only [%s]\n  decide +kernel\n" % (doc, nm, body, lem)
out.append(wthm("ua1Path_wired", pw, "The episode path is wired: every listed pin reads the next listed gate's output, from ua1's pin A5 back to ua1's own output (gate %d)." % gi))
out.append("/-- The feedback route consists of copy gates (one pin, table 0b10). -/\ntheorem ua1Loop_copies :\n    " + " ∧\n    ".join("(gate %d).k = 1 ∧ (gate %d).init = 2" % (m, m) for m in route) + " := by\n  simp only [%s]\n  decide +kernel\n" % ", ".join("gate_%d" % m for m in route))
out.append(wthm("ua1Loop_wired", lw, "ua1's feedback loop is wired: pin A1 reads a chain of copy gates that starts at ua1's own output."))
out.append("end Formal.Cells.TargetLink")
print("\n".join(out))
