#!/usr/bin/env python3
"""Probe Bwit: emit formal/lean/Formal/Cells/BWit3Data.lean, the gate-timed gcd_hw run of
bsim.py as C's `CD` event lists (format of C's gen_data.py, reused read-only).
usage: python3 -B gen_cdata3.py [a b] [--check]"""
import os, sys, math
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import bsim3 as bsim  # noqa: E402
S = bsim.S
sys.path.insert(0, bsim.CAP)
import gen_data as G  # noqa: E402
OUT = os.path.join(S.ROOT, "formal", "lean", "Formal", "Cells", "BWit3Data.lean")

def render(a, b):
    names, ops, out0 = S.load_net()
    tr = bsim.simulate(a, b, names, ops)
    tr4 = [x[:4] for x in tr]
    errs, falls = S.check(a, b, names, ops, out0, tr4)
    if errs: raise SystemExit(f"run violates C's models: {errs[:10]}")
    rows = G.rows_of(names, ops, tr4)
    T = len(tr) - 1
    srq = S.toggles([s[0][2] for s in tr]); assert len(srq) == 2
    return f'''import Formal.Net.CapstoneWitnessLib
import Formal.Net.CapstoneNetChk

/-!
# GENERATED by formal/tools-B/bwit/gen_cdata3.py -- DO NOT EDIT

Probe Bwit (shard B): a GATE-TIMED run of the concrete gcd_hw network on a = {a}, b = {b}
(`bsim3.py`): as C's unit-delay run, except that every operator B gate-models (2..4-way fork
acknowledge, 2-input join request, steer branches and acknowledge OR) takes TWO ticks from
channel to channel (B's LUT 1 + wire 1), every bd_mux and every bd_arbiter gate-modelled too (bsim3.py; C's mux j traces are B's join nodes 6 ticks late, C's arbiter g1/g2 are B's ugrant nodes). Quiescent after {T} ticks; out0 (channel {out0})
closes at tick {falls}. Format: C's `CD` (toggle lists, bus, producer internal traces).
Nothing here is trusted: `BWit3Cells` checks it with C's checkers.
-/

namespace Formal.Cells.BWit3
open Formal.Net Formal.Net.CapNet Formal.Net.CapNet.Gcd Formal.Net.CapNet.Wit

set_option maxRecDepth 100000

def cdsB : List CD := [
''' + ",\n".join(rows) + f'''
]

def cdB (c : Fin NC) : CD := cdsB.getD c.val ⟨[], [], 0, [], []⟩

/-- The gate-timed run. -/
def chB : Fin NC → Handshake.Chan := wch cdB

def startRiseB : Nat := {srq[0]}
def startFallB : Nat := {srq[1]}
def out0CloseB : Nat := {falls[0]}

end Formal.Cells.BWit3
'''

def main():
    args = [x for x in sys.argv[1:] if not x.startswith("--")]
    a = int(args[0]) if args else 12; b = int(args[1]) if len(args) > 1 else 18
    txt = render(a, b)
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == txt
        print("gen_cdata:", "ok" if ok else "DRIFT"); return 0 if ok else 1
    open(OUT, "w").write(txt); print("wrote", OUT, len(txt), "bytes; gcd", math.gcd(a, b)); return 0

if __name__ == "__main__":
    sys.exit(main())
