#!/usr/bin/env python3
"""Probe Bwit: emit formal/lean/Formal/Cells/BWitNData.lean -- per channel the request and
acknowledge pin wire delays of the driver-bound network on the gate-timed run (bsim.py), and
per steer the token select table. Untrusted: BWitNet checks every item by kernel.
usage: python3 -B gen_bdata.py [--check]"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import bsim  # noqa: E402
S = bsim.S
OUT = os.path.join(S.ROOT, "formal", "lean", "Formal", "Cells", "BWitNData.lean")

def render():
    names, ops, out0 = S.load_net()
    tr = bsim.simulate(12, 18, names, ops)
    NC = len(names)
    prod, cons = {}, {}
    for n, o in enumerate(ops):
        for c in S.outs_of(o): prod[c] = n
        for c in S.ins_of(o): cons[c] = n
    rq = [S.toggles([s[0][c] for s in tr]) for c in range(NC)]
    ak = [S.toggles([s[1][c] for s in tr]) for c in range(NC)]
    def lst(d):
        o = ops[d[1]]
        if d[0] == "lk": return rq[o["o"]]
        if d[0] == "fa": return ak[o["i"]]
        if d[0] == "jr": return rq[o["o"]]
        if d[0] == "sb": return rq[o["t"] if d[2] else o["f"]]
        if d[0] == "ao": return ak[o["j"]]
    def w_of(L, d):
        if d is None: return 1
        Ld = lst(d)
        for w in range(1, 10):
            if [e + w - 1 for e in Ld] == L: return w
        raise SystemExit(f"no wire delay {L[:4]} vs {Ld[:4]} {d}")
    wR = [w_of(rq[c], bsim.reqSrc(16, c, ops, prod)) for c in range(NC)]
    wA = [w_of(ak[c], bsim.ackSrc(16, c, ops, cons)) for c in range(NC)]
    tabs = []
    for n, o in enumerate(ops):
        if not bsim.steer(o): tabs.append([]); continue
        j = o["j"]; r = rq[j]
        sel = [S.sel2(tr[r[2 * k] + 1][3][j]) for k in range((len(r) + 1) // 2)]
        if len(sel) % 2: sel.append(False)
        tabs.append(sel)
    bl = lambda xs: "[" + ", ".join("true" if x else "false" for x in xs) + "]"
    nl = lambda xs: "[" + ", ".join(str(x) for x in xs) + "]"
    return f'''import Formal.Cells.BWitData

/-!
# GENERATED by formal/tools-B/bwit/gen_bdata.py -- DO NOT EDIT (untrusted data)

Probe Bwit: for the driver-bound network on the gate-timed run `chB`: per channel, the wire
delay of the request pin (`wRT`) and acknowledge pin (`wAT`) from their netlist drivers; per
operator, the steer token select table (`tabB`; padded to even length). Checked in `BWitNet`.
-/

namespace Formal.Cells.BWit

def wRT : List Nat := {nl(wR)}
def wAT : List Nat := {nl(wA)}

def tabB : List (List Bool) := [
''' + ",\n".join("  " + bl(t) for t in tabs) + '''
]

end Formal.Cells.BWit
'''

def main():
    txt = render()
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == txt
        print("gen_bdata:", "ok" if ok else "DRIFT"); return 0 if ok else 1
    open(OUT, "w").write(txt); print("wrote", OUT, len(txt)); return 0

if __name__ == "__main__":
    sys.exit(main())
