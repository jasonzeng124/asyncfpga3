#!/usr/bin/env python3
"""Probe Bwit2: emit formal/lean/Formal/Cells/BWit3NData.lean -- for the mux-extended
driver-bound network on the run of bsim2.py: per channel the request / acknowledge pin wire
delays from the drivers FiniteNetBoundM names; per operator the token select table (steers and
muxes) and, for muxes, the internal node lists (cL form) of uj0, uj1, uor, udly[0].
Untrusted: BWit3Net checks every item by kernel.  usage: python3 -B gen_bdata3.py [--check]"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import bsim3 as bsim  # noqa: E402
S = bsim.S
OUT = os.path.join(S.ROOT, "formal", "lean", "Formal", "Cells", "BWit3NData.lean")

def render():
    names, ops, out0 = S.load_net()
    tr = bsim.simulate(12, 18, names, ops)
    NC = len(names)
    prod, cons = {}, {}
    for n, o in enumerate(ops):
        for c in S.outs_of(o): prod[c] = n
        for c in S.ins_of(o): cons[c] = n
    rq = [S.toggles([s[0][c] for s in tr]) for c in range(NC)]
    ak = [S.toggles([s[1][c] for s in tr]) for c in range(NC)]
    node = lambda n, k: [e + 1 for e in S.toggles([s[4][n][k] for s in tr])]
    def lst(d):
        o = ops[d[1]]
        if d[0] == "lk": return rq[o["o"]]
        if d[0] == "fa": return ak[o["i"]]
        if d[0] == "jr": return rq[o["o"]]
        if d[0] == "sb": return rq[o["t"] if d[2] else o["f"]]
        if d[0] == "ao": return ak[o["j"]]
        if d[0] == "md": return rq[o["z"]] if d[2] == 1 else node(d[1], 3)
        if d[0] == "ma": return ak[o["y"] if d[2] else o["x"]]
        if d[0] == "aR": return rq[o["z"]]
        if d[0] == "aA": return ak[o["y"] if d[2] else o["x"]]
    def w_of(L, d):
        if d is None: return 1
        Ld = lst(d)
        for w in range(1, 12):
            if [e + w - 1 for e in Ld] == L: return w
        raise SystemExit(f"no wire delay {L[:4]} vs {Ld[:4]} {d}")
    wR = [w_of(rq[c], bsim.reqSrc(16, c, ops, prod)) for c in range(NC)]
    wA = [w_of(ak[c], bsim.ackSrc(16, c, ops, cons)) for c in range(NC)]
    tabs, mj0, mj1, mo, md0, aq, ag1, ag2, tabA = [], [], [], [], [], [], [], [], []
    for n, o in enumerate(ops):
        if bsim.steer(o) or o["k"] == "mux":
            j = o["j"] if bsim.steer(o) else o["c"]; r = rq[j]
            sel = [S.sel2(tr[r[2 * k] + 1][3][j]) for k in range((len(r) + 1) // 2)]
            if len(sel) % 2: sel.append(False)
            tabs.append(sel)
        else: tabs.append([])
        if o["k"] == "mux":
            mj0.append(node(n, 0)); mj1.append(node(n, 1)); mo.append(node(n, 2)); md0.append(node(n, 3))
            assert node(n, 4) == rq[o["z"]] and node(n, 5) == ak[o["x"]] and node(n, 6) == ak[o["y"]]
        else:
            mj0.append([]); mj1.append([]); mo.append([]); md0.append([])
        if o["k"] == "amerge":
            aq.append(node(n, 0)); ag1.append(node(n, 2)); ag2.append(node(n, 3))
            r = rq[o["z"]]
            win = [bool(tr[r[2 * k] + 1][4][n][3]) for k in range((len(r) + 1) // 2)]  # g2 high
            assert all(tr[r[2 * k] + 1][4][n][2] != tr[r[2 * k] + 1][4][n][3] for k in range((len(r) + 1) // 2))
            if len(win) % 2: win.append(False)
            tabA.append(win)
            assert node(n, 1) == rq[o["z"]] and node(n, 4) == ak[o["x"]] and node(n, 5) == ak[o["y"]]
        else:
            aq.append([]); ag1.append([]); ag2.append([]); tabA.append([])
    bl = lambda xs: "[" + ", ".join("true" if x else "false" for x in xs) + "]"
    nl = lambda xs: "[" + ", ".join(str(x) for x in xs) + "]"
    ll = lambda L: "[\n" + ",\n".join("  " + nl(x) for x in L) + "\n]"
    return f'''import Formal.Cells.BWit3Data

/-!
# GENERATED by formal/tools-B/bwit/gen_bdata3.py -- DO NOT EDIT (untrusted data)

Probe Bwit2: for the mux-extended driver-bound network on the gate-timed run `chB`
(`BWit3Data`): per channel, the request / acknowledge pin wire delays (`wRT`, `wAT`); per
operator, the token select table (`tabB`, steers and muxes, padded to even length) and, for
each `bd_mux`, the internal node lists (`cL` form) of `uj0`, `uj1`, `uor`, `udly[0]`; for each
`bd_arbiter`, those of `q`, `g1`, `g2` and the winner table `tabAL` (per
`z.req` token: `true` iff grant 2 is high, padded to even length).
Checked in `BWit3Net`.
-/

namespace Formal.Cells.BWit3

def wRT : List Nat := {nl(wR)}
def wAT : List Nat := {nl(wA)}

def tabB : List (List Bool) := [
''' + ",\n".join("  " + bl(t) for t in tabs) + f'''
]

def mj0L : List (List Nat) := {ll(mj0)}
def mj1L : List (List Nat) := {ll(mj1)}
def moL : List (List Nat) := {ll(mo)}
def md0L : List (List Nat) := {ll(md0)}
def aqL : List (List Nat) := {ll(aq)}
def ag1L : List (List Nat) := {ll(ag1)}
def ag2L : List (List Nat) := {ll(ag2)}
def tabAL : List (List Bool) := [
''' + ",\n".join("  " + bl(t) for t in tabA) + f'''
]

end Formal.Cells.BWit3
'''

def main():
    txt = render()
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == txt
        print("gen_bdata3:", "ok" if ok else "DRIFT"); return 0 if ok else 1
    open(OUT, "w").write(txt); print("wrote", OUT, len(txt)); return 0

if __name__ == "__main__":
    sys.exit(main())
