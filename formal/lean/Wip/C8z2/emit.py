"""C-8z2: write the generated Lean files of the liveness witness run (called by livesim.py --emit).

Files (all under formal/lean/Formal/Net/):
  CapstoneLiveWitData.lean   the run (8t's CD event-list format) and the no-deadlock certificate
Nothing here is trusted: CapstoneLiveWitCells / Step* / Nd check it in the kernel.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "formal", "tools", "capwit"))
import gen_data  # noqa: E402  (8t's CD row renderer, unmodified)

NET = os.path.join(ROOT, "formal", "lean", "Formal", "Net")


def emit(a, b, names, ops, out0, tr, falls, cert, suffix=""):
    rows = gen_data.rows_of(names, ops, tr)
    T = len(tr) - 1
    F = falls[0]
    srq = [t for t in range(T) if tr[t + 1][0][2] != tr[t][0][2]]
    ce = ",\n  ".join(f"({n}, {j}, {'true' if v else 'false'})" for (n, j, v) in cert)
    txt = f'''import Formal.Net.CapstoneLiveWitLib

/-!
# GENERATED by formal/lean/Wip/C8z2/livesim.py --emit -- DO NOT EDIT

Probe C-8z2: one unit-delay run of the concrete gcd_hw network on a = {a}, b = {b}, meant to meet
every hypothesis of `gcd_hw_live_final` with `H = 1`: every gate fires one tick after it is
excited (C-elements hold while their inputs disagree); the a/b sources are free-running
(`req := !ack`); `start` offers one token at tick {srq[0]} and never again; sinks acknowledge after
one tick. out0's acknowledge falls at tick {F} (value {tr[F][3][out0]}); every gate but `start`'s LUT
is quiescent from tick {T} on.

`cdsL` is in 8t's `CD` format. `certL` names, for every tick `0 .. {F}`, one gate (operator,
index in `gatesE`, target value) that is excited and not yet at its target.
Nothing here is trusted: CapstoneLiveWitCells, CapstoneLiveWitStep* and CapstoneLiveWitNd
check it in the kernel.
-/

namespace Formal.Net.CapNet.LiveWit
open Formal.Net Formal.Net.CapNet Formal.Net.CapNet.Gcd Formal.Net.CapNet.Wit

set_option maxRecDepth 100000

abbrev Aw : Nat := {a}
abbrev Bw : Nat := {b}

def cdsL : List CD := [
{(","+chr(10)).join(rows)}
]

def cdW (c : Fin NC) : CD := cdsL.getD c.val ⟨[], [], 0, [], []⟩

/-- The run. -/
def chL : Fin NC → Handshake.Chan := wch cdW

/-- out0's first close. -/
def closeL : Nat := {F}

def certL : List (Nat × Nat × Bool) := [
  {ce}
]

end Formal.Net.CapNet.LiveWit
'''
    path = os.path.join(NET, f"CapstoneLiveWitData{suffix}.lean")
    open(path, "w").write(txt)
    print("wrote", path)


def emit_cex(a, b, names, ops, out0, tr):
    rows = gen_data.rows_of(names, ops, tr)
    T = len(tr) - 1
    srq = [t for t in range(T) if tr[t + 1][0][2] != tr[t][0][2]]
    txt = f'''import Formal.Net.CapstoneLiveWitLib

/-!
# GENERATED by formal/lean/Wip/C8z2/livesim.py {a} {b} --hold --emit -- DO NOT EDIT

Probe C-8z2: the COUNTEREXAMPLE run for 8z's H_NO_DEADLOCK' (a = {a}, b = {b}). Same unit-delay
gate semantics as `CapstoneLiveWitData`, except that `start`'s LUT, after offering its one
token at tick {srq[0]}, never releases the request (8z's hypotheses put no bound on that LUT once
it has offered). The network is quiescent (but for `start`'s LUT) from tick {T} on, and out0's
acknowledge never falls.
Nothing here is trusted: CapstoneLiveWitCex* check it in the kernel.
-/

namespace Formal.Net.CapNet.LiveWit
open Formal.Net Formal.Net.CapNet Formal.Net.CapNet.Gcd Formal.Net.CapNet.Wit

set_option maxRecDepth 100000

def cdsX : List CD := [
{(","+chr(10)).join(rows)}
]

def cdX (c : Fin NC) : CD := cdsX.getD c.val ⟨[], [], 0, [], []⟩

/-- The counterexample run. -/
def chX : Fin NC → Handshake.Chan := wch cdX

end Formal.Net.CapNet.LiveWit
'''
    path = os.path.join(NET, "CapstoneLiveWitCexData.lean")
    open(path, "w").write(txt)
