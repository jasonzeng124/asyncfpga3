"""Generate formal/lean/Formal/Net/RingResetCert.lean from loopgen's exit model."""
import sys
from loopgen import explore
out=[]
out.append('''import Formal.Net.RingReset

/-!
# Probe C-9d (a): kernel-checked certificates for the bdc loop ring (generated)

Generated by `formal/lean/Wip/C9d/py/gencert.py` (BFS in Python, untrusted). The kernel checks
that each state list contains the reset state, is closed under `succ` (every gate firing and
environment move), and satisfies `goodB` everywhere; so every reachable state satisfies
`Good` (`RingReset.good_of`). For `N = 1, 2` a run to a stuck state is checked instead.
-/

namespace Formal.Net.RingReset
''')
def chunks(L,k=16):
    return ",\n    ".join(", ".join(str(v) for v in L[i:i+k]) for i in range(0,len(L),k))
for N in (3,4,5):
    s0,S,gates,env=explore(N,True)
    out.append(f"def L{N} : List Nat := [\n    {chunks(S)}]\n")
    out.append(f"""theorem L{N}_cert : (L{N}.contains (s0 {N}) && closedB {N} L{N} && L{N}.all (goodB {N})) = true := by
  decide +kernel

/-- **Loop ring with `N = {N}` links**: every reachable state from bdc's reset satisfies `Good`. -/
theorem loop{N}_good {{s : Nat}} (hs : Reach {N} s) : Good {N} s := by
  have h := L{N}_cert
  simp only [Bool.and_eq_true] at h
  exact good_of (cert_good h.1.1 h.1.2 h.2 hs)
""")
for N in (1,2):
    s0,S,gates,env=explore(N,True)
    par={s0:None}; st=[s0]; tgt=None
    from collections import deque
    q=deque([s0])
    EXb=N+14
    while q:
        s=q.popleft()
        if not gates(s) and not env(s) and not (s>>EXb)&1: tgt=s; break
        for t in [s^(1<<g) for g in gates(s)]+env(s):
            if t not in par: par[t]=s; q.append(t)
    path=[]; s=tgt
    while par[s] is not None: path.append(s); s=par[s]
    path.reverse()
    out.append(f"""def P{N} : List Nat := [{", ".join(map(str,path))}]

theorem P{N}_ok : (pathB {N} (s0 {N}) P{N} && stuckB {N} (lastOf (s0 {N}) P{N})) = true := by
  decide +kernel

/-- **Loop ring with `N = {N}` link(s) deadlocks** with the token inside: a run from bdc's
reset reaches a state where no gate is excited, no environment move is allowed, and the token
has not left. -/
theorem loop{N}_stuck : ∃ s, Reach {N} s ∧ (∀ g, g ∈ gates {N} → excB {N} s g = false) ∧
    succ {N} s = [] ∧ bit s (EX {N}) = false := by
  have h := P{N}_ok
  simp only [Bool.and_eq_true] at h
  exact ⟨_, reach_path Reach.refl h.1, stuck_of h.2⟩
""")
out.append("end Formal.Net.RingReset\n")
open(sys.argv[1],'w').write("\n".join(out))
