#!/usr/bin/env bash
# CO4b: synthesize bd_join N = 3 (the 3-input compute units of ipow and collatz:
# `select` and fused regions; formal/tools/gen/targets.txt has bd_join N = 2 only)
# with gen.sh's exact flow, and convert it with yosys2lean.py into
# Formal/Net/CellBindKNets.lean (namespace renamed). Copied from Wip/CO4/gen_extra.sh.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../../../.." && pwd)"
TC="${TC:-$HOME/dev2/lib/fpgatoolchain}"
YOSYS="$TC/openxc7/bin/yosys"
CELLS_SIM="$TC/openxc7/share/yosys/xilinx/cells_sim.v"
OUT="$HERE/json"; mkdir -p "$OUT"
for N in 3; do
  name=bd_join_N$N
  ( cd "$REPO/cells" && "$YOSYS" -q -p "
read_verilog -lib -specify $CELLS_SIM
read_verilog rtl/*.v
chparam -set N $N bd_join
synth_xilinx -family xc7 -flatten -nosrl -nolutram -nobram -noclkbuf -noiopad -top bd_join
write_json $OUT/$name.json" >/dev/null )
  python3 -I - "$OUT/$name.json" "$name bd_join N=$N" <<'PY'
import json, sys
p, tgt = sys.argv[1], sys.argv[2]
d = json.load(open(p))
d["modules"] = {n: m for n, m in d["modules"].items()
                if str(m.get("attributes", {}).get("top", "0")).strip("0")}
d["target"] = tgt
json.dump(d, open(p, "w"), indent=1)
PY
done
python3 -I "$REPO/formal/tools/gen/yosys2lean.py" "$HERE/CellBindKNets.raw.lean" \
  "$OUT/bd_join_N3.json"
sed -e 's/^namespace Formal.Gen.Cells/namespace Formal.Net.CellBind.KNets/' \
    -e 's/^end Formal.Gen.Cells/end Formal.Net.CellBind.KNets/' \
    -e 's|^Regenerate: .*|Regenerate: formal/lean/Wip/CO4b/gen_extra.sh (gen.sh flow; NOT covered by gen.sh --check)|' \
    -e 's|^/-! GENERATED by formal/tools/gen/yosys2lean.py -- DO NOT EDIT.|/-! GENERATED by formal/tools/gen/yosys2lean.py via Wip/CO4b/gen_extra.sh -- DO NOT EDIT.|' \
    "$HERE/CellBindKNets.raw.lean" > "$REPO/formal/lean/Formal/Net/CellBindKNets.lean"
rm -f "$HERE/CellBindKNets.raw.lean"
echo "wrote Formal/Net/CellBindKNets.lean"
