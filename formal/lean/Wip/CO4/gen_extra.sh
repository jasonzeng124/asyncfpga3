#!/usr/bin/env bash
# CO4: synthesize the bd_fork widths gcd_hw uses that formal/tools/gen/targets.txt
# does not (N = 3, 4, 6), with gen.sh's exact flow, and convert them with
# yosys2lean.py into Formal/Net/CellBindNets.lean (namespace renamed).
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../../../.." && pwd)"
TC="${TC:-$HOME/dev2/lib/fpgatoolchain}"
YOSYS="$TC/openxc7/bin/yosys"
CELLS_SIM="$TC/openxc7/share/yosys/xilinx/cells_sim.v"
OUT="$HERE/json"; mkdir -p "$OUT"
for N in 3 4 6; do
  name=bd_fork_N$N
  ( cd "$REPO/cells" && "$YOSYS" -q -p "
read_verilog -lib -specify $CELLS_SIM
read_verilog rtl/*.v
chparam -set N $N bd_fork
synth_xilinx -family xc7 -flatten -nosrl -nolutram -nobram -noclkbuf -noiopad -top bd_fork
write_json $OUT/$name.json" >/dev/null )
  python3 -I - "$OUT/$name.json" "$name bd_fork N=$N" <<'PY'
import json, sys
p, tgt = sys.argv[1], sys.argv[2]
d = json.load(open(p))
d["modules"] = {n: m for n, m in d["modules"].items()
                if str(m.get("attributes", {}).get("top", "0")).strip("0")}
d["target"] = tgt
json.dump(d, open(p, "w"), indent=1)
PY
done
python3 -I "$REPO/formal/tools/gen/yosys2lean.py" "$HERE/CellBindNets.raw.lean" \
  "$OUT/bd_fork_N3.json" "$OUT/bd_fork_N4.json" "$OUT/bd_fork_N6.json"
sed -e 's/^namespace Formal.Gen.Cells/namespace Formal.Net.CellBind.Nets/' \
    -e 's/^end Formal.Gen.Cells/end Formal.Net.CellBind.Nets/' \
    -e 's|^Regenerate: .*|Regenerate: formal/lean/Wip/CO4/gen_extra.sh (gen.sh flow; NOT covered by gen.sh --check)|' \
    -e 's|^/-! GENERATED by formal/tools/gen/yosys2lean.py -- DO NOT EDIT.|/-! GENERATED by formal/tools/gen/yosys2lean.py via Wip/CO4/gen_extra.sh -- DO NOT EDIT.|' \
    "$HERE/CellBindNets.raw.lean" > "$REPO/formal/lean/Formal/Net/CellBindNets.lean"
rm -f "$HERE/CellBindNets.raw.lean"
echo "wrote Formal/Net/CellBindNets.lean"
