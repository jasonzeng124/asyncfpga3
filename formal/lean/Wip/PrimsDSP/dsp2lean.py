#!/usr/bin/env python3
"""Generate formal/lean/Formal/Core/Prims/DspData.lean (probe PrimsDSP, shard A).

    python3 -I dsp2lean.py PRJXRAY_TIMINGS_DIR ROUTED_SDF OUT.lean [--check]

PRJXRAY_TIMINGS_DIR: prjxray-db zynq7/timings (DSP_L.sdf, DSP_R.sdf; they must be identical).
ROUTED_SDF: a nextpnr-xilinx routed SDF of ipow (for the comparison table only).

Every prjxray number comes from one SDF line, ns -> integer ps exactly (fails on >3 decimals).
A prjxray triple is (FAST_MIN::FAST_MAX)(SLOW_MIN::SLOW_MAX): fast and slow process corners,
NOT rise and fall. The nextpnr SDF has (v:v:v)(v:v:v) with one v per (input group, output group)
in this chipdb; the script fails if a group has two different values.
"""
import hashlib, re, sys
from fractions import Fraction

TRIPLE = re.compile(r"\(([-0-9.]+)::([-0-9.]+)\)\(([-0-9.]+)::([-0-9.]+)\)")

def ps(s):
    v = Fraction(s) * 1000
    if v.denominator != 1:
        raise SystemExit("not an integer ps value: %s" % s)
    return int(v)

# (lean name, prjxray celltype, src pin, dst pin) -- the cell types are the ones whose
# name matches the ipow configuration: every *REG = 0, USE_MULT MULTIPLY, USE_DPORT FALSE.
ARCS = [
    ("A_P",        "DSP48E1_AREG_0_A_INPUT_DIRECT_MREG_0_PREG_0_USE_DPORT_FALSE_USE_MULT_MULTIPLY", "A", "P"),
    ("A_PCOUT",    "DSP48E1_AREG_0_A_INPUT_DIRECT_MREG_0_PREG_0_USE_DPORT_FALSE_USE_MULT_MULTIPLY", "A", "PCOUT"),
    ("ACIN_P",     "DSP48E1_AREG_0_A_INPUT_CASCADE_MREG_0_PREG_0_USE_DPORT_FALSE_USE_MULT_MULTIPLY", "ACIN", "P"),
    ("ACIN_PCOUT", "DSP48E1_AREG_0_A_INPUT_CASCADE_MREG_0_PREG_0_USE_DPORT_FALSE_USE_MULT_MULTIPLY", "ACIN", "PCOUT"),
    ("A_ACOUT",    "DSP48E1_ACASCREG_0_A_INPUT_DIRECT", "A", "ACOUT"),
    ("ACIN_ACOUT", "DSP48E1_ACASCREG_0_A_INPUT_CASCADE", "ACIN", "ACOUT"),
    ("B_P",        "DSP48E1_BREG_0_B_INPUT_DIRECT_MREG_0_PREG_0_USE_MULT_MULTIPLY", "B", "P"),
    ("B_PCOUT",    "DSP48E1_BREG_0_B_INPUT_DIRECT_MREG_0_PREG_0_USE_MULT_MULTIPLY", "B", "PCOUT"),
    ("PCIN_P",     "DSP48E1_PREG_0", "PCIN", "P"),
    ("PCIN_PCOUT", "DSP48E1_PREG_0", "PCIN", "PCOUT"),
]

def read_prjxray(path):
    rows, ct = {}, None
    for ln, line in enumerate(open(path), 1):
        m = re.search(r'\(CELLTYPE "([^"]+)"\)', line)
        if m:
            ct = m.group(1); continue
        m = re.search(r"\(IOPATH (\S+) (\S+) (\(.*)$", line)
        if m:
            t = TRIPLE.match(m.group(3))
            if not t:
                raise SystemExit("bad triple %s:%d" % (path, ln))
            key = (ct, m.group(1), m.group(2))
            if key in rows:
                raise SystemExit("duplicate arc %s" % (key,))
            rows[key] = (tuple(ps(x) for x in t.groups()), ln)
    return rows

def read_nextpnr(path):
    """-> {(src group, dst group): value ps} over every DSP48E1_DSP48E1 cell"""
    out, in_dsp = {}, False
    for line in open(path):
        m = re.search(r'\(CELLTYPE "([^"]+)"\)', line)
        if m:
            in_dsp = (m.group(1) == "DSP48E1_DSP48E1"); continue
        if not in_dsp:
            continue
        m = re.search(r"\(IOPATH ([A-Z]+)\d* ([A-Z]+)\d* \(([0-9.]+):([0-9.]+):([0-9.]+)\) \(([0-9.]+):([0-9.]+):([0-9.]+)\)", line)
        if m:
            vals = {m.group(i) for i in range(3, 9)}
            if len(vals) != 1:
                raise SystemExit("nextpnr DSP arc with several values: " + line)
            v = int(Fraction(vals.pop()))
            k = (m.group(1), m.group(2))
            if out.setdefault(k, v) != v:
                raise SystemExit("nextpnr group %s has two values" % (k,))
    return out

def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()

def main():
    tdir, routed, outp = sys.argv[1], sys.argv[2], sys.argv[3]
    check = "--check" in sys.argv[4:]
    l, r = tdir + "/DSP_L.sdf", tdir + "/DSP_R.sdf"
    if open(l, "rb").read() != open(r, "rb").read():
        raise SystemExit("DSP_L.sdf and DSP_R.sdf differ: generate per tile type")
    px = read_prjxray(l)
    npr = read_nextpnr(routed)
    o = []
    o.append("-- GENERATED by formal/lean/Wip/PrimsDSP/dsp2lean.py -- do not edit.")
    o.append("-- prjxray-db zynq7/timings/DSP_L.sdf sha256 %s (DSP_R.sdf identical)" % sha(l))
    o.append("-- nextpnr routed SDF sha256 %s (ipow_hw, nextpnr 9c732bc6303458df)" % sha(routed))
    o.append("import Formal.Core.Prims.Xray")
    o.append("")
    o.append("/-! # Formal.Core.Prims.DspData — DSP48E1 delay arcs (integer ps)")
    o.append("")
    o.append("`px*`: prjxray-db `(FAST_MIN::FAST_MAX)(SLOW_MIN::SLOW_MAX)` as `Band` (fast/slow corners,")
    o.append("not rise/fall). `np*`: the single value nextpnr-xilinx writes into the routed SDF for that")
    o.append("(input group, output group) of every DSP48E1 (min = typ = max, both edges). -/")
    o.append("")
    o.append("namespace Formal.Core.Prims.DspData")
    o.append("open Formal.Core.Prims")
    o.append("")
    for name, ct, s, d in ARCS:
        k = (ct, s, d)
        if k not in px:
            raise SystemExit("missing prjxray arc %s" % (k,))
        b, ln = px[k]
        o.append("/-- %s -> %s, `%s` (DSP_L.sdf:%d) -/" % (s, d, ct, ln))
        o.append("def px%s : Band := ⟨%d, %d, %d, %d⟩" % ((name,) + b))
    o.append("")
    for name, ct, s, d in ARCS:
        v = npr.get((s, d))
        if v is None:
            o.append("-- nextpnr SDF has no %s -> %s arc on any DSP48E1 of this route" % (s, d))
            o.append("def np%s : Option Int := none" % name)
        else:
            o.append("def np%s : Option Int := some %d" % (name, v))
    o.append("")
    o.append("end Formal.Core.Prims.DspData")
    text = "\n".join(o) + "\n"
    if check:
        cur = open(outp).read()
        if cur != text:
            print("DRIFT: %s differs from the SDFs" % outp); sys.exit(1)
        print("OK: %s matches" % outp); return
    open(outp, "w").write(text)
    print("wrote", outp)

main()
