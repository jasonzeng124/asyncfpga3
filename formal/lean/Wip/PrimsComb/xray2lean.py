#!/usr/bin/env python3
"""Generate formal/lean/Formal/Core/Prims/XrayData.lean from prjxray-db's
zynq7/timings/slicel.sdf and slicem.sdf (probe PrimsComb, shard A).

    python3 -I xray2lean.py SDF_DIR OUT.lean          # write
    python3 -I xray2lean.py SDF_DIR OUT.lean --check  # fail if OUT.lean differs

Every number in the output comes from one SDF line, converted ns -> integer ps
exactly (the script fails if a value has more than 3 decimals). A prjxray SDF
triple is (FAST_MIN::FAST_MAX)(SLOW_MIN::SLOW_MAX) (prjxray utils/makesdf.py):
fast and slow process corners, NOT rise and fall.
"""
import hashlib
import os
import re
import sys
from fractions import Fraction

TRIPLE = re.compile(r"\(([-0-9.]+)::([-0-9.]+)\)\(([-0-9.]+)::([-0-9.]+)\)")


def ps(s):
    v = Fraction(s) * 1000
    if v.denominator != 1:
        raise SystemExit("not an integer ps value: %s" % s)
    return int(v)


def read_sdf(path):
    """-> list of (celltype, instance, kind, src, dst, (fmin, fmax, smin, smax), line)"""
    rows = []
    ct = inst = None
    for ln, line in enumerate(open(path), 1):
        m = re.search(r'\(CELLTYPE "([^"]+)"\)', line)
        if m:
            ct = m.group(1)
            continue
        m = re.search(r"\(INSTANCE ([^)]+)\)", line)
        if m:
            inst = m.group(1)
            continue
        m = re.search(r"\((IOPATH|INTERCONNECT) (\S+) (\S+) (\(.*)$", line)
        if m:
            t = TRIPLE.match(m.group(4))
            if not t:
                raise SystemExit("bad triple %s:%d" % (path, ln))
            rows.append((ct, inst, m.group(1), m.group(2), m.group(3),
                         tuple(ps(x) for x in t.groups()), ln))
    return rows


def band(b):
    return "⟨%d, %d, %d, %d⟩" % b


def main():
    sdfdir, out = sys.argv[1], sys.argv[2]
    check = "--check" in sys.argv[3:]
    src = {}
    for st in ("slicel", "slicem"):
        p = os.path.join(sdfdir, st + ".sdf")
        src[st] = (read_sdf(p), hashlib.sha256(open(p, "rb").read()).hexdigest())

    L = []
    w = L.append
    w("import Formal.Core.Prims.Xray")
    w("")
    w("/-!")
    w("# Formal.Core.Prims.XrayData -- GENERATED, do not edit")
    w("")
    w("Generated by `formal/lean/Wip/PrimsComb/xray2lean.py` from prjxray-db")
    w("`zynq7/timings/slicel.sdf` and `slicem.sdf` (fetched from")
    w("`https://raw.githubusercontent.com/f4pga/prjxray-db/master/`, 2026-10-29):")
    for st in ("slicel", "slicem"):
        w("* `%s.sdf` sha256 `%s`" % (st, src[st][1]))
    w("")
    w("Each band is one SDF triple `(FAST_MIN::FAST_MAX)(SLOW_MIN::SLOW_MAX)` in")
    w("integer ps (fast and slow corners, not rise and fall); the comment after each")
    w("arm gives the SDF line it came from. Regenerate / drift check:")
    w("`python3 -I Wip/PrimsComb/xray2lean.py <dir with the two sdf> Formal/Core/Prims/XrayData.lean [--check]`.")
    w("-/")
    w("")
    w("namespace Formal.Core.Prims")
    w("")
    ST = {"slicel": ".slicel", "slicem": ".slicem"}
    SITE = {"slicel": "SLICEL", "slicem": "SLICEM"}

    def find(st, ct, inst, a, z):
        hits = [r for r in src[st][0] if r[0] == ct and r[1] == inst and r[3] == a and r[4] == z]
        if len(hits) > 1:
            raise SystemExit("duplicate %s" % ((st, ct, inst, a, z),))
        return hits[0] if hits else None

    # --- SELMUX2_1 ---
    w("/-- prjxray `SELMUX2_1` (`<SITE>/F7AMUX|F7BMUX|F8MUX`, IOPATH `0`, `1`, `S0` -> `OUT`). -/")
    w("def selmux : SiteType → FMux → MuxArcs")
    for st in ("slicel", "slicem"):
        for fm, nm in (("f7a", "F7AMUX"), ("f7b", "F7BMUX"), ("f8", "F8MUX")):
            r = [find(st, "SELMUX2_1", SITE[st] + "/" + nm, p, "OUT") for p in ("0", "1", "S0")]
            if None in r:
                raise SystemExit("missing SELMUX arc %s %s" % (st, nm))
            w("  | %s, .%s => ⟨%s, %s, %s⟩ -- %s.sdf:%d,%d,%d" % (
                ST[st], fm, band(r[0][5]), band(r[1][5]), band(r[2][5]), st, r[0][6], r[1][6], r[2][6]))
    w("")

    # --- ROUTING_BEL LUT -> F7 mux data input ---
    w("/-- prjxray `ROUTING_BEL <SITE>/F7AMUX|F7BMUX`: `x6lut -> f7?mux` (the LUT O6 to")
    w("F7 data-input wire; A,B feed F7AMUX, C,D feed F7BMUX). -/")
    w("def f7Hop : SiteType → Letter → Band")
    for st in ("slicel", "slicem"):
        for Lt, fm in (("A", "F7AMUX"), ("B", "F7AMUX"), ("C", "F7BMUX"), ("D", "F7BMUX")):
            r = find(st, "ROUTING_BEL", SITE[st] + "/" + fm, Lt.lower() + "6lut", fm.lower())
            w("  | %s, .%s => %s -- %s.sdf:%d" % (ST[st], Lt, band(r[5]), st, r[6]))
    w("")
    w("/-- prjxray `ROUTING_BEL <SITE>/F8MUX`: `bx -> f8mux` (the F8 select). -/")
    w("def f8SelHop : SiteType → Band")
    for st in ("slicel", "slicem"):
        r = find(st, "ROUTING_BEL", SITE[st] + "/F8MUX", "bx", "f8mux")
        w("  | %s => %s -- %s.sdf:%d" % (ST[st], band(r[5]), st, r[6]))
    w("")

    # --- CARRY4 family ---
    VARS = [("base", "CARRY4"), ("o5", "CARRY4_O5"), ("ax", "CARRY4_AX"), ("axLboth", "CARRY4_AX_LBOTH"),
            ("axLff", "CARRY4_AX_LFF"), ("bx", "CARRY4_BX"), ("bxLboth", "CARRY4_BX_LBOTH"),
            ("bxLff", "CARRY4_BX_LFF"), ("cx", "CARRY4_CX"), ("cxLboth", "CARRY4_CX_LBOTH"),
            ("cxLff", "CARRY4_CX_LFF"), ("dx", "CARRY4_DX"), ("lboth", "CARRY4_LBOTH"), ("lff", "CARRY4_LFF")]
    PIN = {"CIN": "cin", "CYINIT": "cyinit", "S0": "s0", "S1": "s1", "S2": "s2", "S3": "s3",
           "DI0": "di0", "DI1": "di1", "DI2": "di2", "DI3": "di3"}
    OUTP = {"O0": "o0", "O1": "o1", "O2": "o2", "O3": "o3", "CO0": "co0", "CO1": "co1", "CO2": "co2", "CO3": "co3"}
    w("/-- prjxray `CARRY4*` IOPATH arcs (`<SITE>` instance), by cell variant, or `none` where")
    w("that variant lists no arc. -/")
    w("def carry4Arc : SiteType → C4Var → CPin → COut → Option Band")
    n = 0
    for st in ("slicel", "slicem"):
        for v, ct in VARS:
            for r in src[st][0]:
                if r[0] == ct and r[1] == SITE[st] and r[2] == "IOPATH":
                    if r[3] not in PIN or r[4] not in OUTP:
                        raise SystemExit("unexpected CARRY4 arc %s" % (r,))
                    w("  | %s, .%s, .%s, .%s => some %s -- %s.sdf:%d" % (
                        ST[st], v, PIN[r[3]], OUTP[r[4]], band(r[5]), st, r[6]))
                    n += 1
    w("  | _, _, _, _ => none")
    w("")
    w("/-- Number of generated `carry4Arc` arms. -/")
    w("def carry4ArcRows : Nat := %d" % n)
    w("")

    # --- LUT arcs ---
    for (k, o, ctl, ctm, nm) in ((6, "O6", "LUT6", "LUT_OR_MEM6LRAM", "lut6Arc"),
                                 (5, "O5", "LUT5", "LUT_OR_MEM5LRAM", "lut5Arc")):
        w("/-- prjxray `%s`/`%s` `<SITE>/<x>%dLUT`: `A<j+1> -> %s` (index `j`). -/" % (ctl, ctm, k, o))
        w("def %s : SiteType → Letter → Nat → Option Band" % nm)
        for st in ("slicel", "slicem"):
            ct = ctl if st == "slicel" else ctm
            for Lt in "ABCD":
                for j in range(k):
                    r = find(st, ct, "%s/%s%dLUT" % (SITE[st], Lt, k), "A%d" % (j + 1), o)
                    w("  | %s, .%s, %d => some %s -- %s.sdf:%d" % (ST[st], Lt, j, band(r[5]), st, r[6]))
        w("  | _, _, _ => none")
        w("")

    # --- OUTMUX (?MUX) and ?MUXL ---
    def osrc(Lt, name):
        l = Lt.lower()
        m = {l + "5lut": ".lut5", l + "6lut": ".lut6", "o5": ".o5", "o6": ".o6", l + "5ff": ".ff5",
             "carry4_o" + str("ABCD".index(Lt)): ".cyO", "carry4_co" + str("ABCD".index(Lt)): ".cyCO",
             "f7amux": ".fmux", "f7bmux": ".fmux", "f8mux": ".fmux"}
        if Lt != "A":
            m["a6lut"] = ".a6lut"
        if name not in m:
            raise SystemExit("unexpected OUTMUX source %s" % name)
        return m[name]

    for suf, nm, doc in (("MUX", "outMux", "`<SITE>/<x>MUX` (the site OUTMUX)"),
                         ("MUXL", "outMuxL", "`<SITE>/<x>MUXL` (meaning not recorded by the fuzzer)")):
        w("/-- prjxray `ROUTING_BEL` %s: `src -> <x>mux`. -/" % doc)
        w("def %s : SiteType → Letter → OSrc → Option Band" % nm)
        for st in ("slicel", "slicem"):
            for Lt in "ABCD":
                for r in src[st][0]:
                    if r[0] == "ROUTING_BEL" and r[1] == "%s/%s%s" % (SITE[st], Lt, suf):
                        w("  | %s, .%s, %s => some %s -- %s.sdf:%d (%s)" % (
                            ST[st], Lt, osrc(Lt, r[3]), band(r[5]), st, r[6], r[3]))
        w("  | _, _, _ => none")
        w("")

    # --- carry input hops ---
    w("/-- prjxray `ROUTING_BEL <SITE>/CARRY4`: `x5lut|x6lut|x -> carry4` (LUT O5 / O6 / bypass")
    w("pin into the CARRY4 DI/S inputs), and `<SITE>/<x>CY0`: `x -> di<i>`. -/")
    w("def carryHop : SiteType → CHop → Option Band")
    nh = 0
    for st in ("slicel", "slicem"):
        for Lt in "ABCD":
            l = Lt.lower()
            for name, ctor in ((l + "5lut", "lut5"), (l + "6lut", "lut6"), (l, "x")):
                r = find(st, "ROUTING_BEL", SITE[st] + "/CARRY4", name if ctor != "x" else l + "x", "carry4")
                if r:
                    w("  | %s, .%s .%s => some %s -- %s.sdf:%d" % (ST[st], ctor, Lt, band(r[5]), st, r[6]))
                    nh += 1
            i = "ABCD".index(Lt)
            r = find(st, "ROUTING_BEL", "%s/%sCY0" % (SITE[st], Lt), l + "x", "di%d" % i)
            if r:
                w("  | %s, .cy0 .%s => some %s -- %s.sdf:%d" % (ST[st], Lt, band(r[5]), st, r[6]))
                nh += 1
    if nh < 32:
        w("  | _, _ => none")
    w("")
    w("end Formal.Core.Prims")
    text = "\n".join(L) + "\n"
    if check:
        cur = open(out).read()
        if cur != text:
            print("DRIFT: %s differs from the generated text" % out)
            sys.exit(1)
        print("OK: %s is up to date" % out)
    else:
        open(out, "w").write(text)
        print("wrote %s (%d carry4 arms)" % (out, n))


if __name__ == "__main__":
    main()
