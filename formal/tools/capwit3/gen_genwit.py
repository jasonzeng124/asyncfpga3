#!/usr/bin/env python3
"""C-witgen: emit the generated data of the generated-netlist-level gcd_hw witness.

  gen_genwit.py            -> Formal/Net/GenWitData.lean (channels) and GenWitOx.lean (internal nodes)
  gen_genwit.py --check    -> compare with the files on disk (exit 1 on drift)

The run is simgen.py's (a = 12, b = 18, chain lengths simgen.LEN). Expected value 6 is
gcd 12 18 (`Nat.gcd`, decided in Lean), never read from this run.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import sim, simgen  # noqa: E402

NETDIR = os.path.join(sim.ROOT, "formal", "lean", "Formal", "Net")
VALS = [12, 18, 0]


def lst(xs): return "[" + ", ".join(str(x) for x in xs) + "]"


def stage(s):
    return {"buf": lambda: f".buf {s[1]}", "and": lambda: f".andT {s[1]} {s[2]}",
            "or": lambda: f".orT {s[1]} {s[2]}"}[s[0]]()


def render():
    names, ops, out0, start, tr, P, errs, falls = simgen.run("gcd", VALS)
    if errs:
        raise SystemExit(f"run violates the models: {errs[:10]}")
    NC, NO, T = len(names), len(ops), len(tr) - 1
    prod = {}
    for n, o in enumerate(ops):
        for c in sim.outs_of(o): prod[c] = n
    rows = []
    for c in range(NC):
        rs = [s[0][c] for s in tr]
        assert not rs[0]
        ds = [s[3][c] for s in tr]
        o = ops[prod[c]]
        ax = []
        if o["k"] in sim.NINT:
            n = prod[c]
            ax = [sim.toggles([s[2][n][k] for s in tr]) for k in range(sim.NINT[o["k"]])]
        rows.append(f"  ⟨{lst(sim.toggles(rs))}, {lst(sim.toggles([s[1][c] for s in tr]))}, {ds[0]}, "
                    f"[{', '.join(f'({t}, {v})' for t, v in sim.dchanges(ds))}], [{', '.join(lst(x) for x in ax)}]⟩")
    L = simgen.LEN
    stdefs = {"stJ": simgen.gated(L["DJ"]), "stN": simgen.gated(L["DN"]), "stA": simgen.gated(L["DA"]),
              "stK": simgen.uackst(L["DK"])}
    oxr = []
    nint = 0
    for n, o in enumerate(ops):
        tg = lambda comp, k: sim.toggles([s[comp][n][k] for s in tr])
        m = [tg(4, k) for k in range(P[n][0])]
        ca = [tg(5, k) for k in range(len(P[n][1]) - 1)] if P[n][1] else []
        cb = [tg(6, k) for k in range(P[n][2] - 1)] if P[n][2] else []
        nint += sum(len(x) for x in m + ca + cb)
        sa = {"join": "stJ", "muxn": "stN", "amerge": "stA", "link": "stK"}[o["k"]] if P[n][1] else "[]"
        assert not P[n][1] or tuple(stdefs[sa]) == tuple(P[n][1])
        oxr.append(f"  ⟨[{', '.join(lst(x) for x in m)}], {sa}, [{', '.join(lst(x) for x in ca)}], "
                   f"[{', '.join(lst(x) for x in cb)}]⟩")
    nt = sum(len(sim.toggles([s[0][c] for s in tr])) + len(sim.toggles([s[1][c] for s in tr])) for c in range(NC))
    srises = [t for t in range(T) if not tr[t][0][start] and tr[t + 1][0][start]]
    sfalls = [t for t in range(T) if tr[t][0][start] and not tr[t + 1][0][start]]
    assert len(srises) == 1 and len(sfalls) == 1 and len(falls) == 1
    hdr = f'''/-!
# GENERATED by formal/tools/capwit3/gen_genwit.py -- DO NOT EDIT

Probe C-witgen: one unit-delay run of the concrete gcd_hw network (`CapstoneNet`, {NC} channels,
{NO} operators) at the GENERATED-NETLIST level (formal/tools/capwit3/simgen.py): every LUT node and
every delay-chain stage of every operator has delay exactly 1 (R0 = g1 OR g2 at the same tick),
with bdc's chain shapes: compute units `uor` + bd_delay_gated N = {L["DJ"]}, bd_mux plain
udly N = {L["DM"]}, muxN `uor` + bd_delay_gated N = {L["DN"]}, amerge `uor` + bd_delay_gated N = {L["DA"]},
bd_link rdly N = {L["DL"]} plus a route stage, uack FASTRISE N = {L["DK"]} plus a route stage.
Sources a = 12, b = 18, start: one token each, then wait; sinks acknowledge after one tick.
Quiescent after {T} ticks; {nt} channel request/acknowledge toggles, {nint} internal-node toggles.
out0 (channel {out0}) closes at {falls}; start (channel {start}) rises at {srises}.
Nothing here is trusted: the kernel checks it (`GenWitCells*`).
-/
'''
    parts = []
    for i in range(0, NC, 60):
        parts.append(f"def gcdsP{i // 60} : List CD := [\n" + ",\n".join(rows[i:i + 60]) + "\n]\n")
    cat = " ++ ".join(f"gcdsP{i}" for i in range(len(parts)))
    data = ("import Formal.Net.GenWitLib\nimport Formal.Net.CapstoneNetChk\n\n" + hdr + '''
namespace Formal.Net.CellBind.GenWit
open Formal.Net Formal.Net.CapNet Formal.Net.CapNet.Wit Formal.Net.CapNet.Gcd

set_option maxRecDepth 100000

''' + "\n".join(parts) + f'''
def gcds : List CD := {cat}

def gcdA (c : Fin NC) : CD := gcds.getD c.val ⟨[], [], 0, [], []⟩

def gStartRise : Nat := {srises[0]}
def gStartFall : Nat := {sfalls[0]}
def gOut0Close : Nat := {falls[0]}
def gTEnd : Nat := {T}

end Formal.Net.CellBind.GenWit
''')
    oparts = []
    for i in range(0, NO, 50):
        oparts.append(f"def goxP{i // 50} : List OX := [\n" + ",\n".join(oxr[i:i + 50]) + "\n]\n")
    ocat = " ++ ".join(f"goxP{i}" for i in range(len(oparts)))
    sts = "\n".join(f"def {k} : List Stage := [{', '.join(stage(s) for s in v)}]" for k, v in stdefs.items())
    oxf = ("import Formal.Net.GenWitData\n\n" + hdr + '''
namespace Formal.Net.CellBind.GenWit
open Formal.Net Formal.Net.CellBind.Ops

set_option maxRecDepth 100000

''' + sts + "\n\n" + "\n".join(oparts) + f'''
def goxs : List OX := {ocat}

def goxA (i : Nat) : OX := goxs.getD i ox0

end Formal.Net.CellBind.GenWit
''')
    return {"GenWitData.lean": data, "GenWitOx.lean": oxf}


def main():
    out = render()
    bad = 0
    for f, txt in out.items():
        p = os.path.join(NETDIR, f)
        if "--check" in sys.argv:
            ok = os.path.exists(p) and open(p).read() == txt
            print(f"gen_genwit {f}:", "ok" if ok else "DRIFT")
            bad |= not ok
        else:
            open(p, "w").write(txt)
            print("wrote", p, len(txt), "bytes")
    return bad


if __name__ == "__main__":
    sys.exit(main())
