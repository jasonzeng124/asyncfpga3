#!/usr/bin/env python3
"""C-witgen negative controls: emit Wip/Cwitgen/neg/Neg{Settled,Init}.lean.

* NegSettled: the gcd_hw generated-level run with ONE delay-chain node slowed down: bd_link
  operator 192's `uack` head (LUT1 buf(c)) gets an inertial delay of 291 ticks (every other
  node 1 tick). The node still obeys its LUT (it moves only to its function of the previous
  tick), the lumped Ops model (`kChk`, H_CELLS) still holds for EVERY operator, and only
  bdc's 7-stage uack decomposition is unsettled (c falls while the slow head never rose), so
  `kChkG` with that decomposition fails; with the one-stage decomposition (GenWitChain's
  `genChain_iff`) the WHOLE run satisfies H_GEN (`GenCell` on all operators): checked here.
  291 is the smallest delay that unsettles it in this run (simgen.py search).
* NegInit: fork operator 67 (N = 5) with ONE INIT bit of its chunk C-element flipped (leaves
  1,0,1,1 with q = 0 set m); the run follows the mutant LUT. `kChkG` must fail on op 67.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import sim, simgen, gen_genwit as G  # noqa: E402

OUT = os.path.join(sim.ROOT, "formal", "lean", "Wip", "Cwitgen", "neg")

CF = {
    "NegSettled": dict(mut={"slowhead": (192, 291)}, op=192),
    "NegInit": dict(mut={"init5": (67, [True, False, True, True])}, op=67),
}


def render(name):
    cf = CF[name]
    names, ops, out0, start, tr, P, errs, falls = simgen.run("gcd", G.VALS, mut=cf["mut"])
    rows, oxr, sts, nint = G.rows_ox(names, ops, tr, P)
    ns = f"Formal.Net.CellBind.GenWit.{name}"
    body = f'''import Formal.Net.GenWitLib
import Formal.Net.CapstoneNetChk

/-! GENERATED by formal/tools/capwit3/gen_neg3.py -- negative control {name}: {cf["mut"]}.
Python mirror reports: {sorted(set(str(e[1]) for e in errs))}. -/

namespace {ns}
open Formal.Net Formal.Net.CapNet Formal.Net.CapNet.Wit Formal.Net.CapNet.Gcd Formal.Net.CellBind.GenWit
open Formal.Net.CellBind.Ops

set_option maxRecDepth 100000

{G.chunked("ncds", "CD", rows, 60)}
def nA (c : Fin NC) : CD := ncds.getD c.val ⟨[], [], 0, [], []⟩

{sts}

{G.chunked("noxs", "OX", oxr, 50)}
def nOx (i : Nat) : OX := noxs.getD i ox0

'''
    if name == "NegSettled":
        body += '''/-- Operator 192's record with its `uack` chain collapsed to ONE stage (x0 = c, x1 = ack_in):
`GenChain` quantifies the stages, so this decomposition is as admissible as bdc's 7-stage one. -/
def colOx (i : Nat) : OX := if i = 192 then ⟨(nOx 192).m, [.buf 0], [], (nOx 192).cb⟩ else nOx i

def nP (i : Nat) : Bool := kChkG nA (colOx i) (srcV 12 18) (ops.getD i (K.sink 0))

-- must SUCCEED: the whole mutated run satisfies H_GEN (`GenCell` on all 367 operators, via
-- `kChkG_sound`; op 192 through the one-stage uack decomposition)
theorem gen1 : (List.range' 0 92).all nP = true := by decide +kernel
theorem gen2 : (List.range' 92 92).all nP = true := by decide +kernel
theorem gen3 : (List.range' 184 92).all nP = true := by decide +kernel
theorem gen4 : (List.range' 276 91).all nP = true := by decide +kernel
theorem op192_gen : GenCell (wch nA) (srcV 12 18) (ops.getD 192 (K.sink 0)) :=
  kChkG_sound _ _ _ (List.all_eq_true.mp gen3 192 (by decide))
'''
    body += f'''-- MUST FAIL: the generated-level check of operator {cf["op"]} with bdc's decomposition
theorem gen_op : kChkG nA (nOx {cf["op"]}) (srcV 12 18) (ops.getD {cf["op"]} (K.sink 0)) = true := by decide +kernel

end {ns}
'''
    return body


def main():
    os.makedirs(OUT, exist_ok=True)
    for name in CF:
        p = os.path.join(OUT, name + ".lean")
        txt = render(name)
        if "--check" in sys.argv:
            ok = os.path.exists(p) and open(p).read() == txt
            print(f"gen_neg3 {name}:", "ok" if ok else "DRIFT")
        else:
            open(p, "w").write(txt)
            print("wrote", p, len(txt))


if __name__ == "__main__":
    main()
