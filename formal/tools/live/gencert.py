#!/usr/bin/env python3
"""gencert.py OUT.lean GRAPH.json... -- Lean certificates of "no trap" for exported stage graphs.

Each GRAPH.json (formal/tools/live/fixtures/graphs/) is {n, edges: [[p, t]] (p feeds t), x: [0/1], ...}.
For a trap-free state the token-free arcs (p->t if x_p == x_t, t->p if x_p != x_t, for every edge p->t) form a DAG;
the rank is the longest-path depth in it. Writes one `theorem` per graph:
    Cert.check <data> = true      (by decide +kernel)
so `Cert.check_sound` + `StageNet.deadlock_free` / `fair_all_fire` apply to it. Graphs with a token-free cycle get no
theorem; they are listed in a comment with the cycle (untrusted: the cycle is found here, not checked in Lean).
Untrusted generator: only the Lean check counts.
"""
import json, sys, re, collections

def zarcs(n, edges, x):
    for p, t in edges:
        if x[p] == x[t]:
            yield p, t
        else:
            yield t, p

def rank_or_cycle(n, edges, x):
    succ = collections.defaultdict(list); indeg = [0] * n
    for a, b in zarcs(n, edges, x):
        succ[a].append(b); indeg[b] += 1
    rank = [0] * n; q = [v for v in range(n) if indeg[v] == 0]; seen = 0
    while q:
        v = q.pop(); seen += 1
        for w in succ[v]:
            rank[w] = max(rank[w], rank[v] + 1); indeg[w] -= 1
            if indeg[w] == 0: q.append(w)
    if seen == n:
        return rank, None
    # find a cycle among the rest
    rest = {v for v in range(n) if indeg[v] > 0}
    v = next(iter(rest)); path = []; pos = {}
    while v not in pos:
        pos[v] = len(path); path.append(v)
        v = next(w for w in succ[v] if w in rest)
    return None, path[pos[v]:]

def ident(s):
    return re.sub(r'[^A-Za-z0-9_]', '_', s)

def main():
    out, files = sys.argv[1], sys.argv[2:]
    mod = ident(out.split('/')[-1].replace('.lean', ''))
    L = ["import Formal.Net.StageNetCert", "", "/-! Generated by formal/tools/live/gencert.py (untrusted generator; the",
         "theorems below are checked by the kernel). Each says: the exported stage graph of that design and mode,",
         "in the exported state, has no trap (`Cert.check_sound`), hence no reachable deadlock",
         "(`StageNet.deadlock_free`) and every stage fires infinitely often in fair runs (`fair_all_fire`)",
         "-- for the stage model and that mode only. -/", "", "namespace Formal.Net.StageNet.Live", "open Formal.Net.StageNet", ""]
    bad = []
    for f in files:
        g = json.load(open(f))
        n, edges, x = g["n"], g["edges"], [int(b) for b in g["x"]]
        rank, cyc = rank_or_cycle(n, edges, x)
        name = ident(f.split('/')[-1].replace('.json', ''))
        if rank is None:
            names = g.get("names") or [str(i) for i in range(n)]
            bad.append(f"-- TRAP {f}: " + " -> ".join(names[i] for i in cyc))
            continue
        xs = ", ".join("true" if b else "false" for b in x)
        es = ", ".join(f"({p}, {t})" for p, t in edges)
        rs = ", ".join(str(r) for r in rank)
        L.append(f"-- {f}: {g.get('fixture')} {g.get('flow')} {g.get('floor')} mode: {g.get('mode')}")
        L.append(f"theorem cert_{name} : Cert.check ⟨{n}, [{es}],\n    [{xs}],\n    [{rs}]⟩ = true := by decide +kernel")
        L.append("")
    L += bad + ["", "end Formal.Net.StageNet.Live", ""]
    open(out, "w").write("\n".join(L))
    print(f"{len(files) - len(bad)} certificates, {len(bad)} traps -> {out}")

if __name__ == "__main__":
    main()
