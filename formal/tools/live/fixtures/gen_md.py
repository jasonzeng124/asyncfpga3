#!/usr/bin/env python3
"""gen_md.py OUTDIR -- RESULTS.md from OUTDIR/results.jsonl and OUTDIR/validation.jsonl."""
import json
import os
import sys


def load(p):
    if not os.path.exists(p):
        return []
    rows = {}
    for l in open(p):
        d = json.loads(l)
        rows[(d.get("fixture"), d.get("flow"), d.get("floor"), d.get("config"))] = d
    return list(rows.values())


def mine(r):
    v = r.get("verdict")
    if v == "LIVE":
        s = "LIVE-exhaustive (unbounded trips, 1 inv"
        if r.get("inv2") == "LIVE":
            s += "; 2 inv too"
        elif r.get("inv2") == "DEADLOCK":
            s += f"; **2nd inv DEADLOCK** {' '.join(r.get('inv2_trace') or [])}"
        elif r.get("inv2"):
            s += f"; 2 inv: {r['inv2']}"
        return s + ")"
    if v == "SAMPLED-LIVE":
        return (f"SAMPLED-LIVE (exhaustive: {r.get('exhaustive')}; {r.get('walks')} random walks, no deadlock; "
                f"Z-traps in {r.get('z_traps')} of {r.get('z_checked')} sampled states)")
    if v == "DEADLOCK":
        return "**DEADLOCK** " + " ".join(r.get("trace_choices") or [])
    if v == "SAME-AS-AUTO":
        return "= auto (auto.py rewrote nothing)"
    if v == "REFUSED":
        return "REFUSED: " + (r.get("error") or "")[:110].replace("|", "/")
    if v == "MODEL-ERROR":
        return "MODEL-ERROR: " + (r.get("error") or "")[:110].replace("|", "/")
    return f"{v} (not exhaustive)"


def agree(r):
    v, rs = r.get("verdict"), r.get("research", "")
    if v in ("LIVE", "SAMPLED-LIVE"):
        return rs == "live"
    if v == "DEADLOCK":
        return rs.startswith("short")
    if v == "SAME-AS-AUTO":
        return True
    if v == "REFUSED":
        return rs in ("refused", "?")
    return None


def main():
    out = sys.argv[1]
    res = load(os.path.join(out, "results.jsonl"))
    val = load(os.path.join(out, "validation.jsonl"))
    res.sort(key=lambda r: (r["fixture"], r["flow"], r["floor"]))
    L = ["# live.py over every fixture (independent liveness check)", "",
         "Generated by `formal/tools/live/fixtures/run.sh OUTDIR` (gen_md.py). Model, semantics and limits: README "
         "section at the end. `research` = research/tools/suite/ring_tokens.py's walk view on the same design "
         "(same flow, same BDC_TOKEN_FLOOR), i.e. bdc's token_graph / short_walk.", ""]
    dis = [r for r in res if agree(r) is False]
    unk = [r for r in res if agree(r) is None]
    L += [f"## Disagreements with research's walk view ({len(dis)})", ""]
    if dis:
        L += ["| fixture | flow | floor | live.py | research |", "|---|---|---|---|---|"]
        for r in dis:
            L.append(f"| {r['fixture']} | {r['flow']} | {r['floor']} | {mine(r)} | {r.get('research')} |")
    else:
        L.append("None.")
    L += ["", f"## Not decided exhaustively ({len(unk)})", ""]
    if unk:
        L += ["| fixture | flow | floor | live.py | research |", "|---|---|---|---|---|"]
        for r in unk:
            L.append(f"| {r['fixture']} | {r['flow']} | {r['floor']} | {mine(r)} | {r.get('research')} |")
    if val:
        n = sum(1 for r in val if r.get("agree"))
        L += ["", f"## Validation against simcheck (research/data/suite/ringfloor/validation.txt): {n} / {len(val)} agree",
              "", "| config | env | simcheck | live.py | states |", "|---|---|---|---|---|"]
        for r in val:
            env = " ".join(f"{k}={v}" for k, v in (r.get("env") or {}).items())
            L.append(f"| {r['config']} | `{env}` | {r['simcheck']} | {mine(r)} | {r.get('states')} |")
    L += ["", "## Every fixture", "",
          "| fixture | flow | floor | stages | states (1 inv) | live.py | research | traps in sampled states |",
          "|---|---|---|---|---|---|---|---|"]
    for r in res:
        z = r.get("samples_z")
        zs = "" if z is None else f"{sum(1 for x in z if x)} / {len(z)}"
        L.append(f"| {r['fixture']} | {r['flow']} | {r['floor']} | {r.get('stages', '')} | {r.get('states', '')} | "
                 f"{mine(r)} | {r.get('research')} | {zs} |")
    cnt = {}
    for r in res:
        cnt[r.get("verdict")] = cnt.get(r.get("verdict"), 0) + 1
    L += ["", "Totals: " + ", ".join(f"{k} {v}" for k, v in sorted(cnt.items(), key=lambda x: str(x[0]))), ""]
    L += [open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "MODEL.md")).read()] \
        if os.path.exists(os.path.join(os.path.dirname(os.path.abspath(__file__)), "MODEL.md")) else []
    open(os.path.join(out, "RESULTS.md"), "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
