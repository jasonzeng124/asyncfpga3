#!/usr/bin/env python3
"""rhoinj (probe C-11g): certificates that the renaming `rho` of a generated design
(Formal/Net/FasmDesign/<NS>/) is a bijection on nets outside route-throughs
(see Formal/Net/FasmRho.lean).

    python3 rhoinj.py LEANDIR NS OUTDIR     # writes OUTDIR/FasmRho<Tag>{Inv,Occ,Mark,Data,}.lean

Tag = NS without its "Gcd" prefix ("D" for GcdD). The certificates are hints; the
Lean `decide +kernel` checks them (markOk, coverOk, keysOk, invOk)."""
import os
import re
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import check3  # noqa: E402

SPLIT = 6


def split(d, depth=0, path="r", a=1, b=0):
    """The trie's shape down to depth SPLIT: ('leaf',) | ('sub', path, a, b) | ('node', left, right).
    Same recursion as gen3's trie emitter, so subtree names match."""
    if not d:
        return ("leaf",)
    if depth == SPLIT:
        return ("sub", path, a, b)
    left = {(k - 1) // 2: x for k, x in d.items() if k % 2 == 1}
    right = {(k - 2) // 2: x for k, x in d.items() if k > 0 and k % 2 == 0}
    return ("node", split(left, depth + 1, path + "l", 2 * a, a + b), split(right, depth + 1, path + "r", 2 * a, 2 * a + b))


def subs_of(s):
    if s[0] == "sub":
        return [s]
    if s[0] == "node":
        return subs_of(s[1]) + subs_of(s[2])
    return []


def proof(s, name):
    if s[0] == "leaf":
        return "(kvAll_leaf _ _ _)"
    if s[0] == "sub":
        return "ck_%s_%s" % (name, s[1])
    return "(kvAll_node _ _ _ _ _ _ (by decide +kernel)\n    %s\n    %s)" % (proof(s[1], name), proof(s[2], name))


def emit_check(f, name, pred, trie, d, total):
    """`theorem <name>_ok : kvAll pred trie 1 0 = true`, one `decide` per depth-SPLIT subtree."""
    s = split(d)
    for _, path, a, b in subs_of(s):
        f.write("theorem %s_%s : kvAll (%s) %s_%s %d %d = true := by decide +kernel\n\n" % (name, path, pred, trie, path, a, b))
    f.write("theorem %s_ok : kvAll (%s) %s 1 0 = true := by\n  unfold %s\n  exact %s\n\n" % (name, pred, trie, trie, proof(s, name)))


def emit_trie(f, name, d):
    subs = []

    def trie(d, depth=0, path="r"):
        if not d:
            return ".leaf"
        if depth == SPLIT:
            subs.append((path, trie(d, depth + 100, path)))
            return "%s_%s" % (name, path)
        v = d.get(0)
        left = {(k - 1) // 2: x for k, x in d.items() if k % 2 == 1}
        right = {(k - 2) // 2: x for k, x in d.items() if k > 0 and k % 2 == 0}
        vs = "(some (.net %d))" % v if v is not None else "none"
        return "(.node %s\n  %s\n  %s)" % (vs, trie(left, depth + 1, path + "l"), trie(right, depth + 1, path + "r"))
    top = trie(d)
    for path, body in subs:
        f.write("def %s_%s : Trie :=\n  %s\n\n" % (name, path, body))
    f.write("def %s : Trie :=\n  %s\n\n" % (name, top))


def main():
    d, ns, out = sys.argv[1:4]
    tag = ns[3:] if ns.startswith("Gcd") else ns
    rho = check3.parse_trie(os.path.join(d, "Rho.lean"))
    chunks = sorted(fn for fn in os.listdir(d) if re.match(r"C\d+\.lean$", fn))
    mark, occ = {}, {}
    for ci, fn in enumerate(chunks):
        assert fn == "C%03d.lean" % ci
        txt = open(os.path.join(d, fn)).read()
        body = txt[txt.index("def insts"):txt.index("theorem ok")]
        for j, m in enumerate(re.finditer(r"  ⟨(⟨.*?⟩),\n   (none|some ⟨.*?⟩),\n   \[(.*?)\], \[(.*?)\]⟩", body)):
            assert j < 1000
            idx = 1000 * ci + j
            p = check3.parse_cell(m.group(1))
            l = None if m.group(2) == "none" else check3.parse_cell(m.group(2)[5:])
            if l is None:
                for pp, _ in re.findall(r"\(\.(\w+), \.(\w+)\)", m.group(3)):
                    s = p["conn"].get(pp)
                    if s and s[0] == "net":
                        mark.setdefault(s[1], idx)
            else:
                for q, s in l["conn"].items():
                    if s[0] == "net":
                        occ.setdefault(s[1], idx)
    inv = {}
    for k, v in rho.items():
        if v[0] == "net" and k not in mark:
            if v[1] in inv:
                sys.exit("rhoinj: rho merges physical nets %d and %d (logical %d) outside route-throughs"
                         % (inv[v[1]], k, v[1]))
            inv[v[1]] = k
    missing = [v for v in occ if v not in inv]
    extra = [v for v in inv if v not in occ]
    print("rhoinj: %s rho %d, route-through outputs %d, non-rt nets %d, logical pin nets %d, "
          "uncovered %d, not on a logical cell %d" % (ns, len(rho), len(mark), len(inv), len(occ), len(missing), len(extra)))
    hdr = ("/-! GENERATED by formal/tools/fasm2lean3/rhoinj.py (probe C-11g) from Formal/Net/FasmDesign/%s.\n"
           "    Do not edit; regenerate. Certificates for Formal.Net.FasmRho.bij_of_checks. -/\n" % ns)
    NSL = "Formal.Net.FasmRho%s" % tag
    docs = {"inv": "Logical net -> its physical net (%d entries)." % len(inv),
            "occ": "Logical net -> index of an instance whose logical cell has it (%d entries)." % len(occ),
            "mark": "Route-through output net -> index of its instance (%d entries)." % len(mark)}
    for nm, dd in (("inv", inv), ("occ", occ), ("mark", mark)):
        # one file per trie: the elaborator's memory for ~13k entries is ~1 GB
        with open(os.path.join(out, "FasmRho%s%s.lean" % (tag, nm.capitalize())), "w") as f:
            f.write("import Formal.Net.FasmRho\n\n%s\n" % hdr)
            f.write("namespace %s\nopen Formal.Net.FasmDesign Formal.Net.FasmRho\n\n" % NSL)
            f.write("/-- %s -/\n" % docs[nm])
            emit_trie(f, nm, dd)
            f.write("end %s\n" % NSL)
    with open(os.path.join(out, "FasmRho%sData.lean" % tag), "w") as f:
        f.write("import Formal.Net.FasmDesign.%s.Rho\nimport Formal.Net.FasmRho%sInv\nimport Formal.Net.FasmRho%sOcc\nimport Formal.Net.FasmRho%sMark\n\n%s\n" % (ns, tag, tag, tag, hdr))
        f.write("namespace %s\nopen Formal.Net.FasmDesign Formal.Net.FasmRho\n\n" % NSL)
        emit_check(f, "keys", "keysP inv mark", "%s.rho" % ns, rho, len(rho))
        f.write("end %s\n" % NSL)
    with open(os.path.join(out, "FasmRho%s.lean" % tag), "w") as f:
        f.write("import Formal.Net.FasmDesign.%s.All\nimport Formal.Net.FasmRho%sData\n\n%s\n" % (ns, tag, hdr))
        f.write("namespace %s\nopen Formal.Net.FasmDesign Formal.Net.FasmRho\n\n" % NSL)
        f.write("/-- The instances, chunk by chunk (`at?` indices are `1000 * chunk + position`). -/\n")
        f.write("def cs : List (List Inst) := %s.chunks.map Prod.fst\n\n" % ns)
        f.write("theorem cs_flatten : cs.flatten = %s.insts := %s.chunks_insts\n\n" % (ns, ns))
        emit_check(f, "mark", "markP cs", "mark", mark, len(mark))
        emit_check(f, "inv", "invP cs %s.rho mark occ" % ns, "inv", inv, len(inv))
        for ci in range(len(chunks)):
            f.write("theorem cover_%03d : coverOk mark inv %s.C%03d.insts = true := by decide +kernel\n\n" % (ci, ns, ci))
        f.write("theorem cover_ok : coverOk mark inv cs.flatten = true := by\n"
                "  apply coverOk_flatten\n"
                "  simp only [cs, %s.chunks, List.map_cons, List.map_nil, List.all_cons, List.all_nil,\n    %s, Bool.and_true]\n\n"
                % (ns, ", ".join("cover_%03d" % ci for ci in range(len(chunks)))))
        f.write("/-- Route %s: outside route-through outputs, `rho` is a bijection from the physical nets\n"
                "it sends to a logical net onto the logical nets on the instances' logical cells. -/\n" % tag.lower())
        f.write("theorem rho_bij :\n"
                "    (∀ k k' v, NonRt %(ns)s.insts %(ns)s.rho k v → NonRt %(ns)s.insts %(ns)s.rho k' v → k = k') ∧\n"
                "    (∀ k v, NonRt %(ns)s.insts %(ns)s.rho k v → LNet %(ns)s.insts v) ∧\n"
                "    (∀ v, LNet %(ns)s.insts v → ∃ k, NonRt %(ns)s.insts %(ns)s.rho k v) := by\n"
                "  rw [← cs_flatten]\n"
                "  exact bij_of_checks cs %(ns)s.rho inv mark occ mark_ok cover_ok keys_ok inv_ok\n\n" % {"ns": ns})
        f.write("end %s\n" % NSL)


if __name__ == "__main__":
    main()
