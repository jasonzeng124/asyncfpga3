#!/usr/bin/env bash
# Probe C-10f: RT_FB for every C-element of a routed Muller pipeline seed
# (route first with route_muller.sh).  Runs 11b's fasm2lean (unchanged) on the
# FASM READ BACK from the bits, then 10d's rt_all.py (unchanged) -> report + Lean data.
#     formal/tools/rtfb/muller_rt.sh SEED [N] [--lean]
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd); REPO=$(cd "$HERE/../../.." && pwd)
F2L=$REPO/formal/tools/fasm2lean; R2L=$REPO/formal/tools/routed2lean
SEED=$1; N=${2:-64}; B=$HERE/build/muller/muller${N}_s$SEED
python3 "$F2L/fasm2lean.py" "$B.fromBit.fasm" "$R2L/pipe/muller_pipe.xdc" --ns X --json "$B.f2l.json" \
    --out /dev/null 2> "$B.f2l.log"
OUTL=/dev/null
[ "${3:-}" = --lean ] && OUTL=$REPO/formal/lean/Formal/Timing/RtFbM${N}S$SEED.lean
python3 -I "$R2L/rt_all.py" "$B.f2l.json" --ns RtFbM${N}S$SEED --sdf "$B.sdf" --routed "$B"_routed.json \
    --out "$OUTL" --report "$B.rt.txt" > /dev/null
[ "$OUTL" != /dev/null ] && sed -i "s#Generated by formal/tools/routed2lean/rt_all.py#Generated by formal/tools/rtfb/muller_rt.sh (10d's rt_all.py), seed $SEED#" "$OUTL"
tail -2 "$B.rt.txt"
