#!/usr/bin/env python3
"""Probe C-10f2: write Formal/Timing/RtFbMuller.lean (summary theorems over the 64-stage Muller
pipeline seeds 1..8, data RtFbM64S<seed>.lean from rtfb_design.py --lean-all, WITH the driver-side
OUTMUX hop).  Expected numbers come from rtfb_design.py's reports build/muller/muller64_s<s>.rtd.txt
(Python); the kernel re-checks every one of them.  Theorem names are C-10f's (m64sN_pass,
m64sN_worst, m64sN_wf, m64sN_sep, m64sN_slowE, m64_seeds_slowE_range) plus m64sN_len.
    python3 -I formal/tools/rtfb/lean_muller.py [SEED...]     (default 1..8)
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LEAN = os.path.join(HERE, "..", "..", "lean", "Formal", "Timing")
V = ["indep", "fast", "slow", "fastE", "slowE", "sdf"]
seeds = sys.argv[1:] or [str(s) for s in range(1, 9)]
info = {}
for s in seeds:
    t = open(os.path.join(HERE, "build", "muller", "muller64_s%s.rtd.txt" % s)).read()
    assert "driver-side OUTMUX hop: on;" in t, s
    fail = {v: int(re.search(r"^%s\s+failing (\d+)/" % v, t, re.M).group(1)) for v in V}
    worst = {v: int(re.search(r"^%s\s+failing \d+/\d+\s+worst \((-?\d+)," % v, t, re.M).group(1)) for v in V}
    nce = int(re.search(r"C-elements (\d+),", t).group(1))
    nlean = int(re.search(r"def nEntries : Nat := (\d+)", open(os.path.join(LEAN, "RtFbM64S%s.lean" % s)).read()).group(1))
    nnone = int(re.search(r"no response path inside the bound: (\d+)", t).group(1))
    nhop = int(re.search(r"feedback routes through an xMUX pin: (\d+) of", t).group(1))
    assert nlean == nce == 64, (s, nlean, nce)
    info[s] = (fail, worst, nnone, nhop)
lo = min(64 - info[s][0]["slowE"] for s in seeds)
hi = max(64 - info[s][0]["slowE"] for s in seeds)
L = ["import Formal.Timing.RtFbCore"] + ["import Formal.Timing.RtFbM64S%s" % s for s in seeds]
L.append('''
/-!
# RT_FB on 8 placer seeds of the routed 64-stage Muller pipeline (probes C-10f, C-10f2)

Data `RtFbM64S<seed>` (seeds 1..8), generated by `formal/tools/rtfb/muller_rt.sh` (rtfb_design.py
--lean-all on the FASM read back from each seed's bitstream; 10d's `pipe/` design, cells/flow.sh
options, `--freq 100 --seed s`, fasm_audit PASS, nextpnr fingerprint in the C-10f2 note).

C-10f2 (2026-10-29): every route that leaves its slice through an AMUX..DMUX pin now carries the
driver-side OUTMUX hop (prjxray slicel/slicem.sdf, e.g. a6lut -> amux (0.071::0.088)(0.168::0.209)
ns), on the feedback and on every response net.  C-10f's data (10d's rt_all.py; seed 1 was 10d's
`RoutedMuller64S1`) had no such hop; the theorem names are kept, the numbers changed.

Each entry is one C-element: the TREE of its feedback route and every simple response path whose
H_INDEP lower bound is below the feedback's H_INDEP upper bound, through any number of LUTs.  An
entry with no such path (column "none") has an empty response list: RT_FB holds for it trivially
in Lean, and for real by H_CONE (Python, Dijkstra-checked, not in Lean).

Variants (10d): `indep` = H_INDEP, `fast`/`slow` = H_ONE_CORNER with RC in [0, E],
`fastE`/`slowE` = H_ONE_CORNER + H_RC_EXACT, `sdf` = nextpnr's numbers (not a bound).
Each count is exact in its model: passing entries hold in every run (`rt_sound_of`), failing
entries have a violating fixed-delay run (`rt_violated_of`; side conditions `m64sN_wf`, `m64sN_sep`).

| seed | fb via xMUX | none | indep | fast | slow | fastE | slowE | sdf |  (failing of 64)
|---|---|---|---|---|---|---|---|---|''')
for s in seeds:
    f, w, nn, nh = info[s]
    L.append("| %s | %d | %d | %s |" % (s, nh, nn, " | ".join(str(f[v]) for v in V)))
L.append("-/")
L.append('''
namespace Formal.Timing.RtFb
open Formal.Timing Formal.Net Formal.Timing.Routed
''')
for s in seeds:
    f, w, nn, nh = info[s]
    n = "RtFbM64S%s" % s
    L.append("theorem m64s%s_len : %s.slowE.length = 64 := by decide +kernel" % (s, n))
    L.append("theorem m64s%s_pass :\n    %s := by decide +kernel" % (s, " ∧\n    ".join(
        "nPass %s.%s = %d" % (n, v, 64 - f[v]) for v in V)))
    L.append("theorem m64s%s_worst :\n    %s := by decide +kernel" % (s, " ∧\n    ".join(
        "worstSlack %s.%s = some (%d)" % (n, v, w[v]) for v in V)))
    L.append("theorem m64s%s_wf : %s.indep.all wfOne = true ∧ %s.fastE.all wfOne = true ∧ %s.slowE.all wfOne = true := by\n  decide +kernel" % (s, n, n, n))
    L.append("theorem m64s%s_sep : %s.indep.all sepOne = true ∧ %s.fastE.all sepOne = true ∧ %s.slowE.all sepOne = true := by\n  decide +kernel" % (s, n, n, n))
    L.append('''/-- Seed %s, H_ONE_CORNER (slow die) + H_RC_EXACT: passing C-elements are safe in every run,
failing ones (%d of 64) really violate RT_FB in some fixed-delay run. -/
theorem m64s%s_slowE :
    (∀ e ∈ %s.slowE, rtOne e = true → ∀ {sig : Nat → Trace}, Run (ofBuckets e.1) sig →
      ∀ r ∈ e.2.1, ∀ s t, changes (sig e.2.2.1) s → changes (sig r) t → s ≤ t) ∧
    (∀ e ∈ %s.slowE, rtOne e = false → ∃ r ∈ e.2.1, ∃ sig, Nonempty (FixedRun (ofBuckets e.1) sig) ∧
      ∃ s t, changes (sig e.2.2.1) s ∧ changes (sig r) t ∧ t < s) :=
  ⟨rt_sound_of _ m64s%s_wf.2.2, rt_violated_of _ m64s%s_wf.2.2 m64s%s_sep.2.2⟩
''' % (s, f["slowE"], s, n, n, s, s, s))
L.append('''/-- Over the %d seeds, under H_ONE_CORNER + H_RC_EXACT, at least %d and at most %d of the 64
C-elements fail RT_FB at the slow corner. -/
theorem m64_seeds_slowE_range :
    [%s].all (fun L => %d ≤ nPass L && nPass L ≤ %d) = true := by decide +kernel
''' % (len(seeds), 64 - hi, 64 - lo, ", ".join("RtFbM64S%s.slowE" % s for s in seeds), lo, hi))
L.append("end Formal.Timing.RtFb")
open(os.path.join(LEAN, "RtFbMuller.lean"), "w").write("\n".join(L) + "\n")
print("wrote RtFbMuller.lean; slowE pass range [%d..%d]" % (lo, hi))
