#!/usr/bin/env python3
"""Generate Formal/Net/PipeGcd.lean: kernel-checked token-level runs of the imported gcd_hw
graph (Formal/Net/GcdHw.lean) from a store holding TWO input pairs.  The schedules are found
by toksim.py's random scheduler (untrusted); Lean re-executes every firing (decide +kernel).

usage: gen_reorder.py [--check]   (pairs fixed below; --check: diff against the committed file)
"""
import os, sys, re, random
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
sys.path.insert(0, HERE)
import toksim  # noqa: E402

LEAN = os.path.join(ROOT, "formal", "lean", "Formal", "Net", "GcdHw.lean")
OUT = os.path.join(ROOT, "formal", "lean", "Formal", "Net", "PipeGcd.lean")
# gcd_rig.v's table: vector 9 (a = 0x10000, b = 0x1000, gcd 0x1000), then vector 4 (a = b = 1)
PAIRS = [(65536, 4096), (1, 1)]
CHUNK = 40

def find(rules, N, out_ch, want, seed0):
    for seed in range(seed0, seed0 + 2000):
        rng = random.Random(seed)
        st = [[] for _ in range(N)]
        for a, b in PAIRS: st[0].append(a); st[1].append(b); st[2].append(0)
        init = [list(q) for q in st]
        sched, stores = [], [init]
        while True:
            en = [i for i, r in enumerate(rules) if toksim.fire(r, st) is not None]
            if not en: break
            i = rng.choice(en)
            pops, pushes = toksim.fire(rules[i], st)
            for c, m in pops.items(): del st[c][:m]
            for c, v in pushes: st[c].append(v)
            sched.append(i); stores.append([list(q) for q in st])
        if st[out_ch] == want:
            return seed, sched, stores
    raise SystemExit(f"no run with out0 = {want}")

def sp(store):
    ent = ", ".join(f"({c}, {q})" for c, q in enumerate(store) if q)
    return f"sp 252 [{ent}]"

def gen():
    rules = toksim.parse_rules(LEAN)
    names = eval(re.search(r"def chanNames : List String := (\[.*\])", open(LEAN).read()).group(1))
    N = len(names); oc = names.index("170")
    assert N == 252 and oc == 250
    w = []
    w.append("import Formal.Net.GcdHw\n")
    w.append('''/-!
# GENERATED by formal/tools/pipe/gen_reorder.py -- DO NOT EDIT

**Problem, plainly.** THE goal (formal/PROGRAM.md, owner 2026-10-31) lets the environment
offer pair k+1 before pair k's result is out, and asks that the k-th output be the gcd of the
k-th pair. This file checks, at the TOKEN level (the Kahn graph bdc emits for gcd_hw,
`Formal.Net.GcdHw.Gcd.rules`, unbounded channels), two pairs queued: gcd_rig.v's vector 9
(a = 65536, b = 4096, gcd 4096) first, then vector 4 (a = b = 1, gcd 1), on `a` (channel 0),
`b` (channel 1), with two tokens on `start` (channel 2).

**Proved (kernel, every firing re-executed):** a COMPLETE run (no rule enabled at the end)
from that store that ends with out0 (channel 250) = [1, 4096]: the first output is the
second pair's gcd. Both `end` tokens are on channel 3 at the end, and nothing else.

**Not shown here:** that the hardware takes this schedule (the handshake network has finite
storage and real delays): see `PipeWit` (the capstone's cell models, unit delays) and
notes/C-pipe-cex.md. The values themselves stay right in every token-level run tried
(300 random runs, tool only, not Lean).
-/
''')
    w.append("namespace Formal.Net.PipeGcd\n")
    w.append("open Formal.Net.GcdHw Formal.Net.GcdHw.Gcd Formal.Net.Kahn\n")
    w.append('''theorem execL_append {V : Type} (I : VI V) (rs : List Rule) :
    ∀ (l : List (List V)) (s t : List Nat),
      execL I rs l (s ++ t) = (execL I rs l s).bind fun m => execL I rs m t
  | l, [], t => by simp [execL]
  | l, i :: s, t => by
    simp only [List.cons_append, execL]
    cases stepL I rs l i with
    | none => rfl
    | some m => simp only [Option.bind_some]; exact execL_append I rs m s t

theorem execL_chain {V : Type} (I : VI V) (rs : List Rule) {l m n : List (List V)} {s t : List Nat}
    (h1 : execL I rs l s = some m) (h2 : execL I rs m t = some n) :
    execL I rs l (s ++ t) = some n := by
  rw [execL_append, h1]; exact h2

/-- The two-pair store: (12, 18) then (3, 5) queued on a and b, two start tokens. -/
''')
    init = [[] for _ in range(N)]
    for a, b in PAIRS: init[0].append(a); init[1].append(b); init[2].append(0)
    w.append(f"def L0 : List (List Nat) := {sp(init)}\n")
    for tag, want, seed0 in (("reordered", [1, 4096], 1),):
        seed, sched, stores = find(rules, N, oc, want, seed0)
        k = 0; names_ = []
        w.append(f"\n/-! ## Run `{tag}` (toksim seed {seed}, {len(sched)} firings) -/\n")
        w.append(f"namespace {tag.capitalize()}\n")
        cuts = list(range(0, len(sched), CHUNK)) + [len(sched)]
        for j in range(len(cuts) - 1):
            a, b = cuts[j], cuts[j + 1]
            w.append(f"def S{j} : List (List Nat) := {sp(stores[b])}")
            w.append(f"def s{j} : List Nat := {sched[a:b]}")
            prev = "L0" if j == 0 else f"S{j-1}"
            w.append(f"theorem c{j} : execL natVI rules {prev} s{j} = some S{j} := by decide +kernel\n")
        nchunks = len(cuts) - 1
        allS = " ++ ".join(f"s{j}" for j in range(nchunks))
        w.append(f"def sched : List Nat := {allS}\n")
        proof = "c0"
        for j in range(1, nchunks):
            proof = f"(execL_chain natVI rules {proof} c{j})"
        w.append(f"theorem exec : execL natVI rules L0 sched = some S{nchunks-1} := {proof}\n")
        w.append(f"theorem final_out0 : ofL S{nchunks-1} 250 = [Nat.gcd 1 1, Nat.gcd 65536 4096] := by decide +kernel\n")
        w.append(f"theorem final_end : ofL S{nchunks-1} 3 = [0, 0] := by decide +kernel\n")
        w.append(f"theorem terminal : Terminal (step (graph rules)) (ofL S{nchunks-1}) :=\n  terminal_of_dead rules (ofL S{nchunks-1}) (by decide +kernel)\n")
        w.append(f"theorem run : Run (step (graph rules)) (ofL L0) sched.length (ofL S{nchunks-1}) :=\n  execL_run bounded_ok sched (by decide +kernel) exec\n")
        w.append(f"def final : List (List Nat) := S{nchunks-1}\n")
        w.append(f"end {tag.capitalize()}\n")
    w.append('''
/-- **Token-level reordering.** From the store with gcd_rig's vector 9 (65536, 4096) queued
before vector 4 (1, 1), the imported gcd_hw graph has a complete run ending with
out0 = [gcd 1 1, gcd 65536 4096] = [1, 4096]. -/
theorem gcd_hw_pipelined_reorders :
    ∃ n f, Run (step (graph rules)) (ofL L0) n (ofL f) ∧ Terminal (step (graph rules)) (ofL f) ∧
      ofL f 250 = [Nat.gcd 1 1, Nat.gcd 65536 4096] :=
  ⟨_, _, Reordered.run, Reordered.terminal, Reordered.final_out0⟩

end Formal.Net.PipeGcd
''')
    return "\n".join(w)

if __name__ == "__main__":
    txt = gen()
    if "--check" in sys.argv:
        ok = open(OUT).read() == txt
        print("PipeGcd.lean up to date" if ok else "PipeGcd.lean DRIFT"); sys.exit(0 if ok else 1)
    open(OUT, "w").write(txt); print("wrote", OUT, len(txt), "bytes")
