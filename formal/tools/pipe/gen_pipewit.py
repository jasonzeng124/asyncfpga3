#!/usr/bin/env python3
"""Emit Formal/Net/PipeWitData.lean: hwsim.py's unit-delay run of the gcd_hw CapNet network
(Formal/Net/CapstoneNet.lean, C-8t/C-wit cell models) under a PIPELINED four-phase
environment, as C-wit event lists (format of formal/tools/capwit2/gen_wit.py, requests may
start high).  Nothing here is trusted: Formal/Net/PipeWit.lean re-checks every operator.

  gen_pipewit.py [--check]
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "capwit3"))
import sim, hwsim  # noqa: E402

NETDIR = os.path.join(sim.ROOT, "formal", "lean", "Formal", "Net")
OUT = os.path.join(NETDIR, "PipeWitData.lean")
# gcd_rig.v vector 9 (a = 0x10000, b = 0x1000), then vector 4 (a = b = 1)
PAIRS = [(65536, 4096, 0), (1, 1, 0)]


def lst(xs): return "[" + ", ".join(str(x) for x in xs) + "]"


def rows_of(names, ops, tr):   # = capwit2/gen_wit.py rows_of with r0 = True
    prod = {}
    for n, o in enumerate(ops):
        for c in sim.outs_of(o): prod[c] = n
    rows = []
    for c in range(len(names)):
        rs = [s[0][c] for s in tr]
        ds = [s[3][c] for s in tr]
        o = ops[prod[c]]
        ax = []
        if o["k"] in sim.NINT:
            ax = [sim.toggles([s[2][prod[c]][k] for s in tr]) for k in range(sim.NINT[o["k"]])]
        rows.append(f"  ⟨{'true' if rs[0] else 'false'}, {lst(sim.toggles(rs))}, "
                    f"{lst(sim.toggles([s[1][c] for s in tr]))}, {ds[0]}, "
                    f"[{', '.join(f'({t}, {v})' for t, v in sim.dchanges(ds))}], [{', '.join(lst(x) for x in ax)}]⟩")
    return rows


def render():
    names, ops, out0, start = sim.load_net("gcd")
    env = {"mode": "pipe", "offers": len(PAIRS), "start": start, "out0": out0, "r0low": True}
    tr = hwsim.simulate(PAIRS, names, ops, env)
    T = len(tr) - 1
    srcs = [(o["z"], o["which"]) for o in ops if o["k"] == "src"]
    R = lambda c, t: tr[t][0][c]
    offs = lambda c: [t for t in range(T) if not R(c, t) and R(c, t + 1)] if not R(c, 0) else \
        [-1] + [t for t in range(T) if not R(c, t) and R(c, t + 1)]
    o0 = offs(out0)
    rows = rows_of(names, ops, tr)
    hdr = f'''import Formal.Net.RigAllWitLib
import Formal.Net.CapstoneNetChk

/-!
# GENERATED by formal/tools/pipe/gen_pipewit.py -- DO NOT EDIT

One unit-delay run of the concrete gcd_hw CapNet network ({len(names)} channels), every gate of
every cell model with delay exactly 1 (as C-8t), under a PIPELINED environment: the three source
requests are one wire env_c (gcd_rig's bd_fork), low at tick 0 (first offer at tick 0 -> 1); in_ack = C(source acks);
env_c' = not in_ack, so pair 2 is offered as soon as pair 1's input handshake is complete.
Pairs (a, b): {[p[:2] for p in PAIRS]}. Quiescent after {T} ticks.
Source channels (z, which): {srcs}; their request rises: {[offs(z) for z, _ in srcs]} (-1 = high at 0).
out0 (channel {out0}) request rises at {o0}, carrying {[tr[t + 1][3][out0] for t in o0]}.
Nothing here is trusted: `PipeWit.lean` checks it in the kernel.
-/

namespace Formal.Net.CapNet.PipeWit
open Formal.Net Formal.Net.CapNet Formal.Net.CapNet.Gcd Formal.Net.CapNet.RigWit

set_option maxRecDepth 100000

'''
    parts = [f"def cdsP{i // 60} : List CD := [\n" + ",\n".join(rows[i:i + 60]) + "\n]\n"
             for i in range(0, len(names), 60)]
    cat = " ++ ".join(f"cdsP{i}" for i in range(len(parts)))
    ftr = f'''
def cds : List CD := {cat}

def cdA (c : Fin NC) : CD := cds.getD c.val ⟨false, [], [], 0, [], []⟩

def tEnd : Nat := {T}

end Formal.Net.CapNet.PipeWit
'''
    return hdr + "\n".join(parts) + ftr


if __name__ == "__main__":
    txt = render()
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == txt
        print("PipeWitData:", "ok" if ok else "DRIFT"); sys.exit(0 if ok else 1)
    open(OUT, "w").write(txt); print("wrote", OUT, len(txt), "bytes")
