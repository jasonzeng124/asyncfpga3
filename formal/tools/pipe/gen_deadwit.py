#!/usr/bin/env python3
"""Emit Formal/Net/PipeDeadData.lean: hwsim.py's unit-delay run of the gcd_hw CapNet network under a
pipelined four-phase environment that offers gcd_rig.v's vector 9 (a = 0x10000, b = 0x1000) TWICE,
every request low at tick 0 (env "r0low"), in C-8t's event-list format (`Wit.CD`, no initial
level).  Untrusted: Formal/Net/PipeDead.lean re-checks it in the kernel.

  gen_deadwit.py [--check]
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "capwit3"))
import sim, hwsim  # noqa: E402

OUT = os.path.join(sim.ROOT, "formal", "lean", "Formal", "Net", "PipeDeadData.lean")
PAIRS = [(65536, 4096, 0), (65536, 4096, 0)]


def lst(xs): return "[" + ", ".join(str(x) for x in xs) + "]"


def render():
    names, ops, out0, start = sim.load_net("gcd")
    env = {"mode": "pipe", "offers": len(PAIRS), "start": start, "out0": out0, "r0low": True}
    tr = hwsim.simulate(PAIRS, names, ops, env)
    T = len(tr) - 1
    prod = {}
    for n, o in enumerate(ops):
        for c in sim.outs_of(o): prod[c] = n
    rows = []
    for c in range(len(names)):
        rs = [s[0][c] for s in tr]
        assert not rs[0]
        ds = [s[3][c] for s in tr]
        o = ops[prod[c]]
        ax = [sim.toggles([s[2][prod[c]][k] for s in tr]) for k in range(sim.NINT[o["k"]])] if o["k"] in sim.NINT else []
        rows.append(f"  ⟨{lst(sim.toggles(rs))}, {lst(sim.toggles([s[1][c] for s in tr]))}, {ds[0]}, "
                    f"[{', '.join(f'({t}, {v})' for t, v in sim.dchanges(ds))}], [{', '.join(lst(x) for x in ax)}]⟩")
    R = lambda c, t: tr[t][0][c]
    rises = [[t for t in range(T) if not R(z, t) and R(z, t + 1)] for z in (0, 1, 2)]
    hdr = f'''import Formal.Net.CapstoneLiveWitLib

/-!
# GENERATED by formal/tools/pipe/gen_deadwit.py -- DO NOT EDIT

Probe C-pipe: one unit-delay run of the concrete gcd_hw CapNet network ({len(names)} channels) under a
PIPELINED environment: the three source requests are one wire env_c (gcd_rig's bd_fork), low at
tick 0; in_ack = C(source acks); env_c' = not in_ack (two offers, then low). Both offers are
gcd_rig.v's vector 9: a = 65536, b = 4096. Requests of a, b, start rise at {rises}.
Quiescent after {T} ticks; out0 (channel {out0}) never requests.
Nothing here is trusted: `PipeDead.lean` checks it in the kernel.
-/

namespace Formal.Net.CapNet.PipeDead
open Formal.Net Formal.Net.CapNet Formal.Net.CapNet.Gcd Formal.Net.CapNet.Wit

set_option maxRecDepth 100000

'''
    parts = [f"def cdsP{i // 60} : List CD := [\n" + ",\n".join(rows[i:i + 60]) + "\n]\n"
             for i in range(0, len(names), 60)]
    cat = " ++ ".join(f"cdsP{i}" for i in range(len(parts)))
    ftr = f'''
def cdsD : List CD := {cat}

def cdD (c : Fin NC) : CD := cdsD.getD c.val ⟨[], [], 0, [], []⟩

/-- The run. -/
def chD : Fin NC → Handshake.Chan := wch cdD

/-- The last tick at which anything changes. -/
def tEnd : Nat := {T}

end Formal.Net.CapNet.PipeDead
'''
    return hdr + "\n".join(parts) + ftr


if __name__ == "__main__":
    txt = render()
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == txt
        print("PipeDeadData:", "ok" if ok else "DRIFT"); sys.exit(0 if ok else 1)
    open(OUT, "w").write(txt); print("wrote", OUT, len(txt), "bytes")
