#!/usr/bin/env python3
"""H_COMPUTE_FN netlist extractor (shard C, 2026-10-31).

    python3 extract.py SYNTH.json UNIT NS OUT.lean

Reads a yosys `synth_xilinx` JSON netlist (hierarchical: each `bdc_fused_*` compute unit is its
own module), takes the module whose name contains `bdc_fused_<UNIT>`, and writes the combinational
cone of its `z_data` output as Lean data over `Formal.Net.Compute` (`cells`, `outs`):

* inputs: port `e<p>_data` bit `k` -> `.inp p k`; constant bits "0"/"1" -> `.c0`/`.c1`;
* cells, in a topological order (each cell after the drivers of its inputs): LUT1..6 (INIT as
  the number yosys prints MSB first; pins I0..I5), MUXF7/MUXF8 (I0, I1, S), INV, CARRY4 (CI,
  CYINIT, DI[0..3], S[0..3]; outputs O[0..3], CO[0..3]);
* nets keep yosys' bit numbers.

Refuses anything else in the cone (a flop, a latch, an unknown cell type, an "x" bit). Trusted
only for being a faithful transcription: the Lean side re-checks nothing about the JSON, so a
wrong transcription is a wrong theorem about a different netlist (the drift check
`check.sh` regenerates and compares).
"""
import json, sys

COMB = {"LUT1", "LUT2", "LUT3", "LUT4", "LUT5", "LUT6", "MUXF7", "MUXF8", "INV", "CARRY4"}
OUTP = {"O", "CO"}


def main():
    js, unit, ns, out = sys.argv[1:5]
    j = json.load(open(js))
    mods = [(k, v) for k, v in j["modules"].items() if f"bdc_fused_{unit}\\" in k or k.endswith(f"bdc_fused_{unit}")]
    if len(mods) != 1:
        sys.exit(f"extract: {len(mods)} modules match bdc_fused_{unit}")
    mname, m = mods[0]
    inb = {}
    for p, v in m["ports"].items():
        if v["direction"] == "input" and p.startswith("e") and p.endswith("_data"):
            pi = int(p[1:-5])
            for k, b in enumerate(v["bits"]):
                inb[b] = (pi, k)
    drv = {}
    for cn, c in m["cells"].items():
        if c["type"].startswith("$"):
            continue
        for p, bits in c["connections"].items():
            if p in OUTP:
                for b in bits:
                    if isinstance(b, int):
                        drv[b] = cn
    order, seen = [], set()

    def wire(b):
        if b == "0": return ".c0"
        if b == "1": return ".c1"
        if isinstance(b, str): sys.exit(f"extract: bit {b!r} in the cone")
        if b in inb: return ".inp %d %d" % inb[b]
        return ".net %d" % b

    def visit(b):
        if isinstance(b, str) or b in inb: return
        cn = drv.get(b)
        if cn is None: sys.exit(f"extract: net {b} has no driver")
        if cn in seen: return
        seen.add(cn)
        c = m["cells"][cn]
        if c["type"] not in COMB: sys.exit(f"extract: {c['type']} in the cone of z_data")
        for p, bits in sorted(c["connections"].items()):
            if p not in OUTP:
                for bb in bits: visit(bb)
        order.append(cn)

    zs = m["ports"]["z_data"]["bits"]
    for b in zs: visit(b)
    fresh = [10 ** 7]

    def onet(b):
        if isinstance(b, int): return b
        fresh[0] += 1
        return fresh[0]

    lines = []
    for cn in order:
        c = m["cells"][cn]; t = c["type"]; con = c["connections"]
        if t.startswith("LUT"):
            n = int(t[3:])
            init = int(c["parameters"]["INIT"], 2)
            ins = ", ".join(wire(con[f"I{i}"][0]) for i in range(n))
            lines.append(f"  .lut {init} [{ins}] {con['O'][0]}")
        elif t in ("MUXF7", "MUXF8"):
            lines.append(f"  .muxf ({wire(con['I0'][0])}) ({wire(con['I1'][0])}) ({wire(con['S'][0])}) {con['O'][0]}")
        elif t == "INV":
            lines.append(f"  .inv ({wire(con['I'][0])}) {con['O'][0]}")
        elif t == "CARRY4":
            di = ", ".join(wire(b) for b in con["DI"]); s = ", ".join(wire(b) for b in con["S"])
            os_ = " ".join(str(onet(b)) for b in con.get("O", ["x"] * 4) + con.get("CO", ["x"] * 4))
            lines.append(f"  .carry4 ({wire(con['CI'][0])}) ({wire(con['CYINIT'][0])}) [{di}] [{s}] {os_}")
    outs = ", ".join(wire(b) for b in zs)
    ports = sorted(set(p for p, _ in inb.values()))
    src = f"""import Formal.Net.Compute.Basic

/-!
# GENERATED by formal/tools/compute/extract.py -- DO NOT EDIT

The combinational cone of `z_data` of yosys module `{mname}` (gcd_hw, from the committed
synthesis netlist), as `Formal.Net.Compute` cells in topological order. Input ports
{", ".join("e%d_data = %d" % (p, p) for p in ports)}; {len(order)} cells; {len(zs)} output bits.
-/

namespace {ns}
open Formal.Net.Compute

def cells : List Cell := [
""" + ",\n".join(lines) + f"""]

def outs : List W := [{outs}]

set_option maxRecDepth 100000 in
theorem nodup : (cells.flatMap Cell.outs).Nodup := by decide +kernel

end {ns}
"""
    open(out, "w").write(src)
    print(f"extract: {unit}: {len(order)} cells, {len(zs)} outputs -> {out}")


if __name__ == "__main__":
    main()
