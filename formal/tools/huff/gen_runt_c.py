#!/usr/bin/env python3
"""[Shard C copy, 2026-11-07: namespace from CEXNS, per-arc slow list (@classes.json -> codes 8*out+pin), and every
gate-chunk check split into CEXSPLIT (default 3) decides (shard A's split_x.py layout).]
Shard A (2026-11-07): Lean data for an H_RUNT(w) witness run (simrunt.py --exact --w W --dump): per-chunk BTL
trees of node codes (as shard C's gen_cex.py), one sparse BTC tree of narrow-pulse chains per node, the slow-node
list, per-chunk gate checks (CexRunt72.gateWR).
usage: gen_runt.py dump.json net.json bnd.json OUTDIR W SLOWNODE..."""
import json, sys, os
Wd = json.load(open(sys.argv[1])); net = json.load(open(sys.argv[2])); BJ = json.load(open(sys.argv[3])); out = sys.argv[4]
W = int(sys.argv[5])
G = net["gates"]; N = net["nodes"]; idx = {n: i for i, n in enumerate(N)}; ENV = set(idx[x] for x in BJ["env"])
nN = len(N); nG = len(G); C, D = 2500, 12
drv = {g["out"]: gi for gi, g in enumerate(G) if g["out"] not in ENV}
ARCS = None
if len(sys.argv) > 6 and sys.argv[6].startswith("@"):
    ARCS = sorted(8 * idx[x[0]] + x[1] for x in json.load(open(sys.argv[6][1:]))["S"]); sys.argv = sys.argv[:6]
SLOW = set(idx[x] for x in sys.argv[6:])
for n0 in list(SLOW):
    for u in G[drv[n0]]["ins"]:
        while u in drv and G[drv[u]]["k"] == 1 and G[drv[u]]["init"] == 2: SLOW.add(u); u = G[drv[u]]["ins"][0]
nodes = {int(k): v for k, v in Wd["nodes"].items()}
def leaf(n):
    v = nodes.get(n)
    if v is None or (not v[0] and not v[1]): return ".lf none"
    return f".lf (some ({'true' if v[0] else 'false'}, [{', '.join(map(str, v[1]))}]))"
def tree(ns, d):
    if d == 0: return leaf(ns[0]) if ns[0] is not None else ".lf none"
    h = len(ns) // 2
    return f".nd ({tree(ns[:h], d - 1)}) ({tree(ns[h:], d - 1)})"
def chains(ts):
    bnd = [0] + ts; ch = []; cs = None
    for i in range(1, len(bnd)):          # the power-up interval [0, first flip) is never part of a chain
        nar = i + 1 < len(bnd) and bnd[i + 1] - bnd[i] < W
        if nar and cs is None: cs = bnd[i]
        if not nar and cs is not None: ch.append((cs, bnd[i])); cs = None
    return ch
CH = {n: chains(v[1]) for n, v in nodes.items()}
CH = {n: c for n, c in CH.items() if c}
DC = 18
assert nN <= 2 ** DC
def ctree(lo, d):
    if not any(lo <= n < lo + 2 ** d for n in CH): return ".lf []"
    if d == 0: return ".lf [" + ", ".join(f"({a}, {b})" for a, b in CH[lo]) + "]"
    return f".nd ({ctree(lo, d - 1)}) ({ctree(lo + 2 ** (d - 1), d - 1)})"
NS = os.environ["CEXNS"]; HDR = "/-! GENERATED by formal/tools/huff/gen_runt_c.py. Do not edit. -/\n\n"
nch = (nN + C - 1) // C; nchG = (nG + C - 1) // C
for c in range(nch):
    ns = list(range(c * C, min((c + 1) * C, nN))); ns += [None] * (2 ** D - len(ns))
    open(f"{out}/L{c:03d}.lean", "w").write(f"import {NS}.RBase\n\n" + HDR + f"namespace {NS}\n\n"
        "set_option maxRecDepth 100000 in\n" + f"def l{c:03d} : BTL :=\n  {tree(ns, D)}\n\nend {NS}\n")
open(f"{out}/Ch.lean", "w").write(f"import {NS}.RBase\n\n" + HDR + f"namespace {NS}\n\n"
    "set_option maxRecDepth 100000 in\n"
    f"/-- Narrow-pulse chains (maximal runs of pulses < {W} ps, power-up interval excluded) of {len(CH)} nodes. -/\n"
    f"def chT : BTC :=\n  {ctree(0, DC)}\n\nend {NS}\n")
L = ", ".join(f"l{c:03d}" for c in range(nch))
open(f"{out}/EncR.lean", "w").write("".join(f"import {NS}.L{c:03d}\n" for c in range(nch)) + f"import {NS}.Ch\n\n" + HDR +
    f"namespace {NS}\n\ndef llR : List BTL := [{L}]\n\n/-- The run's node codes. -/\n"
    f"def encR : Nat → Option (Bool × List Nat) := lookL llR {C} {D}\n\n"
    f"/-- Each node's narrow-pulse chains. -/\ndef chR (n : Nat) : List (Nat × Nat) := chT.get {DC} n\n\n"
    f"/-- The slow gates (their output nodes) and the copy gates on their input routes. -/\n"
    f"def slR : List Nat := [{', '.join(map(str, ARCS if ARCS is not None else sorted(SLOW)))}]\n\nend {NS}\n")
P = int(os.environ.get("CEXSPLIT", "3"))
F = f"(fun g => !keepPS g || gateWR {W} encR chR slR g)"
def slc(c, j, q):
    e = f"g{c:03d}"
    for _ in range(j): e = f"({e}.drop {q})"
    return e if j == P - 1 else f"({e}.take {q})"
for c in range(nchG):
    q = C // P + 1
    parts = [f"set_option maxRecDepth 100000 in\ntheorem x{c:03d}_p{j} : {slc(c, j, q)}.all {F} = true := by decide +kernel\n"
             for j in range(P)]
    comb = f"theorem x{c:03d}_ok : g{c:03d}.all {F} = true := by\n"
    e = f"g{c:03d}"
    for j in range(P - 1):
        comb += f"  rw [← List.take_append_drop {q} {e}, List.all_append, x{c:03d}_p{j}, Bool.true_and]\n"
        e = f"({e}.drop {q})"
    comb += f"  exact x{c:03d}_p{P-1}\n"
    open(f"{out}/X{c:03d}.lean", "w").write(f"import {NS}.EncR\n\n" + HDR +
        f"namespace {NS}\nopen Formal.Target.DecodedPS Formal.Net.CViewPS\n\n" + "\n".join(parts) + "\n" + comb + f"\nend {NS}\n")
print("gen_runt: %d node chunks, %d gate chunks, %d slow gates, %d nodes with chains" % (nch, nchG, len(SLOW), len(CH)))
