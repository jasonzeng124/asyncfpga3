#!/usr/bin/env python3
"""Shard C: Lean data for the counterexample witness (simadv --exact --dump output): per-chunk BTL trees of
node codes (initial value, transition times), the slow-node list, per-chunk gate checks (gateWK).
usage: gen_cex.py dump.json net.json bnd.json OUTDIR SLOWNODE..."""
import json, sys
W = json.load(open(sys.argv[1])); net = json.load(open(sys.argv[2])); BJ = json.load(open(sys.argv[3])); out = sys.argv[4]
G = net["gates"]; N = net["nodes"]; idx = {n: i for i, n in enumerate(N)}; ENV = set(idx[x] for x in BJ["env"])
nN = len(N); nG = len(G); C, D = 2500, 12
drv = {g["out"]: gi for gi, g in enumerate(G) if g["out"] not in ENV}
ARCS = None
if len(sys.argv) > 5 and sys.argv[5].startswith("@"):   # per-arc slow list (simadv --classes JSON "S": [[node, pin]]) -> codes 8*out+pin
    ARCS = sorted(8 * idx[x[0]] + x[1] for x in json.load(open(sys.argv[5][1:]))["S"]); sys.argv = sys.argv[:5]
SLOW = set(idx[x] for x in sys.argv[5:])
for n0 in list(SLOW):
    for u in G[drv[n0]]["ins"]:
        while u in drv and G[drv[u]]["k"] == 1 and G[drv[u]]["init"] == 2: SLOW.add(u); u = G[drv[u]]["ins"][0]
nodes = {int(k): v for k, v in W["nodes"].items()}
def leaf(n):
    v = nodes.get(n)
    if v is None or (not v[0] and not v[1]): return ".lf none"
    return f".lf (some ({'true' if v[0] else 'false'}, [{', '.join(map(str, v[1]))}]))"
def tree(ns, d):
    if d == 0: return leaf(ns[0]) if ns[0] is not None else ".lf none"
    h = len(ns) // 2
    return f".nd ({tree(ns[:h], d - 1)}) ({tree(ns[h:], d - 1)})"
import os
NS = os.environ.get("CEXNS", "Formal.Net.CexPS"); HDR = "/-! GENERATED by formal/tools/huff/gen_cex.py. Do not edit. -/\n\n"
nch = (nN + C - 1) // C; nchG = (nG + C - 1) // C
for c in range(nch):
    ns = list(range(c * C, min((c + 1) * C, nN))); ns += [None] * (2 ** D - len(ns))
    open(f"{out}/L{c:03d}.lean", "w").write(f"import {NS}.KBase\n\n" + HDR + f"namespace {NS}\n\n"
        "set_option maxRecDepth 100000 in\n" + f"def l{c:03d} : BTL :=\n  {tree(ns, D)}\n\nend {NS}\n")
L = ", ".join(f"l{c:03d}" for c in range(nch))
open(f"{out}/EncK.lean", "w").write("".join(f"import {NS}.L{c:03d}\n" for c in range(nch)) + "\n" + HDR +
    f"namespace {NS}\n\ndef llK : List BTL := [{L}]\n\n/-- The counterexample run's node codes. -/\n"
    f"def encK : Nat → Option (Bool × List Nat) := lookL llK {C} {D}\n\n"
    f"/-- The slow gates (their output nodes) and the copy gates on their input routes. -/\n"
    f"def slK : List Nat := [{', '.join(map(str, ARCS if ARCS is not None else sorted(SLOW)))}]\n\nend {NS}\n")
for c in range(nchG):
    open(f"{out}/X{c:03d}.lean", "w").write(f"import {NS}.EncK\n\n" + HDR +
        f"namespace {NS}\nopen Formal.Target.DecodedPS Formal.Net.CViewPS\n\nset_option maxRecDepth 100000 in\n"
        f"theorem x{c:03d}_ok : g{c:03d}.all (fun g => !keepPS g || gateWK encK slK g) = true := by decide +kernel\n\nend {NS}\n")
print("gen_cex: %d node chunks, %d gate chunks, %d slow gates" % (nch, nchG, len(SLOW)))
