#!/usr/bin/env python3
"""C-8t: emit formal/lean/Formal/Net/CapstoneWitnessData.lean from the unit-delay run of sim.py.

Usage: gen_data.py [a b] [--check]   (--check: compare with the file on disk, exit 1 on drift)
"""
import os, sys, math
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import sim  # noqa: E402

OUT = os.path.join(sim.ROOT, "formal", "lean", "Formal", "Net", "CapstoneWitnessData.lean")


def lst(xs): return "[" + ", ".join(str(x) for x in xs) + "]"


def render(a, b):
    names, ops, out0 = sim.load_net()
    tr = sim.simulate(a, b, names, ops)
    errs, falls = sim.check(a, b, names, ops, out0, tr)
    if errs:
        raise SystemExit(f"run violates the models: {errs[:10]}")
    NC = len(names)
    prod = {}
    for n, o in enumerate(ops):
        for c in sim.outs_of(o): prod[c] = n
    rows = []
    for c in range(NC):
        rq = sim.toggles([s[0][c] for s in tr])
        ak = sim.toggles([s[1][c] for s in tr])
        ds = [s[3][c] for s in tr]
        dt = sim.dchanges(ds)
        o = ops[prod[c]]
        ax = []
        if o["k"] in sim.NINT:
            n = prod[c]
            ax = [sim.toggles([s[2][n][k] for s in tr]) for k in range(sim.NINT[o["k"]])]
        rows.append(f"  ⟨{lst(rq)}, {lst(ak)}, {ds[0]}, [{', '.join(f'({t}, {v})' for t, v in dt)}], "
                    f"[{', '.join(lst(x) for x in ax)}]⟩")
    T = len(tr) - 1
    nt = sum(len(sim.toggles([s[0][c] for s in tr])) + len(sim.toggles([s[1][c] for s in tr])) for c in range(NC))
    srq = sim.toggles([s[0][2] for s in tr])
    hdr = f'''import Formal.Net.CapstoneWitnessLib
import Formal.Net.CapstoneNetChk

/-!
# GENERATED by formal/tools/capwit/gen_data.py -- DO NOT EDIT

Probe C-8t: one circuit run of the concrete gcd_hw network (`CapstoneNet`, 465 channels) on
a = {a}, b = {b}: every gate of every cell model with delay exactly 1 (C-elements hold while
their inputs disagree; the arbiters grant input x on a tie), combinational buses, links'
latches transparent while `c` is high; the three sources offer one token each and then wait,
the sinks acknowledge after one tick. Quiescent after {T} ticks; {nt} request/acknowledge
toggles; out0 (channel {out0}) closes at tick {falls}.

`cds`: per channel, the request and acknowledge toggle steps, the bus's initial value and
change points, and the producer's internal traces (link `c`; mux `j0 j1`; 3-way mux
`j0 j1 j2`; arbiter `g1 g2`). Nothing here is trusted: `CapstoneWitnessCells` checks it.
-/

namespace Formal.Net.CapNet.Wit
open Formal.Net Formal.Net.CapNet Formal.Net.CapNet.Gcd

set_option maxRecDepth 100000

abbrev A0 : Nat := {a}
abbrev B0 : Nat := {b}

def cds : List CD := [
'''
    body = ",\n".join(rows)
    ftr = f'''
]

def cdA (c : Fin NC) : CD := cds.getD c.val ⟨[], [], 0, [], []⟩

/-- The run. -/
def chW : Fin NC → Handshake.Chan := wch cdA

/-- The start request toggles (rise, fall). -/
def startRise : Nat := {srq[0]}
def startFall : Nat := {srq[1]}
def out0Close : Nat := {falls[0]}

end Formal.Net.CapNet.Wit
'''
    assert len(srq) == 2
    return hdr + body + ftr


def main():
    args = [x for x in sys.argv[1:] if not x.startswith("--")]
    a = int(args[0]) if args else 12
    b = int(args[1]) if len(args) > 1 else 18
    txt = render(a, b)
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == txt
        print("gen_data:", "ok" if ok else "DRIFT")
        return 0 if ok else 1
    open(OUT, "w").write(txt)
    print("wrote", OUT, len(txt), "bytes; gcd", math.gcd(a, b))
    return 0


if __name__ == "__main__":
    sys.exit(main())
