#!/usr/bin/env python3
"""C-8t negative controls: mutated runs whose kernel check MUST fail.

Writes formal/lean/Wip/C8t/neg/Neg*.lean. Each file contains exactly one `decide +kernel`
claim that is false for its mutated run; `formal/lean/Wip/C8t/negctl.sh` runs Lean on each and
requires that claim, and nothing else, to be rejected.

* NegCell:  the clean run with fork branch g3.0's first request toggle moved one tick
            earlier (the branch rises before the fork's input did): H_CELLS must fail.
* NegHeld:  the clean run with one extra bus change on out0 one tick after its request rose
            (mid-transaction): H_BUNDLE must fail.
* NegStart: a run in which the start source offers two tokens (allowed by `Src`): it still
            passes H_CELLS and H_BUNDLE (checked in the same file, must succeed), and
            H_START_ONCE must fail.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import sim  # noqa: E402
import gen_data  # noqa: E402

NEGDIR = os.path.join(sim.ROOT, "formal", "lean", "Wip", "C8t", "neg")

HDR = '''import Formal.Net.CapstoneWitnessLib
import Formal.Net.CapstoneNetChk
import Formal.Net.CapstoneCutSpine

/-! C-8t negative control (GENERATED by formal/tools/capwit/gen_neg.py): {what} -/

namespace Formal.Net.CapNet.Wit.Neg
open Formal.Net Formal.Net.Handshake Formal.Net.Ops Formal.Net.CapNet Formal.Net.CapNet.Gcd
  Formal.Net.CapNet.Wit

set_option maxRecDepth 100000

def cdsN : List CD := [
{rows}
]

def cdN (c : Fin NC) : CD := cdsN.getD c.val ⟨[], [], 0, [], []⟩

'''


def write(name, what, rows, claims):
    os.makedirs(NEGDIR, exist_ok=True)
    txt = HDR.format(what=what, rows=",\n".join(rows)) + claims + "\nend Formal.Net.CapNet.Wit.Neg\n"
    open(os.path.join(NEGDIR, name + ".lean"), "w").write(txt)
    print("wrote", name)


def main():
    a, b = 12, 18
    names, ops, out0 = sim.load_net()
    tr = sim.simulate(a, b, names, ops)
    g3 = names.index("g3.0")

    def mut_cell(c, rq, ak, d0, dt, ax):
        if c == g3:
            assert rq[0] >= 1
            rq = [rq[0] - 1] + rq[1:]
        return rq, ak, d0, dt, ax
    write("NegCell", "fork branch g3.0 rises one tick early; H_CELLS must FAIL",
          gen_data.rows_of(names, ops, tr, mut_cell),
          "-- MUST FAIL\ntheorem neg_cells : ops.all (fun k => kChk cdN (srcV 12 18) k) = true := by decide +kernel\n")

    r0 = sim.toggles([s[0][out0] for s in tr])[0]

    def mut_held(c, rq, ak, d0, dt, ax):
        if c == out0:
            dt = sorted(dt + [(r0 + 1, 7)])
        return rq, ak, d0, dt, ax
    write("NegHeld", "out0's bus changes one tick after its request rose; H_BUNDLE must FAIL",
          gen_data.rows_of(names, ops, tr, mut_held),
          "-- MUST FAIL\ntheorem neg_held : cdsN.all heldChk = true := by decide +kernel\n")

    tr2 = sim.simulate(a, b, names, ops, start_tokens=2)
    errs, _ = sim.check(a, b, names, ops, out0, tr2)
    assert [e[0] for e in errs] == ["start rises"], errs[:5]
    T2 = len(tr2) - 1
    write("NegStart", "the start source offers two tokens; H_CELLS and H_BUNDLE hold, H_START_ONCE must FAIL",
          gen_data.rows_of(names, ops, tr2),
          "-- must SUCCEED\ntheorem pos_cells : ops.all (fun k => kChk cdN (srcV 12 18) k) = true := by decide +kernel\n"
          "-- must SUCCEED\ntheorem pos_held : cdsN.all heldChk = true := by decide +kernel\n"
          f"-- MUST FAIL\ntheorem neg_start : cnt (riseB (wch cdN start).req) {T2} ≤ 1 := by decide +kernel\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
