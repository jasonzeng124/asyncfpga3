#!/usr/bin/env python3
"""C-wit: emit the generated data files of the C-wit witnesses from sim.py's unit-delay runs.

  gen_wit.py rig       -> Formal/Net/RigAllWitData.lean    (gcd_hw under gcd_rig's environment,
                                                           a = 12, b = 18, 3 start offers)
  gen_wit.py xorshift  -> Formal/Net/XorshiftWitData.lean  (seed 2463534242, rounds 4, once)
  gen_wit.py collatz   -> Formal/Net/CollatzWitData.lean   (n = 7, once)
  --check: compare with the file on disk (exit 1 on drift).

The input values are chosen here; the expected results are NOT taken from these runs (the
witness theorems state values derived from the C sources, see expected.sh).
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import sim  # noqa: E402

NETDIR = os.path.join(sim.ROOT, "formal", "lean", "Formal", "Net")

CFG = {
    "rig": dict(net="gcd", vals=[12, 18, 0], env={"mode": "rig", "offers": 3},
                out="RigAllWitData.lean", ns="Formal.Net.CapNet.RigWit",
                imports=["Formal.Net.RigAllWitLib", "Formal.Net.CapstoneNetChk"],
                opens="open Formal.Net Formal.Net.CapNet Formal.Net.CapNet.Gcd",
                r0=True),
    "xorshift": dict(net="xorshift", vals=[2463534242, 4, 0], env={"mode": "once"},
                     out="XorshiftWitData.lean", ns="Formal.Net.KCap.XorshiftWit",
                     imports=["Formal.Net.CapstoneWitnessLib", "Formal.Net.XorshiftCapData"],
                     opens="open Formal.Net Formal.Net.CapNet Formal.Net.CapNet.Wit", r0=False),
    "collatz": dict(net="collatz", vals=[7, 0], env={"mode": "once"},
                    out="CollatzWitData.lean", ns="Formal.Net.KCap.CollatzWit",
                    imports=["Formal.Net.CapstoneWitnessLib", "Formal.Net.CollatzCapData"],
                    opens="open Formal.Net Formal.Net.CapNet Formal.Net.CapNet.Wit", r0=False),
}


def lst(xs): return "[" + ", ".join(str(x) for x in xs) + "]"


def rows_of(names, ops, tr, r0):
    prod = {}
    for n, o in enumerate(ops):
        for c in sim.outs_of(o): prod[c] = n
    rows = []
    for c in range(len(names)):
        rs = [s[0][c] for s in tr]
        rq = sim.toggles(rs)
        ak = sim.toggles([s[1][c] for s in tr])
        ds = [s[3][c] for s in tr]
        dt = sim.dchanges(ds)
        o = ops[prod[c]]
        ax = []
        if o["k"] in sim.NINT:
            n = prod[c]
            ax = [sim.toggles([s[2][n][k] for s in tr]) for k in range(sim.NINT[o["k"]])]
        pre = (("true" if rs[0] else "false") + ", ") if r0 else ""
        assert r0 or not rs[0]
        rows.append(f"  ⟨{pre}{lst(rq)}, {lst(ak)}, {ds[0]}, [{', '.join(f'({t}, {v})' for t, v in dt)}], "
                    f"[{', '.join(lst(x) for x in ax)}]⟩")
    return rows


def render(which):
    cf = CFG[which]
    names, ops, out0, start, tr, errs, falls, env = sim.run(cf["net"], cf["vals"], cf["env"])
    if errs:
        raise SystemExit(f"run violates the models: {errs[:10]}")
    rows = rows_of(names, ops, tr, cf["r0"])
    NC = len(names)
    T = len(tr) - 1
    nt = sum(len(sim.toggles([s[0][c] for s in tr])) + len(sim.toggles([s[1][c] for s in tr])) for c in range(NC))
    offs = [t for t in range(T) if not tr[t][0][out0] and tr[t + 1][0][out0]]
    srises = [t for t in range(T) if not tr[t][0][start] and tr[t + 1][0][start]]
    envtxt = ("gcd_rig.v's environment (all three source requests are the wire env_c, high at reset "
              "release; env_c = C(out0.ack, not in_ack), in_ack = C(source acks), out0.ack = "
              f"C(out0.req, not env_c); {cf['env'].get('offers')} start offers, then env_c holds)"
              if env["mode"] == "rig" else
              "each source offers one token and then waits; the sinks acknowledge after one tick")
    hdr = "\n".join(f"import {m}" for m in cf["imports"]) + f'''

/-!
# GENERATED by formal/tools/capwit2/gen_wit.py {which} -- DO NOT EDIT

Probe C-wit: one unit-delay circuit run of the concrete {cf["net"]} network ({NC} channels), source
values {cf["vals"]} (by `which`), every gate of every cell model with delay exactly 1 (as C-8t);
environment: {envtxt}. Quiescent after {T} ticks, {nt} request/acknowledge toggles.
out0 (channel {out0}) offers at {offs}, closes at {falls}; start (channel {start}) rises at {srises}.
Nothing here is trusted: the kernel checks it (`*WitCells*`).
-/

namespace {cf["ns"]}
{cf["opens"]}

set_option maxRecDepth 100000

'''
    # chunks of 60 channels
    parts = []
    for i in range(0, NC, 60):
        parts.append(f"def cdsP{i // 60} : List CD := [\n" + ",\n".join(rows[i:i + 60]) + "\n]\n")
    body = "\n".join(parts)
    cat = " ++ ".join(f"cdsP{i}" for i in range(len(parts)))
    ftr = f'''
def cds : List CD := {cat}

def cdA (c : Fin {"NC" if which == "rig" else cf["net"].capitalize() + "Cap.NC"}) : CD := cds.getD c.val ⟨{"false, " if cf["r0"] else ""}[], [], 0, [], []⟩

/-- out0's request rises and acknowledge falls; start's request rises. -/
def out0Offers : List Nat := {lst(offs)}
def out0Closes : List Nat := {lst(falls)}
def startRises : List Nat := {lst(srises)}
def tEnd : Nat := {T}

end {cf["ns"]}
'''
    return hdr + body + ftr


def main():
    which = [x for x in sys.argv[1:] if not x.startswith("--")][0]
    txt = render(which)
    out = os.path.join(NETDIR, CFG[which]["out"])
    if "--check" in sys.argv:
        ok = os.path.exists(out) and open(out).read() == txt
        print(f"gen_wit {which}:", "ok" if ok else "DRIFT")
        return 0 if ok else 1
    open(out, "w").write(txt)
    print("wrote", out, len(txt), "bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
