#!/usr/bin/env python3
"""C-wit negative controls: mutated runs whose kernel check MUST fail.

Writes formal/lean/Wip/Cwit/neg/Neg*.lean; formal/lean/Wip/Cwit/negctl.sh runs Lean on each and
requires exactly one error, at the theorem after the "MUST FAIL" line (the "must SUCCEED"
claims in the same file must pass).

* NegR0:   the rig run with ONE non-source request (the first link output whose first toggle
           is after 0: g6.1) made high at tick 0 and falling at step 0. Every
           "moves only to f(previous tick)" field still holds (checked: `kChk`, must succeed);
           only the reset field the C-wit extension adds (`r0Chk`) rejects it (`kChkR`).
* NegEnv:  gcd_rig's environment with uenv1 replaced by an inverter of in_ack (start is
           re-offered as soon as the sources' acknowledges fall, whatever out0 does): CellR and H_BUNDLE hold (must succeed),
           RigEnv must fail.
* NegXStart / NegCStart: xorshift / collatz with the start source offering two tokens (a
           legal `Src` run): H_CELLS and H_BUNDLE hold (must succeed), H_START_ONCE must fail.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import sim  # noqa: E402
import gen_wit  # noqa: E402

NEGDIR = os.path.join(sim.ROOT, "formal", "lean", "Wip", "Cwit", "neg")


def chunks(rows):
    parts = [f"def cdsP{i // 60} : List CD := [\n" + ",\n".join(rows[i:i + 60]) + "\n]\n"
             for i in range(0, len(rows), 60)]
    return "\n".join(parts) + "\ndef cdsN : List CD := " + " ++ ".join(
        f"cdsP{i}" for i in range(len(parts))) + "\n"


def write(name, hdr, rows, cdN, claims, ns):
    os.makedirs(NEGDIR, exist_ok=True)
    txt = hdr + chunks(rows) + "\n" + cdN + "\n" + claims + f"\nend {ns}\n"
    open(os.path.join(NEGDIR, name + ".lean"), "w").write(txt)
    print("wrote", name)


RIGHDR = '''import Formal.Net.RigAllWitLib
import Formal.Net.CapstoneNetChk
import Formal.Net.CapstoneCutSpine

/-! C-wit negative control (GENERATED by formal/tools/capwit2/gen_neg2.py): {what} -/

namespace Formal.Net.CapNet.RigWit.Neg
open Formal.Net Formal.Net.Handshake Formal.Net.Ops Formal.Net.CapNet Formal.Net.CapNet.Gcd
  Formal.Net.CapNet.RigWit

set_option maxRecDepth 100000

'''
RIGCD = "def cdN (c : Fin NC) : CD := cdsN.getD c.val ⟨false, [], [], 0, [], []⟩\n"

CHUNKED = lambda chk: "\n".join(
    f"theorem {nm}{i} : (((ops.drop {92 * i}).take 92).all (fun k => {chk} k)) = true := by decide +kernel"
    for i in range(4) for nm in ["c"])


def main():
    # NegR0
    names, ops, out0, start, tr, errs, falls, env = sim.run("gcd", [12, 18, 0], {"mode": "rig", "offers": 3})
    assert not errs
    rows = gen_wit.rows_of(names, ops, tr, True)
    prod = {}
    for n, o in enumerate(ops):
        for c in sim.outs_of(o): prod[c] = n
    tgt = next(c for c in range(len(names)) if ops[prod[c]]["k"] == "link"
               and sim.toggles([s[0][c] for s in tr]) and sim.toggles([s[0][c] for s in tr])[0] > 0)
    rq = sim.toggles([s[0][tgt] for s in tr])
    old = f"⟨false, {gen_wit.lst(rq)}, "
    assert rows[tgt].startswith("  " + old)
    rows[tgt] = rows[tgt].replace(old, f"⟨true, {gen_wit.lst([0] + rq)}, ", 1)
    p = prod[tgt]
    what = (f"link output {names[tgt]} (channel {tgt}, operator {p}) requests at tick 0 and drops at step 0; "
            "only the reset field may reject it")
    write("NegR0", RIGHDR.format(what=what), rows, RIGCD,
          "-- must SUCCEED\ntheorem pos_moves : ops.all (fun k => kChk cdN (srcV 12 18) k) = true := by decide +kernel\n"
          "-- MUST FAIL\ntheorem neg_r0 : ops.all (fun k => kChkR cdN (srcV 12 18) k) = true := by decide +kernel\n",
          "Formal.Net.CapNet.RigWit.Neg")
    # NegEnv
    names, ops, out0, start, tr, errs, falls, env = sim.run(
        "gcd", [12, 18, 0], {"mode": "rig", "offers": 3, "noack": True})
    kinds = sorted({e[0] for e in errs})
    assert errs and all(str(e[0]).startswith("RigEnv") for e in errs), errs[:5]
    print("NegEnv python violations:", kinds, len(errs))
    write("NegEnv", RIGHDR.format(what="uenv1 replaced by an inverter of in_ack; CellR and H_BUNDLE hold, RigEnv must FAIL"),
          gen_wit.rows_of(names, ops, tr, True), RIGCD,
          "-- must SUCCEED\ntheorem pos_cells : ops.all (fun k => kChkR cdN (srcV 12 18) k) = true := by decide +kernel\n"
          "-- must SUCCEED\ntheorem pos_held : cdsN.all heldChk = true := by decide +kernel\n"
          "-- MUST FAIL\ntheorem neg_env : envChk (cdN start) (cdN out0).ak = true := by decide +kernel\n",
          "Formal.Net.CapNet.RigWit.Neg")
    # NegXStart, NegCStart
    for nm, net, vals, imp, sv, inst in (
            ("NegXStart", "xorshift", [2463534242, 4, 0], "Formal.Net.KernelCapXorshift",
             "CapNet.srcV 2463534242 4", "XorshiftCap"),
            ("NegCStart", "collatz", [7, 0], "Formal.Net.KernelCapCollatz",
             "KCap.CollatzInst.srcC 7 200", "CollatzCap")):
        names, ops, out0, start, tr, errs, falls, env = sim.run(net, vals, {"mode": "once", "start_tokens": 2})
        assert [e[0] for e in errs] == ["start rises"], errs[:5]
        T = len(tr) - 1
        hdr = f'''import Formal.Net.CapstoneWitnessLib
import {imp}

/-! C-wit negative control (GENERATED by formal/tools/capwit2/gen_neg2.py): {net}, the start source
offers two tokens; H_CELLS and H_BUNDLE hold, H_START_ONCE must FAIL -/

namespace Formal.Net.KCap.Neg{nm}
open Formal.Net Formal.Net.Handshake Formal.Net.Ops Formal.Net.CapNet Formal.Net.CapNet.Wit

set_option maxRecDepth 100000

'''
        write(nm, hdr, gen_wit.rows_of(names, ops, tr, False),
              f"def cdN (c : Fin {inst}.NC) : CD := cdsN.getD c.val ⟨[], [], 0, [], []⟩\n",
              f"-- must SUCCEED\ntheorem pos_cells : {inst}.ops.all (fun k => kChk cdN ({sv}) k) = true := by decide +kernel\n"
              "-- must SUCCEED\ntheorem pos_held : cdsN.all heldChk = true := by decide +kernel\n"
              f"-- MUST FAIL\ntheorem neg_start : cnt (riseB (wch cdN {inst}.start).req) {T} ≤ 1 := by decide +kernel\n",
              f"Formal.Net.KCap.Neg{nm}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
