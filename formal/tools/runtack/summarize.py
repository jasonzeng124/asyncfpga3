#!/usr/bin/env python3
"""C-10j: build/summary.json -> build/summary.md (per instance and client, the runt
window W, the ack margin and the index margin at the four consistent corners)."""
import collections
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
S = json.load(open(HERE / "build/summary.json"))
COLS = ("FMIN", "FMAX", "SMIN", "SMAX")


def fmt(v):
    return "-" if v is None else str(v)


ack = collections.defaultdict(dict)
idx = collections.defaultdict(lambda: collections.defaultdict(list))
for s in S:
    k = (s["design"], s["inst"].replace("urig.udut.ucontrol_", ""), s["client"])
    if s["kind"] == "ack":
        ack[k][s["col"]] = s
    else:
        idx[k][s["col"]].append(s)

L = ["# C-10j per-instance H_RUNT_ACK (generated by summarize.py)", "",
     "W = runt window (ps, > 0: runt exists, C-10i); margin = earliest A0 at ua_k's core minus runt end there",
     "(ps, from q's edge; prjxray at the corner, server = certified min path on the full routed graph);",
     "need = smallest server latency R0(O5) -> A0 at ua_k's pin that keeps the handshake (only when W > 0);",
     "idx = worst index/data-reader margin against z_req (rise graph, H_FF_DRAINED). ENV = server off-chip.", "",
     "| design | instance | k | W F/S | ack margin FMIN/FMAX/SMIN/SMAX | need max | verdict | idx margin min |",
     "|---|---|---|---|---|---|---|---|"]
live = 0
for k in sorted(ack):
    a = ack[k]
    if any(a[c]["verdict"] == "ENV" for c in COLS if c in a):
        L.append(f"| {k[0]} | {k[1]} | {k[2]} | - | ENV | {max(a[c]['need'] for c in COLS)} | ENV | - |")
        continue
    W = "/".join(fmt(a[c]["W"]) for c in ("FMIN", "SMAX"))
    m = "/".join(fmt(a[c]["margin"]) if a[c]["W"] > 0 else "(no runt)" for c in COLS)
    needs = [a[c]["late"] - (a[c]["margin"] + a[c]["late"] - a[c]["P"]) for c in COLS if a[c]["W"] > 0]
    v = "ok" if all(a[c]["verdict"] == "ok" for c in COLS) else "FAIL"
    live += any(a[c]["W"] > 0 for c in COLS)
    im = [z["margin"] for c in COLS for z in idx[k][c] if z["W"] > 0]
    L.append(f"| {k[0]} | {k[1]} | {k[2]} | {W} | {m} | {fmt(max(needs) if needs else None)} | {v} | "
             f"{fmt(min(im) if im else None)} |")
acks = [s for s in S if s["kind"] == "ack" and s["verdict"] in ("ok", "FAIL")]
lv = [s for s in acks if s["W"] > 0]
ix = [s for s in S if s["kind"] == "idx" and s["W"] > 0]
L += ["", f"ack rows: {len(acks)} (kernel-decided), with a runt (W > 0): {len(lv)}, failing: "
      f"{sum(s['verdict'] == 'FAIL' for s in acks)}; worst live margin {min(s['margin'] for s in lv)} ps; "
      f"arbiter-clients with a runt at some corner: {live}.",
      f"index rows with a runt: {len(ix)}, failing: {sum(s['verdict'] == 'FAIL' for s in ix)}, worst margin "
      f"{min(s['margin'] for s in ix)} ps (rise graph); on the FULL graph (no H_FF_DRAINED) "
      f"{sum(s['margin_fullgraph'] < 0 for s in ix)} of them would fail.",
      f"converse side conditions (hu, hsa) hold on {sum(1 for s in acks if s['side'] and s['side']['hu'] and s['side']['hsa'])}"
      f" of {len(acks)} rows."]
(HERE / "build/summary.md").write_text("\n".join(L) + "\n")
print("\n".join(L[-3:]))
