#!/usr/bin/env python3
"""C-10j: write Formal/Timing/RuntAckInst.lean (kernel-decided verdicts) and
build/summary.{tsv,md} from build/runtack.json (written by extract.py).

    python3 -I emit.py LEANPATH
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
import importlib.util  # noqa: E402
_spec = importlib.util.spec_from_file_location("runtack_extract", HERE / "extract.py")
X = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(X)

FIELDS = ("dqg", "dqs", "drg", "drs", "agq", "agr", "asq", "asr", "dqs5", "drs5", "aRq", "aRr", "gw", "ga", "aa")

HEAD = """import Formal.Timing.RuntAck

/-!
# C-10j: H_RUNT_ACK verdicts per routed bd_arbiter instance (GENERATED)

Generated by `formal/tools/runtack/emit.py` from `build/runtack.json`
(`extract.py`, UNTRUSTED extraction: prjxray at one consistent corner column per
row, outward-rounded to integer ps; see the notes). Per instance and corner:
* `..._F : Cert`, a truncated potential certificate on the FULL routed timing graph
  (every SDF arc, prjxray-priced) from ustate's O5 (R0); `..._F_ok` (kernel `decide`)
  with `cert_bound` makes `..._F.p n` a lower bound on every path R0 → node n.
* `..._R : Cert`, the same on the RISE graph (fast-fall side taps removed,
  H_FF_DRAINED), used for z_req (the matched-delay chain tail).
* `..._c<k> : Row` with `P := ..._F.p <ua_k's A0 pin>`; `..._c<k>_ack : okAck .. = b`
  is the H_RUNT_ACK verdict (`inst_no_extra_ack1/2` when true; `okAck_exact1/2` +
  `spurious_ack1/2_iff` when false).
* `..._c2_i<j> : Row`, one per LUT reading g2 (the amerge index `g2 | A2`, the data
  mux), `P := ..._R.p <z_req>`, `aa := 0`; `.._idx : okAck .. = b` is the
  wrong-index verdict (`inst_idx_clean2`).
-/

namespace Formal.Timing.RuntAck.Inst
open Formal.Timing.RuntAck

"""


def tree(items):
    """balanced BST literal from sorted [(k, v)]"""
    if not items:
        return "PTree.leaf"
    m = len(items) // 2
    k, v = items[m]
    return f"(PTree.node {k} {v} {tree(items[:m])} {tree(items[m + 1:])})"


def cert_lean(name, cert, extra_nodes):
    ids = {}

    def nid(n):
        if n not in ids:
            ids[n] = len(ids)
        return ids[n]
    nid(cert["_src"])
    for n in sorted(cert["pot"]):
        nid(n)
    for n in extra_nodes:
        nid(n)
    edges = []
    for u, v, w in cert["cone"]:
        edges.append(f"({nid(u)}, {nid(v)}, {w})")
    pot = sorted((ids[n], p) for n, p in cert["pot"].items())
    txt = (f"def {name} : Cert where\n  M := {cert['M']}\n  src := 0\n  pot := {tree(pot)}\n"
           f"  edges := [{', '.join(edges)}]\n"
           f"theorem {name}_ok : {name}.ok = true := by decide\n")
    return txt, ids


def row_lean(name, x, Pexpr):
    body = ", ".join(f"{k} := {x[k]}" for k in FIELDS)
    return f"def {name} : Row := {{ {body}, P := {Pexpr} }}\n"


def lname(design, inst):
    d = design.replace("gcd_hw_", "g").replace("link_arb_s", "l")
    i = inst.replace("urig.udut.ucontrol_", "").replace(".", "_")
    return f"{d}_{i}"


def write(rows, certs, path):
    out = [HEAD]
    summ = []
    by = {(r["design"], r["inst"], r["client"]): r for r in rows}
    nok = nfail = 0
    for c in certs:
        design = c["design"]
        base = lname(design, c["inst"])
        for col in X.COLS:
            e = c["C"][col]
            env = all(v is None for v in e["dist_full"].values())
            if env:   # A0 / R0 leave the chip (link_arb): the server is the environment
                for k in (1, 2):
                    r = by[(design, c["inst"], k)]
                    nr = X.need_rows(r, col)
                    if nr is None:
                        continue
                    ack, _idx, _b = nr
                    need = X.late(ack) - X.early0(ack)
                    summ.append(dict(design=design, inst=c["inst"], client=k, col=col, kind="ack",
                                     W=X.W(ack), late=X.late(ack), P=None, margin=None,
                                     verdict="ENV", need=need, fb=None))
                continue
            F = dict(e["full"], _src=c["src"])
            tF, idsF = cert_lean(f"{base}_{col}_F", F, [c["a0pin"]["1"], c["a0pin"]["2"]])
            out.append(tF)
            idsR = None
            if "rise" in e:
                Rr = dict(e["rise"], _src=c["src"])
                tR, idsR = cert_lean(f"{base}_{col}_R", Rr, [c["tail"]])
                out.append(tR)
            for k in (1, 2):
                r = by[(design, c["inst"], k)]
                nr = X.need_rows(r, col)
                if nr is None:
                    summ.append(dict(design=design, inst=c["inst"], client=k, col=col, kind="ack",
                                     verdict="MISSING"))
                    continue
                ack, idx, b = nr
                Pn = min(e["dist_full"][c["a0pin"][str(k)]], F["M"])
                ok = X.W(ack) <= 0 or X.late(ack) <= X.early0(ack) + Pn
                nm = f"{base}_{col}_c{k}"
                out.append(row_lean(nm, ack, f"{base}_{col}_F.p {idsF[c['a0pin'][str(k)]]}"))
                out.append(f"theorem {nm}_ack : okAck {nm} = {'true' if ok else 'false'} := by decide\n")
                nok += ok
                nfail += not ok
                Pex = e["dist_full"][c["a0pin"][str(k)]]
                summ.append(dict(design=design, inst=c["inst"], client=k, col=col, kind="ack",
                                 W=X.W(ack), late=X.late(ack), P=Pex,
                                 margin=X.early0(ack) + Pex - X.late(ack),
                                 verdict="ok" if ok else "FAIL", fb=e["full"]["fb"],
                                 side=side(by, design, c["inst"], k, col, e, c)))
                if k == 2 and idsR is not None:
                    for j, z in enumerate(idx):
                        Pz = min(e["dist_tail_rise"][c["tail"]], e["rise"]["M"])
                        okz = X.W(z) <= 0 or X.late(z) <= X.early0(z) + Pz
                        nz = f"{nm}_i{j}"
                        out.append(row_lean(nz, z, f"{base}_{col}_R.p {idsR[c['tail']]}"))
                        out.append(f"theorem {nz}_idx : okAck {nz} = {'true' if okz else 'false'} := by decide\n")
                        Pzx = e["dist_tail_rise"][c["tail"]]
                        summ.append(dict(design=design, inst=c["inst"], client=k, col=col, kind="idx",
                                         reader=z["reader"], W=X.W(z), late=X.late(z), P=Pzx,
                                         margin=X.early0(z) + Pzx - X.late(z),
                                         margin_fullgraph=X.early0(z) + e["dist_tail_full"][c["tail"]] - X.late(z),
                                         verdict="ok" if okz else "FAIL", fb=e["rise"]["fb"]))
    out.append("end Formal.Timing.RuntAck.Inst\n")
    pathlib.Path(path).write_text("\n".join(out))
    json.dump(summ, open(HERE / "build/summary.json", "w"), indent=1)
    print(f"lean: ack rows ok {nok}, fail {nfail}", file=sys.stderr)
    return summ


def side(by, design, inst, k, col, e, c):
    """The converse's physical side conditions at this corner (prefix-free sufficient
    forms): hu (the other request reaches R0's core before the q it caused) and hsa
    (A0 reaches ustate after q's own feedback)."""
    me = X.corner_row(by[(design, inst, k)], col)
    ot = X.corner_row(by[(design, inst, 3 - k)], col)
    if me is None or ot is None:
        return None
    hu = (ot["drs5"] + ot["aRr"]) - (ot["drs"] + ot["asr"]) <= me["dqs5"] + me["aRq"]
    pst = e["dist_full"][c["a0st"]]
    m = min(me["dqs5"] + me["aRq"], me["dqs"] + me["asq"] - (me["drs"] + me["asr"]) + me["drs5"] + me["aRr"])
    hsa = pst is not None and me["dqs"] + me["asq"] <= m + pst + me["aSa"]
    return dict(hu=hu, hsa=hsa)


def main():
    d = json.load(open(HERE / "build/runtack.json"))
    write(d["rows"], d["certs"], sys.argv[1])


if __name__ == "__main__":
    main()
