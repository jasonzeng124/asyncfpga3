#!/usr/bin/env python3
"""Shard C: generate the rank certificate (Formal/Net/CViewPS/R*.lean, RK.lean, K*.lean, Huffman.lean)
for THE target's collapsed view: combinational gates (kept, not copy, not storage) get a rank
increasing along pin->source links. Untrusted; the kernel checks it (Formal.Timing.Huffman).
usage: gen_rank.py net.json NetPS/All.lean OUTDIR"""
import json, sys, re, collections
net = json.load(open(sys.argv[1])); G = net["gates"]; allsrc = open(sys.argv[2]).read(); out = sys.argv[3]
env = set(int(x) for x in re.search(r"env := \[([0-9, ]+)\]", allsrc).group(1).split(","))
C, D = 2500, 12; nch = (len(G) + C - 1) // C
def is_copy(g): return g["k"] == 1 and g["init"] == 2
def keep(g): return g["out"] not in env
cm = {i: (g["ins"][0] if keep(g) and is_copy(g) else None) for i, g in enumerate(G)}
def src(u):
    while cm.get(u) is not None: u = cm[u]
    return u
pv = {i: [src(u) for u in g["ins"]] for i, g in enumerate(G) if keep(g) and not is_copy(g)}
comb = {i for i, ss in pv.items() if i not in ss}
succ = collections.defaultdict(list); indeg = collections.Counter()
for i in comb:
    for s in pv[i]:
        if s in comb: succ[s].append(i); indeg[i] += 1
rank = {}; q = [i for i in comb if indeg[i] == 0]
for i in q: rank[i] = 0
while q:
    v = q.pop()
    for w in succ[v]:
        rank[w] = max(rank.get(w, 0), rank[v] + 1); indeg[w] -= 1
        if indeg[w] == 0: q.append(w)
assert len(rank) == len(comb), "combinational part is cyclic"
NS = "Formal.Net.CViewPS"; HDR = "/-! GENERATED by formal/tools/cview/gen_rank.py. Do not edit. -/\n\n"
def tree(vals, d):
    if d == 0: return ".lf none" if vals[0] is None else f".lf (some {vals[0]})"
    h = len(vals) // 2
    return f".nd ({tree(vals[:h], d - 1)}) ({tree(vals[h:], d - 1)})"
for c in range(nch):
    vals = [rank.get(i) for i in range(c * C, min((c + 1) * C, len(G)))]
    vals += [None] * (2 ** D - len(vals))
    open(f"{out}/R{c:03d}.lean", "w").write(f"import Formal.Timing.Huffman\n\n" + HDR + f"namespace {NS}\nopen Formal.Timing.ChunkCM\n\n"
        "set_option maxRecDepth 100000 in\n" + f"def r{c:03d} : BT :=\n  {tree(vals, D)}\n\nend {NS}\n")
L = lambda pre: ", ".join(f"{pre}{c:03d}" for c in range(nch))
open(f"{out}/RK.lean", "w").write("".join(f"import {NS}.R{c:03d}\n" for c in range(nch)) + f"import {NS}.CM\n\n" + HDR +
    f"namespace {NS}\nopen Formal.Timing.ChunkCM\n\ndef rl : List BT := [{L('r')}]\n\n/-- The rank lookup (data; nothing is assumed about it). -/\ndef rkPS : Nat → Option Nat := cmOf rl {C} {D}\n\nend {NS}\n")
for c in range(nch):
    open(f"{out}/K{c:03d}.lean", "w").write(f"import {NS}.RK\nimport {NS}.V{c:03d}\n\n" + HDR +
        f"namespace {NS}\nopen Formal.Target.DecodedPS Formal.Timing.Huffman\n\nset_option maxRecDepth 100000 in\n"
        f"theorem k{c:03d}_ok : rankChunkOK rkPS keepPS ({C} * {c}) g{c:03d} v{c:03d} = true := by decide +kernel\n\nend {NS}\n")
with open(f"{out}/Ranks.lean", "w") as f:
    f.write("".join(f"import {NS}.K{c:03d}\n" for c in range(nch)) + f"import {NS}.All\n\n" + HDR)
    f.write(f"namespace {NS}\nopen Formal.Target Formal.Target.DecodedPS Formal.Timing.Huffman\n\n")
    f.write("set_option maxRecDepth 100000 in\nset_option maxHeartbeats 4000000 in\n")
    f.write(f"theorem ranks_ok : ∀ c, c < cs.length → rankChunkOK rkPS keepPS ({C} * c) (cs.getD c []) (vss.getD c []) = true := by\n"
            "  intro c hc\n  rw [cs_len] at hc\n  match c, hc with\n")
    for c in range(nch):
        f.write(f"  | {c}, _ => simp only [cs, vss, List.getD_cons_succ, List.getD_cons_zero]; exact k{c:03d}_ok\n")
    f.write(f"  | n + {nch}, h => exact absurd h (by omega)\n\nend {NS}\n")
print("comb", len(comb), "storage", len(pv) - len(comb), "max rank", max(rank.values()))
