#!/usr/bin/env python3
"""Shard C: Lean data for the zero-pair witness (witn0.py output) of THE target: per-chunk trees of
node codes (sig1 encoding) and per-chunk gate checks (gateW).  usage: gen_wit0.py wit0.json net.json OUTDIR"""
import json, sys
W = json.load(open(sys.argv[1])); net = json.load(open(sys.argv[2])); out = sys.argv[3]
nN = len(net["nodes"]); nG = len(net["gates"]); C, D = 2500, 12
v0 = set(W["v0"]); tr = {int(k): v for k, v in W["trans"].items()}
def code(n):
    b = 1 if n in v0 else 0
    if n in tr:
        assert len(tr[n]) == 1; return 2 * (tr[n][0] + 1) + b
    return b if b else None
def tree(vals, d):
    if d == 0: return ".lf none" if vals[0] is None else f".lf (some {vals[0]})"
    h = len(vals) // 2
    return f".nd ({tree(vals[:h], d - 1)}) ({tree(vals[h:], d - 1)})"
NS = "Formal.Net.CViewPS"; HDR = "/-! GENERATED by formal/tools/cview/gen_wit0.py. Do not edit. -/\n\n"
nchN = (nN + C - 1) // C; nchG = (nG + C - 1) // C
for c in range(nchN):
    vals = [code(n) for n in range(c * C, min((c + 1) * C, nN))]; vals += [None] * (2 ** D - len(vals))
    open(f"{out}/E{c:03d}.lean", "w").write(f"import {NS}.WitBase\n\n" + HDR + f"namespace {NS}\nopen Formal.Timing.ChunkCM\n\n"
        "set_option maxRecDepth 100000 in\n" + f"def e{c:03d} : BT :=\n  {tree(vals, D)}\n\nend {NS}\n")
L = ", ".join(f"e{c:03d}" for c in range(nchN))
open(f"{out}/Enc.lean", "w").write("".join(f"import {NS}.E{c:03d}\n" for c in range(nchN)) + "\n" + HDR +
    f"namespace {NS}\nopen Formal.Timing.ChunkCM\n\ndef el : List BT := [{L}]\n\n/-- The witness's node codes. -/\ndef encW : Nat → Option Nat := cmOf el {C} {D}\n\nend {NS}\n")
for c in range(nchG):
    open(f"{out}/W{c:03d}.lean", "w").write(f"import {NS}.Enc\n\n" + HDR +
        f"namespace {NS}\nopen Formal.Target.DecodedPS\n\nset_option maxRecDepth 100000 in\n"
        f"theorem w{c:03d}_ok : g{c:03d}.all (fun g => !keepPS g || gateW encW g) = true := by decide +kernel\n\nend {NS}\n")
print("node chunks", nchN, "gate chunks", nchG)
