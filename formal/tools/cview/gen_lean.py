#!/usr/bin/env python3
"""Shard C: generate the Lean collapsed view of THE target (Formal/Net/CViewPS/*) from the
committed Lean netlist (via tools-B/target/lean2json.py JSON). Untrusted: every fact it
emits is checked by the kernel (decide +kernel per chunk).
usage: gen_lean.py net.json NetPS/All.lean OUTDIR"""
import json, sys, os, re
net = json.load(open(sys.argv[1])); G = net["gates"]
allsrc = open(sys.argv[2]).read(); out = sys.argv[3]
env = set(int(x) for x in re.search(r"env := \[([0-9, ]+)\]", allsrc).group(1).split(","))
C, D = 2500, 12
nch = (len(G) + C - 1) // C
def is_copy(g): return g["k"] == 1 and g["init"] == 2
def keep(g): return g["out"] not in env
def cpk(g): return g["ins"][0] if keep(g) and is_copy(g) else None
cm = {i: cpk(g) for i, g in enumerate(G)}
os.makedirs(out, exist_ok=True)
NS = "Formal.Net.CViewPS"
HDR = "/-! GENERATED by formal/tools/cview/gen_lean.py. Do not edit. -/\n\n"
def tree(vals, d):
    if d == 0:
        v = vals[0]
        return ".lf none" if v is None else f".lf (some {v})"
    h = len(vals) // 2
    return f".nd ({tree(vals[:h], d - 1)}) ({tree(vals[h:], d - 1)})"
for c in range(nch):
    gs = G[c * C:(c + 1) * C]
    vals = [cpk(g) for g in gs] + [None] * (2 ** D - len(gs))
    with open(f"{out}/T{c:03d}.lean", "w") as f:
        f.write(f"import {NS}.Base\n\n" + HDR + f"namespace {NS}\nopen Formal.Target Formal.Target.DecodedPS Formal.Timing.ChunkCM\n\n")
        f.write("set_option maxRecDepth 100000 in\n")
        f.write(f"def t{c:03d} : BT :=\n  {tree(vals, D)}\n\n")
        f.write("set_option maxRecDepth 100000 in\n")
        f.write(f"theorem t{c:03d}_fact : t{c:03d}.perf {D} = true ∧\n"
                f"    t{c:03d}.toList = g{c:03d}.map (cpK keepPS) ++ List.replicate (2 ^ {D} - g{c:03d}.length) none ∧\n"
                f"    outsOK g{c:03d} ({C} * {c}) = true ∧ g{c:03d}.length ≤ {C} :=\n"
                f"  ⟨by decide +kernel, by decide +kernel, by decide +kernel, by decide +kernel⟩\n\n"
                f"end {NS}\n")
# per-gate pin data
def pins(g):
    res = []
    for u in g["ins"]:
        r = 0; v = u
        while cm.get(v) is not None: v = cm[v]; r += 1
        res.append((v, r))
    return res
for c in range(nch):
    gs = G[c * C:(c + 1) * C]
    ents = []
    for g in gs:
        if not keep(g) or is_copy(g): ents.append("[]")
        else: ents.append("[" + ", ".join(f"({s}, {r})" for s, r in pins(g)) + "]")
    with open(f"{out}/V{c:03d}.lean", "w") as f:
        f.write(f"import {NS}.CM\n\n" + HDR + f"namespace {NS}\nopen Formal.Target Formal.Target.DecodedPS Formal.Timing.ChunkCM Formal.Timing.SpecChainM\n\n")
        f.write("set_option maxRecDepth 100000 in\n")
        f.write(f"def v{c:03d} : List PinData := [\n  " + ",\n  ".join(ents) + "]\n\n")
        f.write("set_option maxRecDepth 100000 in\n")
        f.write(f"theorem v{c:03d}_ok : chunkViewOK cmPS keepPS g{c:03d} v{c:03d} = true := by decide +kernel\n\n")
        f.write(f"end {NS}\n")
L = lambda pre: ", ".join(f"{pre}{c:03d}" for c in range(nch))
with open(f"{out}/CM.lean", "w") as f:
    f.write("".join(f"import {NS}.T{c:03d}\n" for c in range(nch)) + "\n" + HDR)
    f.write(f"namespace {NS}\nopen Formal.Target Formal.Target.DecodedPS Formal.Timing.ChunkCM\n\n")
    f.write(f"def tl : List BT := [{L('t')}]\n\ndef cs : List (List Gate) := [{L('g')}]\n\n")
    f.write(f"/-- The copy map of THE target's circuit. -/\ndef cmPS : Nat → Option Nat := cmOf tl {C} {D}\n\n")
    f.write("theorem cs_len : cs.length = %d := rfl\ntheorem tl_len : tl.length = cs.length := rfl\n\n" % nch)
    f.write("set_option maxRecDepth 100000 in\nset_option maxHeartbeats 4000000 in\n")
    f.write("/-- One chunk fact per chunk (from `T*.lean`). -/\n")
    f.write(f"theorem facts : ∀ c, c < cs.length → ChunkFact tl cs keepPS {C} {D} c := by\n  intro c hc\n  rw [cs_len] at hc\n  match c, hc with\n")
    for c in range(nch):
        f.write(f"  | {c}, _ => simp only [ChunkFact, tl, cs, List.getD_cons_succ, List.getD_cons_zero]; exact t{c:03d}_fact\n")
    f.write(f"  | n + {nch}, h => exact absurd h (by omega)\n\nend {NS}\n")
with open(f"{out}/All.lean", "w") as f:
    f.write("".join(f"import {NS}.V{c:03d}\n" for c in range(nch)) + "\n" + HDR)
    f.write(f"namespace {NS}\nopen Formal.Target Formal.Target.DecodedPS Formal.Timing.ChunkCM Formal.Timing.SpecChainM\n\n")
    f.write(f"def vss : List (List PinData) := [{L('v')}]\n\n")
    f.write("set_option maxRecDepth 100000 in\n")
    f.write("theorem views_ok : ∀ p ∈ cs.zip vss, chunkViewOK cmPS keepPS p.1 p.2 = true := by\n"
            "  have h : (cs.zip vss).all (fun p => chunkViewOK cmPS keepPS p.1 p.2) = true := by\n"
            "    simp only [cs, vss, List.zip_cons_cons, List.zip_nil_left, List.all_cons, List.all_nil, Bool.and_true, "
            + ", ".join(f"v{c:03d}_ok" for c in range(nch)) + "]\n"
            "  simpa [List.all_eq_true] using h\n\n")
    f.write(f"end {NS}\n")
print("chunks", nch, "logic entries", sum(1 for g in G if keep(g) and not is_copy(g)))
