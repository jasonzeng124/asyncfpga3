#!/usr/bin/env python3
"""Shard C: Lean data for the one-pair witness (witn1.py output): per-chunk BTL trees of node codes
(initial value, transition times) and per-chunk gate checks (gateWL).  usage: gen_wit1.py wit1.json net.json OUTDIR"""
import json, sys
W = json.load(open(sys.argv[1])); net = json.load(open(sys.argv[2])); out = sys.argv[3]
nN = len(net["nodes"]); nG = len(net["gates"]); C, D = 2500, 12
v0 = set(W["v0"]); tr = {int(k): v for k, v in W["trans"].items()}
def leaf(n):
    b = n in v0; ts = tr.get(n, [])
    if not b and not ts: return ".lf none"
    return f".lf (some ({'true' if b else 'false'}, [{', '.join(map(str, ts))}]))"
def tree(ns, d):
    if d == 0: return leaf(ns[0]) if ns[0] is not None else ".lf none"
    h = len(ns) // 2
    return f".nd ({tree(ns[:h], d - 1)}) ({tree(ns[h:], d - 1)})"
NS = "Formal.Net.CViewPS"; HDR = "/-! GENERATED by formal/tools/cview/gen_wit1.py. Do not edit. -/\n\n"
nch = (nN + C - 1) // C; nchG = (nG + C - 1) // C
for c in range(nch):
    ns = list(range(c * C, min((c + 1) * C, nN))); ns += [None] * (2 ** D - len(ns))
    open(f"{out}/L{c:03d}.lean", "w").write(f"import {NS}.WitBaseL\n\n" + HDR + f"namespace {NS}\n\n"
        "set_option maxRecDepth 100000 in\n" + f"def l{c:03d} : BTL :=\n  {tree(ns, D)}\n\nend {NS}\n")
L = ", ".join(f"l{c:03d}" for c in range(nch))
open(f"{out}/EncL.lean", "w").write("".join(f"import {NS}.L{c:03d}\n" for c in range(nch)) + "\n" + HDR +
    f"namespace {NS}\n\ndef ll : List BTL := [{L}]\n\n/-- The one-pair witness's node codes. -/\ndef encW1 : Nat → Option (Bool × List Nat) := lookL ll {C} {D}\n\nend {NS}\n")
for c in range(nchG):
    open(f"{out}/X{c:03d}.lean", "w").write(f"import {NS}.EncL\n\n" + HDR +
        f"namespace {NS}\nopen Formal.Target.DecodedPS\n\nset_option maxRecDepth 100000 in\n"
        f"theorem x{c:03d}_ok : g{c:03d}.all (fun g => !keepPS g || gateWL encW1 g) = true := by decide +kernel\n\nend {NS}\n")
print("ok")
