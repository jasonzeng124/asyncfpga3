#!/usr/bin/env python3
"""Probe C-10o2: emit chainck2's dumped chain networks as Lean data + kernel-decided verdicts.

    python3 gen_lean.py build/dump_gcd_d.json PREFIX OUTDIR [--chunk 150]

Writes OUTDIR/ChainSettleExe<PREFIX>Data<k>.lean (rows) and OUTDIR/ChainSettleExe<PREFIX><k>.lean
(one theorem per row: the verdict at the late side T, the exact verdict at T* and T*-1, the
bridge verdict at Tb* and Tb*-1, all by `decide +kernel`), plus build/cmp_<PREFIX>.tsv comparing
with chainck's own Python verdicts.

The Python here (`verdict`, a mirror of ChainSettleExe.verdict) is UNTRUSTED: it only chooses
the statements. Lean's kernel decides them; a wrong mirror value makes the build fail.
F = 1 (chainck uses F = 0; every interval shifts by 1, verdicts and margins are unchanged).
"""
import json
import sys

F = 1


def norm(iv):
    out = []
    for x, y in sorted(iv):
        if x >= y:
            continue
        if out and x <= out[-1][1] and out[-1][0] <= y:
            out[-1] = (min(out[-1][0], x), max(out[-1][1], y))
        else:
            out.append((x, y))
    return out


def img(lo, hi, L):
    return [(x + hi, y + lo) for x, y in L if x + hi < y]


def sets(arcs, T, N):
    S = [[(F, F + T)]]
    for v in range(1, N + 1):
        acc = []
        for (s, d, lo, hi) in arcs:
            if d == v:
                acc += img(lo, hi, S[s] if s < len(S) else [])
        S.append(norm(acc))
    return S


def sep(L):
    for i, (x, y) in enumerate(L):
        if not x < y:
            return False
        if i + 1 < len(L) and not y < L[i + 1][0]:
            return False
    return True


def lrip(arcs, N, z, taps):
    tab = []
    for v in range(N + 1):
        if v == 0:
            tab.append(0)
            continue
        c = [tab[s] + lo for k, (s, d, lo, hi) in enumerate(arcs)
             if d == v and k not in taps and s < len(tab) and tab[s] is not None]
        tab.append(min(c) if c else None)
    r = tab[z] if z < len(tab) else None
    return 0 if r is None else r


def cover_end(W, x):
    for (a, b) in W:
        if a <= x < b:
            return b
    return x


def verdict(row, T):
    arcs, N, z, taps = row["arcs"], row["N"], row["z"], row["taps"]
    S = sets(arcs, T, N)
    Z = S[z] if z < len(S) else []
    Lr = lrip(arcs, N, z, taps)
    wf = (all(s < d and lo <= hi for s, d, lo, hi in arcs) and all(d <= N for _, d, _, _ in arcs)
          and T >= 1 and F >= 1 and z != 0 and z <= N)
    A, B = Z[0] if Z else (0, 0)
    exact = len(Z) == 1 and F + T + Lr <= Z[0][1]
    s1 = any(a <= F + T - 1 < b for a, b in Z)
    d = True
    for k, (s, dd, lo, hi) in enumerate(arcs):
        other = any(k2 != k and a2[1] == dd for k2, a2 in enumerate(arcs))
        if s != 0 and other:
            ce = cover_end(S[dd], F + T)
            if not any(max(F + T, q0) <= ce and max(F + T, q0) < q1 for q0, q1 in img(lo, hi, S[s])):
                d = False
    return dict(wf=wf, sep=all(sep(L) for L in S), nint=len(Z), A=A, B=B, Lr=Lr, exact=exact, s1=s1,
                d=d, bridge=wf and s1 and d, tail=Z)


def tstar(row, key, T0):
    ok = lambda T: verdict(row, T)[key]  # noqa: E731
    lo, hi = 1, max(T0, 1)
    if not ok(hi):
        lo = hi
        while not ok(hi):
            hi *= 2
            if hi > 10 ** 7:
                return None
    while lo < hi:
        m = (lo + hi) // 2
        if ok(m):
            hi = m
        else:
            lo = m + 1
    return lo


def b(x):
    return "true" if x else "false"


def lean_verdict(v):
    return (f"⟨{b(v['wf'])}, {b(v['sep'])}, {v['nint']}, {v['A']}, {v['B']}, {v['Lr']}, "
            f"{b(v['exact'])}, {b(v['s1'])}, {b(v['d'])}⟩")


def main():
    dump, prefix, outdir = sys.argv[1], sys.argv[2], sys.argv[3]
    chunk = int(sys.argv[sys.argv.index("--chunk") + 1]) if "--chunk" in sys.argv else 150
    rows = json.load(open(dump))
    cmp = ["idx\tbase\tvar\tkind\tT\tpy_pass\tlean_exact\tpy_Lrip\tlean_Lr\tpy_Tstar\tlean_Tstar\t"
           "margin_exact\tlean_bridge\tTb_star\tmargin_bridge\ts1\td\tpy_tail\tlean_tail-1\tagree"]
    chunks = [rows[i:i + chunk] for i in range(0, len(rows), chunk)]
    for ci, rs in enumerate(chunks):
        dname = f"ChainSettleExe{prefix}Data{ci}"
        tname = f"ChainSettleExe{prefix}{ci}"
        D = [f"import Formal.Timing.ChainSettleExe\n",
             f"/-! C-10o2 GENERATED by formal/tools/chainck2/gen_lean.py from {dump} (chunk {ci}).",
             "Chain networks extracted by chainck2 (tcheck's extract.py, prjxray/SDF intervals per variant;",
             "UNTRUSTED front end). Node 0 = side-tap source, `z` = tail; F = 1. -/\n",
             f"namespace Formal.Timing.ChainSettleExe.{prefix}",
             "open Formal.Timing Formal.Timing.ChainSettleExe\n"]
        TH = [f"import Formal.Timing.{dname}\n",
              f"/-! C-10o2 GENERATED: kernel-decided verdicts of chunk {ci} (see ChainSettleExe.verdict).",
              "Per row: `verdict` at chainck's late side `T`; exact PASS at `T*` and FAIL at `T* - 1`",
              "(margin_exact = T - T*); bridge PASS at `Tb*` and FAIL at `Tb* - 1`. -/\n",
              f"namespace Formal.Timing.ChainSettleExe.{prefix}",
              "open Formal.Timing Formal.Timing.ChainSettleExe\n"]
        for j, row in enumerate(rs):
            i = ci * chunk + j
            name = f"r{i}"
            arcs = ", ".join(f"⟨{s}, {d}, {lo}, {hi}⟩" for s, d, lo, hi in row["arcs"])
            D.append(f"/-- {row['base']} [{row['kind']}] {row['var']} -/")
            D.append(f"def {name} : Row := {{ arcs := [{arcs}], N := {row['N']}, z := {row['z']}, "
                     f"F := {F}, T := {row['T']}, taps := {row['taps']} }}")
            T = row["T"]
            v = verdict(row, T)
            ts = tstar(row, "exact", T)
            tb = tstar(row, "bridge", T)
            parts = [f"verdict {name} = {lean_verdict(v)}"]
            if ts is not None:
                parts.append(f"(verdict {{ {name} with T := {ts} }}).exact = true")
                if ts > 1:
                    parts.append(f"(verdict {{ {name} with T := {ts - 1} }}).exact = false")
            if tb is not None:
                parts.append(f"(verdict {{ {name} with T := {tb} }}).bridge = true")
                if tb > 1:
                    parts.append(f"(verdict {{ {name} with T := {tb - 1} }}).bridge = false")
            TH.append(f"theorem v{i} :\n    " + " ∧\n    ".join(parts) + " := by decide +kernel")
            py = row["py"]
            pyt = [tuple(x) for x in py["tail"]]
            lt = [(x - F, y - F) for x, y in v["tail"]]
            agree = (py["pass"] == v["exact"] and py["Lrip"] == v["Lr"] and py["Tstar"] == ts
                     and pyt == lt)
            cmp.append("\t".join(str(x) for x in [
                i, row["base"], row["var"], row["kind"], T, py["pass"], v["exact"], py["Lrip"], v["Lr"],
                py["Tstar"], ts, None if ts is None else T - ts, v["bridge"], tb,
                None if tb is None else T - tb, v["s1"], v["d"], pyt, lt, agree]))
        D.append(f"\nend Formal.Timing.ChainSettleExe.{prefix}\n")
        TH.append(f"\nend Formal.Timing.ChainSettleExe.{prefix}\n")
        open(f"{outdir}/{dname}.lean", "w").write("\n".join(D))
        open(f"{outdir}/{tname}.lean", "w").write("\n".join(TH))
        print(f"{dname}, {tname}: {len(rs)} rows")
    open(f"build/cmp_{prefix}.tsv", "w").write("\n".join(cmp) + "\n")


if __name__ == "__main__":
    main()
