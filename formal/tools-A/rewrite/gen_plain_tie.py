#!/usr/bin/env python3
"""gen_plain_tie.py KERNEL NAME RS2P_EVAL.txt -- tie the per-kernel theorem to the import of ring_dec's MLIR, in Lean.

Writes formal/lean/Formal/Rewrite/Plain/<NAME>PlainRdHw.lean (dfimport of formal/tools-A/rewrite/out/<KERNEL>_plain.mlir)
and <NAME>PlainTie.lean: the channel / rule bijections found by rules_iso.py, checked by `decide +kernel` (fpCheck,
renCheck), and the theorems `tie_forward` / `tie_backward` (Rename.lean + the kernel's PlainGen plain_*). The bijections are
found by an untrusted script; Lean checks them.
"""
import json, os, re, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))

def main():
    k, name, rs3 = sys.argv[1:4]  # rs3 = #eval of the plain graph rs2p
    od = os.path.join(ROOT, 'formal/lean/Formal/Rewrite/Plain')
    rdh = os.path.join(od, name + 'PlainRdHw.lean')
    subprocess.check_call([sys.executable, os.path.join(ROOT, 'formal/tools/dfimport/mlir2lean.py'),
        os.path.join(ROOT, 'formal/tools-A/rewrite/out', k + '_plain.mlir'), '-o', rdh,
        '--ns', f'Formal.Rewrite.Plain.{name}PlainRdHw', '--graph-module', f'Formal.Rewrite.Plain.{name}PlainRdHw',
        '--label', k + '_plain', '--short', k + '_plain'], stdout=subprocess.DEVNULL)
    txt = open(rdh).read()
    txt = re.sub(r'^Source: `[^`]*`', f'Source: `formal/tools-A/rewrite/out/{k}_plain.mlir`', txt, count=1, flags=re.M)
    open(rdh, 'w').write(txt)
    mp = '/tmp/gen_plain_' + k + '_maps.json'
    out = subprocess.run([sys.executable, os.path.join(HERE, 'rules_iso.py'), rs3, rdh, mp], capture_output=True, text=True)
    if out.returncode != 0: print(out.stdout); return 1
    m = json.load(open(mp))
    ch = {int(a): b for a, b in m['chan'].items()}; ru = {int(a): b for a, b in m['rule'].items()}
    K = max(list(ch) + list(ch.values())) + 1
    freeA = [c for c in range(K) if c not in ch]; freeB = [c for c in range(K) if c not in set(ch.values())]
    for a, b in zip(freeA, freeB): ch[a] = b
    P = [ch[c] for c in range(K)]; Pi = [0] * K
    for a, b in ch.items(): Pi[b] = a
    R = len(ru); T = [ru[l] for l in range(R)]; Ti = [0] * R
    for a, b in ru.items(): Ti[b] = a
    ns = f'Formal.Rewrite.Plain.{name}PlainGen'
    hw, rw = (('Formal.Rewrite.CountloopHw', 'Formal.Rewrite.CountloopRewrite') if name == 'Countloop' else
              (f'Formal.Rewrite.Ring.{name}Hw', f'Formal.Rewrite.Ring.{name}'))
    lean = f'''import {ns}
import Formal.Rewrite.Plain.{name}PlainRdHw
import Formal.Rewrite.Rename

/-!
# {ns}Tie -- GENERATED by formal/tools-A/rewrite/gen_plain_tie.py ({k})

`rs2p` of `{ns}` is the import of `formal/tools-A/rewrite/out/{k}_plain.mlir` (`{name}PlainRdHw.rules`) up to a channel
bijection `fp P` and a rule reordering `fp T`, both found by rules_iso.py and checked here by `decide +kernel`.
`tie_forward` / `tie_backward`: every complete run of research's fixture's graph is matched by a complete run of the
rewritten MLIR's graph with the same tokens on every channel outside `changed` (renamed by `fp P`), and vice versa.
Token level.
-/

namespace {ns}Tie

open Formal.Net.Kahn Formal.Net.GcdHw Formal.Rewrite.IncCmp {ns} {rw}

def P : List Nat := {P}
def Pi : List Nat := {Pi}
def T : List Nat := {T}
def Ti : List Nat := {Ti}

theorem hP : fpCheck P Pi = true := by decide +kernel
theorem hPi : fpCheck Pi P = true := by decide +kernel
theorem hT : fpCheck T Ti = true := by decide +kernel
theorem hTi : fpCheck Ti T = true := by decide +kernel
theorem hRen : renCheck rs2p {name}PlainRdHw.rules P Ti = true := by decide +kernel

theorem args_fixed : fp P 0 = 0 ∧ fp P 1 = 1 ∧ fp P 2 = 2 := by decide +kernel
theorem out_maps : fp P {hw}.chOut = {name}PlainRdHw.chOut := by decide +kernel

theorem tie_forward {{σ0 t : Store Nat Nat}} {{n : Nat}} (h0 : ∀ ch, ch ≠ 0 → ch ≠ 1 → ch ≠ 2 → σ0 ch = [])
    (hr : Run (step (graph {hw}.rules)) σ0 n t) (ht : Terminal (step (graph {hw}.rules)) t) :
    ∃ t' m, Run (step (graph {name}PlainRdHw.rules)) (renS (fp Pi) σ0) m t' ∧
      Terminal (step (graph {name}PlainRdHw.rules)) t' ∧ ∀ ch, ch ∉ changed → t' (fp P ch) = t ch := by
  obtain ⟨t3, m, r3, ht3, o3⟩ := plain_forward h0 hr ht
  refine ⟨renS (fp Pi) t3, m, run_ren (fp P) (fp Pi) (fp_inv P Pi hP) (fp_inv Pi P hPi) (fp T) (fp Ti)
    (fp_inv T Ti hT) (renCheck_ok hRen) r3,
    terminal_ren (fp P) (fp Pi) (fp_inv P Pi hP) (fp_inv Pi P hPi) (fp T) (fp Ti) (fp_inv Ti T hTi)
      (renCheck_ok hRen) ht3, ?_⟩
  intro ch hc; simp only [renS, fp_inv P Pi hP]; exact o3 ch hc

theorem tie_backward {{σ0' t' : Store Nat Nat}} {{n : Nat}} (h0 : ∀ ch, ch ≠ 0 → ch ≠ 1 → ch ≠ 2 → σ0' (fp P ch) = [])
    (hr : Run (step (graph {name}PlainRdHw.rules)) σ0' n t') (ht : Terminal (step (graph {name}PlainRdHw.rules)) t') :
    ∃ t m, Run (step (graph {hw}.rules)) (renS (fp P) σ0') m t ∧ Terminal (step (graph {hw}.rules)) t ∧
      ∀ ch, ch ∉ changed → t ch = t' (fp P ch) := by
  have r3 := run_ren_back (fp P) (fp Pi) (fp_inv P Pi hP) (fp_inv Pi P hPi) (fp Ti) (renCheck_ok hRen) hr
  have ht3 := terminal_ren_back (fp P) (fp Pi) (fp_inv P Pi hP) (fp_inv Pi P hPi) (fp T) (fp Ti)
    (fp_inv T Ti hT) (renCheck_ok hRen) ht
  obtain ⟨t, m, r, htt, o⟩ := plain_backward (fun ch a b c => h0 ch a b c) r3 ht3
  exact ⟨t, m, r, htt, fun ch hc => by rw [o ch hc]; rfl⟩

end {ns}Tie
'''
    open(os.path.join(od, name + 'PlainTie.lean'), 'w').write(lean)
    print(f'{k}: wrote Plain/{name}PlainRdHw.lean, Plain/{name}PlainTie.lean ({K} channels, {R} rules)')
    return 0

sys.exit(main())
