#!/usr/bin/env python3
"""gen_plain_same.py NAME KERNEL MD5 -- write Formal/Rewrite/Plain/<NAME>Same.lean from the two autoproof_x files
<NAME>Orig.lean / <NAME>Plain.lean (namespaces Formal.Net.AutoAp<NAME>{Orig,Plain}, graphs Formal.Rewrite.Ap<NAME>{..}Hw):
both graphs end in the C's result on every input where the C returns."""
import re, sys
name, k, md5 = sys.argv[1:4]
D = '/home/user/asyncfpga3/formal/lean/Formal/Rewrite/Plain/'
def hdr(v):
    t = open(D + f'{name}{v}.lean').read()
    m = re.search(r'theorem auto_computes \{fuel ([^}]*) r : Nat\} \(h : kC fuel ([^)]*) = some r\) :\n(.*?) := by', t, re.S)
    args, body = m.group(1).split(), m.group(3)
    ns, hw = f'Formal.Net.AutoAp{name}{v}', f'Formal.Rewrite.Ap{name}{v}Hw'
    body = re.sub(r'\bG\b', ns + '.G', body); body = re.sub(r'\bSt\b', ns + '.St', body)
    body = re.sub(r'\b(T\d+)\b', hw + r'.\1', body)
    parts = [p.strip() for p in body.split(') ∧\n')]
    return args, parts, ns
a1, p1, n1 = hdr('Orig'); a2, p2, n2 = hdr('Plain')
assert a1 == a2
A = ' '.join(a1)
def two(p): return '(' + p[0] + ') ∧\n      (' + p[1].rstrip(')') + ')'
out = f'''import Formal.Rewrite.Plain.{name}Orig
import Formal.Rewrite.Plain.{name}Plain

/-!
# Formal.Rewrite.Plain.{name}Same -- GENERATED by formal/tools-A/rewrite/gen_plain_same.py ({k})

The plain loop-test rewrite (`ring_dec.py --plain`: the test reads `slt(i, m)`, the ring carries `m = n - 1`, no
correction) of research's `{k}` fixture: `formal/tools-A/rewrite/out/{k}_plain.mlir` (md5 {md5}). `same`: on every input
on which the C returns `r`, both graphs have a complete run ending with `[r]` and every complete run of either, under
any schedule, ends there. Both halves generated by autoproof_x.py and checked by Lean. Token level; `kC` totality not
proved here.
-/

namespace Formal.Rewrite.Plain.{name}Same

open Formal.Net.Kahn Formal.Net.GcdHw

theorem kC_eq (fuel {A} : Nat) : {n2}.kC fuel {A} = {n1}.kC fuel {A} := rfl

theorem same {{fuel {A} r : Nat}} (h : {n1}.kC fuel {A} = some r) :
    ({two(p1)}) ∧
    ({two(p2)}) := by
  have h1 := {n1}.auto_computes h
  have h2 := {n2}.auto_computes (by rw [kC_eq]; exact h)
  exact ⟨⟨h1.1, h1.2.1⟩, ⟨h2.1, h2.2.1⟩⟩

end Formal.Rewrite.Plain.{name}Same
'''
open(D + f'{name}Same.lean', 'w').write(out)
