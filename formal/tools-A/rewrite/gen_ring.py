#!/usr/bin/env python3
"""gen_ring.py KERNEL NAME [MLIR] -- per-kernel Lean proof that ring_dec.py's rewrite preserves the kernel's function.

1. dfimport the original MLIR -> formal/lean/Formal/Rewrite/Ring/<NAME>Hw.lean
2. find the pattern in the imported rules (refuses unless exactly one match, in the theorems' exact shape)
3. instantiate ring_inst.lean.tmpl -> formal/lean/Formal/Rewrite/Ring/<NAME>.lean (rules -> rs1 -> rs2 -> rs3, every
   hypothesis by decide +kernel; Lean must still check it)
4. run ring_dec.py on the MLIR -> formal/tools-A/rewrite/out/<KERNEL>_rd.mlir, dfimport it, and print the commands to
   compare its import with rs3 (rules_iso.py, untrusted).
MLIR defaults to research's fixture cloud/fixtures/frontend/<KERNEL>/comp/handshake_transformed.mlir (origin/claude/research).
"""
import os, re, subprocess, sys
from string import Template
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, HERE)
import importlib.util
spec = importlib.util.spec_from_file_location('rules_iso', os.path.join(HERE, 'rules_iso.py'))
ri = importlib.util.module_from_spec(spec); sys.argv_saved = sys.argv
src_iso = open(os.path.join(HERE, 'rules_iso.py')).read().replace('sys.exit(main())', '')
exec(compile(src_iso, 'rules_iso', 'exec'), ri.__dict__)

def main():
    k, name = sys.argv[1], sys.argv[2]
    mlir = sys.argv[3] if len(sys.argv) > 3 else None
    tmp = '/tmp/gen_ring_' + k; os.makedirs(tmp, exist_ok=True)
    if mlir is None:
        mlir = os.path.join(tmp, k + '.mlir')
        open(mlir, 'w').write(subprocess.check_output(['git', '-C', ROOT, 'show',
            f'origin/claude/research:cloud/fixtures/frontend/{k}/comp/handshake_transformed.mlir'], text=True))
    od = os.path.join(ROOT, 'formal/lean/Formal/Rewrite/Ring'); os.makedirs(od, exist_ok=True)
    hw = os.path.join(od, name + 'Hw.lean')
    subprocess.check_call([sys.executable, os.path.join(ROOT, 'formal/tools/dfimport/mlir2lean.py'), mlir, '-o', hw,
        '--ns', f'Formal.Rewrite.Ring.{name}Hw', '--graph-module', f'Formal.Rewrite.Ring.{name}Hw', '--label', k,
        '--short', k], stdout=subprocess.DEVNULL)
    txt = open(hw).read()
    txt = re.sub(r'^Source: `[^`]*`', f'Source: `cloud/fixtures/frontend/{k}/comp/handshake_transformed.mlir` '
                 '(origin/claude/research)', txt, count=1, flags=re.M)
    open(hw, 'w').write(txt)
    N = int(re.search(r'^def N : Nat := (\d+)', txt, re.M).group(1))
    R = ri.load(hw); L = len(R)
    SLT = ('bin', ('cmpi', ('slt',)), 32, ('var', 0), ('var', 1))
    INC = ('bin', ('addi',), 32, ('var', 0), ('lit', 1))
    found = []
    for C, rc in enumerate(R):
        if rc[0] != 'comp' or len(rc[1]) != 2 or rc[3] != SLT: continue
        y, kk = rc[1]; c = rc[2]
        try:
            d = next(i for i, r in enumerate(R) if r[0] == 'fork' and len(r[2]) == 2 and r[2][1] == y)
            s, s0 = R[d][1], R[d][2][0]
            b = next(i for i, r in enumerate(R) if r[0] == 'comp' and r[2] == s and len(r[1]) == 1 and r[3] == INC)
            e = R[b][1][0]
            F = next(i for i, r in enumerate(R) if r[0] == 'fork' and len(r[2]) == 2 and r[2][1] == kk)
            rr_, r0 = R[F][1], R[F][2][0]
            M = next(i for i, r in enumerate(R) if r[0] == 'mux' and r[3] == rr_ and len(r[2]) == 2 and r[4] == 1)
            sel, (ne, nb) = R[M][1], R[M][2]
            B = next(i for i, r in enumerate(R) if r[0] == 'branch' and r[2] == r0 and r[3] == nb)
            cnd, nx = R[B][1], R[B][4]
            S = next(i for i, r in enumerate(R) if r[0] == 'sink' and r[1] == nx)
        except StopIteration:
            continue
        found.append(dict(M=M, F=F, B=B, S=S, C=C, D=L, sel=sel, ne=ne, nep=N, r=rr_, r0=r0, k=kk, nb=nb, nx=nx,
            cnd=cnd, y=y, c=c, b=b, d=d, e=e, s=s, s0=s0, e0=N + 1, e1=N + 2, y1=N + 3, y2=N + 4, w=N + 5,
            q=L + 1, rr=L + 2, L=L, L1=L + 1, L3=L + 3))
    if len(found) != 1:
        print(f'{k}: refused, {len(found)} matches of the exact theorem shape in the import'); return 2
    P = found[0]
    t = open(os.path.join(HERE, 'ring_inst.lean.tmpl')).read()
    out = Template(t).substitute({**{a: str(v) for a, v in P.items()}, 'K': name})
    out = re.sub(r'/-!\n# Formal\.Rewrite\.CountloopRewrite.*?\n-/\n',
        f'/-!\n# Formal.Rewrite.Ring.{name} -- GENERATED by formal/tools-A/rewrite/gen_ring.py ({k})\n\n'
        f'The ring / moved-test / split rewrite of `CountloopRewrite`, instantiated on `{name}Hw.rules` (dfimport of\n'
        f'research\'s `{k}` fixture). `same3_forward` / `same3_backward`: every complete run of the original graph is\n'
        f'matched by one of `rs3` ending in the same store outside `changed3`, and vice versa. Token level.\n-/\n',
        out, count=1, flags=re.S)
    out = re.sub(r'/-- The ring rewrite \(RingMap\):.*?-/', '/-- The ring rewrite (RingMap). -/', out)
    out = re.sub(r'/-- The test rewrite \(IncCmp2\):.*?-/', '/-- The test rewrite (IncCmp2). -/', out)
    open(os.path.join(od, name + '.lean'), 'w').write(out)
    rd = os.path.join(ROOT, 'formal/tools-A/rewrite/out', k + '_rd.mlir')
    subprocess.check_call([sys.executable, os.path.join(HERE, 'ring_dec.py'), mlir, rd])
    subprocess.check_call([sys.executable, os.path.join(ROOT, 'formal/tools/dfimport/mlir2lean.py'), rd, '-o',
        os.path.join(tmp, 'rd_import.lean')], stdout=subprocess.DEVNULL)
    print(f'{k}: wrote Ring/{name}Hw.lean, Ring/{name}.lean, out/{k}_rd.mlir; params {P}')
    print(f'  next: compile Ring/{name}.lean, #eval Formal.Rewrite.Ring.{name}.rs3, rules_iso.py it against {tmp}/rd_import.lean')
    return 0

sys.exit(main())
