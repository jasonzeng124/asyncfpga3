#!/usr/bin/env python3
"""Probe K3: regenerate routed2x_k3.py from the CURRENT ../routed2x.py plus --cut-type (each edit
must apply exactly once, else this fails), so the k3 netlist builder tracks routed2x.py changes
(e.g. E8Mux's --inverted).   python3 mk_routed2x_k3.py   -> routed2x_k3.py next to this file."""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
s = open(os.path.join(here, "..", "routed2x.py")).read()
HDR = '''"""routed2x_k3.py -- GENERATED by k3/mk_routed2x_k3.py from ../routed2x.py, with ONE addition,
--cut-type T (repeatable): cells of type T under the prefix are treated like a flip-flop (a hard
cell): their outputs become FREE INPUTS (arbitrary behaviour) and their inputs observed outputs.
Used for ipow's DSP48E1 (--cut-type DSP48E1_DSP48E1), which routed2x.py rejects ("not
combinational").  The event checkers' verdicts hold for every waveform of a free input, so this is
sound for them; k3/skel_dsp_check.py reports whether the control skeleton reads such a net at all.
It makes an xaudit transaction meaningless for the datapath (the product is a free input).
Without --cut-type the output is byte-identical to routed2x.py's.

'''
edits = [
    ('"""routed2x.py -- a nextpnr', HDR + 'routed2x.py -- a nextpnr'),
    ('    ap.add_argument("--xray-arcs")\n',
     '    ap.add_argument("--xray-arcs")\n    ap.add_argument("--cut-type", action="append", default=[])\n'),
    ('    keep = set(cn for cn in cells if cn.startswith(a.keep_prefix))\n',
     '    cut_types = set(a.cut_type)\n'
     '    cut_cells = sorted(cn for cn in cells if cn.startswith(a.keep_prefix) and cells[cn]["type"] in cut_types)\n'
     '    keep = set(cn for cn in cells if cn.startswith(a.keep_prefix) and cells[cn]["type"] not in cut_types)\n'),
    ('    rep.append("free inputs (%d):" % len(free))\n',
     '    if cut_types:\n'
     '        rep.append("cut cells (--cut-type %s) under the prefix (%d): %s" % (",".join(sorted(cut_types)), len(cut_cells), cut_cells))\n'
     '    rep.append("free inputs (%d):" % len(free))\n'),
]
s = s.replace('"""routed2x.py -- a nextpnr', '"""routed2x.py -- a nextpnr', 1)
for old, new in edits:
    if s.count(old) != 1:
        sys.exit(f"mk_routed2x_k3: anchor not found exactly once: {old[:60]!r}")
    s = s.replace(old, new, 1)
open(os.path.join(here, "routed2x_k3.py"), "w").write(s)
print("wrote routed2x_k3.py from ../routed2x.py")
