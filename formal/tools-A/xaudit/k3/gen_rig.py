#!/usr/bin/env python3
"""Probe K3: write <k>_rig.v and <k>_hw.v for a kernel with two 32-bit data inputs plus `start`
(ipow: b, e; xorshift: seed, rounds), from k2/collatz_rig.v's closed ring and k2/collatz_hw.v.

  gen_rig.py ipow|xorshift OUTDIR

The ring, the fork (N = 3 here: two operands + start), the p_end sink, urdly(CMPD), uenv0/uenv1
and the width-filtered err/ok checker are collatz_rig.v's, unchanged.  The ROM is
{expected, a, b}, 96 bits, computed below from the kernel's C source semantics (32-bit wrap,
signed compare/shift where the C uses int) -- not from any run.  Vector 1 is the formal tools'
transaction: two loop iterations for ipow (3^2 = 9: one even and one odd exponent bit), one round
for xorshift (seed 1 -> 0x42021).  Neither answer is 0.
"""
import sys, os, re

def s32(x):
    x &= 0xffffffff
    return x - (1 << 32) if x >> 31 else x

def ipow(b, e):  # kernels/ipow/ipow.c
    b, e, r = s32(b), s32(e), 1
    while e > 0:
        if (e & 1) == 1:
            r = s32(r * b)
        b = s32(b * b)
        e = e >> 1
    return r & 0xffffffff

def xorshift(seed, rounds):  # kernels/xorshift/xorshift.c
    x, i, rounds = seed & 0xffffffff, 0, s32(rounds)
    while i < rounds:
        x ^= (x << 13) & 0xffffffff
        x ^= x >> 17
        x ^= (x << 5) & 0xffffffff
        i += 1
    return x

K = {
  "ipow": dict(a="b", b="e", f=ipow, tag="6F",
      vec=[(3,7),(3,2),(2,10),(5,3),(7,0),(-2,5),(10,9),(3,20),(2,31),(1,1000),(0,5),(13,4),(6,6),(9,1),(-1,7),(17,8)]),
  "xorshift": dict(a="seed", b="rounds", f=xorshift, tag="70",
      vec=[(2463534242,4),(1,1),(1,0),(1,2),(123456789,3),(0xdeadbeef,1),(7,5),(42,10),(0x80000000,2),
           (0xffffffff,1),(5,7),(99,4),(2463534242,1),(1000,3),(0x12345678,6),(31337,2)]),
}

k, out = sys.argv[1], sys.argv[2]
p = K[k]; A, B = p["a"], p["b"]; U = k.upper()
rows = "\n".join(f"            4'd{i}: vector = {{32'h{p['f'](a, b):08x}, 32'h{a & 0xffffffff:08x}, 32'h{b & 0xffffffff:08x}}};"
                 for i, (a, b) in enumerate(p["vec"]))
rig = f"""// {k}_rig.v -- k2/collatz_rig.v (= cells/hw/gcd_rig.v's closed ring) with bdc_{k} (probe K3,
// generated by formal/tools-A/xaudit/k3/gen_rig.py; do not edit by hand).
//   * DUT bdc_{k} ({A}, {B}, start) -> (out0, end); the fork has N = 3;
//   * ROM {{expected, {A}, {B}}} from kernels/{k}/{k}.c semantics (gen_rig.py), not from a run;
//   * everything else (uenv0/uenv1, urdly(CMPD), p_end sink, err/ok filter) as collatz_rig.v.
// Not part of cells/: built only in an exported copy of the tree (k3/build_k3.sh).
`default_nettype none
module {k}_rig #(parameter integer IDXW  = 4,
                 parameter integer WFILT = 2,
                 parameter integer CMPD  = 16)
    (input  wire            rst,
     input  wire [IDXW-1:0] idx,
     output wire            lap,
     output wire            err_flt,
     output wire            ok_flt,
     output wire            probe,
     output wire [31:0]     res_data);

    function [95:0] vector(input [3:0] i);
        case (i)
{rows}
        endcase
    endfunction
    wire [95:0] vec = vector(idx);
    wire [31:0] b_v = vec[31:0];
    wire [31:0] a_v = vec[63:32];
    wire [31:0] g_v = vec[95:64];

    wire a_req, a_ack, b_req, b_ack, start_req, start_ack;
    wire out0_req, out0_ack, p_end_req, p_end_ack;
    wire [31:0] out0_data;

`ifdef {U}_DUT_PARAMS
    bdc_{k} #(`{U}_DUT_PARAMS) udut (
`else
    bdc_{k} udut (
`endif
        .rst(rst),
        .{A}_req(a_req), .{A}_ack(a_ack), .{A}_data(a_v),
        .{B}_req(b_req), .{B}_ack(b_ack), .{B}_data(b_v),
        .start_req(start_req), .start_ack(start_ack),
        .out0_req(out0_req),   .out0_ack(out0_ack),   .out0_data(out0_data),
        .p_end_req(p_end_req), .p_end_ack(p_end_ack));

    wire env_c, in_ack;
    wire [2:0] in_req, in_acks;
    assign in_acks = {{start_ack, b_ack, a_ack}};
    assign {{start_req, b_req, a_req}} = in_req;
    bd_fork #(.N(3)) ufork (
        .rst(rst), .req(env_c), .ack(in_ack),
        .req_out(in_req), .ack_in(in_acks));

    bd_delay #(.N(2)) upsnk (.a(p_end_req), .z(p_end_ack));

    wire res_req, res_ack;
    bd_delay #(.N(CMPD)) urdly (.a(out0_req), .z(res_req));
    assign out0_ack = res_ack;

    wire env_c0;
    bd_c2n     uenv0 (.a(res_req), .b(env_c),  .rst(rst), .q(env_c0));
    bd_c2n_set uenv1 (.a(env_c0),  .b(in_ack), .rst(rst), .q(env_c));
    assign res_ack = env_c0;

    wire mism = |(out0_data ^ g_v);
    wire err_raw, ok_raw, err_d, ok_d;
    (* keep *) LUT2 #(.INIT(4'h8)) uerr_d (.I0(mism), .I1(res_req), .O(err_raw));
    (* keep *) LUT2 #(.INIT(4'h4)) uok_d  (.I0(mism), .I1(res_req), .O(ok_raw));
    bd_delay #(.N(WFILT)) uerr_w (.a(err_raw), .z(err_d));
    bd_delay #(.N(WFILT)) uok_w  (.a(ok_raw),  .z(ok_d));
    (* keep *) LUT2 #(.INIT(4'h8)) uerr_a (.I0(err_raw), .I1(err_d), .O(err_flt));
    (* keep *) LUT2 #(.INIT(4'h8)) uok_a  (.I0(ok_raw),  .I1(ok_d),  .O(ok_flt));

    assign lap      = res_req;
    assign probe    = env_c;
    assign res_data = out0_data;
endmodule
`default_nettype wire
"""
here = os.path.dirname(os.path.abspath(__file__))
hw = open(os.path.join(here, "..", "k2", "collatz_hw.v")).read()
hw = hw.replace("collatz_rig #(", f"{k}_rig #(").replace("module collatz_hw", f"module {k}_hw")
hw = hw.replace("8'h6E;   // gcd_hw is 6D", f"8'h{p['tag']};   // gcd_hw 6D, collatz_hw 6E")
hw = re.sub(r"\A(//.*\n)+", f"// {k}_hw.v -- generated by k3/gen_rig.py from k2/collatz_hw.v (collatz_rig -> {k}_rig, TAG {p['tag']}).\n"
            "// Same shell as gcd_hw.v minus gcd's probes; the formal cut is urig.* with free inputs idx, rig_rst.\n", hw)
body = [l for l in hw.splitlines() if not l.lstrip().startswith("//") and "collatz" in l.split("//")[0]]
assert not body, body
open(os.path.join(out, f"{k}_rig.v"), "w").write(rig)
open(os.path.join(out, f"{k}_hw.v"), "w").write(hw)
print(f"wrote {k}_rig.v {k}_hw.v; vector 1 = {p['vec'][1]} -> 0x{p['f'](*p['vec'][1]):x}")
