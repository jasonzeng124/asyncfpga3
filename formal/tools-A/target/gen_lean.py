#!/usr/bin/env python3
"""gen_lean.py (shard A, THE goal): the decoded target netlist as Lean data (Formal.Target.Spec's Net).

    python3 gen_lean.py NET.json BND.json OUTDIR [--chunk 2500]

Writes OUTDIR/G000.lean .. (gate chunks), OUTDIR/Nodes.lean (node names, chunked), OUTDIR/All.lean
(`net : Net`, `boundary : Boundary`). Generated; untrusted until the Lean round trip checks it.
Gate names are FASM-meaningful: a pip is its feature `TILE.DST.SRC` (an implicit pip is prefixed
`~`), a LUT output is `<site>.<L>LUT.O6/O5`, etc.
"""
import json, os, sys
net = json.load(open(sys.argv[1])); bnd = json.load(open(sys.argv[2])); out = sys.argv[3]
CH = int(sys.argv[sys.argv.index("--chunk") + 1]) if "--chunk" in sys.argv else 2500
os.makedirs(out, exist_ok=True)
NS = "Formal.Target.Decoded"


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def gate(g):
    nm = g["name"]
    if g["kind"] == "pip" and g["prov"].get("pseudo"):
        nm = "~" + nm
    a = g["arcs"]
    if g["kind"] in ("pip", "hop") and g["k"] == 1:
        e = a[0]
        return "P %s %d %d %d %d %d %d" % (q(nm), g["ins"][0], g["out"], e["fmin"], e["fmax"], e["smin"], e["smax"])
    arcs = "[" + ", ".join("⟨%d, %d, %d, %d⟩" % (e["fmin"], e["fmax"], e["smin"], e["smax"]) for e in a) + "]"
    return "⟨%s, %d, %d, [%s], %s, %d⟩" % (q(nm), g["k"], g["init"], ", ".join(map(str, g["ins"])), arcs, g["out"])


# renumber: gate i drives node i (so the no-two-drivers half of Net.WF is "outputs = range"),
# undriven nodes (env inputs, FF/BUFG outputs, floating) after the driven ones
gs0 = net["gates"]
old_names = net["nodes"]
perm = {}
for i, g in enumerate(gs0):
    if g["out"] in perm:
        sys.exit("node %s driven twice" % old_names[g["out"]])
    perm[g["out"]] = i
for o in range(len(old_names)):
    if o not in perm:
        perm[o] = len(perm)
gs = []
for g in gs0:
    h = dict(g)
    h["ins"] = [perm[i] for i in g["ins"]]
    h["out"] = perm[g["out"]]
    gs.append(h)
newnames = [None] * len(old_names)
for o, n in perm.items():
    newnames[n] = old_names[o]
net["nodes"] = newnames
nch = (len(gs) + CH - 1) // CH
for c in range(nch):
    with open(os.path.join(out, "G%03d.lean" % c), "w") as f:
        f.write("import Formal.Target.NetBase\n\n/-! GENERATED by formal/tools-A/target/gen_lean.py. Do not edit. -/\n\n")
        f.write("namespace %s\nopen Formal.Target\n\n" % NS)
        f.write("set_option maxRecDepth 100000 in\ndef g%03d : List Gate := [\n" % c)
        f.write(",\n".join("  " + gate(g) for g in gs[c * CH:(c + 1) * CH]))
        f.write("]\n\n")
        f.write("theorem g%03d_wf : ∀ g ∈ g%03d, g.WFn %d := by decide +kernel\n\n" % (c, c, len(net["nodes"])))
        f.write("theorem g%03d_outs : outsOK g%03d %d = true := by decide +kernel\n\n" % (c, c, c * CH))
        f.write("theorem g%03d_len : g%03d.length = %d := by decide +kernel\n\n" % (c, c, len(gs[c * CH:(c + 1) * CH])))
        f.write("end %s\n" % NS)
names = net["nodes"]
NCH = 20000
nn = (len(names) + NCH - 1) // NCH
with open(os.path.join(out, "Nodes.lean"), "w") as f:
    f.write("import Formal.Target.Spec\n\n/-! GENERATED by formal/tools-A/target/gen_lean.py. Do not edit. -/\n\nnamespace %s\n\n" % NS)
    for c in range(nn):
        f.write("set_option maxRecDepth 100000 in\ndef n%02d : List String := [%s]\n\n" % (c, ", ".join(q(x) for x in names[c * NCH:(c + 1) * NCH])))
    f.write("def names : List String := %s\n\nend %s\n" % (" ++ ".join("n%02d" % c for c in range(nn)), NS))
idx = {n: i for i, n in enumerate(names)}
B = bnd["boundary"]


def node(x):
    if x.startswith("const"):
        return idx["CONST%s" % x[-1]]
    return idx[x]


def lst(xs):
    return "[" + ", ".join(str(node(x)) for x in xs) + "]"


with open(os.path.join(out, "All.lean"), "w") as f:
    f.write("\n".join("import Formal.Target.Net.G%03d" % c for c in range(nch)) + "\nimport Formal.Target.Net.Nodes\n\n")
    f.write("/-! GENERATED by formal/tools-A/target/gen_lean.py. The decoded target netlist (UNTRUSTED decoder,\n"
            "formal/tools-A/target/; the Lean round trip that checks it is not written yet). -/\n\nnamespace %s\nopen Formal.Target\n\n" % NS)
    def rnest(xs):
        return xs[0] if len(xs) == 1 else "%s ++ (%s)" % (xs[0], rnest(xs[1:]))
    f.write("set_option maxRecDepth 100000 in\ndef gates : List Gate := %s\n\n" % rnest(["g%03d" % c for c in range(nch)]))
    f.write("def net : Net := ⟨%d, names, gates⟩\n\n" % len(names))
    f.write("/-- Number of gates; gate `i` drives node `i`. -/\ndef nGates : Nat := %d\n\n" % len(gs))
    def nest(xs):
        return xs[0] if len(xs) == 1 else "List.forall_mem_append.2 ⟨%s, %s⟩" % (xs[0], nest(xs[1:]))
    f.write("set_option maxRecDepth 100000 in\ntheorem gates_wf : ∀ g ∈ gates, g.WFn %d :=\n  %s\n\n" % (len(names), nest(["g%03d_wf" % c for c in range(nch)])))
    f.write("set_option maxRecDepth 100000 in\ntheorem gates_outs : outsOK gates 0 = true := by\n  simp only [gates, outsOK_append, %s, %s, Bool.and_true]\n\n" % (
        ", ".join("g%03d_len" % c for c in range(nch)), ", ".join("g%03d_outs" % c for c in range(nch)) + ", Nat.reduceAdd, Bool.true_and"))
    if "--arbs" in sys.argv:
        A = json.load(open(sys.argv[sys.argv.index("--arbs") + 1]))
        f.write("/-- The target's arbiters (formal/tools-A/target/arbs.py; untrusted naming): state node `q` and the\n"
                "other inputs of its state LUT. -/\ndef arbs : List ArbNodes := [\n%s]\n\n" % ",\n".join(
                    "  ⟨%d, [%s]⟩" % (node(a["q"]), ", ".join(str(node(x)) for x in a["ins"])) for a in A))
    f.write("/-- **The decoded target netlist is well formed** (`Spec.Net.WF`): pin and arc lists of length `k`,\n"
            "node indices in range, INITs in range, every arc ordered, and no node with two drivers. -/\n"
            "theorem net_wf : net.WF := Net.wf_of_outs net gates_wf gates_outs\n\n")
    f.write("/-- The chunk size of `g000 ..`: chunk `c` holds gates `c*%d ..`. -/\ndef chunk : Nat := %d\n\n" % (CH, CH))
    f.write("def boundary : Boundary :=\n  { rst := %d,\n    a := ⟨%d, %d, %s⟩,\n    b := ⟨%d, %d, %s⟩,\n    start := ⟨%d, %d, []⟩,\n"
            "    out0 := ⟨%d, %d, %s⟩,\n    pend := ⟨%d, %d, []⟩,\n    env := %s }\n\nend %s\n" % (
                node(B["rst"]), node(B["req"]), node(B["a_ack"]), lst(B["a_data"]),
                node(B["req"]), node(B["b_ack"]), lst(B["b_data"]),
                node(B["req"]), node(B["start_ack"]),
                node(B["out0_req"]), node(B["out0_ack"]), lst(B["out0_data"]),
                node(B["req"]), node(B["pend_ack"]), lst(bnd["env"]), NS))
print("gen_lean: %d gate chunks, %d nodes" % (nch, len(names)))
