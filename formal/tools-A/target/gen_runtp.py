#!/usr/bin/env python3
"""Shard A (2026-11-07): Lean data for an H_RUNT(w) witness run at κ = P/25 with per-arc delay classes (C's
simadv.py --classes CLS.json --cdefault F --w W, exact): per-chunk BTL trees of node codes, a sparse BTC tree of
narrow-pulse chains, the per-arc slow list (codes 8·out + pin), per-chunk gate checks (CexRuntP.gateWR), each split
in 3 slices (one decide over a whole chunk needs > 15 GB).
usage: gen_runtp.py dump.json net.json bnd.json OUTDIR NAMESPACE P W classes.json"""
import json, sys, os
Wd = json.load(open(sys.argv[1])); net = json.load(open(sys.argv[2])); BJ = json.load(open(sys.argv[3])); out = sys.argv[4]
NS = sys.argv[5]; P = int(sys.argv[6]); W = int(sys.argv[7]); CJ = json.load(open(sys.argv[8]))
G = net["gates"]; N = net["nodes"]; idx = {n: i for i, n in enumerate(N)}; ENV = set(idx[x] for x in BJ["env"])
nN = len(N); nG = len(G); C, D = 2500, 12
drv = {g["out"]: gi for gi, g in enumerate(G) if g["out"] not in ENV}
assert not CJ.get("F") and all(isinstance(x, list) for x in CJ["S"])
SLOW = set(8 * idx[n] + p for n, p in CJ["S"])
assert all(p < 8 for _, p in CJ["S"])
nodes = {int(k): v for k, v in Wd["nodes"].items()}
def leaf(n):
    v = nodes.get(n)
    if v is None or (not v[0] and not v[1]): return ".lf none"
    return f".lf (some ({'true' if v[0] else 'false'}, [{', '.join(map(str, v[1]))}]))"
def tree(ns, d):
    if d == 0: return leaf(ns[0]) if ns[0] is not None else ".lf none"
    h = len(ns) // 2
    return f".nd ({tree(ns[:h], d - 1)}) ({tree(ns[h:], d - 1)})"
def chains(ts):
    bnd = [0] + ts; ch = []; cs = None
    for i in range(1, len(bnd)):          # the power-up interval [0, first flip) is never part of a chain
        nar = i + 1 < len(bnd) and bnd[i + 1] - bnd[i] < W
        if nar and cs is None: cs = bnd[i]
        if not nar and cs is not None: ch.append((cs, bnd[i])); cs = None
    return ch
CH = {n: chains(v[1]) for n, v in nodes.items()}
CH = {n: c for n, c in CH.items() if c}
DC = 18
assert nN <= 2 ** DC
def ctree(lo, d):
    if not any(lo <= n < lo + 2 ** d for n in CH): return ".lf []"
    if d == 0: return ".lf [" + ", ".join(f"({a}, {b})" for a, b in CH[lo]) + "]"
    return f".nd ({ctree(lo, d - 1)}) ({ctree(lo + 2 ** (d - 1), d - 1)})"
HDR = "/-! GENERATED by formal/tools-A/target/gen_runtp.py. Do not edit. -/\n\n"
nch = (nN + C - 1) // C; nchG = (nG + C - 1) // C
for c in range(nch):
    ns = list(range(c * C, min((c + 1) * C, nN))); ns += [None] * (2 ** D - len(ns))
    open(f"{out}/L{c:03d}.lean", "w").write(f"import Formal.Target.CexRuntP.RBase\n\n" + HDR + f"namespace {NS}\nopen Formal.Net.CexPS72 Formal.Target.CexRuntP\n\n"
        "set_option maxRecDepth 100000 in\n" + f"def l{c:03d} : BTL :=\n  {tree(ns, D)}\n\nend {NS}\n")
open(f"{out}/Ch.lean", "w").write(f"import Formal.Target.CexRuntP.RBase\n\n" + HDR + f"namespace {NS}\nopen Formal.Target.CexRuntP\n\n"
    "set_option maxRecDepth 100000 in\n"
    f"/-- Narrow-pulse chains (maximal runs of pulses < {W} ps, power-up interval excluded) of {len(CH)} nodes. -/\n"
    f"def chT : BTC :=\n  {ctree(0, DC)}\n\nend {NS}\n")
L = ", ".join(f"l{c:03d}" for c in range(nch))
open(f"{out}/EncR.lean", "w").write("".join(f"import {NS}.L{c:03d}\n" for c in range(nch)) + f"import {NS}.Ch\n\n" + HDR +
    f"namespace {NS}\nopen Formal.Net.CexPS72 Formal.Target.CexRuntP\n\ndef llR : List BTL := [{L}]\n\n/-- The run's node codes. -/\n"
    f"def encR : Nat → Option (Bool × List Nat) := lookL llR {C} {D}\n\n"
    f"/-- Each node's narrow-pulse chains. -/\ndef chR (n : Nat) : List (Nat × Nat) := chT.get {DC} n\n\n"
    f"/-- The slow arcs, as codes 8·out + pin. -/\n"
    f"def slR : List Nat := [{', '.join(map(str, sorted(SLOW)))}]\n\nend {NS}\n")
F = f"(fun g => !keepPS g || gateWR {P} {W} encR chR slR g)"
for c in range(nchG):
    q = 834
    def slc(j):
        e = f"g{c:03d}"
        for _ in range(j): e = f"({e}.drop {q})"
        return e if j == 2 else f"({e}.take {q})"
    parts = "\n".join(f"set_option maxRecDepth 100000 in\ntheorem x{c:03d}_p{j} : {slc(j)}.all {F} = true := by decide +kernel\n" for j in range(3))
    comb = (f"theorem x{c:03d}_ok : g{c:03d}.all {F} = true := by\n"
            f"  rw [← List.take_append_drop {q} g{c:03d}, List.all_append, x{c:03d}_p0, Bool.true_and]\n"
            f"  rw [← List.take_append_drop {q} (g{c:03d}.drop {q}), List.all_append, x{c:03d}_p1, Bool.true_and]\n"
            f"  exact x{c:03d}_p2\n")
    open(f"{out}/X{c:03d}.lean", "w").write(f"import {NS}.EncR\n\n" + HDR +
        f"namespace {NS}\nopen Formal.Target.DecodedPS Formal.Net.CViewPS Formal.Net.CexPS72 Formal.Target.CexRuntP\n\n" + parts + "\n" + comb + f"\nend {NS}\n")
print("gen_runtp: %d node chunks, %d gate chunks, %d slow arcs, %d nodes with chains" % (nch, nchG, len(SLOW), len(CH)))
