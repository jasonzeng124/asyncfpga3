#!/usr/bin/env python3
"""gen_o5.py (shard A, S1): per-chunk kernel checks that every LUT5 (O5) gate of Decoded.gates agrees with its
LUT6 (O6) gate (Formal/Target/LutPair.lean), and their assembly `o5_gates`.

    python3 gen_o5.py NCHUNKS OUTDIR        # writes OUTDIR/O000.lean .. and OUTDIR/OAll.lean
"""
import os
import sys

nC, OUT = int(sys.argv[1]), sys.argv[2]
NS = sys.argv[sys.argv.index("--ns") + 1] if "--ns" in sys.argv else "Formal.Target.RT.Data"
MP = sys.argv[sys.argv.index("--mp") + 1] if "--mp" in sys.argv else "FormalWit.RT"
NETMP = sys.argv[sys.argv.index("--netmp") + 1] if "--netmp" in sys.argv else "Formal.Target.Net"   # the netlist modules
NETNS = sys.argv[sys.argv.index("--netns") + 1] if "--netns" in sys.argv else "Formal.Target.Decoded"   # the netlist namespace
os.makedirs(OUT, exist_ok=True)
OPEN = "namespace %s\nopen Formal.Target Formal.Target.RT %s\n\n" % (NS, NETNS)
for c in range(nC):
    with open(os.path.join(OUT, "O%03d.lean" % c), "w") as f:
        imp = "import Formal.Target.LutPair\nimport %s.G%03d\n" % (NETMP, c)
        if c > 0:
            imp += "import %s.G%03d\n" % (NETMP, c - 1)
        f.write(imp + "\n/-! GENERATED by formal/tools-A/target/gen_o5.py. -/\n\n" + OPEN)
        prev = "default" if c == 0 else "(g%03d.getLast?.getD default)" % (c - 1)
        f.write("theorem o%03d : o5ok %s g%03d = true := by decide +kernel\n\nend %s\n" % (c, prev, c, NS))
steps = []
for c in range(nC - 1):
    s = "o5ok_append, o%03d, Bool.true_and" % c
    if c > 0:
        s += ", getLastD_ne g%03d (List.ne_nil_of_length_pos (by rw [g%03d_len]; decide)) _ default" % (c, c)
    steps.append(s)
with open(os.path.join(OUT, "OAll.lean"), "w") as f:
    f.write("\n".join("import %s.O%03d" % (MP, c) for c in range(nC)) + "\nimport %s.All\n\n" % NETMP)
    f.write('''/-!
# LUT5 outputs of the decoded target agree with their LUT6 (S1, part 2)

GENERATED by formal/tools-A/target/gen_o5.py. `o5_gates`: every O5 gate of `Decoded.gates` (k = 5, name
`<site>.<L>LUT.O5`) has an O6 gate in `gates` with the same `<site>.<L>LUT.` name, whose first five pins are its
pins and whose INIT mod 2^32 is its INIT. With `roundtrip` (the O6 INITs are the bitstream's), the O5 functions
are the bitstream's too. Not shown: that the O6's first five pins are A1..A5 in order (the decoder's pin map).
-/

''' + OPEN)
    f.write("set_option maxRecDepth 100000 in\ntheorem o5_all : o5ok default gates = true := by\n  simp only [gates]\n")
    for s in steps:
        f.write("  rw [%s]\n" % s)
    f.write("  exact o%03d\n\n" % (nC - 1))
    f.write("theorem o5_gates : ∀ g ∈ gates, isO5 g = true → ∃ q ∈ gates, o5match q g = true :=\n  o5_of_ok gates o5_all\n\nend %s\n" % NS)
