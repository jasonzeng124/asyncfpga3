#!/usr/bin/env python3
"""gen_wit.py (shard A, THE goal): a simulated behaviour of the decoded target as Lean witness data.

    python3 gen_wit.py NET.json BND.json DUMP.json NAME OUTDIR [--chunk 2500]

DUMP.json is sim.py --dump of a run at --corner 1 --pos 1 (every pin delay = the slow end of its
band, Witness.dsl) with --full (every circuit gate). Node indices are renumbered exactly as
gen_lean.py does (gate i drives node i). Writes, under namespace Formal.Target.Wit.<NAME>:
  T00..   subtrees of the description table (BT), Top.lean: `bt`, `D`, `b`, `P`, `Dm`;
  C000..  per gate chunk: `∀ g ∈ g<c>, g.out ∉ boundary.env → chkFrom D g (dsl g) b F g.dmax = true`;
  Q000..  per node chunk: `∀ n, lo ≤ n < hi → chkPer (D n) P (b - Dm) b F (b - Dm) = true`.
The period P and the cut b are found from the dump (the ring oscillator) and checked in Lean.
"""
import json, os, sys

net = json.load(open(sys.argv[1])); bnd = json.load(open(sys.argv[2])); W = json.load(open(sys.argv[3]))
NAME, OUT = sys.argv[4], sys.argv[5]
CH = int(sys.argv[sys.argv.index("--chunk") + 1]) if "--chunk" in sys.argv else 2500
NS = "Formal.Target.Wit.%s" % NAME
os.makedirs(OUT, exist_ok=True)
gs0, names0 = net["gates"], net["nodes"]
perm = {}
for i, g in enumerate(gs0):
    perm[g["out"]] = i
for o in range(len(names0)):
    if o not in perm:
        perm[o] = len(perm)
nN, nG = len(names0), len(gs0)
desc = {}
for k, (v0, ts) in W["nodes"].items():
    desc[perm[int(k)]] = (bool(v0), ts)
# ---- the period and the cut
tend = W["tend"]
late = {n: ts for n, (v0, ts) in desc.items() if ts and ts[-1] > tend - 200000}
gaps = {b - a for ts in late.values() for a, b in zip(ts[-6:], ts[-5:])}
if len(gaps) != 1:
    sys.exit("gen_wit: the late toggles are not one period: %s" % sorted(gaps)[:10])
half = gaps.pop()
P = 2 * half
T0 = max(ts[-1] for n, (v0, ts) in desc.items() if ts and n not in late)
Dm = max(e["smax"] for g in gs0 for e in g["arcs"]) if gs0 else 0
b = T0 + Dm + 2 * P + 1
if b > tend - P:
    sys.exit("gen_wit: the run is too short: b = %d, tend = %d" % (b, tend))
print("gen_wit: P = %d ps, T0 = %d, Dm = %d, b = %d; %d nodes with flips, %d periodic" %
      (P, T0, Dm, b, sum(1 for v in desc.values() if v[1]), len(late)))
# truncate every description at b
D = {n: (v0, [t for t in ts if t < b]) for n, (v0, ts) in desc.items()}
D = {n: v for n, v in D.items() if v[0] or v[1]}


def sd(v):
    return "⟨%s, [%s]⟩" % ("true" if v[0] else "false", ", ".join(map(str, v[1])))


def tree(lo, hi):
    """BT over [lo, hi) as a Lean term."""
    if not any(lo <= n < hi for n in keys_in(lo, hi)):
        return ".leaf ⟨false, []⟩"
    if hi - lo == 1:
        return ".leaf %s" % sd(D[lo])
    mid = (lo + hi) // 2
    return "(.node %d %s %s)" % (mid, tree(lo, mid), tree(mid, hi))


import bisect
skeys = sorted(D)


def keys_in(lo, hi):
    i = bisect.bisect_left(skeys, lo)
    j = bisect.bisect_left(skeys, hi)
    return skeys[i:j]


NT = 64
step = (nN + NT - 1) // NT
hdr = "import Formal.Target.Witness\n\n/-! GENERATED by formal/tools-A/target/gen_wit.py. Do not edit. -/\n\n"
for k in range(NT):
    lo, hi = k * step, min(nN, (k + 1) * step)
    with open(os.path.join(OUT, "T%02d.lean" % k), "w") as f:
        f.write(hdr + "namespace %s\nopen Formal.Target Formal.Target.Wit\n\n" % NS)
        f.write("set_option maxRecDepth 100000 in\ndef t%02d : BT := %s\n\nend %s\n" % (k, tree(lo, hi), NS))


def top(ks):
    if len(ks) == 1:
        return "t%02d" % ks[0]
    m = len(ks) // 2
    return "(.node %d %s %s)" % (ks[m] * step, top(ks[:m]), top(ks[m:]))


with open(os.path.join(OUT, "Top.lean"), "w") as f:
    f.write("\n".join("import %s.T%02d" % (NS, k) for k in range(NT)) + "\nimport Formal.Target.Net.All\n\n")
    f.write("/-! GENERATED by formal/tools-A/target/gen_wit.py: the witness behaviour `%s` (sim.py run %s). -/\n\n" % (NAME, W["args"]))
    f.write("namespace %s\nopen Formal.Target Formal.Target.Wit\n\n" % NS)
    f.write("def bt : BT := %s\n\ndef D (n : Nat) : SD := bt.find n\n\n" % top(list(range(NT))))
    f.write("/-- The ring oscillator's period. -/\ndef P : Nat := %d\n\n/-- The cut: descriptions hold below it. -/\ndef b : Nat := %d\n\n"
            "/-- The longest arc (slow end) of the netlist. -/\ndef Dm : Nat := %d\n\nend %s\n" % (P, b, Dm, NS))
FUEL = 10000000
for c in range((nG + CH - 1) // CH):
    with open(os.path.join(OUT, "C%03d.lean" % c), "w") as f:
        f.write("import %s.Top\n\n/-! GENERATED by formal/tools-A/target/gen_wit.py. -/\n\nnamespace %s\nopen Formal.Target Formal.Target.Wit Formal.Target.Decoded\n\n" % (NS, NS))
        f.write("theorem c%03d : ∀ g ∈ g%03d, g.out ∉ boundary.env → chkFrom D g (dsl g) b %d g.dmax = true := by\n  decide +kernel\n\nend %s\n" % (c, c, FUEL, NS))
NQ = 2500
for c in range((nN + NQ - 1) // NQ):
    lo, hi = c * NQ, min(nN, (c + 1) * NQ)
    with open(os.path.join(OUT, "Q%03d.lean" % c), "w") as f:
        f.write("import %s.Top\n\n/-! GENERATED by formal/tools-A/target/gen_wit.py. -/\n\nnamespace %s\nopen Formal.Target Formal.Target.Wit\n\n" % (NS, NS))
        f.write("theorem q%03d : ∀ n, %d ≤ n → n < %d → chkPer (D n) P b %d (b - Dm) = true := by\n  decide +kernel\n\nend %s\n" % (c, lo, hi, FUEL, NS))
print("gen_wit: wrote %s" % OUT)
