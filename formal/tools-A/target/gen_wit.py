#!/usr/bin/env python3
"""gen_wit.py (shard A, THE goal): a simulated behaviour of the decoded target as Lean witness data.

    python3 gen_wit.py NET.json BND.json DUMP.json NAME OUTDIR [--chunk 2500]

DUMP.json is sim.py --dump of a run at --corner 1 --pos 1 (every pin delay = the slow end of its
band, Witness.dsl) with --full (every circuit gate). Node indices are renumbered exactly as
gen_lean.py does (gate i drives node i). Writes, under namespace Formal.Target.Wit.<NAME>:
  T00..   subtrees of the description table (BT), Top.lean: `bt`, `D`, `b`, `P`, `Dm`;
  C000..  per gate chunk: `∀ g ∈ g<c>, g.out ∉ boundary.env → chkFrom D g (dsl g) b F g.dmax = true`;
  Q000..  per node chunk: `∀ n, lo ≤ n < hi → chkPer (D n) P (b - Dm) b F (b - Dm) = true`.
The period P and the cut b are found from the dump (the ring oscillator) and checked in Lean.
"""
import json, os, sys

net = json.load(open(sys.argv[1])); bnd = json.load(open(sys.argv[2])); W = json.load(open(sys.argv[3]))
NAME, OUT = sys.argv[4], sys.argv[5]
CH = int(sys.argv[sys.argv.index("--chunk") + 1]) if "--chunk" in sys.argv else 2500
NS = "Formal.Target.Wit.%s" % NAME
os.makedirs(OUT, exist_ok=True)
gs0, names0 = net["gates"], net["nodes"]
perm = {}
for i, g in enumerate(gs0):
    perm[g["out"]] = i
for o in range(len(names0)):
    if o not in perm:
        perm[o] = len(perm)
nN, nG = len(names0), len(gs0)
desc = {}
for k, (v0, ts) in W["nodes"].items():
    desc[perm[int(k)]] = (bool(v0), ts)
# ---- the period and the cut
tend = W["tend"]
late = {n: ts for n, (v0, ts) in desc.items() if ts and ts[-1] > tend - 200000}
gaps = {b - a for ts in late.values() for a, b in zip(ts[-6:], ts[-5:])}
if len(gaps) != 1:
    sys.exit("gen_wit: the late toggles are not one period: %s" % sorted(gaps)[:10])
half = gaps.pop()
P = 2 * half
T0 = max(ts[-1] for n, (v0, ts) in desc.items() if ts and n not in late)
Dm = max(e["smax"] for g in gs0 for e in g["arcs"]) if gs0 else 0
b = T0 + Dm + 2 * P + 1
if b > tend - P:
    sys.exit("gen_wit: the run is too short: b = %d, tend = %d" % (b, tend))
print("gen_wit: P = %d ps, T0 = %d, Dm = %d, b = %d; %d nodes with flips, %d periodic" %
      (P, T0, Dm, b, sum(1 for v in desc.values() if v[1]), len(late)))
# truncate every description at b
D = {n: (v0, [t for t in ts if t < b]) for n, (v0, ts) in desc.items()}
D = {n: v for n, v in D.items() if v[0] or v[1]}


def sd(v):
    return "⟨%s, [%s]⟩" % ("true" if v[0] else "false", ", ".join(map(str, v[1])))


def tree(lo, hi):
    """BT over [lo, hi) as a Lean term."""
    if not any(lo <= n < hi for n in keys_in(lo, hi)):
        return "(.leaf ⟨false, []⟩)"
    if hi - lo == 1:
        return "(.leaf %s)" % sd(D[lo])
    mid = (lo + hi) // 2
    return "(.node %d %s %s)" % (mid, tree(lo, mid), tree(mid, hi))


import bisect
skeys = sorted(D)


def keys_in(lo, hi):
    i = bisect.bisect_left(skeys, lo)
    j = bisect.bisect_left(skeys, hi)
    return skeys[i:j]


NT = 64
step = (nN + NT - 1) // NT
hdr = "import Formal.Target.Witness\n\n/-! GENERATED by formal/tools-A/target/gen_wit.py. Do not edit. -/\n\n"
for k in range(NT):
    lo, hi = k * step, min(nN, (k + 1) * step)
    with open(os.path.join(OUT, "T%02d.lean" % k), "w") as f:
        f.write(hdr + "namespace %s\nopen Formal.Target Formal.Target.Wit\n\n" % NS)
        f.write("set_option maxRecDepth 100000 in\ndef t%02d : BT := %s\n\nend %s\n" % (k, tree(lo, hi), NS))


def top(ks):
    if len(ks) == 1:
        return "t%02d" % ks[0]
    m = len(ks) // 2
    return "(.node %d %s %s)" % (ks[m] * step, top(ks[:m]), top(ks[m:]))


with open(os.path.join(OUT, "Top.lean"), "w") as f:
    f.write("\n".join("import %s.T%02d" % (NS, k) for k in range(NT)) + "\nimport Formal.Target.Net.All\n\n")
    f.write("/-! GENERATED by formal/tools-A/target/gen_wit.py: the witness behaviour `%s` (sim.py run %s). -/\n\n" % (NAME, W["args"]))
    f.write("namespace %s\nopen Formal.Target Formal.Target.Wit\n\n" % NS)
    f.write("def bt : BT := %s\n\ndef D (n : Nat) : SD := bt.find n\n\n" % top(list(range(NT))))
    f.write("/-- The ring oscillator's period. -/\ndef P : Nat := %d\n\n/-- The cut: descriptions hold below it. -/\ndef b : Nat := %d\n\n"
            "/-- The longest arc (slow end) of the netlist. -/\ndef Dm : Nat := %d\n\nend %s\n" % (P, b, Dm, NS))
FUEL = 10000000
for c in range((nG + CH - 1) // CH):
    with open(os.path.join(OUT, "C%03d.lean" % c), "w") as f:
        f.write("import %s.Top\n\n/-! GENERATED by formal/tools-A/target/gen_wit.py. -/\n\nnamespace %s\nopen Formal.Target Formal.Target.Wit Formal.Target.Decoded\n\n" % (NS, NS))
        f.write("theorem c%03d : ∀ g ∈ g%03d, g.out ∉ boundary.env → chkFrom D g (dsl g) b %d g.dmax = true ∧ g.dmax ≤ Dm := by\n  decide +kernel\n\nend %s\n" % (c, c, FUEL, NS))
NQ = 2500
for c in range((nN + NQ - 1) // NQ):
    lo, hi = c * NQ, min(nN, (c + 1) * NQ)
    with open(os.path.join(OUT, "Q%03d.lean" % c), "w") as f:
        f.write("import %s.Top\n\n/-! GENERATED by formal/tools-A/target/gen_wit.py. -/\n\nnamespace %s\nopen Formal.Target Formal.Target.Wit\n\n" % (NS, NS))
        f.write("theorem q%03d : ∀ n, %d ≤ n → n < %d → chkPer (D n) P b %d (b - Dm) = true := by\n  decide +kernel\n\nend %s\n" % (c, lo, hi, FUEL, NS))
print("gen_wit: wrote %s" % OUT)

# ---------------------------------------------------------------------------------------------
# Refute.lean: the assembly of ¬ NetCorrect for this witness (pairs, R, Δo, T from the run)
R0 = W["args"]["R"]
DO = W["args"]["dout"] - 1
pairs = W["pairs"]
outs = W["outs"]
nb = len(pairs)
# H_ARB's T for this run: largest gap from an input flip to the arbiter-state flip it causes, + 1
A = json.load(open(sys.argv[sys.argv.index("--arbs") + 1])) if "--arbs" in sys.argv else []
idx0 = {n: i for i, n in enumerate(names0)}
Tarb = 1
for a_ in A:
    q = D.get(perm[idx0[a_["q"]]], (False, []))[1]
    ins = sorted(t for n in a_["ins"] for t in D.get(perm[idx0[n]], (False, []))[1])
    for tau in q:
        prev = [t for t in ins if t <= tau]
        Tarb = max(Tarb, tau - max(prev) + 1)
# the first out0 offer: the run's first sample time (= ack rise - 1) and its request rise
s0 = outs[0][0]
oreq = perm[idx0[bnd["boundary"]["out0_req"]]]
rise0 = [t for t in D[oreq][1] if t <= s0][-1]
vafun = " else ".join("if k = %d then %d" % (i, p_[0]) for i, p_ in enumerate(pairs)) + " else 0"
vbfun = " else ".join("if k = %d then %d" % (i, p_[1]) for i, p_ in enumerate(pairs)) + " else 0"
nG2 = (nG + CH - 1) // CH
nQ2 = (nN + NQ - 1) // NQ


def nestC(xs):
    return xs[0] if len(xs) == 1 else "List.forall_mem_append.2 ⟨%s, %s⟩" % (xs[0], nestC(xs[1:]))


def perTerm(c):
    lo, hi = c * NQ, min(nN, (c + 1) * NQ)
    if c == nQ2 - 1:
        return "q%03d n (by omega) hn" % c
    return "if h%d : n < %d then q%03d n (by omega) h%d else\n    %s" % (c, hi, c, c, perTerm(c + 1))


with open(os.path.join(OUT, "Refute.lean"), "w") as f:
    f.write("\n".join("import %s.C%03d" % (NS, c) for c in range(nG2)) + "\n")
    f.write("\n".join("import %s.Q%03d" % (NS, c) for c in range(nQ2)) + "\nimport Formal.Target.WitBoundary\nimport Mathlib.Tactic.IntervalCases\n\n")
    f.write('''/-!
# THE refutation for witness %s: the pipelined statement is false for the decoded target

GENERATED by formal/tools-A/target/gen_wit.py from sim.py run %s.
`refuted : ¬ NetCorrect net boundary arbs pSlow %d %d 0 %d`: at the strictest delay model
(slow corner, guard 1, scatter 0), with every arbiter resolving within %d ps, reset length %d ps,
data setup 0, output acknowledge margin %d ps, the environment that offers the pairs %s
(pipelined: the next pair as soon as all input acknowledges are low) gets %s first on out0.
-/

namespace %s
open Formal.Target Formal.Target.Wit Formal.Target.Decoded

theorem hP : 0 < P := by decide
theorem hPb : P + Dm ≤ b := by decide
theorem hPlo : P ≤ b - Dm := by decide

set_option maxRecDepth 100000 in
theorem allC : ∀ g ∈ gates, g.out ∉ boundary.env → chkFrom D g (dsl g) b %d g.dmax = true ∧ g.dmax ≤ Dm :=
  %s

set_option maxRecDepth 100000 in
theorem perAll (n : Nat) (hn : n < %d) : chkPer (D n) P b %d (b - Dm) = true :=
  %s

/-- **The witness is a behaviour of the circuit** (Spec.Behaves at the slow corner, g = 1, κ = 0). -/
theorem beh_ok : Behaves pSlow (circuit net boundary) (ext D b P) := by
  refine ⟨1, by norm_num, le_refl _, fun g hg => ?_⟩
  simp only [circuit, Boundary.envNodes, List.mem_filter, decide_eq_true_eq] at hg
  obtain ⟨hgm, hno⟩ := hg
  obtain ⟨hl1, hl2, hout, hins, _, harc⟩ := gates_wf g hgm
  obtain ⟨hc, hdm⟩ := allC g hgm hno
  exact gateOK_slow D g hP hPb (by have := hPb; omega) hdm hl2
    (fun e he => ⟨(harc e he).2.2.1, (harc e he).2.1⟩) hc
    (perOn_of_chk _ hPlo (perAll _ hout))
    (fun i hi => perOn_of_chk _ hPlo (perAll _ (hins _ (getD_mem _ _ (by omega)))))

theorem arbChk : ∀ a ∈ arbs, (D a.q).ok = true ∧ (∀ n ∈ a.ins, (D n).ok = true) ∧
    arbFlipsOK %d (D a.q) (a.ins.map D) = true ∧ (∀ τ ∈ (D a.q).ts, τ + P < b) ∧
    (∀ n ∈ a.ins, ∀ τ ∈ (D n).ts, τ + P < b) := by decide +kernel

theorem quiet_eq (n : Nat) (h : ∀ τ ∈ (D n).ts, τ + P < b) : ext D b P n = (D n).val :=
  funext (ext_eq_val D hP (by have := hPb; omega) h)

/-- **H_ARB(%d) holds in the witness.** -/
theorem arb_ok : ArbOK %d arbs (ext D b P) := by
  intro a ha t1 t2 hc
  obtain ⟨h1, h2, h3, h4, h5⟩ := arbChk a ha
  rw [quiet_eq _ h4]
  exact arbOK_one %d _ _ h1 (fun d hd => by obtain ⟨n, hn, rfl⟩ := List.mem_map.1 hd; exact h2 n hn) h3 t1 t2
    (fun d hd => by
      obtain ⟨n, hn, rfl⟩ := List.mem_map.1 hd
      have := hc n hn; rw [quiet_eq _ (h5 n hn)] at this; exact this)

/-- The boundary nodes and their flips. -/
def bnodes : List Nat := [boundary.rst, boundary.a.req, boundary.a.ack, boundary.b.ack, boundary.start.ack,
  boundary.out0.req, boundary.out0.ack, boundary.pend.ack] ++ boundary.a.data ++ boundary.b.data ++ boundary.out0.data

def bp : List Nat := bnodes.flatMap fun n => (D n).ts

theorem bchk : ∀ n ∈ bnodes, (D n).ok = true ∧ (∀ τ ∈ (D n).ts, τ + P < b) ∧ (∀ τ ∈ (D n).ts, τ ∈ bp) := by
  decide +kernel

theorem bcap : ∀ x ∈ bp, x < b := by decide +kernel

theorem bq (n : Nat) (hn : n ∈ bnodes) : ext D b P n = beh D n := quiet_eq n (bchk n hn).2.1

def va (k : Nat) : Nat := %s
def vb (k : Nat) : Nat := %s

theorem env_a : EnvIn (beh D) boundary.a %d 0 (some %d) va :=
  envIn_of D bp b %d %d _ _ _ (by decide +kernel) (by decide +kernel) bcap (by decide +kernel) (by decide +kernel)
    (by decide +kernel) (by decide +kernel) (by decide +kernel) (by decide +kernel)
theorem env_b : EnvIn (beh D) boundary.b %d 0 (some %d) vb :=
  envIn_of D bp b %d %d _ _ _ (by decide +kernel) (by decide +kernel) bcap (by decide +kernel) (by decide +kernel)
    (by decide +kernel) (by decide +kernel) (by decide +kernel) (by decide +kernel)
theorem env_s : EnvIn (beh D) boundary.start %d 0 (some %d) (fun _ => 0) :=
  envIn_of D bp b %d %d _ _ _ (by decide +kernel) (by decide +kernel) bcap (by decide +kernel) (by decide +kernel)
    (by decide +kernel) (by decide +kernel) (by decide +kernel) (by decide +kernel)
theorem env_o : EnvOut (beh D) boundary.out0 %d %d :=
  envOut_of D bp b %d %d _ _ (by decide +kernel) (by decide +kernel) bcap (by decide +kernel) (by decide +kernel)
    (by decide +kernel) (by decide +kernel)
theorem env_p : EnvOut (beh D) boundary.pend %d %d :=
  envOut_of D bp b %d %d _ _ (by decide +kernel) (by decide +kernel) bcap (by decide +kernel) (by decide +kernel)
    (by decide +kernel) (by decide +kernel)

/-- **The environment of the witness obeys H_ENV** (pipelined, broad data rule). -/
theorem env_ok : Env (ext D b P) boundary %d 0 %d (some %d) va vb := by
  have hrst : (D boundary.rst).ok = true ∧ (D boundary.rst).v0 = true ∧ (D boundary.rst).ts = [%d] := by decide +kernel
  have er : ext D b P boundary.rst = (D boundary.rst).val := bq _ (by decide +kernel)
  refine ⟨fun t ht => ?_, fun t ht => ?_, fun k hk => ?_, ?_, ?_, ?_, ?_, ?_⟩
  · rw [er, val_before _ (T := %d) (by rw [hrst.2.2]; simp) t (by omega)]; decide +kernel
  · rw [er, val_after _ (T := %d) (by rw [hrst.2.2]; simp) t ht]; decide +kernel
  · simp only [Offered] at hk; interval_cases k <;> decide
  · exact envIn_congr _ _ _ _ _ _ _ (fun v hv => bq v (by revert v; decide +kernel) |>.trans rfl) env_a
  · exact envIn_congr _ _ _ _ _ _ _ (fun v hv => bq v (by revert v; decide +kernel) |>.trans rfl) env_b
  · exact envIn_congr _ _ _ _ _ _ _ (fun v hv => bq v (by revert v; decide +kernel) |>.trans rfl) env_s
  · exact envOut_congr _ _ _ _ _ (fun v hv => bq v (by revert v; decide +kernel) |>.trans rfl) env_o
  · exact envOut_congr _ _ _ _ _ (fun v hv => bq v (by revert v; decide +kernel) |>.trans rfl) env_p

/-- **`Correct` fails**: the first out0 value is not gcd of the first pair. -/
theorem not_correct : ¬ Correct (ext D b P) boundary %d %d (some %d) va vb := by
  intro hC
  have eR : ext D b P boundary.out0.req = (D boundary.out0.req).val := bq _ (by decide +kernel)
  have eA : ext D b P boundary.out0.ack = (D boundary.out0.ack).val := bq _ (by decide +kernel)
  have hok : (D boundary.out0.req).ok = true := (bchk _ (by decide +kernel)).1
  have hgap : ∀ s, %d ≤ s → s ≤ %d → ext D b P boundary.out0.req s = true ∧ ext D b P boundary.out0.ack s = false := by
    intro s h1 h2
    rw [eR, eA]
    rw [(D boundary.out0.req).val_const h1 (fun y hy h3 => by
          have := (show ∀ y ∈ (D boundary.out0.req).ts, %d < y → %d < y by decide +kernel) y hy h3; omega),
        (D boundary.out0.ack).val_const (Nat.zero_le s) (fun y hy h3 => by
          have := (show ∀ y ∈ (D boundary.out0.ack).ts, %d < y by decide +kernel) y hy; omega)]
    decide +kernel
  have hd := hC.2.2.2.2.2.1 %d %d (by norm_num) (by rw [eR]; decide +kernel) (by rw [eR]; decide +kernel)
    (by norm_num) hgap
  rw [busVal_congr _ (beh D) _ _ (fun v hv => congrFun (bq v (by revert v; decide +kernel)) _), eR,
    rises_eq _ hok] at hd
  revert hd; decide +kernel

/-- **THE pipelined statement is false for the decoded target** (at the strictest delay model). -/
theorem refuted : ¬ NetCorrect net boundary arbs pSlow %d %d 0 %d := fun H =>
  not_correct (H (ext D b P) (some %d) va vb beh_ok arb_ok env_ok)

end %s
''' % (NAME, W["args"], Tarb, R0, DO, Tarb, R0, DO, pairs, outs[0][1], NS,
       FUEL, nestC(["c%03d" % c for c in range(nG2)]), nN, FUEL, perTerm(0),
       Tarb, Tarb, Tarb, Tarb, vafun, vbfun,
       R0, nb, FUEL, R0, R0, nb, FUEL, R0, R0, nb, FUEL, R0,
       R0, DO, FUEL, R0, R0, DO, FUEL, R0,
       R0, DO, nb, R0, R0 - 1, R0,
       R0, DO, nb, rise0, rise0 + DO, rise0, rise0 + DO, rise0 + DO, rise0 - 1, rise0 + DO,
       Tarb, R0, DO, nb, NS))
print("gen_wit: Refute.lean: T = %d, R = %d, Δo = %d, first out0 sample %d, request rise %d" % (Tarb, R0, DO, s0, rise0))
