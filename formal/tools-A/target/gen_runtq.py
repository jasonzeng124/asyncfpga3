#!/usr/bin/env python3
"""Shard A (2026-11-09; UNTRUSTED generator): Lean data for an EVENTUALLY PERIODIC H_RUNT(w) witness run (a livelock)
at κ = P/25, corner 0, per-arc delay classes (C's simadv.py --classes CLS.json --w W, exact delays), checked by
Formal.Target.CexRuntQ.gateQ: per-chunk BTL trees of the prefix codes (transitions < t0), a sparse BTN tree of one
period per node (transitions in [t0, t0+Q)), a sparse BTC tree of the narrow-pulse chains of the run unrolled m
periods (transitions < H = t0 + m·Q), the per-arc slow list, per-chunk gate checks split in 3 slices.
Aborts unless the dump's transitions in [t0, H) are exactly the period unrolled (so the Lean run IS the dump up to H).
(CEXHEAVY=7,14,15,65,70,72 for CexQ36: those gate chunks need > 15 GB in 3 slices.)
usage: gen_runtq.py dump.json net.json bnd.json OUTDIR NAMESPACE P W classes.json Q t0 m V"""
import json, sys, os
Wd = json.load(open(sys.argv[1])); net = json.load(open(sys.argv[2])); BJ = json.load(open(sys.argv[3])); out = sys.argv[4]
NS = sys.argv[5]; P = int(sys.argv[6]); W = int(sys.argv[7]); CJ = json.load(open(sys.argv[8]))
Q, T0, M, V = map(int, sys.argv[9:13]); H = T0 + M * Q
assert V + Q + W <= H and V >= T0
RB = "Formal.Target.CexRuntQ.QBase"
G = net["gates"]; N = net["nodes"]; idx = {n: i for i, n in enumerate(N)}; ENV = set(idx[x] for x in BJ["env"])
nN = len(N); nG = len(G); C, D = 2500, 12
assert not CJ.get("F") and all(isinstance(x, list) for x in CJ["S"]) and all(p < 8 for _, p in CJ["S"])
SLOW = set(8 * idx[n] + p for n, p in CJ["S"])
raw = {int(k): v for k, v in Wd["nodes"].items()}
pre, per, unr = {}, {}, {}
for n, (v0, ts) in raw.items():
    A = [t for t in ts if t < T0]; B = [t for t in ts if T0 <= t < T0 + Q]
    assert len(B) % 2 == 0, n
    U = [p + k * Q for k in range(M) for p in B]
    assert [t for t in ts if T0 <= t < H] == sorted(U), ("not periodic", n)
    if v0 or A: pre[n] = (v0, A)
    if B: per[n] = B
    unr[n] = A + sorted(U)
def leaf(n):
    v = pre.get(n)
    if v is None: return ".lf none"
    return f".lf (some ({'true' if v[0] else 'false'}, [{', '.join(map(str, v[1]))}]))"
def tree(ns, d):
    if d == 0: return leaf(ns[0]) if ns[0] is not None else ".lf none"
    h = len(ns) // 2
    return f".nd ({tree(ns[:h], d - 1)}) ({tree(ns[h:], d - 1)})"
def chains(ts):
    bnd = [0] + ts; ch = []; cs = None
    for i in range(1, len(bnd)):          # the power-up interval [0, first flip) is never part of a chain
        nar = i + 1 < len(bnd) and bnd[i + 1] - bnd[i] < W
        if nar and cs is None: cs = bnd[i]
        if not nar and cs is not None: ch.append((cs, bnd[i])); cs = None
    return ch
CH = {n: chains(u) for n, u in unr.items()}
CH = {n: c for n, c in CH.items() if c}
DC = 18
assert nN <= 2 ** DC
def stree(lo, d, Dct, fmt):
    if not any(lo <= n < lo + 2 ** d for n in Dct): return ".lf []"
    if d == 0: return ".lf [" + ", ".join(fmt(x) for x in Dct[lo]) + "]"
    return f".nd ({stree(lo, d - 1, Dct, fmt)}) ({stree(lo + 2 ** (d - 1), d - 1, Dct, fmt)})"
HDR = "/-! GENERATED by formal/tools-A/target/gen_runtq.py. Do not edit. -/\n\n"
OP = f"open Formal.Net.CexPS72 Formal.Target.CexRuntP Formal.Target.CexRuntQ"
nch = (nN + C - 1) // C; nchG = (nG + C - 1) // C
for c in range(nch):
    ns = list(range(c * C, min((c + 1) * C, nN))); ns += [None] * (2 ** D - len(ns))
    open(f"{out}/L{c:03d}.lean", "w").write(f"import {RB}\n\n" + HDR + f"namespace {NS}\n{OP}\n\n"
        "set_option maxRecDepth 100000 in\n" + f"def l{c:03d} : BTL :=\n  {tree(ns, D)}\n\nend {NS}\n")
open(f"{out}/Ch.lean", "w").write(f"import {RB}\n\n" + HDR + f"namespace {NS}\n{OP}\n\n"
    "set_option maxRecDepth 100000 in\n"
    f"/-- Narrow-pulse chains (maximal runs of pulses < {W} ps, power-up interval excluded) of {len(CH)} nodes, "
    f"of the run unrolled to {H} ps. -/\n"
    f"def chT : BTC :=\n  {stree(0, DC, CH, lambda ab: f'({ab[0]}, {ab[1]})')}\n\n"
    "set_option maxRecDepth 100000 in\n"
    f"/-- One period ([{T0}, {T0 + Q}) ps) of the transitions of the {len(per)} nodes that oscillate for ever. -/\n"
    f"def perT : BTN :=\n  {stree(0, DC, per, str)}\n\nend {NS}\n")
L = ", ".join(f"l{c:03d}" for c in range(nch))
open(f"{out}/EncR.lean", "w").write("".join(f"import {NS}.L{c:03d}\n" for c in range(nch)) + f"import {NS}.Ch\n\n" + HDR +
    f"namespace {NS}\n{OP}\n\ndef llR : List BTL := [{L}]\n\n/-- The run's prefix codes (transitions before {T0} ps). -/\n"
    f"def encR : Nat → Option (Bool × List Nat) := lookL llR {C} {D}\n\n"
    f"/-- One period of each node (empty: constant from {T0} ps on). -/\ndef perR (n : Nat) : List Nat := perT.get {DC} n\n\n"
    f"/-- Each node's narrow-pulse chains (run unrolled to {H} ps). -/\ndef chR (n : Nat) : List (Nat × Nat) := chT.get {DC} n\n\n"
    f"/-- The slow arcs, as codes 8·out + pin. -/\n"
    f"def slR : List Nat := [{', '.join(map(str, sorted(SLOW)))}]\n\nend {NS}\n")
F = f"(fun g => !keepPS g || gateQ {P} {W} {Q} {T0} {M} {V} encR perR chR slR g)"
HEAVY = set(int(x) for x in os.environ.get("CEXHEAVY", "").split(",") if x)   # chunks split in 24 slices (memory)
for c in range(nchG):
    q = 834
    def slc(j):
        e = f"g{c:03d}"
        for _ in range(j): e = f"({e}.drop {q})"
        return e if j == 2 else f"({e}.take {q})"
    S = 24 if c in HEAVY else 3
    q = (2500 + S - 1) // S
    def slc(j):
        e = f"g{c:03d}"
        for _ in range(j): e = f"({e}.drop {q})"
        return e if j == S - 1 else f"({e}.take {q})"
    parts = "\n".join(f"set_option maxRecDepth 100000 in\ntheorem x{c:03d}_p{j} : {slc(j)}.all {F} = true := by decide +kernel\n" for j in range(S))
    comb = f"theorem x{c:03d}_ok : g{c:03d}.all {F} = true := by\n"
    e = f"g{c:03d}"
    for j in range(S - 1):
        comb += f"  rw [← List.take_append_drop {q} {e}, List.all_append, x{c:03d}_p{j}, Bool.true_and]\n"
        e = f"({e}.drop {q})"
    comb += f"  exact x{c:03d}_p{S-1}\n"
    open(f"{out}/X{c:03d}.lean", "w").write(f"import {NS}.EncR\n\n" + HDR +
        f"namespace {NS}\nopen Formal.Target.DecodedPS Formal.Net.CViewPS {OP[5:]}\n\n" + parts + "\n" + comb + f"\nend {NS}\n")
print("gen_runtq: %d node chunks, %d gate chunks, %d slow arcs, %d nodes with chains, %d periodic nodes, H = %d"
      % (nch, nchG, len(SLOW), len(CH), len(per), H))
