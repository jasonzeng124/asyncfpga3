#!/usr/bin/env python3
"""Shard A: rewrite CexRunt72 chunk checks X<c>.lean into P parts (one `decide +kernel` per slice of the gate chunk)
when one decide needs more memory than the sandbox has. usage: split_x.py DIR P c..."""
import sys
D, P = sys.argv[1], int(sys.argv[2])
NS = "Formal.Target.CexRunt72"
def slc(c, j, P, q):
    e = f"g{c:03d}"
    for _ in range(j): e = f"({e}.drop {q})"
    return e if j == P - 1 else f"({e}.take {q})"
for c in map(int, sys.argv[3:]):
    q = 2500 // P + 1
    F = "(fun g => !keepPS g || gateWR 20 encR chR slR g)"
    parts = [f"set_option maxRecDepth 100000 in\ntheorem x{c:03d}_p{j} : {slc(c, j, P, q)}.all {F} = true := by decide +kernel\n"
             for j in range(P)]
    comb = f"theorem x{c:03d}_ok : g{c:03d}.all {F} = true := by\n"
    e = f"g{c:03d}"
    for j in range(P - 1):
        comb += f"  rw [← List.take_append_drop {q} {e}, List.all_append, x{c:03d}_p{j}, Bool.true_and]\n"
        e = f"({e}.drop {q})"
    comb += f"  exact x{c:03d}_p{P-1}\n"
    open(f"{D}/X{c:03d}.lean", "w").write(f"import {NS}.EncR\n\n/-! GENERATED by formal/tools-A/target/split_x.py. Do not edit. -/\n\n"
        f"namespace {NS}\nopen Formal.Target.DecodedPS Formal.Net.CViewPS Formal.Net.CexPS72\n\n" + "\n".join(parts) + "\n" + comb + f"\nend {NS}\n")
