#!/usr/bin/env python3
"""Shard A: rewrite CexRunt72 chunk checks X<c>.lean into P parts (one `decide +kernel` per slice of the gate chunk)
when one decide needs more memory than the sandbox has. usage: split_x.py DIR P c..."""
import sys
D, P = sys.argv[1], int(sys.argv[2])
NS = "Formal.Target.CexRunt72"
for c in map(int, sys.argv[3:]):
    q = 2500 // P + 1
    parts = []
    for j in range(P):
        parts.append(f"set_option maxRecDepth 100000 in\ntheorem x{c:03d}_p{j} : ((g{c:03d}.drop {j*q}).take {q}).all "
                     f"(fun g => !keepPS g || gateWR 20 encR chR slR g) = true := by decide +kernel\n")
    comb = (f"theorem x{c:03d}_ok : g{c:03d}.all (fun g => !keepPS g || gateWR 20 encR chR slR g) = true := by\n"
            f"  rw [List.all_eq_true]\n  intro g hg\n")
    # g ∈ l → g ∈ some slice (drop (j*q)).take q, for l.length ≤ P*q
    comb += (f"  have hl : g{c:03d}.length ≤ {P*q} := by decide\n"
             f"  obtain ⟨n, hn, rfl⟩ := List.getElem_of_mem hg\n")
    for j in range(P):
        comb += (f"  {'if' if j == 0 else 'else if'} h{j} : n < {(j+1)*q} then\n"
                 f"    have hm : g{c:03d}[n] ∈ (g{c:03d}.drop {j*q}).take {q} := by\n"
                 f"      rw [List.mem_iff_getElem]\n"
                 f"      exact ⟨n - {j*q}, by simp; omega, by simp [List.getElem_take, List.getElem_drop]; congr 1; omega⟩\n"
                 f"    exact List.all_eq_true.mp x{c:03d}_p{j} _ hm\n")
    comb += "  else by omega\n"
    open(f"{D}/X{c:03d}.lean", "w").write(f"import {NS}.EncR\n\n/-! GENERATED by formal/tools-A/target/split_x.py. Do not edit. -/\n\n"
        f"namespace {NS}\nopen Formal.Target.DecodedPS Formal.Net.CViewPS Formal.Net.CexPS72\n\n" + "\n".join(parts) + "\n" + comb + f"\nend {NS}\n")
