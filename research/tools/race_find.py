#!/usr/bin/env python3
"""race_find.py ROUTED_JSON ARCS_TSV OUTDIR [N] -- every latch-fed steer race of a route (formal B21's kind), each
written as a research/tools/race_mc.py spec and run through it.

The race: a steer LUT (`*.u$LUT6` / `*.u$LUT5` of a bd_steer) reads its condition from a link's data latch (`L.lat.odd.u`,
transparent while L's controller is high) and its request from its join, one of whose inputs is the same link's request
line (`L.rdly.chain.g[last].u`). Both start at the rise of L's controller (`L.ctl.u.u/O6`):
  condition S: ctl -> lat.odd (enable pin) -> lat.odd -> the steer's condition pin -> the steer's output
  request   F: ctl -> rdly g[0] -> ... -> g[last] -> the join's pin -> the join -> the steer's request pin -> the output
The condition must arrive first. Everything is read from xray_delay.py's --arcs table (the IC arcs are the route's
nets, src pin -> dst pin; the IO arcs a cell's pin -> output). Prints one line per race: the steer half, the link, the
corner margins with no scatter and race_mc's distribution over N model points (default 100000)."""
import os
import re
import subprocess
import sys


def main():
    rj, tsv, out = sys.argv[1:4]
    n = sys.argv[4] if len(sys.argv) > 4 else "100000"
    os.makedirs(out, exist_ok=True)
    ic, io = {}, {}
    hdr = None
    for ln in open(tsv):
        f = ln.rstrip("\n").split("\t")
        if hdr is None:
            hdr = f
            continue
        d = dict(zip(hdr, f))
        if d["kind"] == "IC":
            ic.setdefault(d["dst"], []).append(d["src"])
        elif d["kind"] == "IO":
            io.setdefault(d["src"].rpartition("/")[0], set()).add((d["src"].rpartition("/")[2], d["dst"].rpartition("/")[2]))
    re_steer = re.compile(r"^(?P<p>.*\.)(?P<st>ucond_br\d+)\.u\$LUT(?P<h>[56])/(?P<pin>A\d)$")
    races = []
    for dst, srcs in ic.items():
        m = re_steer.match(dst)
        if not m:
            continue
        for src in srcs:
            ml = re.match(r"^(?P<L>.+)\.lat\.odd\.u/O6$", src)
            if not ml:
                continue
            L = ml.group("L")
            steer = dst.rpartition("/")[0]
            out_pin = "O6" if m.group("h") == "6" else "O5"
            # the request pin: from a join that reads L's request line
            for dst2, srcs2 in ic.items():
                if not dst2.startswith(steer + "/") or dst2 == dst:
                    continue
                for s2 in srcs2:
                    j = s2.rpartition("/")[0]
                    if "_j." not in j:
                        continue
                    gl = [s3 for d3, ss in ic.items() if d3.startswith(j + "/") for s3 in ss
                          if re.match(re.escape(L) + r"\.rdly\.chain\.g\[\d+\]\.u/O6$", s3)]
                    if not gl:
                        continue
                    races.append((steer, m.group("pin"), dst2.rpartition("/")[2], out_pin, L, j, gl[0]))
    esc = lambda s: re.escape(s)
    seen = set()
    for steer, cpin, rpin, opin, L, j, glast in races:
        key = (steer, cpin, rpin)
        if key in seen:
            continue
        seen.add(key)
        ctl = L + ".ctl.u.u/O6"
        lat = L + ".lat.odd.u"
        en = [d for d, ss in ic.items() if d.startswith(lat + "/") and ctl in ss]
        g0 = [d for d, ss in ic.items() if re.match(re.escape(L) + r"\.rdly\.chain\.g\[0\]\.u/A\d$", d) and ctl in ss]
        if len(en) != 1 or len(g0) != 1:
            print("%s %s: skipped (enable pins %d, request-line entries %d)" % (steer, L, len(en), len(g0)))
            continue
        lines = ["# %s condition %s (latch %s) vs request %s (join %s); generated by race_find.py" % (steer, cpin, lat, rpin, j),
                 "S IC %s %s" % (esc(ctl), esc(en[0])),
                 "S IO %s %s" % (esc(en[0]), esc(lat + "/O6")),
                 "S IC %s %s" % (esc(lat + "/O6"), esc(steer + "/" + cpin)),
                 "S IO %s %s" % (esc(steer + "/" + cpin), esc(steer + "/" + opin)),
                 "F IC %s %s" % (esc(ctl), esc(g0[0]))]
        # the request line, element by element, to g[last]
        k, cur = 0, g0[0]
        while True:
            gk = "%s.rdly.chain.g[%d].u" % (L, k)
            lines.append("F IO %s %s" % (esc(cur), esc(gk + "/O6")))
            if gk + "/O6" == glast:
                break
            nxt = [d for d, ss in ic.items() if d.startswith("%s.rdly.chain.g[%d].u/" % (L, k + 1)) and gk + "/O6" in ss]
            if len(nxt) != 1:
                lines = None
                break
            lines.append("F IC %s %s" % (esc(gk + "/O6"), esc(nxt[0])))
            cur, k = nxt[0], k + 1
        if lines is None:
            print("%s %s: skipped (request line not traced)" % (steer, L))
            continue
        jin = [d for d, ss in ic.items() if d.startswith(j + "/") and glast in ss]
        if len(jin) != 1:
            print("%s %s: skipped (join pin not found)" % (steer, L))
            continue
        jo = j + "/O6"
        lines += ["F IC %s %s" % (esc(glast), esc(jin[0])),
                  "F IO %s %s" % (esc(jin[0]), esc(jo)),
                  "F IC %s %s" % (esc(jo), esc(steer + "/" + rpin)),
                  "F IO %s %s" % (esc(steer + "/" + rpin), esc(steer + "/" + opin))]
        name = re.sub(r"[^\w]+", "_", "%s_%s" % (steer.split(".")[-2] + steer[-1], cpin))
        spec = os.path.join(out, name + ".txt")
        open(spec, "w").write("\n".join(lines) + "\n")
        r = subprocess.run([sys.executable, os.path.join(os.path.dirname(os.path.abspath(__file__)), "race_mc.py"),
                            rj, tsv, spec, n], capture_output=True, text=True)
        o = r.stdout.splitlines()
        corners = [l.split("= ")[-1] for l in o if l.startswith("corner")]
        dist = [l for l in o if l.startswith("model points")]
        below = [l.strip() for l in o if l.strip().startswith("below")]
        print("%s (%s cond %s, req %s) link %s: corners %s | %s | %s" % (
            steer.replace("bridge_i.udut.", ""), opin, cpin, rpin, L.replace("bridge_i.udut.", ""), " / ".join(corners),
            dist[0].split(": ", 1)[1] if dist else r.stderr.strip()[-200:], below[0] if below else ""))


if __name__ == "__main__":
    main()
