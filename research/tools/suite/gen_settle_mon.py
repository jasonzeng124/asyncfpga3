#!/usr/bin/env python3
"""gen_settle_mon.py ROUTED_JSON NETS_MAP OUT.v -- a settle monitor on one bundled channel, for the full-stack GLS
(cells/gls/ps/build_ps.sh runs it as PS_MON_GEN, after gen.py, in the work directory; bench_gate.sh passes the
environment through).  Diagnosis only: it changes no verdict.

For every transaction of the watched channel it prints, at the request's fall,
    SETTLE n=K t0=T req=R last=L late=L-R dreq=HEX dfall=HEX
  t0     the start: the rise of the unit's join (net SETTLE_UNIT.joined; SETTLE_UNIT default bridge_i.udut.udivui0)
  req    the request's rise at the unit's matched-delay tail (the output of the last SETTLE_UNIT.udly.chain.g[N].u;
         SETTLE_REQ=<net> instead names a net), ps after t0
  last   the last change of any data bit (SETTLE_DATA[k], default bridge_i.o_data_pl[k]) between t0 and the request's
         fall, ps after t0
  late   last - req: > 0 means the data was still moving when its request arrived (a bundling violation)
  dreq / dfall  the data at the request's rise / at its fall (x shown as x)
Each net is watched at its DRIVER pin in the netlist decoded from the bitstream (nets.map, as gen_runt_mon.py does); a
data bit with no placed driver (a constant) is left out and listed in OUT.v.  Subagent divsize, 2026-11-19."""
import json, os, re, sys


def main():
    rj, nmap, out = sys.argv[1:4]
    UNIT = os.environ.get("SETTLE_UNIT", "bridge_i.udut.udivui0")
    START = UNIT + ".joined"
    REQ = os.environ.get("SETTLE_REQ", "")
    DATA = os.environ.get("SETTLE_DATA", "bridge_i.o_data_pl")
    m = list(json.load(open(rj))["modules"].values())[0]
    nets, cells = m["netnames"], m["cells"]
    drv = {}
    for cn, c in cells.items():
        bel = c["attributes"].get("NEXTPNR_BEL")
        for p, d in c.get("port_directions", {}).items():
            for b in c["connections"].get(p, []):
                if isinstance(b, int) and d == "output" and bel:
                    drv[b] = "%s/%s" % (bel, p)
    by_pin = {}
    for line in open(nmap):
        if line.startswith("#"):
            continue
        w, _, n = line.strip().partition(" ")
        by_pin.setdefault(n, w)

    def wire(net):
        if net not in nets:
            return None, "no net %s" % net
        b = nets[net]["bits"][0]
        if not isinstance(b, int) or b not in drv:
            return None, "no placed driver (%s)" % b
        if drv[b] not in by_pin:
            sys.exit("gen_settle_mon: %s -> %s not in %s" % (net, drv[b], nmap))
        return by_pin[drv[b]], drv[b]
    ws, why = wire(START)
    if REQ:
        wr, whyr = wire(REQ)
    else:                     # the tail: the last link of the unit's request line
        links = sorted((int(mm.group(1)), cn) for cn in cells
                       for mm in [re.match(re.escape(UNIT) + r"\.udly\.chain\.g\[(\d+)\]\.u$", cn)] if mm)
        if not links:
            sys.exit("gen_settle_mon: no %s.udly.chain.g[N].u in %s" % (UNIT, rj))
        REQ = links[-1][1]
        b = cells[REQ]["connections"]["O6"][0]
        wr, whyr = (by_pin.get(drv.get(b)), drv.get(b)) if b in drv else (None, "no placed driver")
    if ws is None or wr is None:
        sys.exit("gen_settle_mon: start %s: %s; request %s: %s" % (START, why, REQ, whyr))
    bits = sorted((int(mm.group(1)), n) for n in nets for mm in [re.match(re.escape(DATA) + r"\[(\d+)\]$", n)] if mm)
    W = (bits[-1][0] + 1) if bits else 0
    data, skipped = {}, []
    for k, n in bits:
        w, why = wire(n)
        if w is None:
            skipped.append("%d (%s)" % (k, why))
        else:
            data[k] = (w, why)
    if not data:
        sys.exit("gen_settle_mon: no data bit of %s has a placed driver" % DATA)
    L = ["// GENERATED by research/tools/suite/gen_settle_mon.py for one route -- do not check in.",
         "// start %s at %s; request %s at %s; %d data bits watched, constant: %s"
         % (START, ws, REQ, wr, len(data), ", ".join(skipped) or "none"),
         "`timescale 1ps/1ps",
         "module settle_mon;",
         "    wire st = tb_ps.dut.%s;" % ws,
         "    wire rq = tb_ps.dut.%s;" % wr,
         "    wire [%d:0] d;" % (W - 1)]
    for k in range(W):
        L.append("    assign d[%d] = %s;" % (k, ("tb_ps.dut.%s" % data[k][0]) if k in data else "1'b0"))
    L += ["    time t0, tr, tl;",
          "    integer n;",
          "    reg [%d:0] dq;" % (W - 1),
          "    initial begin n = 0; t0 = 0; tr = 0; tl = 0; dq = 0; end",
          "    always @(posedge st) begin t0 = $time; tl = $time; end",
          "    always @(d) if ($time > 0) tl = $time;",
          "    always @(posedge rq) begin tr = $time; dq = d; end",
          "    always @(negedge rq) if ($time > 0) begin",
          '        $display("SETTLE n=%0d t0=%0t req=%0d last=%0d late=%0d dreq=%h dfall=%h", n, t0, tr - t0, tl - t0,',
          "                 $signed(tl - tr), dq, d);",
          "        n = n + 1;",
          "    end",
          "endmodule"]
    open(out, "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
