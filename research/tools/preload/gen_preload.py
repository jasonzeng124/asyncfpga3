#!/usr/bin/env python3
"""gen_preload.py -- opt-in loop-state preload for xorshift's bench GLS (research/data/preload/README.md).

    PS_MON_GEN=research/tools/preload/gen_preload.py  (build_ps.sh calls: gen_preload.py ROUTED_JSON nets.map mon_gen.v)
    then run with  +PRELOAD=<hex file: "i0 n" per batch, 2 words per line, as +VECFILE>

Writes a module `preload_mon` compiled into run_baked.vvp beside the netlist decoded from the bits. Without +PRELOAD it
does nothing at all (no force is ever executed); without PS_MON_GEN it is not compiled (build_ps.sh unchanged).

What it preloads.  The kernel (research/data/fifteen/xorshift_predec.mlir) is a do-while over (i, x, n = rounds - 1). The
loop's entry values sit in two bundled-data pipes whose last-stage LUT latches hold them for umux0 / umux2:
    i: bridge_i.udut.n6_data[31:0]              (ulink_n6's output latch; its D is the constant 0: `int i = 0`)
    n: bridge_i.udut.n_trueResult_2_data[31:0]  (ulink_n_trueResult_2's output latch; D = rounds - 1 from the bench)
For each of those 64 latch nodes the module finds the net that the LUT latch DRIVES in the netlist decoded from the
bitstream (nets.map: BEL/pin -> netlist wire; the same lookup as cells/gls/ps/gen_bench_mon.py) and forces it, for the
whole batch, to bit k of i0 / n of the current batch (re-forced when the PS7 model's batch index changes, i.e. while the
bench is idle between batches). The force sits on the latch's output net, upstream of every routed interconnect arc
(GLS_TRANSPORT_IC ICBUFs) to umux0 / umux2's LUTs and of the latch's own feedback pin, so every consumer of the latch
sees the preloaded value through its own routed delay, and the latch's internal state is never read by anything else.
The entry value is static during a call exactly as the constant 0 is in the unforced design, so the first iteration's
timing class is unchanged; every later iteration's i and n are the loop's own, carried through the real latches,
adder (UADDI0) and compare with their routed delays. Bits are checked after each re-force (PRELOAD ... readback).
"""
import json, re, sys


def main():
    rj, nmap, out = sys.argv[1:4]
    m = list(json.load(open(rj))["modules"].values())[0]
    nets, cells = m["netnames"], m["cells"]
    drv = {}
    for c in cells.values():
        bel = c["attributes"].get("NEXTPNR_BEL")
        for p, d in c.get("port_directions", {}).items():
            if d == "output" and bel:
                for b in c["connections"][p]:
                    drv[b] = (bel, p, c["type"])
    by_pin = {}
    for line in open(nmap):
        if line.startswith("#"):
            continue
        w, _, n = line.strip().partition(" ")
        by_pin.setdefault(n, w)

    def wire(name):
        if name not in nets:
            sys.exit("gen_preload: no net %r in %s" % (name, rj))
        b = nets[name]["bits"][0]
        if b not in drv:
            sys.exit("gen_preload: net %r has no placed driver (constant?)" % name)
        bel, port, typ = drv[b]
        pin = bel + "/" + port
        if pin not in by_pin:
            sys.exit("gen_preload: %r -> %s not in %s" % (name, pin, nmap))
        if typ != "SLICE_LUTX":
            sys.exit("gen_preload: %r is driven by a %s, not a LUT latch" % (name, typ))
        return "tb_ps.dut." + by_pin[pin], pin

    # the PS7 model's instance in the decoded netlist (its batch loop index j selects the preload row)
    ps7 = None
    for f in ("netlist_baked.v", "netlist.v"):
        try:
            for line in open(f):
                mm = re.match(r"\s*PS7_PS7\s+(?:#\(.*?\)\s*)?(\S+)", line)
                if mm:
                    ps7 = mm.group(1)
                    break
        except OSError:
            continue
        if ps7:
            break
    if not ps7:
        sys.exit("gen_preload: no PS7_PS7 instance in netlist_baked.v / netlist.v")
    ps7 = ps7 if not ps7.startswith("\\") else ps7 + " "

    I = [wire("bridge_i.udut.n6_data[%d]" % k) for k in range(32)]
    N = [wire("bridge_i.udut.n_trueResult_2_data[%d]" % k) for k in range(32)]
    L = ["// GENERATED by research/tools/preload/gen_preload.py for one route -- do not check in."]
    L += ["// i[%d] = %s" % (k, p) for k, (_, p) in enumerate(I)]
    L += ["// n[%d] = %s" % (k, p) for k, (_, p) in enumerate(N)]
    L += ["`timescale 1ps/1ps", "module preload_mon;", "    reg [31:0] pmem [0:511];", "    reg [1023:0] pf;",
          "    reg [31:0] pi, pn, ri, rn;", "    integer on, jb, k;",
          "    wire [31:0] jj = tb_ps.dut.%s.j;" % ps7]
    L += ["    task reforce; begin"]
    L += ["        force %s = pi[%d];" % (w, k) for k, (w, _) in enumerate(I)]
    L += ["        force %s = pn[%d];" % (w, k) for k, (w, _) in enumerate(N)]
    L += ["    end endtask"]
    L += ["    task readback; begin"]
    L += ["        ri[%d] = %s;" % (k, w) for k, (w, _) in enumerate(I)]
    L += ["        rn[%d] = %s;" % (k, w) for k, (w, _) in enumerate(N)]
    L += ["    end endtask"]
    L += ["""    task load(input integer b); begin
        jb = b; pi = pmem[2 * b]; pn = pmem[2 * b + 1];
        if (^pi === 1'bx || ^pn === 1'bx) begin   // past the last vector (the model's loop exit): keep the forces
            $display("PRELOAD batch=%0d: no row (end of run), forces kept", b); pi = ri; pn = rn;
        end
        reforce; #1 readback;
        $display("PRELOAD batch=%0d i0=%08h n=%08h readback i0=%08h n=%08h %0s t=%0t", b, pi, pn, ri, rn,
                 (ri === pi && rn === pn) ? "OK" : "BAD", $time);
        if (ri !== pi || rn !== pn) $finish;
    end endtask
    initial begin
        on = 0;
        for (k = 0; k < 512; k = k + 1) pmem[k] = 32'hxxxxxxxx;
        if ($value$plusargs("PRELOAD=%s", pf)) begin
            $readmemh(pf, pmem); on = 1;
            #2 load(0);               // from t = 2 ps: before the kernel's reset is released (>= 16 aclk later)
        end
    end
    // the PS7 model increments j after a batch's BENCHRES and its closing write, i.e. with the bench idle
    always @(jj) if (on && $time > 2 && jj !== jb && jj >= 0 && jj < 256) load(jj);
endmodule"""]
    open(out, "w").write("\n".join(L) + "\n")
    print("preload monitor: i <- %s .. %s; n <- %s .. %s; ps7 %s -> %s" % (I[0][1], I[31][1], N[0][1], N[31][1], ps7, out))


if __name__ == "__main__":
    main()
