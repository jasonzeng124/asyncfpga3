#!/usr/bin/env python3
"""lat_mon.py ROUTED_JSON NETS_MAP OUT.v -- a per-call latency monitor in picoseconds for a gen_bench.py bench build,
for build_ps.sh's PS_MON_GEN hook (run1.sh sets it with LATMON=1).

WHY.  The bench counts a call's latency in aclk cycles (10 ns at 100 MHz), so two simulations whose kernels differ by
less than a cycle print the same latmin.  This monitor prints, at every rise of the kernel's out0 request, the time
since the last rise of the kernel's input request, in ps:

  LATMON n=<call> lat_ps=<out0_req rise - in_req rise> t=<ps>

The input request is the bench's req_core flip-flop (gen_bench.py: i_req_pl = req_core, set on an aclk edge, cleared by
i_ack_pl): found as the SLICE_FFX whose D net is bridge_i's $0\\req_core[0:0]; out0's request is core_o_req.  Both are
taken at their DRIVER pins in the netlist decoded from the bits (fasm2net names nets <site>/<bel>/<pin>), so the
FF's own clock-to-Q is outside the measured span and the routing out of the FF is inside it.  A net that cannot be
found is an error, not a silent omission."""
import json, sys


def main():
    rj, nmap, out = sys.argv[1:4]
    m = list(json.load(open(rj))["modules"].values())[0]
    nets, cells = m["netnames"], m["cells"]
    drv = {}
    for c in cells.values():
        bel = c["attributes"].get("NEXTPNR_BEL")
        for p, d in c.get("port_directions", {}).items():
            if d == "output" and bel:
                for b in c["connections"][p]:
                    drv[b] = (bel, p)
    by_pin = {}
    for line in open(nmap):
        if line.startswith("#"):
            continue
        w, _, n = line.strip().partition(" ")
        by_pin.setdefault(n, w)

    def wire_of_bit(b, what):
        if b not in drv:
            sys.exit("lat_mon: %s has no placed driver" % what)
        bel, port = drv[b]
        pin = bel + "/" + port
        if pin not in by_pin:
            sys.exit("lat_mon: %s -> %s not in %s" % (what, pin, nmap))
        return "tb_ps.dut." + by_pin[pin], pin

    dnets = [k for k in nets if k.endswith("bridge_i.$0\\req_core[0:0]")]
    if len(dnets) != 1:
        sys.exit("lat_mon: expected one bridge_i $0\\req_core net, found %r" % dnets)
    db = nets[dnets[0]]["bits"][0]
    ffs = [c for c in cells.values() if c["type"] == "SLICE_FFX" and c["connections"].get("D") == [db]]
    if len(ffs) != 1:
        sys.exit("lat_mon: expected one SLICE_FFX on %s, found %d" % (dnets[0], len(ffs)))
    ireq, ipin = wire_of_bit(ffs[0]["connections"]["Q"][0], "req_core Q")
    if "core_o_req" not in nets:
        sys.exit("lat_mon: no net core_o_req")
    oreq, opin = wire_of_bit(nets["core_o_req"]["bits"][0], "core_o_req")
    L = ["// GENERATED by research/data/bandfit/lat_mon.py for one route -- do not check in.",
         "// in_req = req_core Q @ %s; out0_req = core_o_req @ %s" % (ipin, opin),
         "`timescale 1ps/1ps",
         "module lat_mon;",
         "    wire ireq = %s;" % ireq,
         "    wire oreq = %s;" % oreq,
         "    time t_i = 0;",
         "    integer n = 0;",
         "    always @(posedge ireq) t_i = $time;",
         "    always @(posedge oreq) begin",
         "        n = n + 1;",
         "        $display(\"LATMON n=%0d lat_ps=%0d t=%0t\", n, $time - t_i, $time);",
         "    end",
         "endmodule"]
    open(out, "w").write("\n".join(L) + "\n")
    print("lat_mon: in_req %s, out0_req %s -> %s" % (ipin, opin, out))


if __name__ == "__main__":
    main()
