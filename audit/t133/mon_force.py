#!/usr/bin/env python3
"""T133b (audit, own code): PS_MON_GEN hook = t131/mon_x.py plus a defined start-up emulation for named pin wires:
env FORCE_NETS = comma list of wires, FORCE_VAL = 0|1, FORCE_UNTIL = ps. From t = 0 each wire is forced to FORCE_VAL and
released at FORCE_UNTIL (after the injected-late real value has arrived). This stands in for META_INIT for the injected pin
only: the pin holds a defined (stale) value instead of X while its delayed driver catches up."""
import os, sys, subprocess
rj, nmap, out = sys.argv[1:4]
H = os.path.dirname(os.path.abspath(__file__))
subprocess.run([sys.executable, '-I', os.path.join(H, '..', 't131', 'mon_x.py'), rj, nmap, out + '.x'], check=True)
nets = [n for n in os.environ['FORCE_NETS'].split(',') if n]; v = os.environ.get('FORCE_VAL', '0'); u = os.environ['FORCE_UNTIL']
L = ["// GENERATED by audit/t133/mon_force.py", "`timescale 1ps/1ps", "module force_mon;", "    initial begin"]
L += [f"        force tb_ps.dut.{n} = 1'b{v};" for n in nets]
L += [f"        #{u};"] + [f"        release tb_ps.dut.{n};" for n in nets] + ['        $display("FORCE released at %0t", $time);', "    end", "endmodule"]
open(out, 'w').write(open(out + '.x').read() + "\n" + "\n".join(L) + "\n")
print(f"mon_force: {len(nets)} nets forced to {v} until {u}", file=sys.stderr)
