#!/usr/bin/env python3
"""T94 (audit, own code): value tracer (PS_MON_GEN hook). env TRACE = "bus:width:reqnet,..." (kernel-local names, e.g.
n27_data:32:n27_req). At every edge of the request net (at its driver) prints the bus value read at the bus's drivers, and
again 2 ns later. env TRACE_T0/TRACE_T1 (ps) bound the window. Writes the monitor module to argv[3]."""
import json, re, sys, os, collections
rj, nmap, out = sys.argv[1:4]
m = list(json.load(open(rj))["modules"].values())[0]
wire_of_name = {}
for l in open(nmap):
    if l.startswith('#'): continue
    w, _, n = l.strip().partition(' '); wire_of_name.setdefault(n, w)
def wire(n):
    if n.startswith('bridge_i.'): return wire_of_name.get(n)
    w = wire_of_name.get('bridge_i.udut.' + n)
    if w: return w
    nn = m['netnames'].get('bridge_i.udut.' + n)
    if nn:
        for k, v in m['netnames'].items():
            if v['bits'] == nn['bits'] and k in wire_of_name: return wire_of_name[k]
    return None
t0, t1 = int(os.environ.get('TRACE_T0', 0)), int(os.environ.get('TRACE_T1', 10**12))
L = ["// GENERATED by audit/t94/mon_val.py", "`timescale 1ps/1ps", "module val_mon;"]
miss = []
for i, spec in enumerate(os.environ['TRACE'].split(',')):
    bus, wd, rq = spec.split(':'); wd = int(wd)
    rw = wire(rq)
    bits = [wire(f"{bus}[{k}]") if wd > 1 or wire(f"{bus}[0]") else wire(bus) for k in range(wd)]
    if not rw or any(b is None for b in bits): miss.append((spec, rw, sum(b is None for b in bits))); continue
    cat = "{" + ", ".join(f"tb_ps.dut.{b}" for b in reversed(bits)) + "}"
    L.append(f"    always @(tb_ps.dut.{rw}) if ($time >= {t0} && $time <= {t1}) begin"
             f" $display(\"VAL t=%0t {rq}=%b {bus}=%h\", $time, tb_ps.dut.{rw}, {cat});"
             f" #2000 $display(\"VAL t=%0t {rq}+2ns {bus}=%h\", $time, {cat}); end")
for e in [x for x in os.environ.get('TRACE_EDGES', '').split(',') if x]:
    w = wire(e)
    if not w: miss.append((e, None, 1)); continue
    L.append(f"    always @(tb_ps.dut.{w}) if ($time >= {t0} && $time <= {t1}) $display(\"EDGE t=%0t {e}=%b\", $time, tb_ps.dut.{w});")
L += ["endmodule"]
open(out, 'w').write("\n".join(L) + "\n")
print(f"mon_val: missing {miss}", file=sys.stderr)
