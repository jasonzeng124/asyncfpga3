#!/usr/bin/env python3
"""T116b (audit, own code): PS_MON_GEN hook. For bd_mux instances umux0 / umux2 (MON_MUXES), classify every select change
seen at the data-mux LUT select PINS (after interconnect) by the state of the mux's z_req and z_ack at their drivers:
  A: z_req=1 and z_ack=0 -- the request stands and not every consumer has acknowledged: a real arrival/hold hazard;
  B: z_req=1 and z_ack=1 -- after every consumer captured (4-phase: data may change once ack is up): benign;
  C: z_req=0 -- outside the request.
Pin changes within 3 ns of each other are one EVENT (one select transition fans out to 32 pins); counts are per event.
Reuses t83/mon_mux.py's pin discovery by importing its generated text (z_req net and select pins)."""
import json, re, sys, os, subprocess
rj, nmap, out = sys.argv[1:4]
d = os.path.dirname(os.path.abspath(__file__))
tmp = out + ".mux"
subprocess.run([sys.executable, "-I", os.path.join(d, "..", "t83", "mon_mux.py"), rj, nmap, tmp], check=True)
txt = open(tmp).read()
ker = open(os.environ["MON_KERNEL"]).read()
wire_of = {}
for l in open(nmap):
    if l.startswith('#'): continue
    w, _, n = l.strip().partition(' '); wire_of.setdefault(n, w)
L = ["// GENERATED by audit/t116/mon_sel.py", "`timescale 1ps/1ps", "module sel_mon;"]
disp = []
for mux in os.environ.get("MON_MUXES", "umux0,umux2").split(","):
    mm = re.search(r'// %s: z_req (\w+), \d+ select pins' % mux, txt)
    if not mm: continue
    zreq = mm[1]
    pins = re.findall(r'always @\(tb_ps\.dut\.(\w+)\) begin ts\d+_\d+ = \$time; if \(tb_ps\.dut\.%s ' % zreq, txt)
    zk = re.search(r'%s\s*\(.*?\.z_ack\((\w+)\)' % mux, ker, re.S)[1]
    ov = dict(x.split('=') for x in os.environ.get('ZACKS', '').split(',') if '=' in x)
    zack = wire_of.get(ov[mux]) if mux in ov else wire_of.get('bridge_i.udut.' + zk)
    if not zack:
        mj = list(json.load(open(rj))["modules"].values())[0]
        bits = mj['netnames'].get('bridge_i.udut.' + zk, {}).get('bits')
        for k, v in mj['netnames'].items():
            if v['bits'] == bits and k in wire_of: zack = wire_of[k]; break
    if not zack: print(f"mon_sel: no z_ack wire for {mux}", file=sys.stderr); continue
    t = mux
    L.append(f"    // {mux}: z_req {zreq}, z_ack {zack} ({zk}), {len(pins)} pins")
    L.append(f"    time last_{t} = 0, tzr_{t} = 0, tev_{t} = 0; integer nA_{t} = 0, nB_{t} = 0, nC_{t} = 0, nlate_{t} = 0, maxlate_{t} = 0, latepins_{t} = 0, lateev_{t} = 0; reg evlate_{t} = 0;")
    L.append(f"    always @(posedge tb_ps.dut.{zreq}) tzr_{t} = $time;")
    for p in pins:
        L.append(f"    always @(tb_ps.dut.{p}) begin if ($time > last_{t} + 3000 || last_{t} == 0) begin tev_{t} = $time; evlate_{t} = 0; end"
                 f" if (tzr_{t} > tev_{t} && tb_ps.dut.{zreq} === 1'b1) begin latepins_{t} = latepins_{t} + 1; if (!evlate_{t}) begin evlate_{t} = 1; lateev_{t} = lateev_{t} + 1; end"
                 f" if ($time - tzr_{t} > maxlate_{t}) maxlate_{t} = $time - tzr_{t}; end end")
        L.append(f"    always @(tb_ps.dut.{p}) if ($time > last_{t} + 3000 || last_{t} == 0) begin last_{t} = $time;"
                 f" if (tb_ps.dut.{zreq} === 1'b1 && tb_ps.dut.{zack} !== 1'b1) begin nA_{t} = nA_{t} + 1; if (nA_{t} <= 5) $display(\"SELMON A t=%0t {mux} select moved, z_req=1 z_ack=0\", $time); end"
                 f" else if (tb_ps.dut.{zreq} === 1'b1) nB_{t} = nB_{t} + 1; else nC_{t} = nC_{t} + 1; end")
    disp.append(f'$display("SELMON t=%0t {mux} events: A(req=1,ack=0)=%0d B(req=1,ack=1)=%0d C(req=0)=%0d; events whose pins change AFTER z_req rose: %0d (pins %0d), max lateness %0d ps", $time, nA_{t}, nB_{t}, nC_{t}, lateev_{t}, latepins_{t}, maxlate_{t});')
L.append("    initial forever begin #5000000; " + " ".join(disp) + " end")
L.append("endmodule")
open(out, "w").write("\n".join(L) + "\n")
