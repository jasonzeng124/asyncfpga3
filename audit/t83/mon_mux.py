#!/usr/bin/env python3
"""T83 (audit, own code): bd_mux select monitor (PS_MON_GEN hook; env MON_KERNEL = the kernel Verilog of the build).
For each bd_mux instance umuxN: its data-mux LUTs ('umuxN.udat.pair[i].u$LUT6/5'); the select s = the one non-constant input
net every such LUT shares; z_req = the net on the instance's .z_req port (kernel text).  Monitors, at each data-mux LUT's s pin
after interconnect delay: s changes while z_req (at its driver) is 1 -> violation (the mux output data would change while its
request stands); and rise margin = t(z_req rise) - t(last s change at that pin)."""
import json, re, sys, os, collections
rj, nmap, out = sys.argv[1:4]
ker = open(os.environ["MON_KERNEL"]).read()
zreq = {m[1]: m[2] for m in re.finditer(r'bd_mux\s*#\(.*?\)\s*(umux\d+)\s*\(.*?\.z_req\((\w+)\)', ker, re.S)}
m = list(json.load(open(rj))["modules"].values())[0]
names_of_bit = collections.defaultdict(set)
for n, v in m["netnames"].items():
    for b in v["bits"]: names_of_bit[b].add(n)
wire_of_name = {}
for l in open(nmap):
    if l.startswith('#'): continue
    w, _, n = l.strip().partition(' '); wire_of_name.setdefault(n, w)
site_of_c = {}
for l in open('names.map'):
    if l.startswith('#'): continue
    c, s = l.split(None, 1); site_of_c[s.strip()] = c
inst_pins, ic_src = {}, {}
for l in open('netlist_baked.v'):
    mm = re.match(r'\s*ICBUF #\(\.D\(\d+\)\) \S+ \(\.I\((\w+)\), \.O\((\w+)\)\);', l)
    if mm: ic_src[mm[2]] = mm[1]; continue
    mm = re.match(r'\s*SLICE_LUTX #\(.*\) (c_\d+) \((.*)\);', l)
    if mm: inst_pins[mm[1]] = dict(re.findall(r'\.(\w+)\((\w+)\)', mm[2]))
def wire_of_bit(b):
    for n in names_of_bit[b]:
        if n in wire_of_name: return wire_of_name[n]
luts = collections.defaultdict(list)
for cn, c in m["cells"].items():
    mm = re.match(r'bridge_i\.udut\.(umux\d+)\.udat\..*\.u(\$LUT6|\$LUT5)?$', cn)
    if not mm: continue
    dirs = c.get("port_directions", {})
    ins = {b for p, bb in c["connections"].items() if dirs.get(p) == "input" for b in bb if isinstance(b, int)
           and not any(n.startswith('$PACKER') for n in names_of_bit[b])}
    luts[mm[1]].append((c["attributes"].get("NEXTPNR_BEL"), ins))
mons, miss = [], []
for mux, lst in luts.items():
    sh = set.intersection(*(i for _, i in lst)) if len(lst) > 1 else set()
    if len(sh) != 1 or mux not in zreq: miss.append(mux); continue
    sw = wire_of_bit(sh.pop()); zw = wire_of_name.get('bridge_i.udut.' + zreq[mux])
    if not zw and ('bridge_i.udut.' + zreq[mux]) not in m['netnames']:   # DELAY 0: z_req is the bypassed 'either'
        eb = m['netnames'].get('bridge_i.udut.' + mux + '.either'); zw = wire_of_bit(eb['bits'][0]) if eb else None
    if not zw: miss.append(mux + ':zreq'); continue
    pins = []
    for bel, _ in lst:
        p = inst_pins.get(site_of_c.get(bel, ''), {})
        pins += [p[k] for k in p if k.startswith('A') and ic_src.get(p[k]) == sw]
    if pins: mons.append((mux, zw, sorted(set(pins))))
L = ["// GENERATED by audit/t83/mon_mux.py (audit)", "`timescale 1ps/1ps", "module mux_mon;"]
for i, (mux, zw, pins) in enumerate(mons):
    L.append(f"    // {mux}: z_req {zw}, {len(pins)} select pins")
    L.append(f"    time mr{i} = 64'd999999999; integer nv{i} = 0, nr{i} = 0; reg pz{i} = 0;")
    for k, p in enumerate(pins):
        L.append(f"    time ts{i}_{k} = 0; always @(tb_ps.dut.{p}) begin ts{i}_{k} = $time; if (tb_ps.dut.{zw} === 1'b1) begin nv{i} = nv{i} + 1;"
                 f" if (nv{i} <= 3) $display(\"MUXMON VIOLATION t=%0t {mux} select changed while z_req=1\", $time); end end")
    mx = " ".join(f"if ($time - ts{i}_{k} < mr{i}) mr{i} = $time - ts{i}_{k};" for k in range(len(pins)))
    L.append(f"    always @(tb_ps.dut.{zw}) begin if (tb_ps.dut.{zw} === 1'b1 && pz{i} === 1'b0) begin nr{i} = nr{i} + 1; {mx} end pz{i} = tb_ps.dut.{zw}; end")
L.append("    initial forever begin #5000000;")
for i, (mux, *_r) in enumerate(mons):
    L.append(f'        $display("MUXMON t=%0t {mux} rises=%0d min_sel_to_zreq_ps=%0d violations=%0d", $time, nr{i}, mr{i}, nv{i});')
L += ["    end", "endmodule"]
open(out, 'w').write("\n".join(L) + "\n")
print(f"mon_mux: {len(mons)} muxes mapped ({sum(len(p) for *_x, p in mons)} select pins), not: {miss}", file=sys.stderr)
