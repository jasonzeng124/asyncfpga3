#!/usr/bin/env python3
"""T83 (audit, own code): latch setup/hold monitor for a bits-decoded bench netlist.
Called by cells/gls/ps/build_ps.sh as PS_MON_GEN: mon_latch.py ROUTED_JSON nets.map OUT.v (cwd = the GLS work dir, where
gen.py already wrote netlist_baked.v and names.map).  For every bd_latch LUT of the kernel (routed-JSON cells named
'*.lat.pair[*].u$LUT6/$LUT5' or '*.lat.odd.u...'), finds its physical site, the LUT instance in netlist_baked.v, and
which of its A1..A6 pins (after the per-sink ICBUF interconnect delay) carry the enable and the data bits, by matching the
ICBUF's source net against the JSON nets of the cell's logical I1 (en) and I0/I3 (d).  The monitor records, for every
closing edge of en (1 -> 0): setup = time since the last change of each data pin; and the first data change after a
closing edge within 2 ns: hold.  Per latch INSTANCE (the link/stage), it prints min setup, min hold, and counts."""
import json, re, sys, collections
rj, nmap, out = sys.argv[1:4]
m = list(json.load(open(rj))["modules"].values())[0]
names_of_bit = collections.defaultdict(set)
for n, v in m["netnames"].items():
    for b in v["bits"]:
        names_of_bit[b].add(n)
wire_of_name = {}
names_of_wire = collections.defaultdict(set)
for l in open(nmap):
    if l.startswith('#'): continue
    w, _, n = l.strip().partition(' ')
    wire_of_name.setdefault(n, w); names_of_wire[w].add(n)
site_of_c = {}
for l in open('names.map'):
    if l.startswith('#'): continue
    c, s = l.split(None, 1); site_of_c[s.strip()] = c
inst_pins, ic_src = {}, {}
for l in open('netlist_baked.v'):
    mm = re.match(r'\s*ICBUF #\(\.D\(\d+\)\) \S+ \(\.I\((\w+)\), \.O\((\w+)\)\);', l)
    if mm: ic_src[mm[2]] = mm[1]; continue
    mm = re.match(r'\s*SLICE_LUTX #\(.*\) (c_\d+) \((.*)\);', l)
    if mm: inst_pins[mm[1]] = dict(re.findall(r'\.(\w+)\((\w+)\)', mm[2]))
def wire_of_bit(b):
    for n in names_of_bit[b]:
        if n in wire_of_name: return wire_of_name[n]
    return None
groups = collections.defaultdict(list)   # latch instance -> [(en_pin_wire, [d_pin_wires])]
miss = 0
luts = collections.defaultdict(list)     # instance -> [(bel, input bits, output bits)]
for cn, c in m["cells"].items():
    mm = re.match(r'(bridge_i\.udut\..*)\.lat\.(pair\[\d+\]|odd)\.u(\$LUT6|\$LUT5)?$', cn)
    if not mm: continue
    cc = c["connections"]; dirs = c.get("port_directions", {})
    ins = {b for p, bb in cc.items() if dirs.get(p) == "input" for b in bb if isinstance(b, int)}
    outs = {b for p, bb in cc.items() if dirs.get(p) == "output" for b in bb if isinstance(b, int)}
    luts[mm[1]].append((c["attributes"].get("NEXTPNR_BEL"), ins, outs))
for inst, lst in luts.items():
    allouts = set().union(*(o for _, _, o in lst))
    cand = [ins - allouts - {b for b in ins if any(n.startswith('$PACKER') for n in names_of_bit[b])} for _, ins, _ in lst]
    shared = set.intersection(*cand) if len(cand) > 1 else set()
    if len(shared) != 1: miss += len(lst); continue
    en_b = shared.pop(); en_w = wire_of_bit(en_b)
    for (bel, ins, outs), cs in zip(lst, cand):
        d_ws = {wire_of_bit(b) for b in cs - {en_b}}
        if not bel or bel not in site_of_c or site_of_c[bel] not in inst_pins: miss += 1; continue
        pins = inst_pins[site_of_c[bel]]
        src = {p: ic_src.get(w) for p, w in pins.items() if p.startswith('A')}
        en_p = [pins[p] for p, s_ in src.items() if s_ == en_w]
        d_p = [pins[p] for p, s_ in src.items() if s_ in d_ws]
        if not en_p or not d_p: miss += 1; continue
        groups[inst].append((en_p[0], d_p))
L = ["// GENERATED by audit/t83/mon_latch.py -- latch setup/hold monitor (audit)", "`timescale 1ps/1ps", "module latch_mon;"]
gi = 0
for inst, lst in sorted(groups.items()):
    L.append(f"    // {inst}: {len(lst)} latch LUT(s)")
    L.append(f"    time ms{gi} = 64'd999999999; time mh{gi} = 64'd999999999; integer nc{gi} = 0;")
    for k, (en, ds) in enumerate(lst):
        t = f"g{gi}_{k}"
        L.append(f"    time td_{t} = 0; time tc_{t} = 0; reg pe_{t} = 0;")
        L.append(f"    always @({' or '.join('tb_ps.dut.'+d for d in ds)}) begin td_{t} = $time;"
                 f" if ($time > tc_{t} && $time - tc_{t} < 2000 && tc_{t} > 0 && $time - tc_{t} < mh{gi}) mh{gi} = $time - tc_{t}; end")
        L.append(f"    always @(tb_ps.dut.{en}) begin if (tb_ps.dut.{en} === 1'b0 && pe_{t} === 1'b1) begin"
                 f" tc_{t} = $time; nc{gi} = nc{gi} + 1; if ($time - td_{t} < ms{gi}) ms{gi} = $time - td_{t}; end pe_{t} = tb_ps.dut.{en}; end")
    gi += 1
L.append("    initial forever begin #50000000;")
for i, inst in enumerate(sorted(groups)):
    L.append(f'        $display("LATCHMON t=%0t {inst} captures=%0d min_setup_ps=%0d min_hold_ps=%0d", $time, nc{i}, ms{i}, mh{i});')
L.append("    end")
L.append("endmodule")
open(out, 'w').write("\n".join(L) + "\n")
print(f"mon_latch: {sum(len(v) for v in groups.values())} latch LUTs in {len(groups)} instances, {miss} not mapped", file=sys.stderr)
