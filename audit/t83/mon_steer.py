#!/usr/bin/env python3
"""T83 (audit, own code): steer-select monitor (PS_MON_GEN hook, as mon_latch.py).  bd_steer is combinational
(req0 = req.~s, req1 = req.s), so its select s must settle before req rises and must not change while req is high.
For every bd_steer LUT of the kernel (routed-JSON cells '<inst>.u' / '<inst>.u$LUT6/5' whose inputs include the net
'<inst>_req'), at the LUT's own pins after interconnect delay: rise margin = t(req rise) - t(last s change); and every s
change while req is 1 (a violation: a runt on the other branch).  Also writes the same for every 1-bit and 32-bit bd_mux
select is NOT covered here.  Per steer: min rise margin, violations, rises."""
import json, re, sys, collections
rj, nmap, out = sys.argv[1:4]
m = list(json.load(open(rj))["modules"].values())[0]
names_of_bit = collections.defaultdict(set)
for n, v in m["netnames"].items():
    for b in v["bits"]: names_of_bit[b].add(n)
wire_of_name = {}
for l in open(nmap):
    if l.startswith('#'): continue
    w, _, n = l.strip().partition(' '); wire_of_name.setdefault(n, w)
site_of_c = {}
for l in open('names.map'):
    if l.startswith('#'): continue
    c, s = l.split(None, 1); site_of_c[s.strip()] = c
inst_pins, ic_src = {}, {}
for l in open('netlist_baked.v'):
    mm = re.match(r'\s*ICBUF #\(\.D\(\d+\)\) \S+ \(\.I\((\w+)\), \.O\((\w+)\)\);', l)
    if mm: ic_src[mm[2]] = mm[1]; continue
    mm = re.match(r'\s*SLICE_LUTX #\(.*\) (c_\d+) \((.*)\);', l)
    if mm: inst_pins[mm[1]] = dict(re.findall(r'\.(\w+)\((\w+)\)', mm[2]))
def wire_of_bit(b):
    for n in names_of_bit[b]:
        if n in wire_of_name: return wire_of_name[n]
steers, miss = [], []
for cn, c in m["cells"].items():
    mm = re.match(r'(bridge_i\.udut\.(ucond_br\d+))\.u(\$LUT6|\$LUT5)?$', cn)
    if not mm: continue
    dirs = c.get("port_directions", {})
    ins = [b for p, bb in c["connections"].items() if dirs.get(p) == "input" for b in bb if isinstance(b, int)
           and not any(n.startswith('$PACKER') for n in names_of_bit[b])]
    req_b = [b for b in ins if any(n.endswith('.' + mm[2] + '_req') or n == mm[1] + '_req' for n in names_of_bit[b])]
    s_b = [b for b in ins if b not in req_b]
    bel = c["attributes"].get("NEXTPNR_BEL")
    if len(req_b) != 1 or len(s_b) != 1 or bel not in site_of_c: miss.append(cn); continue
    pins = inst_pins.get(site_of_c[bel], {})
    rw, sw = wire_of_bit(req_b[0]), wire_of_bit(s_b[0])
    rp = [pins[p] for p in pins if p.startswith('A') and ic_src.get(pins[p]) == rw]
    sp = [pins[p] for p in pins if p.startswith('A') and ic_src.get(pins[p]) == sw]
    if not rp or not sp: miss.append(cn); continue
    steers.append((cn, rp[0], sp[0], sorted(names_of_bit[s_b[0]])[0]))
L = ["// GENERATED by audit/t83/mon_steer.py (audit)", "`timescale 1ps/1ps", "module steer_mon;"]
for i, (cn, rp, sp, sn) in enumerate(steers):
    L += [f"    // {cn}: req pin {rp}, s pin {sp} ({sn})",
          f"    time ts{i} = 0; time mr{i} = 64'd999999999; integer nv{i} = 0, nr{i} = 0; reg pr{i} = 0;",
          f"    always @(tb_ps.dut.{sp}) begin ts{i} = $time; if (tb_ps.dut.{rp} === 1'b1) begin nv{i} = nv{i} + 1;"
          f" if (nv{i} <= 3) $display(\"STEERMON VIOLATION t=%0t {cn} s changed while req=1\", $time); end end",
          f"    always @(tb_ps.dut.{rp}) begin if (tb_ps.dut.{rp} === 1'b1 && pr{i} === 1'b0) begin nr{i} = nr{i} + 1;"
          f" if ($time - ts{i} < mr{i}) mr{i} = $time - ts{i}; end pr{i} = tb_ps.dut.{rp}; end"]
L.append("    initial forever begin #50000000;")
for i, (cn, *_r) in enumerate(steers):
    L.append(f'        $display("STEERMON t=%0t {cn} rises=%0d min_rise_margin_ps=%0d violations=%0d", $time, nr{i}, mr{i}, nv{i});')
L += ["    end", "endmodule"]
open(out, 'w').write("\n".join(L) + "\n")
print(f"mon_steer: {len(steers)} steers mapped, {len(miss)} not: {miss[:5]}", file=sys.stderr)
