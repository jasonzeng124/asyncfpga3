#!/usr/bin/env python3
"""T109 (audit, own code): PS_MON_GEN hook. Reads H_JSON (from t109/rule_h.py JSON=..., same route) and, for every row
with static margin < H_THRESH (default 500 ps), emits a monitor of:
  HDYN: per latch LUT, at every release (the controller node, at its driver, 1->0) arm; the first change of any of its
        D pins after the release (t_d) and the bit's own close (enable pin 1->0 after interconnect, t_c) give
        t_d - t_c: negative = data moved while this bit was still open after the release (rule H violated, as simulated);
        min over all releases = the dynamic rule H margin;
  HC:   the first state node on the static path (an upstream controller C-element): at every output change, which input
        pin changed last; counts of firings where the static path's entry pin was the last input (the OR-join
        assumption held) and, for the others, min wait = t(output change) - t(entry pin's last change)."""
import json, os, sys
rj, nmap, out = sys.argv[1:4]
J = json.load(open(os.environ['H_JSON'])); th = int(os.environ.get('H_THRESH', 500))
L = ["// GENERATED by audit/t109/mon_h.py", "`timescale 1ps/1ps", "module h_mon;"]
pins = {}
for l in open('netlist_baked.v'):
    import re
    mm = re.match(r'\s*SLICE_LUTX #\(.*\) (c_\d+) \((.*)\);', l)
    if mm: pins[mm[1]] = dict(re.findall(r'\.(\w+)\((\w+)\)', mm[2]))
disp = []
for i, r in enumerate(x for x in J if x['margin'] < th):
    tag = f"r{i}"
    L.append(f"    // {r['inst']} static {r['margin']}")
    L.append(f"    integer hm_{tag} = 999999999; integer hn_{tag} = 0;")
    st = r['start']
    for k, (c, enp, dps) in enumerate(r['latches']):
        en = pins[c][enp]; ds = [pins[c][p] for p in dps]; t = f"{tag}_{k}"
        L.append(f"    time tr_{t} = 0, td_{t} = 0, tc_{t} = 0; reg ad_{t} = 0, ac_{t} = 0;")
        L.append(f"    always @(negedge tb_ps.dut.{st}) begin ad_{t} = 1; ac_{t} = 1; end")
        L.append(f"    always @({' or '.join('tb_ps.dut.' + d for d in ds)}) if (ad_{t}) begin ad_{t} = 0; td_{t} = $time;"
                 f" if (!ac_{t}) begin if ($time - tc_{t} < hm_{tag}) hm_{tag} = $time - tc_{t}; end end")
        L.append(f"    always @(negedge tb_ps.dut.{en}) if (ac_{t}) begin ac_{t} = 0; tc_{t} = $time; hn_{tag} = hn_{tag} + 1;"
                 f" if (!ad_{t}) begin if (td_{t} - $time < hm_{tag}) hm_{tag} = td_{t} - $time; $display(\"HVIOL t=%0t {r['inst']} {c} D moved %0d ps before close\", $time, $time - td_{t}); end end")
    fs = r['first_state']
    if fs:
        c = fs['cell']; o = pins[c].get('O6') or pins[c].get('O5')
        ins = [p for p in fs['inputs']]
        L.append(f"    time te_{tag} = 0, tl_{tag} = 0; integer nl_{tag}[0:1]; integer nw_{tag}[0:1]; time mw_{tag}[0:1]; reg [7:0] lp_{tag};")
        L.append(f"    initial begin nl_{tag}[0]=0; nl_{tag}[1]=0; nw_{tag}[0]=0; nw_{tag}[1]=0; mw_{tag}[0]=64'd999999999; mw_{tag}[1]=64'd999999999; end")
        for p in ins:
            L.append(f"    always @(tb_ps.dut.{pins[c][p]}) begin tl_{tag} = $time; lp_{tag} = {int(p[1])};"
                     + (f" te_{tag} = $time;" if p == fs['entry'] else "") + " end")
        L.append(f"    always @(tb_ps.dut.{o}) if (tb_ps.dut.{o} !== 1'bx) begin if (lp_{tag} == {int(fs['entry'][1])}) nl_{tag}[tb_ps.dut.{o}] = nl_{tag}[tb_ps.dut.{o}] + 1;"
                 f" else begin nw_{tag}[tb_ps.dut.{o}] = nw_{tag}[tb_ps.dut.{o}] + 1; if ($time - te_{tag} < mw_{tag}[tb_ps.dut.{o}]) mw_{tag}[tb_ps.dut.{o}] = $time - te_{tag}; end end")
        disp.append(f'$display("HC t=%0t {r["inst"]} first_state={fs["logical"]} entry={fs["entry"]} rise: entry_last=%0d other_last=%0d min_wait_after_entry=%0d fall: entry_last=%0d other_last=%0d min_wait=%0d", $time, nl_{tag}[1], nw_{tag}[1], mw_{tag}[1], nl_{tag}[0], nw_{tag}[0], mw_{tag}[0]);')
    disp.append(f'$display("HDYN t=%0t {r["inst"]} static_ps={r["margin"]} closes=%0d min_D_after_release_minus_close_ps=%0d", $time, hn_{tag}, hm_{tag});')
L.append("    initial forever begin #5000000; " + " ".join(disp) + " end")
L.append("endmodule")
open(out, 'w').write("\n".join(L) + "\n")
print(f"mon_h: {sum(1 for x in J if x['margin'] < th)} rows", file=sys.stderr)
