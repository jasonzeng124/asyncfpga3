#!/usr/bin/env python3
# Resolve nets for the audit judge directly from nextpnr's routed JSON
# (gen.py names a net nNNN where NNN is the JSON bit number; verified for
# rig_lap=56021, hk_fb=56012, rig_res_data[0]=53078 against nets.map/netlist).
import json, sys
d = json.load(open(sys.argv[1]))['modules']['top']['netnames']
def one(n):
    b = d[n]['bits']; assert len(b) == 1 and isinstance(b[0], int), n; return f"dut.n{b[0]}"
out = ["// generated by audit/bq1/mkvh.py from " + sys.argv[1]]
for k, n in [("J_LAP", "rig_lap"), ("J_FB", "hk_fb"), ("J_RST", "rig_rst"),
             ("J_IDX0", "idx[0]"), ("J_IDX1", "idx[1]"), ("J_IDX2", "idx[2]"), ("J_IDX3", "idx[3]")]:
    out.append(f"`define {k} {one(n)}")
bits = [one(f"rig_res_data[{i}]") for i in range(31, -1, -1)]
out.append("`define J_RES {" + ", ".join(bits) + "}")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
