#!/usr/bin/env python3
"""T108 (audit, own code): PS_MON_GEN hook for BDC_SPEC_INC cells. For every routed LUT cell named *.uspec, identifies
its z_short / z_long / abort / z_req nets from the routed json (z_short and z_long by their drivers: the last LUT of
<inst>.udly_s / <inst>.udly chains), and emits a monitor that reports, per instance:
  SPECMON setup: at every rise of z_short (and of z_long) the time since the last abort change ("abort_stable_ps");
  hazards: any abort change while z_short or z_long is high (the LUT3 output could glitch), counted;
  z_req pulses: min high width, number of rises of z_req vs rises of the selected line;
  per-rise selection (abort value) counts.  Then chains audit/t104/mon_both1.py (latch, steer, mux monitors)."""
import json, sys, os, subprocess, re, collections
rj, nmap, out = sys.argv[1:4]
m = list(json.load(open(rj))["modules"].values())[0]
w_of = {}
for l in open(nmap):
    if l.startswith('#'): continue
    w, _, n = l.strip().partition(' '); w_of.setdefault(n, w)
bit2wire = {}
for k, v in m['netnames'].items():
    if k in w_of and len(v['bits']) == 1: bit2wire.setdefault(v['bits'][0], w_of[k])
drv = {}
for cn, c in m['cells'].items():
    for p, bs in c['connections'].items():
        if p.startswith('O') or p in ('Q', 'O6', 'O5'):
            for b in bs: drv[b] = cn
L = ["// GENERATED by audit/t108/mon_spec.py", "`timescale 1ps/1ps", "module spec_mon;"]
found = []
for cn, c in m['cells'].items():
    if not cn.endswith('.uspec'): continue
    inst = cn[:-len('.uspec')]
    ins = {p: bs[0] for p, bs in c['connections'].items() if p.startswith('A') and bs}
    o = c['connections']['O6'][0]
    role = {}
    for p, b in ins.items():
        d = drv.get(b, '')
        if d.startswith(inst + '.udly_s.'): role['short'] = b
        elif d.startswith(inst + '.udly.'): role['long'] = b
        else: role.setdefault('abort', []).append((p, b, d))
    assert len(role.get('abort', [])) == 1, (cn, role)
    role['abort'] = role['abort'][0][1]
    W = {r: bit2wire.get(b) for r, b in role.items()}; W['zreq'] = bit2wire.get(o)
    assert all(W.values()), (cn, W)
    found.append((inst, W, {r: drv.get(b) for r, b in role.items()}))
    i = len(found) - 1
    a, s, lg, z = (f"tb_ps.dut.{W[k]}" for k in ('abort', 'short', 'long', 'zreq'))
    L += [f"    // {inst}: abort={W['abort']} short={W['short']} long={W['long']} z_req={W['zreq']}",
          f"    time ta{i} = 0, tz{i} = 0; integer mins{i} = 999999999, minl{i} = 999999999, haz{i} = 0, nsh{i} = 0, nlo{i} = 0, nz{i} = 0, minz{i} = 999999999, sela{i} = 0, sels{i} = 0;",
          f"    always @({a}) begin if ({s} === 1'b1 || {lg} === 1'b1) begin haz{i} = haz{i} + 1; $display(\"SPECHAZ t=%0t {inst} abort->%b short=%b long=%b\", $time, {a}, {s}, {lg}); end ta{i} = $time; end",
          f"    always @(posedge {s}) begin nsh{i} = nsh{i} + 1; if ($time - ta{i} < mins{i}) mins{i} = $time - ta{i}; if ({a} === 1'b0) sels{i} = sels{i} + 1; else sela{i} = sela{i} + 1; end",
          f"    always @(posedge {lg}) begin nlo{i} = nlo{i} + 1; if ({a} === 1'b1 && $time - ta{i} < minl{i}) minl{i} = $time - ta{i}; end",
          f"    always @(posedge {z}) begin nz{i} = nz{i} + 1; tz{i} = $time; end",
          f"    always @(negedge {z}) if (tz{i} > 0 && $time - tz{i} < minz{i}) minz{i} = $time - tz{i};",
          f"    always #1000000 $display(\"SPECMON t=%0t {inst} short_rises=%0d long_rises=%0d zreq_rises=%0d sel_short=%0d sel_long=%0d min_abort_stable_at_short_ps=%0d min_abort_stable_at_long_sel_ps=%0d hazards=%0d min_zreq_high_ps=%0d\", $time, nsh{i}, nlo{i}, nz{i}, sels{i}, sela{i}, mins{i}, minl{i}, haz{i}, minz{i});"]
L += ["endmodule"]
o1 = out + ".s"; open(o1, 'w').write("\n".join(L) + "\n")
print(f"mon_spec: {[(f[0], f[2]) for f in found]}", file=sys.stderr)
b = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 't104', 'mon_both1.py')
o2 = out + ".x"; subprocess.run([sys.executable, "-I", b, rj, nmap, o2], check=True)
open(out, 'w').write(open(o1).read() + open(o2).read())
