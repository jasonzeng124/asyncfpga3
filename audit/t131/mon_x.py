#!/usr/bin/env python3
"""T131 (audit, own code): PS_MON_GEN hook that logs the first value changes (including to/from X) of named netlist wires.
env MON_X_NETS = comma list of baked-netlist wire names (wNNN / nNNN); MON_X_N = max changes logged per net (default 12).
Used to test whether an injected-select 'no completion' is X propagation from an uninitialized latch (research bd57aa13b)."""
import os, sys
rj, nmap, out = sys.argv[1:4]
nets = [n for n in os.environ['MON_X_NETS'].split(',') if n]; N = int(os.environ.get('MON_X_N', 12))
L = ["// GENERATED by audit/t131/mon_x.py", "`timescale 1ps/1ps", "module x_mon;"]
for i, n in enumerate(nets):
    L.append(f"    integer c{i} = 0; always @(tb_ps.dut.{n}) begin c{i} = c{i} + 1; if (c{i} <= {N}) begin $display(\"XMON t=%0t {n} -> %b\", $time, tb_ps.dut.{n}); $fflush; end end")
    L.append(f"    initial #1 $display(\"XMON t=%0t {n} init %b\", $time, tb_ps.dut.{n});")
L.append(f"    initial begin #{os.environ.get('MON_X_STOP', 5000000)}; $display(\"XMON stop\"); $fflush; $finish; end")
L.append("endmodule")
open(out, 'w').write("\n".join(L) + "\n")
print(f"mon_x: {len(nets)} nets", file=sys.stderr)
