#!/usr/bin/env python3
"""T124c (audit, own code): PS_MON_GEN hook. Reads IH_JSON (t124/input_hold.py JSON=..., same route and corner). For the
kernel-input latch: at every fall of its enable node (driver) arm; per bit, the first fall of that bit's enable PIN after
arming (t_pin) and the first fall of the kernel input ack n_ack after arming (t_ack). Per bit: min over handshakes of
t_ack - t_pin. Offline: zero-hold-sender slack_b = that + data_b - (close_b - en_ic_b) (LUT arc en->O and data route
src->D->O from the static JSON). IHN = handshakes where n_ack fell; IHX = handshakes where it did not fall before re-arm."""
import json, os, sys, re
rj, nmap, out = sys.argv[1:4]
J = json.load(open(os.environ['IH_JSON'])); K = int(os.environ.get('IH_BITS', 64))
pins = {}
for l in open('netlist_baked.v'):
    mm = re.match(r'\s*SLICE_LUTX #\(.*\) (c_\d+) \((.*)\);', l)
    if mm: pins[mm[1]] = dict(re.findall(r'\.(\w+)\((\w+)\)', mm[2]))
L = ["// GENERATED by audit/t124/mon_inhold.py", "`timescale 1ps/1ps", "module ih_mon;",
     "    time ta = 0; reg arm_a = 0; integer nh = 0, nx = 0;",
     f"    always @(negedge tb_ps.dut.{J['en']}) begin if (arm_a) nx = nx + 1; arm_a = 1; nh = nh + 1; end",
     f"    always @(negedge tb_ps.dut.{J['ack']}) if (arm_a) begin arm_a = 0; ta = $time; end"]
disp = []
for k, b in enumerate(J['bits'][:K]):
    en = pins[b['cell']][b['enpin']]
    L += [f"    time tp_{k} = 0; reg ap_{k} = 0; reg pend_{k} = 0; integer mn_{k} = 999999999; integer v_{k};",
          f"    always @(negedge tb_ps.dut.{J['en']}) begin ap_{k} = 1; pend_{k} = 1; end",
          f"    always @(negedge tb_ps.dut.{en}) if (ap_{k}) begin ap_{k} = 0; tp_{k} = $time; end",
          f"    always @(negedge tb_ps.dut.{J['ack']}) if (pend_{k}) begin pend_{k} = 0; if (ap_{k}) v_{k} = -1000000; else v_{k} = $time - tp_{k}; if (v_{k} < mn_{k}) mn_{k} = v_{k}; end"]
    disp.append(f'$display("IHB t=%0t {b["name"]} static_slack={b["slack"]} data={b["data"]} arc={b["close"] - b["en_ic"]} min_tack_minus_tpin=%0d", $time, mn_{k});')
disp.append('$display("IHN t=%0t handshakes=%0d no_ack_before_rearm=%0d", $time, nh, nx);')
L.append("    initial forever begin #5000000; " + " ".join(disp) + " end")
L.append("endmodule")
open(out, 'w').write("\n".join(L) + "\n")
print(f"mon_inhold: {min(K, len(J['bits']))} bits", file=sys.stderr)
