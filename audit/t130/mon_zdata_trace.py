#!/usr/bin/env python3
"""T130b TRACE variant of t130/mon_zdata.py: additionally, for the first 12 late output changes per mux, prints the output net,
the lateness, and the LUT input pin that changed most recently before it (its net and time), to tell a late SELECT from a late DATA input.
T130 (audit, own code): bd_mux DATA-OUTPUT settle monitor (PS_MON_GEN hook; env MON_KERNEL = the build's kernel Verilog;
optional MON_MUXES=umux0,umux1). Mapping as t83/mon_mux.py (data-mux LUTs 'umuxN.udat.*', z_req from the kernel text).
For each mux: at every z_req rise (at its driver) a token starts; any change of a data-mux LUT OUTPUT (O6/O5) while z_req
is 1 AND z_ack is not 1 (state A: request pending, not yet acknowledged; in state B the producer may legitimately move
its data) counts as late for that token. z_ack from the kernel's .z_ack port, or ZACKS=umux0=<net>,... overrides. Reports per mux: tokens, tokens with a late output change, max lateness after the
z_req rise, and total late output changes. This is the dynamic form of rule M at the mux itself (z_data vs z_req), the
quantity research's mux_settle.py reports; it differs from t116/mon_sel.py, which watches the select PINS (a late select
pin need not move the output when both data inputs agree on that bit)."""
import json, re, sys, os, collections
rj, nmap, out = sys.argv[1:4]
ker = open(os.environ["MON_KERNEL"]).read()
want = set(os.environ.get("MON_MUXES", "").split(",")) - {""}
zreq = {m[1]: m[2] for m in re.finditer(r'bd_mux\s*#\(.*?\)\s*(umux\d+)\s*\(.*?\.z_req\((\w+)\)', ker, re.S)}
zack = {m[1]: m[2] for m in re.finditer(r'bd_mux\s*#\(.*?\)\s*(umux\d+)\s*\(.*?\.z_ack\((\w+)\)', ker, re.S)}
ov = dict(x.split('=') for x in os.environ.get('ZACKS', '').split(',') if '=' in x)
m = list(json.load(open(rj))["modules"].values())[0]
names_of_bit = collections.defaultdict(set)
for n, v in m["netnames"].items():
    for b in v["bits"]: names_of_bit[b].add(n)
wire_of_name = {}
for l in open(nmap):
    if l.startswith('#'): continue
    w, _, n = l.strip().partition(' '); wire_of_name.setdefault(n, w)
site_of_c = {}
for l in open('names.map'):
    if l.startswith('#'): continue
    c, s = l.split(None, 1); site_of_c[s.strip()] = c
inst_pins = {}
for l in open('netlist_baked.v'):
    mm = re.match(r'\s*SLICE_LUTX #\(.*\) (c_\d+) \((.*)\);', l)
    if mm: inst_pins[mm[1]] = dict(re.findall(r'\.(\w+)\((\w+)\)', mm[2]))
def wire_of_bit(b):
    for n in names_of_bit[b]:
        if n in wire_of_name: return wire_of_name[n]
cells = collections.defaultdict(list)
for cn, c in m["cells"].items():
    mm = re.match(r'bridge_i\.udut\.(umux\d+)\.udat\..*\.u(\$LUT6|\$LUT5)?$', cn)
    if mm and (not want or mm[1] in want): cells[mm[1]].append(c["attributes"].get("NEXTPNR_BEL"))
mons, miss = [], []
for mux, bels in cells.items():
    zw = wire_of_name.get('bridge_i.udut.' + zreq.get(mux, '?'))
    if not zw:
        eb = m['netnames'].get('bridge_i.udut.' + mux + '.either'); zw = wire_of_bit(eb['bits'][0]) if eb else None
    if not zw: miss.append(mux + ':zreq'); continue
    ka = wire_of_name.get(ov[mux]) if mux in ov else wire_of_name.get('bridge_i.udut.' + zack.get(mux, '?'))
    if not ka: miss.append(mux + ':zack'); continue
    outs = []
    for bel in bels:
        p = inst_pins.get(site_of_c.get(bel, ''), {})
        o = p.get('O6') or p.get('O5')
        if o: outs.append((o, {k: v for k, v in p.items() if re.match(r'A\d$', k)}))
    if outs: mons.append((mux, zw, ka, outs))
    else: miss.append(mux + ':outs')
L = ["// GENERATED by audit/t130/mon_zdata.py (audit)", "`timescale 1ps/1ps", "module zd_mon;"]
for i, (mux, zw, ka, outs) in enumerate(mons):
    L.append(f"    // {mux}: z_req {zw}, z_ack {ka}, {len(outs)} data-LUT outputs")
    L.append(f"    time tz{i} = 0; reg arm{i} = 0, lt{i} = 0; integer nt{i} = 0, nl{i} = 0, nc{i} = 0, ml{i} = 0;")
    L.append(f"    always @(posedge tb_ps.dut.{zw}) begin tz{i} = $time; arm{i} = 1; lt{i} = 0; nt{i} = nt{i} + 1; end")
    L.append(f"    always @(negedge tb_ps.dut.{zw}) arm{i} = 0;")
    for j, (o, ins) in enumerate(outs):
        tn = f"{i}_{j}"
        for pn, net in ins.items():
            L.append(f"    time tp{tn}_{pn} = 0; always @(tb_ps.dut.{net}) tp{tn}_{pn} = $time;")
        lp = " ".join(f"if (tp{tn}_{pn} >= tl{tn}) begin tl{tn} = tp{tn}_{pn}; ln{tn} = \"{pn}:{net}\"; end" for pn, net in ins.items())
        L.append(f"    time tl{tn}; reg [8*40:1] ln{tn};")
        L.append(f"    always @(tb_ps.dut.{o}) if (arm{i} && tb_ps.dut.{zw} === 1'b1 && tb_ps.dut.{ka} !== 1'b1 && $time > tz{i}) begin nc{i} = nc{i} + 1;"
                 f" if (!lt{i}) begin lt{i} = 1; nl{i} = nl{i} + 1; end if ($time - tz{i} > ml{i}) ml{i} = $time - tz{i};"
                 f" if (nc{i} <= 12) begin tl{tn} = 0; {lp} $display(\"ZDTRACE t=%0t {mux} out {o} late %0d ps after z_req; last input %0s at %0t\", $time, $time - tz{i}, ln{tn}, tl{tn}); end end")
L.append("    initial forever begin #5000000;")
for i, (mux, *_r) in enumerate(mons):
    L.append(f'        $display("ZDMON t=%0t {mux} tokens=%0d late_tokens=%0d late_output_changes=%0d max_late_ps=%0d", $time, nt{i}, nl{i}, nc{i}, ml{i});')
L += ["    end", "endmodule"]
open(out, 'w').write("\n".join(L) + "\n")
print(f"mon_zdata: {len(mons)} muxes mapped ({sum(len(m_[3]) for m_ in mons)} outputs), not: {miss}", file=sys.stderr)
