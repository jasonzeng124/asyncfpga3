#!/usr/bin/env python3
"""Export bdc's ring-depth graph to Lean and cross-check emit.py (probe C-9b).

For each handshake MLIR file and each function in it, this builds
emit.Emitter (bdc's own pipeline: link_sites, then ring_depths) and exports
EXACTLY the graph ring_depths() looks at:

  nodes   func.nodes indices
  edges   slack.build_node_graph(func) minus em.mem_absorbed  (parallel
          edges kept: the lightest one is the one that matters)
  weight  storage stages on the channel, three variants:
          "rd"    ring_depths(func, em.linked, em.mem_absorbed) itself --
                  the table whose postcondition is "every cycle >= 3"
          "final" em.depth, what is actually emitted: ring_depths plus
                  _apply_ring_pad, _apply_slack_stages, _apply_link_depths
                  (all of which only raise depths)
          "pre"   1 per linked channel, before ring_depths deepened anything

It writes one Lean file defining `Graph` terms, plus #eval lines running the
verified checker (Formal.Net.RingCheck.check, minCycleCap), and prints an
independent Python reference: Floyd-Warshall min cycle weight, emit.py's
implicit answer (ring_depths returned, so it claims every cycle >= 3) and
whether ring_depths deepened anything.

A second graph per function, "rs", is what bdc/ring_stages.py weighs: edges
collapsed per (producer, consumer) with MAX weight and mem_absorbed edges NOT
removed.  Its lightest cycle is reported to show where the two scripts' views
of the graph differ.

Usage:
  python3 formal/tools/ringcheck/export.py [--cert-dir DIR] OUT.lean FILE.mlir...
--cert-dir also writes DIR/Cert_<kernel>_<func>.lean: the "rd" graph, an
untrusted certificate, and a theorem `<..>_rd_ge3 : AllCyclesGe g 3` proved by
certCheck_sound + `decide +kernel` (a proof, not just evidence).
then
  cd formal/lean && LEAN_PATH=$PWD/.lake/build/lib/lean ../slot.sh lean OUT.lean
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BDC = os.path.normpath(os.path.join(HERE, "..", "..", "..", "bdc"))
sys.path.insert(0, BDC)
import emit                        # noqa: E402
import slack                       # noqa: E402
from hs import parse               # noqa: E402
from map import Table              # noqa: E402

INF = float("inf")


def min_cycle(n, edges):
    """Reference (unverified): min over edges u->v of w + dist(v, u)."""
    d = [[INF] * n for _ in range(n)]
    for i in range(n):
        d[i][i] = 0
    for (u, v, w) in edges:
        if w < d[u][v]:
            d[u][v] = w
    for k in range(n):
        dk = d[k]
        for i in range(n):
            dik = d[i][k]
            if dik == INF:
                continue
            di = d[i]
            for j in range(n):
                x = dik + dk[j]
                if x < di[j]:
                    di[j] = x
    best = INF
    for (u, v, w) in edges:
        best = min(best, w + d[v][u])
    return best


def dist_matrix(n, edges):
    d = [[INF] * n for _ in range(n)]
    for i in range(n):
        d[i][i] = 0
    for (u, v, w) in edges:
        d[u][v] = min(d[u][v], w)
    for m in range(n):
        for i in range(n):
            if d[i][m] == INF:
                continue
            for j in range(n):
                if d[i][m] + d[m][j] < d[i][j]:
                    d[i][j] = d[i][m] + d[m][j]
    return d


def make_cert(edges, k):
    """Untrusted certificate for RingCheck.certCheck: per source s, the table
    v -> min(k, lightest walk of >= 1 edge from s to v).  Lean re-checks it."""
    n = 1 + max([max(u, v) for (u, v, _) in edges], default=-1)
    d = dist_matrix(n, edges)
    cert = []
    for s in range(n):
        t = [k] * n
        for (u, v, w) in edges:
            if d[s][u] != INF:
                t[v] = min(t[v], d[s][u] + w, k)
        cert.append(t)
    return cert


CHUNK = 8   # sources per kernel `decide` (one call on all of isprime OOMs)


def write_cert_file(path, name, edges, k):
    """Graph + certificate + chunked kernel proofs of AllCyclesGe name k."""
    cert = make_cert(edges, k)
    n = len(cert)
    L = ["import Formal.Net.RingCheckCert",
         "/-! Generated by formal/tools/ringcheck/export.py -- do not edit.",
         "Kernel-checked (`decide +kernel`, no native_decide): every cycle of this",
         f"bdc graph carries at least {k} storage stages. The certificate tables",
         "come from untrusted Python; `certCheckFrom_sound` makes them irrelevant",
         "to the claim's correctness. -/",
         "namespace Formal.Net.RingCheck.Data", "open Formal.Net.RingCheck", "",
         "set_option maxRecDepth 20000", "",
         lean_graph(name, edges)]
    for t, row in enumerate(cert):
        L.append(f"def {name}_T{t} : List Nat := [{', '.join(map(str, row))}]")
    L.append(f"def {name}_cert : List (List Nat) := [{', '.join(f'{name}_T{t}' for t in range(n))}]")
    L.append("")
    L.append(f"theorem {name}_n : numNodes {name} = {n} := by decide +kernel")
    blocks = [(a, min(CHUNK, n - a)) for a in range(0, n, CHUNK)]
    for i, (a, m) in enumerate(blocks):
        L.append(f"theorem {name}_B{i} : certCheckFrom {name} {k} {name}_cert "
                 f"(List.range' {a} {m}) = true := by decide +kernel")
    # glue right to left: G_i covers [a_i, n)
    for i in reversed(range(len(blocks))):
        a, m = blocks[i]
        if i == len(blocks) - 1:
            L.append(f"theorem {name}_G{i} : certCheckFrom {name} {k} {name}_cert "
                     f"(List.range' {a} {m}) = true := {name}_B{i}")
        else:
            rest = n - a - m
            L.append(f"theorem {name}_G{i} : certCheckFrom {name} {k} {name}_cert "
                     f"(List.range' {a} {n - a}) = true :=\n"
                     f"  certCheckFrom_append (m := {m}) (b := {rest}) {name}_B{i} {name}_G{i + 1}")
    if blocks:
        L.append(f"\ntheorem {name}_ge{k} : AllCyclesGe {name} {k} :=\n"
                 f"  certCheckFrom_sound {name}_n {name}_G0")
    else:   # no edges: nothing to check
        L.append(f"\ntheorem {name}_ge{k} : AllCyclesGe {name} {k} := fun _ _ h => "
                 f"absurd (walk_src_lt h) (by decide)")
    L += ["", "end Formal.Net.RingCheck.Data", ""]
    open(path, "w").write("\n".join(L))


def lean_graph(name, edges):
    body = ", ".join(f"⟨{u}, {v}, {w}⟩" for (u, v, w) in edges)
    return f"def {name} : Graph := [{body}]\n"


def ident(s):
    return "".join(c if c.isalnum() else "_" for c in s)


def main():
    args = sys.argv[1:]
    cert_dir = None
    if args and args[0] == "--cert-dir":
        cert_dir, args = args[1], args[2:]
    out, files = args[0], args[1:]
    table = Table()
    lean = ["import Formal.Net.RingCheck",
            "/-! Generated by formal/tools/ringcheck/export.py -- do not edit. -/",
            "namespace Formal.Net.RingCheck.Data", "open Formal.Net.RingCheck", ""]
    evals = []
    report = []
    for path in files:
        kname = os.path.basename(os.path.dirname(os.path.dirname(path))) or path
        for func in parse.parse_module(open(path).read(), filename=path):
            em = emit.Emitter(func, table)
            edges_all, _ = slack.build_node_graph(func)
            edges = [e for e in edges_all if e.value not in em.mem_absorbed]
            n = len(func.nodes)
            rd_depth = emit.ring_depths(func, em.linked, exclude=em.mem_absorbed)
            rd = [(e.producer, e.consumer, rd_depth.get(e.value, 0)) for e in edges]
            final = [(e.producer, e.consumer, em.depth.get(e.value, 0)) for e in edges]
            pre = [(e.producer, e.consumer, 1 if e.value in em.linked else 0) for e in edges]
            rs = {}
            for e in edges_all:   # ring_stages.py's view
                key = (e.producer, e.consumer)
                rs[key] = max(rs.get(key, 0), em.depth.get(e.value, 0))
            rs = [(u, v, w) for (u, v), w in sorted(rs.items())]
            base = ident(f"{kname}_{func.name}")
            for tag, g in (("rd", rd), ("final", final), ("pre", pre), ("rs", rs)):
                lean.append(lean_graph(f"{base}_{tag}", g))
            if cert_dir:
                write_cert_file(os.path.join(cert_dir, f"Cert_{base}.lean"),
                                f"{base}_rd", rd, 3)
            deepened = sorted((str(v), d) for v, d in rd_depth.items() if d > 1)
            rec = {
                "kernel": kname, "func": func.name, "nodes": n,
                "edges": len(edges), "mem_absorbed_edges": len(edges_all) - len(edges),
                "linked": len(em.linked),
                "py_min_rd": min_cycle(n, rd),
                "py_min_final": min_cycle(n, final),
                "py_min_pre": min_cycle(n, pre),
                "py_min_rs": min_cycle(n, rs),
                "emit_claims_all_ge_3": True,   # ring_depths returned, did not raise
                "ring_depths_deepened": deepened,
            }
            for k in ("py_min_rd", "py_min_final", "py_min_pre", "py_min_rs"):
                if rec[k] == INF:
                    rec[k] = None    # acyclic
            report.append(rec)
            evals.append(
                f'#eval ("{base}", check {base}_rd 3, minCycleCap 1000 {base}_rd, '
                f'check {base}_final 3, minCycleCap 1000 {base}_final, '
                f'check {base}_pre 3, minCycleCap 1000 {base}_pre, '
                f'minCycleCap 1000 {base}_rs)')
    lean += ["", *evals, "", "end Formal.Net.RingCheck.Data", ""]
    open(out, "w").write("\n".join(lean))
    print(json.dumps(report, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
